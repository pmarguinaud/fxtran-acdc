MODULE UTIL_TIWMX_T_LOAD_MOD
USE MODD_TIWMX, ONLY : TIWMX_T
INTERFACE ACDC_LOAD
MODULE PROCEDURE ACDC_LOAD_TIWMX_T
END INTERFACE

CONTAINS
SUBROUTINE ACDC_LOAD_TIWMX_T (SELF, KLUN)

IMPLICIT NONE
TYPE (TIWMX_T), INTENT (OUT), TARGET :: SELF
INTEGER, INTENT (IN) :: KLUN

READ (KLUN) SELF%ESTABW
READ (KLUN) SELF%DESTABW
READ (KLUN) SELF%ESTABI
READ (KLUN) SELF%DESTABI
READ (KLUN) SELF%A2TAB
READ (KLUN) SELF%BB3TAB
READ (KLUN) SELF%AM3TAB
READ (KLUN) SELF%AF3TAB
READ (KLUN) SELF%A2WTAB
READ (KLUN) SELF%BB3WTAB
READ (KLUN) SELF%REDINTAB
END SUBROUTINE
END MODULE
