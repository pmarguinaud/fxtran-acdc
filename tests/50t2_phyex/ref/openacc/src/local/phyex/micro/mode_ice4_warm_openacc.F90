
MODULE MODE_ICE4_WARM_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE ICE4_WARM_OPENACC (CST, PARAMI, ICEP, ICED, D, LDSOFT, LDCOMPUTE, HSUBG_RC_RR_ACCR, HSUBG_RR_EVAP&
&, PRHODREF, PLVFACT, PT, PPRES, PTHT, PLBDAR, PLBDAR_RF, PKA, PDV, PCJ, PHLC_LCF, PHLC_HCF, PHLC_LRC&
&, PHLC_HRC, PCF, PRF, PRVT, PRCT, PRRT, PCONC, PACRF, PRCAUTR, PRCACCR, PRREVAV, YDSTACK)
!$ACC ROUTINE (ICE4_WARM_OPENACC) SEQ      

USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_CST,ONLY:CST_T
USE MODD_PARAM_ICE_N,ONLY:PARAM_ICE_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T
USE MODD_RAIN_ICE_PARAM_N,ONLY:RAIN_ICE_PARAM_T
USE MODE_MSG,ONLY:NVERB_FATAL, PRINT_MSG

#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (CST_T), INTENT (IN)::CST
TYPE (PARAM_ICE_T), INTENT (IN)::PARAMI
TYPE (RAIN_ICE_PARAM_T), INTENT (IN)::ICEP
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
TYPE (DIMPHYEX_T), INTENT (IN)::D
LOGICAL, INTENT (IN)::LDSOFT
LOGICAL, INTENT (IN)::LDCOMPUTE(D%NIJT)
CHARACTER (LEN=80), INTENT (IN)::HSUBG_RC_RR_ACCR
CHARACTER (LEN=80), INTENT (IN)::HSUBG_RR_EVAP
REAL, INTENT (IN)::PRHODREF(D%NIJT)
REAL, INTENT (IN)::PLVFACT(D%NIJT)
REAL, INTENT (IN)::PT(D%NIJT)
REAL, INTENT (IN)::PPRES(D%NIJT)
REAL, INTENT (IN)::PTHT(D%NIJT)
REAL, INTENT (IN)::PLBDAR(D%NIJT)
REAL, INTENT (IN)::PLBDAR_RF(D%NIJT)
REAL, INTENT (IN)::PKA(D%NIJT)
REAL, INTENT (IN)::PDV(D%NIJT)
REAL, INTENT (IN)::PCJ(D%NIJT)
REAL, INTENT (IN)::PHLC_HCF(D%NIJT)
REAL, INTENT (IN)::PHLC_LCF(D%NIJT)
REAL, INTENT (IN)::PHLC_HRC(D%NIJT)
REAL, INTENT (IN)::PHLC_LRC(D%NIJT)
REAL, INTENT (IN)::PCF(D%NIJT)
REAL, INTENT (IN)::PRF(D%NIJT)
REAL, INTENT (IN)::PRVT(D%NIJT)
REAL, INTENT (IN)::PRCT(D%NIJT)
REAL, INTENT (IN)::PRRT(D%NIJT)
REAL, INTENT (IN)::PCONC(D%NIJT)
REAL, INTENT (IN)::PACRF(D%NIJT)
REAL, INTENT (INOUT)::PRCAUTR(D%NIJT)
REAL, INTENT (INOUT)::PRCACCR(D%NIJT)
REAL, INTENT (INOUT)::PRREVAV(D%NIJT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
REAL::ZZW4
REAL::ZZW3
REAL::ZZW2
REAL::ZUSW
REAL::ZTHLT

INTEGER::JI
LOGICAL::LMASK2
LOGICAL::LMASK1
LOGICAL::LMASK

JI = D%NIB


#ifdef MNH_COMPILER_CCE
#endif


IF (LDCOMPUTE (JI)) THEN

  IF (PARAMI%LKOGAN.AND..NOT.LDSOFT) THEN
    PRCAUTR (JI)=0.

    IF (PRCT (JI)>1.0E-8) THEN
      PRCAUTR (JI)=1350.0*ICEP%XFRMIN (10)*PCONC (JI)**(-1.79)&
      &*(PRCT (JI)/(MAX (ICEP%XFRMIN (11), PCF (JI))))**2.47
      PRCAUTR (JI)=PRCAUTR (JI)*MAX (ICEP%XFRMIN (11), PCF (JI))
    ENDIF

  ELSE

    IF (PHLC_HRC (JI)>ICED%XRTMIN (2).AND.PHLC_HCF (JI)>0.) THEN

      IF (.NOT.LDSOFT) THEN
        PRCAUTR (JI)=ICEP%XTIMAUTC*MAX (PHLC_HRC (JI)-PHLC_HCF (JI)*ICEP%XCRIAUTC/PRHODREF (JI), 0.0)
      ENDIF

    ELSE
      PRCAUTR (JI)=0.
    ENDIF

  ENDIF

ELSE
  PRCAUTR (JI)=0.
ENDIF



IF (HSUBG_RC_RR_ACCR=='NONE') THEN

  

  IF (PRCT (JI)>ICED%XRTMIN (2).AND.PRRT (JI)>ICED%XRTMIN (3).AND.LDCOMPUTE (JI)) THEN

    IF (.NOT.LDSOFT) THEN
      PRCACCR (JI)=ICEP%XFCACCR*PRCT (JI)*PACRF (JI)*PLBDAR&
      & (JI)**ICEP%XEXCACCR*PRHODREF (JI)**(-ICED%XCEXVT)
    ENDIF

  ELSE
    PRCACCR (JI)=0.
  ENDIF

  
ELSEIF (HSUBG_RC_RR_ACCR=='PRFR') THEN
  
  LMASK=PRCT (JI)>ICED%XRTMIN (2).AND.PRRT (JI)>ICED%XRTMIN (3).AND.LDCOMPUTE (JI)
  LMASK1=LMASK.AND.PHLC_HRC (JI)>ICED%XRTMIN (2).AND.PHLC_HCF (JI)>0.
  LMASK2=LMASK.AND.PHLC_LRC (JI)>ICED%XRTMIN (2).AND.PHLC_LCF (JI)>1.E-20

  IF (LMASK1.OR.LMASK2) THEN

    IF (.NOT.LDSOFT) THEN

      IF (LMASK1) THEN
        PRCACCR (JI)=ICEP%XFCACCR*PHLC_HRC (JI)*PLBDAR_RF (JI)**ICEP%XEXCACCR*PRHODREF (JI)**(-ICED%XCEXVT)
      ELSE
        PRCACCR (JI)=0.
      ENDIF


      IF (LMASK2) THEN
        PRCACCR (JI)=PRCACCR (JI)+ICEP%XFCACCR*(PHLC_LRC (JI)/PHLC_LCF (JI))*PLBDAR_RF (JI)**ICEP&
        &%XEXCACCR*PRHODREF (JI)**(-ICED%XCEXVT)*(MIN (PCF (JI), PRF (JI))-PHLC_HCF (JI))
      ENDIF

    ENDIF

  ELSE
    PRCACCR (JI)=0.
  ENDIF

  
ELSE
  CALL FXTRAN_ACDC_ABORT ('wrong HSUBG_RC_RR_ACCR case')
ENDIF


IF (HSUBG_RR_EVAP=='NONE') THEN

  

  IF (PRRT (JI)>ICED%XRTMIN (3).AND.PRCT (JI)<=ICED%XRTMIN (2).AND.LDCOMPUTE (JI)) THEN

    IF (.NOT.LDSOFT) THEN
      PRREVAV (JI)=EXP (CST%XALPW-CST%XBETAW/PT (JI)-CST%XGAMW*LOG (PT (JI)))
      ZUSW =1.-PRVT (JI)*(PPRES (JI)-PRREVAV (JI))/(CST%XEPSILO*PRREVAV (JI))
      PRREVAV (JI)=(CST%XLVTT+(CST%XCPV-CST%XCL)*(PT (JI)-CST%XTT))**2/(PKA &
      &(JI)*CST%XRV*PT (JI)**2)+(CST%XRV*PT (JI))/(PDV (JI)*PRREVAV (JI))
      PRREVAV (JI)=(MAX (0., ZUSW )/(PRHODREF (JI)*PRREVAV (JI)))*(ICEP%X0EVAR*PLBDAR&
      & (JI)**ICEP%XEX0EVAR+ICEP%X1EVAR*PCJ (JI)*PLBDAR (JI)**ICEP%XEX1EVAR)
    ENDIF

  ELSE
    PRREVAV (JI)=0.
  ENDIF

  
ELSEIF (HSUBG_RR_EVAP=='CLFR'.OR.HSUBG_RR_EVAP=='PRFR') THEN

  

  IF (HSUBG_RR_EVAP=='CLFR') THEN
    ZZW4=1.
    ZZW3=PLBDAR (JI)
  ELSE
    ZZW4=PRF (JI)
    ZZW3=PLBDAR_RF (JI)
  ENDIF


  IF (PRRT (JI)>ICED%XRTMIN (3).AND.ZZW4>PCF (JI).AND.LDCOMPUTE (JI)) THEN

    IF (.NOT.LDSOFT) THEN
      ZTHLT =PTHT (JI)-CST%XLVTT*PTHT (JI)/CST%XCPD/PT (JI)*PRCT (JI)
      ZZW2=ZTHLT *PT (JI)/PTHT (JI)
      PRREVAV (JI)=EXP (CST%XALPW-CST%XBETAW/ZZW2-CST%XGAMW*LOG (ZZW2))
      ZUSW =1.0-PRVT (JI)*(PPRES (JI)-PRREVAV (JI))/(CST%XEPSILO*PRREVAV (JI))
      PRREVAV (JI)=(CST%XLVTT+(CST%XCPV-CST%XCL)*(ZZW2-CST%XTT))**2/(PKA&
      & (JI)*CST%XRV*ZZW2**2)+(CST%XRV*ZZW2)/(PDV (JI)*PRREVAV (JI))
      PRREVAV (JI)=MAX (0., ZUSW )/(PRHODREF (JI)*PRREVAV (JI))*(ICEP%X0EVAR&
      &*ZZW3**ICEP%XEX0EVAR+ICEP%X1EVAR*PCJ (JI)*ZZW3**ICEP%XEX1EVAR)
      PRREVAV (JI)=PRREVAV (JI)*(ZZW4-PCF (JI))
    ENDIF

  ELSE
    PRREVAV (JI)=0.
  ENDIF

  
ELSE
  CALL FXTRAN_ACDC_ABORT ('wrong HSUBG_RR_EVAP case')
ENDIF


END SUBROUTINE ICE4_WARM_OPENACC

ENDMODULE MODE_ICE4_WARM_OPENACC
