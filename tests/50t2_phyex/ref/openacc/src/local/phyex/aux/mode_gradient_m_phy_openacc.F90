SUBROUTINE GX_M_U_PHY_OPENACC (D, OFLAT, PY, PDXX, PDZZ, PDZX, PGX_M_U, YDSTACK)
!$ACC ROUTINE (GX_M_U_PHY_OPENACC) SEQ      


USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_PARAMETERS,ONLY:JPHEXT, JPVEXT_TURB
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE

TYPE (DIMPHYEX_T), INTENT (IN)::D
LOGICAL, INTENT (IN)::OFLAT
REAL, INTENT (IN)::PY(D%NIT, D%NJT, D%NKT)
REAL, INTENT (IN)::PDXX(D%NIT, D%NJT, D%NKT)
REAL, INTENT (IN)::PDZZ(D%NIT, D%NJT, D%NKT)
REAL, INTENT (IN)::PDZX(D%NIT, D%NJT, D%NKT)
REAL, INTENT (OUT)::PGX_M_U(D%NIT, D%NJT, D%NKT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
INTEGER IKA
INTEGER IKL
INTEGER JI
INTEGER IKU
INTEGER IIU
INTEGER::IJU


JI = D%NIB


IIU=D%NIT
IJU=D%NJT
IKU=D%NKT
IKL=D%NKL
IKA=D%NKA

PGX_M_U (JI, 1:IJU, 1+JPVEXT_TURB:IKU-JPVEXT_TURB)=(PY (JI, 1:IJU, 1+JPVEXT_TURB:IKU-JPVEXT_TURB)-PY&
& (JI, 1:IJU, 1+JPVEXT_TURB:IKU-JPVEXT_TURB)-((PY (JI, 1:IJU, 1+JPVEXT_TURB:IKU-JPVEXT_TURB)-PY (JI,&
& 1:IJU, JPVEXT_TURB:IKU-JPVEXT_TURB-1))/PDZZ (JI, 1:IJU, 1+JPVEXT_TURB:IKU-JPVEXT_TURB)+(PY (JI, 1:IJU&
&, 1+JPVEXT_TURB:IKU-JPVEXT_TURB)-PY (JI, 1:IJU, JPVEXT_TURB:IKU-JPVEXT_TURB-1))/PDZZ (JI, 1:IJU, 1+JPVEXT_TURB&
&:IKU-JPVEXT_TURB))*PDZX (JI, 1:IJU, 1+JPVEXT_TURB:IKU-JPVEXT_TURB)*0.25-((PY (JI, 1:IJU, 1+JPVEXT_TURB&
&+1:IKU-JPVEXT_TURB+1)-PY (JI, 1:IJU, 1+JPVEXT_TURB:IKU-JPVEXT_TURB))/PDZZ (JI, 1:IJU, 1+JPVEXT_TURB&
&+1:IKU-JPVEXT_TURB+1)+(PY (JI, 1:IJU, 1+JPVEXT_TURB+1:IKU-JPVEXT_TURB+1)-PY (JI, 1:IJU, 1+JPVEXT_TURB&
&:IKU-JPVEXT_TURB))/PDZZ (JI, 1:IJU, 1+JPVEXT_TURB+1:IKU-JPVEXT_TURB+1))*PDZX (JI, 1:IJU, 1+JPVEXT_TURB&
&+1:IKU-JPVEXT_TURB+1)*0.25)/PDXX (JI, 1:IJU, 1+JPVEXT_TURB:IKU-JPVEXT_TURB)

PGX_M_U (JI,:, IKU)=(PY (JI,:, IKU)-PY (JI,:, IKU))/PDXX (JI,:, IKU)
PGX_M_U (JI,:, IKA)=PGX_M_U (JI,:, IKU)



PGX_M_U (JI,:,:)=PGX_M_U (JI,:,:)


END SUBROUTINE GX_M_U_PHY_OPENACC

SUBROUTINE GY_M_V_PHY_OPENACC (D, OFLAT, PY, PDYY, PDZZ, PDZY, PGY_M_V, YDSTACK)
!$ACC ROUTINE (GY_M_V_PHY_OPENACC) SEQ      


USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_PARAMETERS,ONLY:JPHEXT, JPVEXT_TURB
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE

TYPE (DIMPHYEX_T), INTENT (IN)::D
LOGICAL, INTENT (IN)::OFLAT
REAL, INTENT (IN)::PDYY(D%NIT, D%NJT, D%NKT)
REAL, INTENT (IN)::PDZY(D%NIT, D%NJT, D%NKT)
REAL, INTENT (IN)::PDZZ(D%NIT, D%NJT, D%NKT)
REAL, INTENT (IN)::PY(D%NIT, D%NJT, D%NKT)
REAL, INTENT (OUT)::PGY_M_V(D%NIT, D%NJT, D%NKT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
INTEGER IKA
INTEGER IKL
INTEGER JK
INTEGER JJ
INTEGER IKU
INTEGER IJU

INTEGER :: JI

JI = D%NIB


IJU=D%NJT
IKU=D%NKT
IKL=D%NKL
IKA=D%NKA
IKU=D%NKU


DO JK=1+JPVEXT_TURB, IKU-JPVEXT_TURB

  DO JJ=1+JPHEXT, IJU
    PGY_M_V (JI, JJ, JK)=(PY (JI, JJ, JK)-PY (JI, JJ-1, JK)-((PY (JI, JJ, JK)-PY (JI, JJ, JK-IKL))/PDZZ&
    & (JI, JJ, JK)+(PY (JI, JJ-1, JK)-PY (JI, JJ-IKL, JK-IKL))/PDZZ (JI, JJ-1, JK))*PDZY (JI, JJ, JK&
    &)*0.25-((PY (JI, JJ, JK+IKL)-PY (JI, JJ, JK))/PDZZ (JI, JJ, JK+IKL)+(PY (JI, JJ-1, JK+IKL)-PY &
    &(JI, JJ-1, JK))/PDZZ (JI, JJ-1, JK+IKL))*PDZY (JI, JJ, JK+IKL)*0.25)/PDYY (JI, JJ, JK)
  ENDDO

ENDDO


DO JJ=1+JPHEXT, IJU
  PGY_M_V (JI, JJ, IKU)=(PY (JI, JJ, IKU)-PY (JI, JJ-1, IKU))/PDYY (JI, JJ, IKU)
  PGY_M_V (JI, JJ, IKA)=-999.
ENDDO



DO JJ=1, JPHEXT
  PGY_M_V (JI, JJ,:)=PGY_M_V (JI, IJU-2*JPHEXT+JJ,:)
ENDDO



END SUBROUTINE GY_M_V_PHY_OPENACC

