
MODULE MODE_ICE4_FAST_RS_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE ICE4_FAST_RS_OPENACC (CST, PARAMI, ICEP, ICED, D, LDSOFT, LDCOMPUTE, PRHODREF, PLVFACT&
&, PLSFACT, PPRES, PDV, PKA, PCJ, PCOLF, PLBDAR, PLBDAS, PT, PRVT, PRCT, PRRT, PRST, PRIAGGS, PRCRIMSS&
&, PRCRIMSG, PRSRIMCG, PRRACCSS, PRRACCSG, PRSACCRG, PRSMLTG, PRCMLTSR, PRS_TEND, YDSTACK)
!$ACC ROUTINE (ICE4_FAST_RS_OPENACC) SEQ      

USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_CST,ONLY:CST_T
USE MODD_PARAM_ICE_N,ONLY:PARAM_ICE_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T
USE MODD_RAIN_ICE_PARAM_N,ONLY:RAIN_ICE_PARAM_T

#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (CST_T), INTENT (IN)::CST
TYPE (PARAM_ICE_T), INTENT (IN)::PARAMI
TYPE (RAIN_ICE_PARAM_T), INTENT (IN)::ICEP
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
TYPE (DIMPHYEX_T), INTENT (IN)::D
LOGICAL, INTENT (IN)::LDSOFT
LOGICAL, INTENT (IN)::LDCOMPUTE(D%NIJT)
REAL, INTENT (IN)::PRHODREF(D%NIJT)
REAL, INTENT (IN)::PLVFACT(D%NIJT)
REAL, INTENT (IN)::PLSFACT(D%NIJT)
REAL, INTENT (IN)::PPRES(D%NIJT)
REAL, INTENT (IN)::PDV(D%NIJT)
REAL, INTENT (IN)::PKA(D%NIJT)
REAL, INTENT (IN)::PCJ(D%NIJT)
REAL, INTENT (IN)::PCOLF(D%NIJT)
REAL, INTENT (IN)::PLBDAR(D%NIJT)
REAL, INTENT (IN)::PLBDAS(D%NIJT)
REAL, INTENT (IN)::PT(D%NIJT)
REAL, INTENT (IN)::PRVT(D%NIJT)
REAL, INTENT (IN)::PRCT(D%NIJT)
REAL, INTENT (IN)::PRRT(D%NIJT)
REAL, INTENT (IN)::PRST(D%NIJT)
REAL, INTENT (IN)::PRIAGGS(D%NIJT)
REAL, INTENT (OUT)::PRCRIMSS(D%NIJT)
REAL, INTENT (OUT)::PRCRIMSG(D%NIJT)
REAL, INTENT (OUT)::PRSRIMCG(D%NIJT)
REAL, INTENT (OUT)::PRRACCSS(D%NIJT)
REAL, INTENT (OUT)::PRRACCSG(D%NIJT)
REAL, INTENT (OUT)::PRSACCRG(D%NIJT)
REAL, INTENT (INOUT)::PRSMLTG(D%NIJT)
REAL, INTENT (INOUT)::PRCMLTSR(D%NIJT)
REAL, INTENT (INOUT)::PRS_TEND(D%NIJT, 8)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
INTEGER, PARAMETER::IFREEZ2=8
INTEGER, PARAMETER::IFREEZ1=7
INTEGER, PARAMETER::IRSACCRG=6
INTEGER, PARAMETER::IRRACCSS=5
INTEGER, PARAMETER::IRRACCS=4
INTEGER, PARAMETER::IRSRIMCG=3
INTEGER, PARAMETER::IRCRIMSS=2
INTEGER, PARAMETER::IRCRIMS=1
LOGICAL::GACC
LOGICAL::GRIM
INTEGER::IGACC
INTEGER::IGRIM
INTEGER::IBUF3
INTEGER::IBUF2
INTEGER::IBUF1
REAL::ZBUF3
REAL::ZBUF2
REAL::ZBUF1
REAL::ZFREEZ_RATE
REAL::ZZW3
REAL::ZZW2
REAL::ZZW1
REAL::ZZW
INTEGER::JI
REAL::ZZW0D

INTEGER::IINDEX2
INTEGER::IINDEX1
REAL::ZINDEX2
REAL::ZINDEX1
INTEGER::IINDEX
REAL::ZINDEX

JI = D%NIB


#ifdef MNH_COMPILER_CCE
#endif


IF (PRST (JI)>ICED%XRTMIN (5).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRS_TEND (JI, IFREEZ1)=PRVT (JI)*PPRES (JI)/(CST%XEPSILO+PRVT (JI))

    IF (PARAMI%LEVLIMIT) THEN
      PRS_TEND (JI, IFREEZ1)=MIN (PRS_TEND (JI, IFREEZ1), EXP (CST&
      &%XALPI-CST%XBETAI/PT (JI)-CST%XGAMI*LOG (PT (JI))))
    ENDIF

    PRS_TEND (JI, IFREEZ1)=PKA (JI)*(CST%XTT-PT (JI))+(PDV (JI)*(CST%XLVTT+(CST%XCPV-CST&
    &%XCL)*(PT (JI)-CST%XTT))*(CST%XESTT-PRS_TEND (JI, IFREEZ1))/(CST%XRV*PT (JI)))

    IF (.NOT.ICEP%LNEWCOEFF) THEN
      PRS_TEND (JI, IFREEZ1)=PRS_TEND (JI, IFREEZ1)*(ICEP%X0DEPS*PLBDAS (JI)**ICEP%XEX0DEPS+ICEP%X1DEPS&
      &*PCJ (JI)*PLBDAS (JI)**ICEP%XEX1DEPS)/(PRHODREF (JI)*(CST%XLMTT-CST%XCL*(CST%XTT-PT (JI))))
    ELSE
      PRS_TEND (JI, IFREEZ1)=PRS_TEND (JI, IFREEZ1)*PRST (JI)*(ICEP%X0DEPS*PLBDAS (JI)**ICEP%XEX0DEPS+ICEP%X1DEPS&
      &*PCJ (JI)*PLBDAS (JI)**(ICED%XBS+ICEP%XEX1DEPS)*(1+0.5*(ICED%XFVELOS/PLBDAS (JI))**ICED%XALPHAS)**(-ICED&
      &%XNUS+ICEP%XEX1DEPS/ICED%XALPHAS))/(PRHODREF (JI)*(CST%XLMTT-CST%XCL*(CST%XTT-PT (JI))))
    ENDIF

    PRS_TEND (JI, IFREEZ2)=(PRHODREF (JI)*(CST%XLMTT+(CST%XCI-CST%XCL)*(CST%XTT&
    &-PT (JI))))/(PRHODREF (JI)*(CST%XLMTT-CST%XCL*(CST%XTT-PT (JI))))
  ENDIF

  ZFREEZ_RATE =MAX (0., MAX (0., PRS_TEND (JI, IFREEZ1)+PRS_TEND&
  & (JI, IFREEZ2)*PRIAGGS (JI))-PRIAGGS (JI))
ELSE
  PRS_TEND (JI, IFREEZ1)=0.
  PRS_TEND (JI, IFREEZ2)=0.
  ZFREEZ_RATE =0.
ENDIF




IF (PRCT (JI)>ICED%XRTMIN (2).AND.PRST (JI)>ICED%XRTMIN (5).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.ICEP%LNEWCOEFF) THEN
    ZZW =PLBDAS (JI)
  ELSE
    ZZW =(PLBDAS (JI)**ICED%XALPHAS+ICED%XFVELOS**ICED%XALPHAS)**(1./ICED%XALPHAS)
  ENDIF

  GRIM =.TRUE.
ELSE
  GRIM =.FALSE.
  PRS_TEND (JI, IRCRIMS)=0.
  PRS_TEND (JI, IRCRIMSS)=0.
  PRS_TEND (JI, IRSRIMCG)=0.
ENDIF



IF (.NOT.LDSOFT) THEN

  

  IF (PARAMI%LPACK_INTERP) THEN
    IGRIM=0

    

    IF (GRIM ) THEN
      IGRIM=IGRIM+1
      ZBUF1 =ZZW 
      IBUF1 =JI
    ENDIF


    

    IF (IGRIM>0) THEN
      
      ZBUF1 =MAX (1.00001, MIN (REAL (ICEP%NGAMINC)-0.00001, ICEP%XRIMINTP1*LOG (ZBUF1 )+ICEP%XRIMINTP2))
      IBUF2 =INT (ZBUF1 )
      ZBUF1 =ZBUF1 -REAL (IBUF2 )
      
      
      ZBUF2 =ICEP %XGAMINC_RIM1(IBUF2 +1)*ZBUF1 -ICEP %XGAMINC_RIM1(IBUF2 )*(ZBUF1 -1.0)
      
      ZZW1 =0.
      
      ZZW1 =ZBUF2 
      
      
      
      ZBUF2 =ICEP %XGAMINC_RIM2(IBUF2 +1)*ZBUF1 -ICEP %XGAMINC_RIM2(IBUF2 )*(ZBUF1 -1.0)
      
      ZZW2 =0.
      
      ZZW2 =ZBUF2 
      
      
      
      
      ZBUF2 =ICEP %XGAMINC_RIM4(IBUF2 +1)*ZBUF1 -ICEP %XGAMINC_RIM4(IBUF2 )*(ZBUF1 -1.0)
      
      ZZW3 =0.
      
      ZZW3 =ZBUF2 
    
    
    ENDIF

  ELSE
    IGRIM=0

    

    IF (GRIM ) THEN
      IGRIM=IGRIM+1
      ZINDEX=MAX (1.00001, MIN (REAL (ICEP%NGAMINC)-0.00001, ICEP%XRIMINTP1*LOG (ZZW )+ICEP%XRIMINTP2))
      IINDEX=INT (ZINDEX)
      ZINDEX=ZINDEX-REAL (IINDEX)
      ZZW1 =ICEP %XGAMINC_RIM1(IINDEX+1)*ZINDEX-ICEP %XGAMINC_RIM1(IINDEX)*(ZINDEX-1.0)
      
      ZZW2 =ICEP %XGAMINC_RIM2(IINDEX+1)*ZINDEX-ICEP %XGAMINC_RIM2(IINDEX)*(ZINDEX-1.0)
      
      
      ZZW3 =ICEP %XGAMINC_RIM4(IINDEX+1)*ZINDEX-ICEP %XGAMINC_RIM4(IINDEX)*(ZINDEX-1.0)
    
    ELSE
      ZZW1 =0.
      
      ZZW2 =0.
      
      
      ZZW3 =0.
    
    ENDIF

  
  ENDIF


  

  

  IF (IGRIM>0) THEN

    

    IF (.NOT.ICEP%LNEWCOEFF) THEN

      IF (GRIM ) THEN
        PRS_TEND (JI, IRCRIMSS)=ICEP%XCRIMSS*ZZW1 *PRCT (JI)*PCOLF (JI&
        &)*PLBDAS (JI)**ICEP%XEXCRIMSS*PRHODREF (JI)**(-ICED%XCEXVT)
      ENDIF

    ELSE

      IF (GRIM ) THEN
        PRS_TEND (JI, IRCRIMSS)=ICEP%XCRIMSS*ZZW1 *PRCT (JI)*PCOLF (JI)*PRST (JI)*(1+(ICED&
        &%XFVELOS/PLBDAS (JI))**ICED%XALPHAS)**(-ICED%XNUS+ICEP%XEXCRIMSS/ICED%XALPHAS)*PRHODREF&
        & (JI)**(-ICED%XCEXVT+1.)*(PLBDAS (JI))**(ICEP%XEXCRIMSS+ICED%XBS)
      ENDIF

    ENDIF


    

    

    IF (.NOT.ICEP%LNEWCOEFF) THEN

      IF (GRIM ) THEN
        PRS_TEND (JI, IRCRIMS)=ICEP%XCRIMSG*PRCT (JI)*PCOLF (JI)*PLBDAS&
        & (JI)**ICEP%XEXCRIMSG*PRHODREF (JI)**(-ICED%XCEXVT)
      ENDIF

    ELSE

      IF (GRIM ) THEN
        PRS_TEND (JI, IRCRIMS)=ICEP%XCRIMSG*PRCT (JI)*PCOLF (JI)*PRST (JI)*(1+(ICED%XFVELOS&
        &/PLBDAS (JI))**(ICED%XALPHAS))**(-ICED%XNUS+ICEP%XEXCRIMSG/ICED%XALPHAS)*PRHODREF&
        & (JI)**(-ICED%XCEXVT+1.)*PLBDAS (JI)**(ICED%XBS+ICEP%XEXCRIMSG)
      ENDIF

    ENDIF


    

    IF (PARAMI%CSNOWRIMING=='M90 ') THEN

      

      IF (GRIM ) THEN
        ZZW =PRS_TEND (JI, IRCRIMS)-PRS_TEND (JI, IRCRIMSS)
      ENDIF


      IF (.NOT.ICEP%LNEWCOEFF) THEN

        IF (GRIM ) THEN
          PRS_TEND (JI, IRSRIMCG)=ICEP%XSRIMCG*PLBDAS (JI)**ICEP%XEXSRIMCG*(1.0-ZZW2 )
          PRS_TEND (JI, IRSRIMCG)=ZZW *PRS_TEND (JI, IRSRIMCG)/MAX (1.E-20, ICEP%XSRIMCG3*ICEP%XSRIMCG2&
          &*PLBDAS (JI)**ICEP%XEXSRIMCG2*(1.-ZZW3 )-ICEP%XSRIMCG3*PRS_TEND (JI, IRSRIMCG))
        ENDIF

      ELSE

        IF (GRIM ) THEN
          PRS_TEND (JI, IRSRIMCG)=ICEP%XSRIMCG*PRST (JI)*PRHODREF (JI&
          &)*PLBDAS (JI)**(ICEP%XEXSRIMCG+ICED%XBS)*(1.0-ZZW2 )
          PRS_TEND (JI, IRSRIMCG)=ZZW *PRS_TEND (JI, IRSRIMCG)/MAX (1.E-20, ICEP%XSRIMCG3*ICEP%XSRIMCG2*PRST (JI&
          &)*PRHODREF (JI)*PLBDAS (JI)**ICEP%XEXSRIMCG2*(1.-ZZW3 )-ICEP%XSRIMCG3*PRS_TEND (JI, IRSRIMCG))
        ENDIF

      ENDIF

    
    ELSE
      PRS_TEND (JI, IRSRIMCG)=0.
    ENDIF

  ENDIF

ENDIF



IF (GRIM .AND.PT (JI)<CST%XTT) THEN
  PRCRIMSS (JI)=MIN (ZFREEZ_RATE , PRS_TEND (JI, IRCRIMSS))
  ZFREEZ_RATE =MAX (0., ZFREEZ_RATE -PRCRIMSS (JI))
  ZZW0D=MIN (1., ZFREEZ_RATE /MAX (1.E-20, PRS_TEND (JI, IRCRIMS)-PRCRIMSS (JI)))
  PRCRIMSG (JI)=ZZW0D*MAX (0., PRS_TEND (JI, IRCRIMS)-PRCRIMSS (JI))
  ZFREEZ_RATE =MAX (0., ZFREEZ_RATE -PRCRIMSG (JI))
  PRSRIMCG (JI)=ZZW0D*PRS_TEND (JI, IRSRIMCG)
  PRSRIMCG (JI)=PRSRIMCG (JI)*MAX (0.,-SIGN (1.,-PRCRIMSG (JI)))
  PRCRIMSG (JI)=MAX (0., PRCRIMSG (JI))
ELSE
  PRCRIMSS (JI)=0.
  PRCRIMSG (JI)=0.
  PRSRIMCG (JI)=0.
ENDIF




IF (PRRT (JI)>ICED%XRTMIN (3).AND.PRST (JI)>ICED%XRTMIN (5).AND.LDCOMPUTE (JI)) THEN
  GACC =.TRUE.
ELSE
  GACC =.FALSE.
  PRS_TEND (JI, IRRACCS)=0.
  PRS_TEND (JI, IRRACCSS)=0.
  PRS_TEND (JI, IRSACCRG)=0.
ENDIF



IF (.NOT.LDSOFT) THEN
  PRS_TEND (JI, IRRACCS)=0.
  PRS_TEND (JI, IRRACCSS)=0.
  PRS_TEND (JI, IRSACCRG)=0.

  

  IF (PARAMI%LPACK_INTERP) THEN
    IGACC=0

    

    IF (GACC ) THEN
      IGACC=IGACC+1
      ZBUF1 =PLBDAS (JI)
      ZBUF2 =PLBDAR (JI)
      IBUF3 =JI
    ENDIF


    

    IF (IGACC>0) THEN
      
      ZBUF1 =MAX (1.00001, MIN (REAL (ICEP%NACCLBDAS)-0.00001&
      &, ICEP%XACCINTP1S*LOG (ZBUF1 )+ICEP%XACCINTP2S))
      IBUF1 =INT (ZBUF1 )
      ZBUF1 =ZBUF1 -REAL (IBUF1 )
      ZBUF2 =MAX (1.00001, MIN (REAL (ICEP%NACCLBDAR)-0.00001&
      &, ICEP%XACCINTP1R*LOG (ZBUF2 )+ICEP%XACCINTP2R))
      IBUF2 =INT (ZBUF2 )
      ZBUF2 =ZBUF2 -REAL (IBUF2 )
      
      
      ZBUF3 =(ICEP %XKER_RACCSS(IBUF1 +1, IBUF2 +1)*ZBUF2 -ICEP %XKER_RACCSS(IBUF1&
      & +1, IBUF2 )*(ZBUF2 -1.0))*ZBUF1 -(ICEP %XKER_RACCSS(IBUF1 , IBUF2 +1)*ZBUF2&
      & -ICEP %XKER_RACCSS(IBUF1 , IBUF2 )*(ZBUF2 -1.0))*(ZBUF1 -1.0)
      
      ZZW1 =0.
      
      ZZW1 =ZBUF3 
      
      
      
      ZBUF3 =(ICEP %XKER_RACCS(IBUF1 +1, IBUF2 +1)*ZBUF2 -ICEP %XKER_RACCS(IBUF1&
      & +1, IBUF2 )*(ZBUF2 -1.0))*ZBUF1 -(ICEP %XKER_RACCS(IBUF1 , IBUF2 +1)*ZBUF2&
      & -ICEP %XKER_RACCS(IBUF1 , IBUF2 )*(ZBUF2 -1.0))*(ZBUF1 -1.0)
      
      ZZW2 =0.
      
      ZZW2 =ZBUF3 
      
      
      
      
      ZBUF3 =(ICEP %XKER_SACCRG(IBUF2 +1, IBUF1 +1)*ZBUF1 -ICEP %XKER_SACCRG(IBUF2&
      & +1, IBUF1 )*(ZBUF1 -1.0))*ZBUF2 -(ICEP %XKER_SACCRG(IBUF2 , IBUF1 +1)*ZBUF1&
      & -ICEP %XKER_SACCRG(IBUF2 , IBUF1 )*(ZBUF1 -1.0))*(ZBUF2 -1.0)
      
      ZZW3 =0.
      
      ZZW3 =ZBUF3 
    
    
    ENDIF

  ELSE
    IGACC=0

    

    IF (GACC ) THEN
      IGACC=IGACC+1
      ZINDEX1=MAX (1.00001, MIN (REAL (ICEP%NACCLBDAS)-0.00001&
      &, ICEP%XACCINTP1S*LOG (PLBDAS (JI))+ICEP%XACCINTP2S))
      IINDEX1=INT (ZINDEX1)
      ZINDEX1=ZINDEX1-REAL (IINDEX1)
      ZINDEX2=MAX (1.00001, MIN (REAL (ICEP%NACCLBDAS)-0.00001&
      &, ICEP%XACCINTP1R*LOG (PLBDAR (JI))+ICEP%XACCINTP2R))
      IINDEX2=INT (ZINDEX2)
      ZINDEX2=ZINDEX2-REAL (IINDEX2)
      ZZW1 =(ICEP %XKER_RACCSS(IINDEX1+1, IINDEX2+1)*ZINDEX2-ICEP %XKER_RACCSS(IINDEX1&
      &+1, IINDEX2)*(ZINDEX2-1.0))*ZINDEX1-(ICEP %XKER_RACCSS(IINDEX1, IINDEX2+1)*ZINDEX2&
      &-ICEP %XKER_RACCSS(IINDEX1, IINDEX2)*(ZINDEX2-1.0))*(ZINDEX1-1.0)
      
      ZZW2 =(ICEP %XKER_RACCS(IINDEX1+1, IINDEX2+1)*ZINDEX2-ICEP %XKER_RACCS(IINDEX1&
      &+1, IINDEX2)*(ZINDEX2-1.0))*ZINDEX1-(ICEP %XKER_RACCS(IINDEX1, IINDEX2+1)*ZINDEX2&
      &-ICEP %XKER_RACCS(IINDEX1, IINDEX2)*(ZINDEX2-1.0))*(ZINDEX1-1.0)
      
      
      ZZW3 =(ICEP %XKER_SACCRG(IINDEX2+1, IINDEX1+1)*ZINDEX1-ICEP %XKER_SACCRG(IINDEX2&
      &+1, IINDEX1)*(ZINDEX1-1.0))*ZINDEX2-(ICEP %XKER_SACCRG(IINDEX2, IINDEX1+1)*ZINDEX1&
      &-ICEP %XKER_SACCRG(IINDEX2, IINDEX1)*(ZINDEX1-1.0))*(ZINDEX2-1.0)
    
    ELSE
      ZZW1 =0.
      
      ZZW2 =0.
      
      
      ZZW3 =0.
    
    ENDIF

  
  ENDIF


  

  

  IF (IGACC>0) THEN

    

    IF (.NOT.ICEP%LNEWCOEFF) THEN

      IF (GACC ) THEN
        ZZW =ICEP%XFRACCSS*(PLBDAS (JI)**ICED%XCXS)*(PRHODREF (JI)**(-ICED%XCEXVT&
        &-1.))*(ICEP%XLBRACCS1/((PLBDAS (JI)**2))+ICEP%XLBRACCS2/(PLBDAS (JI)*PLBDAR&
        & (JI))+ICEP%XLBRACCS3/((PLBDAR (JI)**2)))/PLBDAR (JI)**4
      ENDIF

    ELSE

      IF (GACC ) THEN
        ZZW =ICEP%XFRACCSS*(PRST (JI)*PLBDAS (JI)**ICED%XBS)*(PRHODREF (JI)**(-ICED&
        &%XCEXVT))*(ICEP%XLBRACCS1/((PLBDAS (JI)**2))+ICEP%XLBRACCS2/(PLBDAS (JI&
        &)*PLBDAR (JI))+ICEP%XLBRACCS3/((PLBDAR (JI)**2)))/PLBDAR (JI)**4
      ENDIF

    ENDIF


    IF (GACC ) THEN
      PRS_TEND (JI, IRRACCSS)=ZZW1 *ZZW 
    ENDIF


    IF (PARAMI%LOCND2) THEN

      IF (GACC ) THEN
        PRS_TEND (JI, IRRACCSS)=PRS_TEND (JI, IRRACCSS)*ICEP%XFRMIN (7)
      ENDIF

    ENDIF


    

    

    IF (GACC ) THEN
      PRS_TEND (JI, IRRACCS)=ZZW2 *ZZW 
    ENDIF


    

    

    IF (.NOT.ICEP%LNEWCOEFF) THEN

      IF (GACC .AND.(.NOT.PARAMI%LOCND2.OR.PRST (JI)>ICEP%XFRMIN (1))) THEN
        PRS_TEND (JI, IRSACCRG)=ICEP%XFSACCRG*ZZW3 *(PLBDAS (JI)**(ICED%XCXS-ICED%XBS))*(PRHODREF&
        & (JI)**(-ICED%XCEXVT-1.))*(ICEP%XLBSACCR1/((PLBDAR (JI)**2))+ICEP%XLBSACCR2/(PLBDAR&
        & (JI)*PLBDAS (JI))+ICEP%XLBSACCR3/((PLBDAS (JI)**2)))/PLBDAR (JI)
      ENDIF

    ELSE

      IF (GACC .AND.(.NOT.PARAMI%LOCND2.OR.PRST (JI)>ICEP%XFRMIN (1))) THEN
        PRS_TEND (JI, IRSACCRG)=ICEP%XFSACCRG*ZZW3 *(PRST (JI))*(PRHODREF (JI)**&
        &(-ICED%XCEXVT))*(ICEP%XLBSACCR1/((PLBDAR (JI)**2))+ICEP%XLBSACCR2/(PLBDAR&
        & (JI)*PLBDAS (JI))+ICEP%XLBSACCR3/((PLBDAS (JI)**2)))/PLBDAR (JI)
      ENDIF

    ENDIF

  
  ENDIF

ENDIF



IF (GACC .AND.PT (JI)<CST%XTT) THEN
  PRRACCSS (JI)=MIN (ZFREEZ_RATE , PRS_TEND (JI, IRRACCSS))
  ZFREEZ_RATE =MAX (0., ZFREEZ_RATE -PRRACCSS (JI))
  ZZW =MIN (1., ZFREEZ_RATE /MAX (1.E-20, PRS_TEND (JI, IRRACCS)-PRRACCSS (JI)))
  PRRACCSG (JI)=ZZW *MAX (0., PRS_TEND (JI, IRRACCS)-PRRACCSS (JI))
  ZFREEZ_RATE =MAX (0., ZFREEZ_RATE -PRRACCSG (JI))
  PRSACCRG (JI)=ZZW *PRS_TEND (JI, IRSACCRG)
  PRSACCRG (JI)=PRSACCRG (JI)*MAX (0.,-SIGN (1.,-PRRACCSG (JI)))
  PRRACCSG (JI)=MAX (0., PRRACCSG (JI))
ELSE
  PRRACCSS (JI)=0.
  PRRACCSG (JI)=0.
  PRSACCRG (JI)=0.
ENDIF




IF (PRST (JI)>ICED%XRTMIN (5).AND.PT (JI)>CST%XTT.AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRSMLTG (JI)=PRVT (JI)*PPRES (JI)/(CST%XEPSILO+PRVT (JI))

    IF (PARAMI%LEVLIMIT) THEN
      PRSMLTG (JI)=MIN (PRSMLTG (JI), EXP (CST%XALPW-CST%XBETAW/PT (JI)-CST%XGAMW*LOG (PT (JI))))
    ENDIF

    PRSMLTG (JI)=PKA (JI)*(CST%XTT-PT (JI))+(PDV (JI)*(CST%XLVTT+(CST%XCPV-CST&
    &%XCL)*(PT (JI)-CST%XTT))*(CST%XESTT-PRSMLTG (JI))/(CST%XRV*PT (JI)))

    IF (.NOT.ICEP%LNEWCOEFF) THEN
      PRSMLTG (JI)=ICEP%XFSCVMG*MAX (0.,(-PRSMLTG (JI)*(ICEP%X0DEPS*PLBDAS (JI)**ICEP%XEX0DEPS&
      &+ICEP%X1DEPS*PCJ (JI)*PLBDAS (JI)**ICEP%XEX1DEPS)-(PRS_TEND (JI, IRCRIMS)+PRS_TEND (JI&
      &, IRRACCS))*(PRHODREF (JI)*CST%XCL*(CST%XTT-PT (JI))))/(PRHODREF (JI)*CST%XLMTT))
    ELSE
      PRSMLTG (JI)=ICEP%XFSCVMG*MAX (0.,(-PRSMLTG (JI)*PRST (JI)*PRHODREF (JI)*(ICEP%X0DEPS*PLBDAS (JI)**&
