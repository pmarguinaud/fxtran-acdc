MODULE UTIL_TIWMX_T_CRC64_MOD
USE MODD_TIWMX, ONLY : TIWMX_T
INTERFACE ACDC_CRC64
MODULE PROCEDURE ACDC_CRC64_TIWMX_T
END INTERFACE

CONTAINS
SUBROUTINE ACDC_CRC64_TIWMX_T (SELF, KLUN, CDPATH)
USE FXTRAN_ACDC_CRC64_INTRINSIC_MOD, ONLY : FCRC64 => FXTRAN_ACDC_CRC64
IMPLICIT NONE
TYPE (TIWMX_T), TARGET :: SELF
INTEGER, INTENT (IN) :: KLUN
CHARACTER(LEN=*), INTENT (IN) :: CDPATH
CHARACTER(LEN=128) :: CLIND
WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%ESTABW), CDPATH//'%ESTABW'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%DESTABW), CDPATH//'%DESTABW'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%ESTABI), CDPATH//'%ESTABI'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%DESTABI), CDPATH//'%DESTABI'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%A2TAB), CDPATH//'%A2TAB'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%BB3TAB), CDPATH//'%BB3TAB'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%AM3TAB), CDPATH//'%AM3TAB'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%AF3TAB), CDPATH//'%AF3TAB'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%A2WTAB), CDPATH//'%A2WTAB'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%BB3WTAB), CDPATH//'%BB3WTAB'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%REDINTAB), CDPATH//'%REDINTAB'

END SUBROUTINE
END MODULE
