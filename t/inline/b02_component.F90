SUBROUTINE B02_COMPONENT (KIDIA, KFDIA, KLEV, YDCFU, YDMF)
USE TYPES_MOD, ONLY : TCFU, TMF
INTEGER, INTENT (IN) :: KIDIA, KFDIA, KLEV
TYPE (TCFU), INTENT (INOUT) :: YDCFU
TYPE (TMF), INTENT (INOUT) :: YDMF
CALL S (KIDIA, KFDIA, KLEV, YDCFU%QTOT, YDCFU%YSTRDU, YDMF%FEVL (:, 1), YDCFU%NFRRC)
CONTAINS
SUBROUTINE S (KIDIA, KFDIA, KLEV, PXFU, YDDESC, PPHY0, KTIME)
USE TYPES_MOD, ONLY : TDESC
INTEGER, INTENT (IN) :: KIDIA, KFDIA, KLEV
REAL, INTENT (INOUT) :: PXFU (:)
TYPE (TDESC), INTENT (IN) :: YDDESC
REAL, INTENT (INOUT) :: PPHY0 (:)
INTEGER, INTENT (IN) :: KTIME
INTEGER :: JLEV
PXFU (KIDIA:KFDIA) = 0.
DO JLEV = 1, KLEV
  PXFU (KIDIA:KFDIA) = PXFU (KIDIA:KFDIA) + REAL (YDDESC%INUMLEV (JLEV))
ENDDO
PPHY0 (KIDIA:KFDIA) = REAL (KTIME)
END SUBROUTINE
END SUBROUTINE
