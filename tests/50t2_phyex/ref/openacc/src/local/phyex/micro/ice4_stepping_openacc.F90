
SUBROUTINE ICE4_STEPPING_OPENACC (D, CST, PARAMI, ICEP, ICED, BUCONF, PTSTEP, KRR&
&, OSAVE_MICRO, LDMICRO, OELEC, PEXN, PRHODREF, PPABST, PCIT, PCLDFR, PHLC_HCF, PHLC_HRC&
&, PHLI_HCF, PHLI_HRI, PTHS, PRS, PRREVAV, PRAINFR, PSIGS, PTHT, PRT, PICLDFR, PZZZ&
&, PCONC3D, PSSIO, PSSIU, PIFR, PBUDGETS, PLATHAM_IAGGS, YDSTACK)
!$ACC ROUTINE (ICE4_STEPPING_OPENACC) SEQ      


USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_BUDGET,ONLY:TBUDGETCONF_T
USE MODD_CST,ONLY:CST_T
USE MODD_PARAM_ICE_N,ONLY:PARAM_ICE_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T
USE MODD_RAIN_ICE_PARAM_N,ONLY:RAIN_ICE_PARAM_T
USE MODD_FIELDS_ADDRESS,ONLY:IRV, IRC, IRR, IRI, IBUNUM&
&, IBUNUM_MR, IBUNUM_EXTRA, IRREVAV, IBUEXTRAIND
USE MODE_ICE4_TENDENCIES,ONLY:ICE4_TENDENCIES
USE MODE_ICE4_TENDENCIES_OPENACC, ONLY : ICE4_TENDENCIES_OPENACC
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (DIMPHYEX_T), INTENT (IN)::D
TYPE (CST_T), INTENT (IN)::CST
TYPE (PARAM_ICE_T), INTENT (IN)::PARAMI
TYPE (RAIN_ICE_PARAM_T), INTENT (IN)::ICEP
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
TYPE (TBUDGETCONF_T), INTENT (IN)::BUCONF
REAL, INTENT (IN)::PTSTEP
INTEGER, INTENT (IN)::KRR
LOGICAL, INTENT (IN)::OSAVE_MICRO
LOGICAL, INTENT (IN)::LDMICRO(D%NIJT)
LOGICAL, INTENT (IN)::OELEC
REAL, INTENT (IN)::PEXN(D%NIJT)
REAL, INTENT (IN)::PRHODREF(D%NIJT)
REAL, INTENT (IN)::PPABST(D%NIJT)
REAL, INTENT (INOUT)::PCIT(D%NIJT)
REAL, INTENT (IN)::PCLDFR(D%NIJT)
REAL, INTENT (IN)::PICLDFR(D%NIJT)
REAL, INTENT (IN)::PZZZ(D%NIJT)
REAL, INTENT (IN)::PCONC3D(D%NIJT)
REAL, INTENT (IN)::PSSIO(D%NIJT)
REAL, INTENT (IN)::PSSIU(D%NIJT)
REAL, INTENT (IN)::PIFR(D%NIJT)
REAL, INTENT (INOUT)::PHLI_HCF(MERGE (D%NIJT, 0, PARAMI%CSUBG_AUCV_RC&
&=='ADJU'.OR.PARAMI%CSUBG_AUCV_RI=='ADJU'))
REAL, INTENT (INOUT)::PHLI_HRI(MERGE (D%NIJT, 0, PARAMI%CSUBG_AUCV_RC&
&=='ADJU'.OR.PARAMI%CSUBG_AUCV_RI=='ADJU'))
REAL, INTENT (INOUT)::PHLC_HCF(MERGE (D%NIJT, 0, PARAMI%CSUBG_AUCV_RC&
&=='ADJU'.OR.PARAMI%CSUBG_AUCV_RI=='ADJU'))
REAL, INTENT (INOUT)::PHLC_HRC(MERGE (D%NIJT, 0, PARAMI%CSUBG_AUCV_RC&
&=='ADJU'.OR.PARAMI%CSUBG_AUCV_RI=='ADJU'))
REAL, INTENT (IN)::PTHS(MERGE (D%NIJT, 0, PARAMI%LEXT_TEND))
REAL, INTENT (IN)::PRS(MERGE (D%NIJT, 0, PARAMI%LEXT_TEND), 7)
REAL, INTENT (OUT)::PRREVAV(D%NIJT)
REAL, INTENT (INOUT)::PRAINFR(D%NIJT)
REAL, INTENT (IN)::PSIGS(MERGE (D%NIJT, 0, PARAMI%CSUBG_AUCV_RC&
&=='PDF '.AND.PARAMI%CSUBG_PR_PDF=='SIGM'))
REAL, INTENT (INOUT)::PTHT(D%NIJT)
REAL, INTENT (INOUT)::PRT(D%NIJT, 7)
REAL, INTENT (OUT)::PBUDGETS(MERGE (D%NIJT, 0, BUCONF%LBU_ENABLE.OR.OSAVE_MICRO&
&), MERGE (IBUNUM-IBUNUM_EXTRA, 0, BUCONF%LBU_ENABLE.OR.OSAVE_MICRO))
REAL, INTENT (IN)::PLATHAM_IAGGS(MERGE (D%NIJT, 0, OELEC))
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
TYPE(FXTRAN_ACDC_STACK) :: YLSTACK

LOGICAL::LSOFT
INTEGER::INB_ITER_MAX
REAL::ZTSTEP
REAL::ZINV_TSTEP
REAL::ZTIME_THRESHOLD
INTEGER::JJV
INTEGER::JV
INTEGER::JI
REAL::ZEXTTH
fxtran_acdc_temp (REAL, ZSIGMA_RC, (D%NIJT))
fxtran_acdc_temp (REAL, ZHLI_LRI, (D%NIJT))
fxtran_acdc_temp (REAL, ZHLI_LCF, (D%NIJT))
fxtran_acdc_temp (REAL, ZHLC_LRC, (D%NIJT))
fxtran_acdc_temp (REAL, ZHLC_LCF, (D%NIJT))
fxtran_acdc_temp (REAL, ZLVFACT, (D%NIJT))
fxtran_acdc_temp (REAL, ZLSFACT, (D%NIJT))
fxtran_acdc_temp (REAL, ZZT, (D%NIJT))
fxtran_acdc_temp (REAL, ZSSI, (D%NIJT))
REAL::ZTIME_LASTCALL
REAL::ZMAXTIME
REAL::ZTIME
REAL::ZEXTPK(7)
fxtran_acdc_temp (LOGICAL, LLCOMPUTE, (D%NIJT))
REAL::ZRSMIN(SIZE (ICED%XRTMIN))
fxtran_acdc_temp (REAL, ZBU_INST, (D%NIJT, IBUNUM))
LOGICAL::LLCPZ0RT
REAL::ZTIME_THRESHOLD1D 
fxtran_acdc_temp (REAL, Z0RT, (D%NIJT, KRR))
fxtran_acdc_temp (REAL, ZB, (D%NIJT, KRR))
fxtran_acdc_temp (REAL, ZA, (D%NIJT, KRR))
fxtran_acdc_temp (REAL, ZBTH, (D%NIJT))
fxtran_acdc_temp (REAL, ZATH, (D%NIJT))
fxtran_acdc_temp (REAL, ZRG_TEND, (D%NIJT, 8))
fxtran_acdc_temp (REAL, ZRS_TEND, (D%NIJT, 8))
fxtran_acdc_temp (REAL, ZRH_TEND, (D%NIJT, 10))
INTEGER::IITER
REAL::ZMAXB
REAL::ZSUM2
REAL::ZX
REAL::ZDEVIDE
LOGICAL::LL_ANY_ITER

YLSTACK = YDSTACK



IF (KIND (ZSIGMA_RC) == 8) THEN
    fxtran_acdc_alloc8 (ZSIGMA_RC)
ELSEIF (KIND (ZSIGMA_RC) == 4) THEN
    fxtran_acdc_alloc4 (ZSIGMA_RC)
ELSE
    STOP 1
ENDIF


IF (KIND (ZHLI_LRI) == 8) THEN
    fxtran_acdc_alloc8 (ZHLI_LRI)
ELSEIF (KIND (ZHLI_LRI) == 4) THEN
    fxtran_acdc_alloc4 (ZHLI_LRI)
ELSE
    STOP 1
ENDIF


IF (KIND (ZHLI_LCF) == 8) THEN
    fxtran_acdc_alloc8 (ZHLI_LCF)
ELSEIF (KIND (ZHLI_LCF) == 4) THEN
    fxtran_acdc_alloc4 (ZHLI_LCF)
ELSE
    STOP 1
ENDIF


IF (KIND (ZHLC_LRC) == 8) THEN
    fxtran_acdc_alloc8 (ZHLC_LRC)
ELSEIF (KIND (ZHLC_LRC) == 4) THEN
    fxtran_acdc_alloc4 (ZHLC_LRC)
ELSE
    STOP 1
ENDIF


IF (KIND (ZHLC_LCF) == 8) THEN
    fxtran_acdc_alloc8 (ZHLC_LCF)
ELSEIF (KIND (ZHLC_LCF) == 4) THEN
    fxtran_acdc_alloc4 (ZHLC_LCF)
ELSE
    STOP 1
ENDIF


IF (KIND (ZLVFACT) == 8) THEN
    fxtran_acdc_alloc8 (ZLVFACT)
ELSEIF (KIND (ZLVFACT) == 4) THEN
    fxtran_acdc_alloc4 (ZLVFACT)
ELSE
    STOP 1
ENDIF


IF (KIND (ZLSFACT) == 8) THEN
    fxtran_acdc_alloc8 (ZLSFACT)
ELSEIF (KIND (ZLSFACT) == 4) THEN
    fxtran_acdc_alloc4 (ZLSFACT)
ELSE
    STOP 1
ENDIF


IF (KIND (ZZT) == 8) THEN
    fxtran_acdc_alloc8 (ZZT)
ELSEIF (KIND (ZZT) == 4) THEN
    fxtran_acdc_alloc4 (ZZT)
ELSE
    STOP 1
ENDIF


IF (KIND (ZSSI) == 8) THEN
    fxtran_acdc_alloc8 (ZSSI)
ELSEIF (KIND (ZSSI) == 4) THEN
    fxtran_acdc_alloc4 (ZSSI)
ELSE
    STOP 1
ENDIF


IF (KIND (LLCOMPUTE) == 8) THEN
    fxtran_acdc_alloc8 (LLCOMPUTE)
ELSEIF (KIND (LLCOMPUTE) == 4) THEN
    fxtran_acdc_alloc4 (LLCOMPUTE)
ELSE
    STOP 1
ENDIF


IF (KIND (ZBU_INST) == 8) THEN
    fxtran_acdc_alloc8 (ZBU_INST)
ELSEIF (KIND (ZBU_INST) == 4) THEN
    fxtran_acdc_alloc4 (ZBU_INST)
ELSE
    STOP 1
ENDIF


IF (KIND (Z0RT) == 8) THEN
    fxtran_acdc_alloc8 (Z0RT)
ELSEIF (KIND (Z0RT) == 4) THEN
    fxtran_acdc_alloc4 (Z0RT)
ELSE
    STOP 1
ENDIF


IF (KIND (ZB) == 8) THEN
    fxtran_acdc_alloc8 (ZB)
ELSEIF (KIND (ZB) == 4) THEN
    fxtran_acdc_alloc4 (ZB)
ELSE
    STOP 1
ENDIF


IF (KIND (ZA) == 8) THEN
    fxtran_acdc_alloc8 (ZA)
ELSEIF (KIND (ZA) == 4) THEN
    fxtran_acdc_alloc4 (ZA)
ELSE
    STOP 1
ENDIF


IF (KIND (ZBTH) == 8) THEN
    fxtran_acdc_alloc8 (ZBTH)
ELSEIF (KIND (ZBTH) == 4) THEN
    fxtran_acdc_alloc4 (ZBTH)
ELSE
    STOP 1
ENDIF


IF (KIND (ZATH) == 8) THEN
    fxtran_acdc_alloc8 (ZATH)
ELSEIF (KIND (ZATH) == 4) THEN
    fxtran_acdc_alloc4 (ZATH)
ELSE
    STOP 1
ENDIF


IF (KIND (ZRG_TEND) == 8) THEN
    fxtran_acdc_alloc8 (ZRG_TEND)
ELSEIF (KIND (ZRG_TEND) == 4) THEN
    fxtran_acdc_alloc4 (ZRG_TEND)
ELSE
    STOP 1
ENDIF


IF (KIND (ZRS_TEND) == 8) THEN
    fxtran_acdc_alloc8 (ZRS_TEND)
ELSEIF (KIND (ZRS_TEND) == 4) THEN
    fxtran_acdc_alloc4 (ZRS_TEND)
ELSE
    STOP 1
ENDIF


IF (KIND (ZRH_TEND) == 8) THEN
    fxtran_acdc_alloc8 (ZRH_TEND)
ELSEIF (KIND (ZRH_TEND) == 4) THEN
    fxtran_acdc_alloc4 (ZRH_TEND)
ELSE
    STOP 1
ENDIF


JI = D%NIB


#ifdef MNH_COMPILER_CCE
#endif
ZINV_TSTEP=1./PTSTEP
ZRSMIN=ICED%XRTMIN

IF (BUCONF%LBU_ENABLE.OR.OSAVE_MICRO) THEN

  DO JV=1, IBUNUM-IBUNUM_EXTRA
    PBUDGETS (JI, JV)=0.
  ENDDO

ENDIF

INB_ITER_MAX=PARAMI%NMAXITER_MICRO

IF (PARAMI%XTSTEP_TS/=0.) THEN
  INB_ITER_MAX=MAX (1, INT (PTSTEP/PARAMI%XTSTEP_TS))
  ZTSTEP=PTSTEP/INB_ITER_MAX
  INB_ITER_MAX=MAX (PARAMI%NMAXITER_MICRO, INB_ITER_MAX)
ENDIF


IF (PARAMI%LEXT_TEND) THEN
  
  ZEXTTH =PTHS (JI)-PTHT (JI)*ZINV_TSTEP

  

  DO JV=1, KRR
    
    ZEXTPK (JV)=PRS (JI, JV)-PRT (JI, JV)*ZINV_TSTEP
  
  ENDDO

ENDIF


IF (PARAMI%CSUBG_AUCV_RC=='PDF '.AND.PARAMI%CSUBG_PR_PDF=='SIGM') THEN
  
  ZSIGMA_RC (JI)=PSIGS (JI)*2.
  
ENDIF


IF (PARAMI%CSUBG_AUCV_RC=='ADJU'.OR.PARAMI%CSUBG_AUCV_RI=='ADJU') THEN
  
  ZHLC_LRC (JI)=PRT (JI, IRC)-PHLC_HRC (JI)
  ZHLI_LRI (JI)=PRT (JI, IRI)-PHLI_HRI (JI)

  IF (PRT (JI, IRC)>0.) THEN
    ZHLC_LCF (JI)=PCLDFR (JI)-PHLC_HCF (JI)
  ELSE
    ZHLC_LCF (JI)=0.
  ENDIF


  IF (PRT (JI, IRI)>0.) THEN
    ZHLI_LCF (JI)=PCLDFR (JI)-PHLI_HCF (JI)
  ELSE
    ZHLI_LCF (JI)=0.
  ENDIF

  
ENDIF

IITER =0


IF (LDMICRO (JI)) THEN
  ZTIME =0.
ELSE
  ZTIME =PTSTEP
ENDIF



DO WHILE (ZTIME <PTSTEP)

  IF (PARAMI%XTSTEP_TS/=0.) THEN
    ZTIME_LASTCALL =ZTIME 
  ENDIF


  

  IF (ZTIME <PTSTEP) THEN
    LLCOMPUTE (JI)=.TRUE.
    IITER =IITER +1
  ELSE
    LLCOMPUTE (JI)=.FALSE.
  ENDIF

  
  LL_ANY_ITER=IITER <INB_ITER_MAX
  LLCPZ0RT=.TRUE.
  LSOFT=.FALSE.

  DO WHILE (LLCOMPUTE (JI))
    ZSUM2 =PRT (JI, IRI)

    DO JV=IRI+1, KRR
      
      ZSUM2 =ZSUM2 +PRT (JI, JV)
    
    ENDDO

    
    ZDEVIDE=(CST%XCPD+CST%XCPV*PRT (JI, IRV)+CST%XCL*(PRT &
    &(JI, IRC)+PRT (JI, IRR))+CST%XCI*ZSUM2 )*PEXN (JI)
    ZZT (JI)=PTHT (JI)*PEXN (JI)
    ZLSFACT (JI)=(CST%XLSTT+(CST%XCPV-CST%XCI)*(ZZT (JI)-CST%XTT))/ZDEVIDE
    ZLVFACT (JI)=(CST%XLVTT+(CST%XCPV-CST%XCL)*(ZZT (JI)-CST%XTT))/ZDEVIDE
    
    CALL ICE4_TENDENCIES_OPENACC (CST, PARAMI, ICEP, ICED, BUCONF, D, KRR, LSOFT, LLCOMPUTE&
    &, OSAVE_MICRO, OELEC, PEXN, PRHODREF, ZLVFACT, ZLSFACT, PPABST, PCLDFR, ZSIGMA_RC, PCIT&
    &, ZZT, PICLDFR, PZZZ, PCONC3D, PSSIO, PSSIU, PIFR, PTHT, PRT, PLATHAM_IAGGS, ZBU_INST&
    &, ZRS_TEND, ZRG_TEND, ZRH_TEND, ZSSI, ZA, ZB, ZATH, ZBTH, PHLC_HCF, ZHLC_LCF, PHLC_HRC&
    &, ZHLC_LRC, PHLI_HCF, ZHLI_LCF, PHLI_HRI, ZHLI_LRI, PRAINFR, YDSTACK=YLSTACK)

    IF (PARAMI%LEXT_TEND) THEN
      
      ZATH (JI)=ZATH (JI)+ZEXTTH 

      

      DO JV=1, KRR
        
        ZA (JI, JV)=ZA (JI, JV)+ZEXTPK (JV)
      
      ENDDO

    ENDIF


    

    IF (LLCOMPUTE (JI)) THEN
      ZMAXTIME =(PTSTEP-ZTIME )
    ELSE
      ZMAXTIME =0.
    ENDIF


    

    IF (PARAMI%LFEEDBACKT) THEN
      
      ZX=CST%XTT/PEXN (JI)

      IF ((PTHT (JI)-ZX)*(PTHT (JI)+ZBTH (JI)-ZX)<0.) THEN
        ZMAXTIME =0.
      ENDIF


      IF (ABS (ZATH (JI))>1.E-20) THEN
        ZTIME_THRESHOLD=(ZX-ZBTH (JI)-PTHT (JI))/ZATH (JI)

        IF (ZTIME_THRESHOLD>0.) THEN
          ZMAXTIME =MIN (ZMAXTIME , ZTIME_THRESHOLD)
        ENDIF

      ENDIF

    
    ENDIF


    DO JV=1, KRR

      

      IF (ZA (JI, JV)<-1.E-20.AND.PRT (JI, JV)>ZRSMIN (JV)) THEN
        ZMAXTIME =MIN (ZMAXTIME ,-(ZB (JI, JV)+PRT (JI, JV))/ZA (JI, JV))
        ZMAXTIME =MAX (ZMAXTIME , CST%XMNH_TINY)
      ENDIF

    
    ENDDO


    

    IF (ZTIME +ZMAXTIME >=PTSTEP) THEN
      LLCOMPUTE (JI)=.FALSE.
    ENDIF


    

    IF (PARAMI%XTSTEP_TS/=0.) THEN

      

      IF ((IITER <INB_ITER_MAX).AND.(ZTIME +ZMAXTIME >ZTIME_LASTCALL +ZTSTEP)) THEN
        ZMAXTIME =ZTIME_LASTCALL -ZTIME +ZTSTEP
        LLCOMPUTE (JI)=.FALSE.
      ENDIF

    
    ENDIF


    IF (PARAMI%XMRSTEP/=0.) THEN

      IF (LL_ANY_ITER) THEN

        DO JV=1, KRR

          IF (LLCPZ0RT) THEN
            Z0RT (JI, JV)=PRT (JI, JV)
          ENDIF


          

          IF (IITER <INB_ITER_MAX.AND.ABS (ZA (JI, JV))>1.E-20) THEN
            ZTIME_THRESHOLD1D =(SIGN (1., ZA (JI, JV))*PARAMI%XMRSTEP&
            &+Z0RT (JI, JV)-PRT (JI, JV)-ZB (JI, JV))/ZA (JI, JV)
          ELSE
            ZTIME_THRESHOLD1D =-1.
          ENDIF


          

          

          IF (ZTIME_THRESHOLD1D >=0.AND.ZTIME_THRESHOLD1D <ZMAXTIME &
            &.AND.(PRT (JI, JV)>ZRSMIN (JV).OR.ZA (JI, JV)>0.)) THEN
            ZMAXTIME =MIN (ZMAXTIME , ZTIME_THRESHOLD1D )
            LLCOMPUTE (JI)=.FALSE.
          ENDIF


          

          IF (JV==1) THEN
            
            ZMAXB =ABS (ZB (JI, JV))
          
          ELSE
            
            ZMAXB =MAX (ZMAXB , ABS (ZB (JI, JV)))
          
          ENDIF

        ENDDO

        LLCPZ0RT=.FALSE.

        

        IF (IITER <INB_ITER_MAX.AND.ZMAXB >PARAMI%XMRSTEP) THEN
          ZMAXTIME =0.
          LLCOMPUTE (JI)=.FALSE.
        ENDIF

      
      ENDIF

    ENDIF


    

    IF (LDMICRO (JI)) THEN
      PTHT (JI)=PTHT (JI)+ZATH (JI)*ZMAXTIME +ZBTH (JI)
    ENDIF


    

    DO JV=1, KRR

      

      IF (LDMICRO (JI)) THEN
        PRT (JI, JV)=PRT (JI, JV)+ZA (JI, JV)*ZMAXTIME +ZB (JI, JV)
      ENDIF

    
    ENDDO


    

    IF (PRT (JI, IRI)<=0..AND.LDMICRO (JI))  THEN
      PCIT (JI)=0.
    ENDIF

    ZTIME =ZTIME +ZMAXTIME 

    

    IF (BUCONF%LBU_ENABLE.OR.OSAVE_MICRO) THEN

      DO JV=1, IBUNUM-IBUNUM_MR-IBUNUM_EXTRA
        
        PBUDGETS (JI, JV)=PBUDGETS (JI, JV)+ZBU_INST (JI, JV)*ZMAXTIME 
      
      ENDDO


      DO JV=IBUNUM-IBUNUM_MR-IBUNUM_EXTRA+1, IBUNUM-IBUNUM_EXTRA
        
        PBUDGETS (JI, JV)=PBUDGETS (JI, JV)+ZBU_INST (JI, JV)
      
      ENDDO


      DO JV=IBUNUM-IBUNUM_EXTRA+1, IBUNUM
        JJV=IBUEXTRAIND (JV)
        
        PBUDGETS (JI, JJV)=PBUDGETS (JI, JJV)+ZBU_INST (JI, JV)
      
      ENDDO

    ENDIF

    LSOFT=.TRUE.
  ENDDO

ENDDO


IF (PARAMI%LEXT_TEND) THEN

  

  IF (LDMICRO (JI)) THEN
    PTHT (JI)=PTHT (JI)-ZEXTTH *PTSTEP
  ENDIF


  

  DO JV=1, KRR

    

    IF (LDMICRO (JI)) THEN
      PRT (JI, JV)=PRT (JI, JV)-ZEXTPK (JV)*PTSTEP
    ENDIF

  
  ENDDO

ENDIF


PRREVAV (JI)=ZBU_INST (JI, IRREVAV)


END SUBROUTINE ICE4_STEPPING_OPENACC
