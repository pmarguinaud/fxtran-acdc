END INTERFACE

CONTAINS
SUBROUTINE ACDC_WIPE_CSTURB_T (SELF, LDDELETED, LDFIELDAPI)

IMPLICIT NONE
TYPE (CSTURB_T), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDDELETED, LDFIELDAPI
LOGICAL :: LLDELETED
LOGICAL :: LLFIELDAPI
