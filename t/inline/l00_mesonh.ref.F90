SUBROUTINE L00_MESONH (D, X, Y)
USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
TYPE (DIMPHYEX_T), INTENT (IN)::D
REAL, INTENT (IN)::X (D%NIJT, D%NKT)
REAL, INTENT (OUT)::Y (D%NIJT, D%NKT)
INTEGER::IKT
INTEGER::JK
INTEGER::JI
IKT=D%NKT
DO JK = 1, IKT
  DO JI = D%NIJB, D%NIJE
    Y (JI, JK)=2.*X (JI, JK)
  ENDDO
ENDDO
DO JK = 1, D%NKT
  DO JI = D%NIJB, D%NIJE
    Y(JI,JK)=2.*X(JI,JK)
  ENDDO
ENDDO
END SUBROUTINE
