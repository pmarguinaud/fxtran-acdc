MODULE UTIL_CONVPAR_SHAL_UPDATE_MOD
USE MODD_CONVPAR_SHAL, ONLY : CONVPAR_SHAL
INTERFACE ACDC_UPDATE
MODULE PROCEDURE ACDC_UPDATE_CONVPAR_SHAL
END INTERFACE

CONTAINS
SUBROUTINE ACDC_UPDATE_CONVPAR_SHAL (SELF, LDCOMPONENT)


USE FXTRAN_ACDC_IS_PRESENT_MOD
USE UTIL_CONVPAR_SHAL_WIPE_MOD
USE UTIL_CONVPAR_SHAL_COPY_MOD
IMPLICIT NONE
TYPE (CONVPAR_SHAL), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDCOMPONENT

IF (FXTRAN_ACDC_IS_PRESENT (C_LOC (SELF), SIZEOF (SELF))) THEN
CALL ACDC_WIPE_CONVPAR_SHAL (SELF, LDDELETED=LDCOMPONENT)
CALL ACDC_COPY_CONVPAR_SHAL (SELF, LDCREATED=LDCOMPONENT)
ENDIF


END SUBROUTINE
END MODULE
