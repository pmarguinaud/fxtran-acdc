SUBROUTINE R11_OPTIONAL (X, N)
INTEGER, INTENT (IN) :: N
REAL, INTENT (INOUT) :: X (N)
CALL S (X, N)
CONTAINS
SUBROUTINE S (P, KT, KE)
INTEGER, INTENT (IN) :: KT
INTEGER, OPTIONAL, INTENT (IN) :: KE
REAL, INTENT (INOUT) :: P (KT)
INTEGER :: IE
IE = MERGE (KE, KT, PRESENT (KE))
P (1:IE) = 0.
END SUBROUTINE
END SUBROUTINE
