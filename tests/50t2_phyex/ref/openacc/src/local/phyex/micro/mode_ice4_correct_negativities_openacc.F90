
MODULE MODE_ICE4_CORRECT_NEGATIVITIES_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE ICE4_CORRECT_NEGATIVITIES_OPENACC (D, ICED, KRR, PR, PTH, PLVFACT, PLSFACT, YDSTACK)
!$ACC ROUTINE (ICE4_CORRECT_NEGATIVITIES_OPENACC) SEQ      


USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T
USE MODD_FIELDS_ADDRESS,ONLY:IRC, IRI, IRR, IRV
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (DIMPHYEX_T), INTENT (IN)::D
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
INTEGER, INTENT (IN)::KRR
REAL, INTENT (INOUT)::PR(D%NIJT, D%NKT, KRR)
REAL, INTENT (INOUT)::PTH(D%NIJT, D%NKT)
REAL, INTENT (IN)::PLSFACT(D%NIJT, D%NKT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
REAL, INTENT (IN)::PLVFACT(D%NIJT, D%NKT)
REAL::ZW
INTEGER::JRR
INTEGER::IIJE
INTEGER::IIJB
INTEGER::IKTE
INTEGER::IKTB
INTEGER::JK
INTEGER::JI


JI = D%NIB


IKTB=D%NKTB
IKTE=D%NKTE
IIJB=D%NIB
IIJE=D%NIE

DO JK=IKTB, IKTE

  

  DO JRR=2, 3
    ZW=PR (JI, JK, JRR)-MAX (PR (JI, JK, JRR), 0.)
    PR (JI, JK, IRV)=PR (JI, JK, IRV)+ZW
    PTH (JI, JK)=PTH (JI, JK)-ZW*PLVFACT (JI, JK)
    PR (JI, JK, JRR)=PR (JI, JK, JRR)-ZW
  ENDDO


  DO JRR=4, KRR
    ZW=PR (JI, JK, JRR)-MAX (PR (JI, JK, JRR), 0.)
    PR (JI, JK, IRV)=PR (JI, JK, IRV)+ZW
    PTH (JI, JK)=PTH (JI, JK)-ZW*PLSFACT (JI, JK)
    PR (JI, JK, JRR)=PR (JI, JK, JRR)-ZW
  ENDDO

  ZW=MIN (1., MAX (ICED%XRTMIN (IRV)-PR (JI, JK, IRV), 0&
  &.)/MAX (PR (JI, JK, IRC)+PR (JI, JK, IRI), 1.E-20))
  PTH (JI, JK)=PTH (JI, JK)-ZW*(PR (JI, JK, IRC)*PLVFACT (JI, JK)+PR (JI, JK, IRI)*PLSFACT (JI, JK))
  PR (JI, JK, IRV)=PR (JI, JK, IRV)+ZW*(PR (JI, JK, IRC)+PR (JI, JK, IRI))
  PR (JI, JK, IRC)=(1.-ZW)*PR (JI, JK, IRC)
  PR (JI, JK, IRI)=(1.-ZW)*PR (JI, JK, IRI)
  JRR=IRR
  ZW=MIN (MAX (PR (JI, JK, JRR), 0.), MAX (ICED%XRTMIN (IRV)-PR (JI, JK, IRV), 0.))
  PR (JI, JK, IRV)=PR (JI, JK, IRV)+ZW
  PR (JI, JK, JRR)=PR (JI, JK, JRR)-ZW
  PTH (JI, JK)=PTH (JI, JK)-ZW*PLVFACT (JI, JK)

  DO JRR=5, KRR
    ZW=MIN (MAX (PR (JI, JK, JRR), 0.), MAX (ICED%XRTMIN (IRV)-PR (JI, JK, IRV), 0.))
    PR (JI, JK, IRV)=PR (JI, JK, IRV)+ZW
    PR (JI, JK, JRR)=PR (JI, JK, JRR)-ZW
    PTH (JI, JK)=PTH (JI, JK)-ZW*PLSFACT (JI, JK)
  ENDDO

  
ENDDO


END SUBROUTINE ICE4_CORRECT_NEGATIVITIES_OPENACC

ENDMODULE MODE_ICE4_CORRECT_NEGATIVITIES_OPENACC
