MODULE UTIL_ELEC_DESCR_T_SIZE_MOD
USE MODD_ELEC_DESCR, ONLY : ELEC_DESCR_T
INTERFACE ACDC_SIZE
MODULE PROCEDURE ACDC_SIZE_ELEC_DESCR_T
END INTERFACE

CONTAINS
FUNCTION ACDC_SIZE_ELEC_DESCR_T (SELF, CDPATH, LDPRINT) RESULT (KSIZE)

IMPLICIT NONE
TYPE (ELEC_DESCR_T),     INTENT (IN), TARGET :: SELF
CHARACTER(LEN=*), INTENT (IN), OPTIONAL :: CDPATH
LOGICAL,          INTENT (IN), OPTIONAL :: LDPRINT
INTEGER*8 :: KSIZE
INTEGER*8 :: ISIZE, JSIZE
LOGICAL :: LLPRINT
CHARACTER(LEN=128) :: CLPATH
LLPRINT = .FALSE.
IF (PRESENT (LDPRINT)) THEN
  LLPRINT = LDPRINT
ENDIF
CLPATH=''
IF (PRESENT (CDPATH)) THEN
  CLPATH = CDPATH
ENDIF
KSIZE = 0
ISIZE = KIND (SELF%XFC)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%XFC'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%XFR)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%XFR'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%XFI)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%XFI'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%XFS)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%XFS'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%XFG)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%XFG'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%XFH)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%XFH'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%XCXR)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%XCXR'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%XECHARGE)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%XECHARGE'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%LSEDIM_BEARD)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%LSEDIM_BEARD'
ENDIF
KSIZE = KSIZE + ISIZE
END FUNCTION
END MODULE
