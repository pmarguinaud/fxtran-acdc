SUBROUTINE F07_ELEMENTAL_ARRAY (KLON, X, Z)
INTEGER, INTENT (IN) :: KLON
REAL, INTENT (IN) :: X (KLON)
REAL, INTENT (OUT) :: Z (KLON)
! Elemental reference with an array argument
Z (:) = F (X (:))
CONTAINS
ELEMENTAL FUNCTION F (A) RESULT (R)
REAL, INTENT (IN) :: A
REAL :: R
R = 2. * A
END FUNCTION
END SUBROUTINE
