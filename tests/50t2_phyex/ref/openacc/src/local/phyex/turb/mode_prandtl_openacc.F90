    STOP 1
ENDIF


IF (KIND (ZWORK4) == 8) THEN
    fxtran_acdc_alloc8 (ZWORK4)
ELSEIF (KIND (ZWORK4) == 4) THEN
    fxtran_acdc_alloc4 (ZWORK4)
ELSE
    STOP 1
ENDIF


IF (KIND (ZWORK3) == 8) THEN
    fxtran_acdc_alloc8 (ZWORK3)
ELSEIF (KIND (ZWORK3) == 4) THEN
    fxtran_acdc_alloc4 (ZWORK3)
ELSE
    STOP 1
ENDIF


IF (KIND (ZWORK2) == 8) THEN
    fxtran_acdc_alloc8 (ZWORK2)
ELSEIF (KIND (ZWORK2) == 4) THEN
    fxtran_acdc_alloc4 (ZWORK2)
ELSE
    STOP 1
ENDIF


IF (KIND (ZWORK1) == 8) THEN
    fxtran_acdc_alloc8 (ZWORK1)
ELSEIF (KIND (ZWORK1) == 4) THEN
    fxtran_acdc_alloc4 (ZWORK1)
ELSE
    STOP 1
ENDIF


IF (KIND (ZW2) == 8) THEN
    fxtran_acdc_alloc8 (ZW2)
ELSEIF (KIND (ZW2) == 4) THEN
    fxtran_acdc_alloc4 (ZW2)
ELSE
    STOP 1
ENDIF


IF (KIND (ZW1) == 8) THEN
    fxtran_acdc_alloc8 (ZW1)
ELSEIF (KIND (ZW1) == 4) THEN
    fxtran_acdc_alloc4 (ZW1)
ELSE
    STOP 1
ENDIF


JI = D%NIB



IKB=D%NKTB
IKE=D%NKTE
IIJE=D%NIE
IIJB=D%NIB
IKT=D%NKT
IKA=D%NKA
IKL=D%NKL
CALL ETHETA_OPENACC (D, CST, KRR, KRRI, PTHLM, PRM, PLOCPEXNM, PATHETA&
&, PSRCM, OOCEAN, OCOMPUTE_SRC, ZWORK1, YDSTACK=YLSTACK)
CALL EMOIST_OPENACC (D, CST, KRR, KRRI, PTHLM, PRM, PLOCPEXNM&
&, PAMOIST, PSRCM, OOCEAN, ZWORK2, YDSTACK=YLSTACK)
CALL MZM_PHY_OPENACC (D, ZWORK1, PETHETA, YDSTACK=YLSTACK)
CALL MZM_PHY_OPENACC (D, ZWORK2, PEMOIST, YDSTACK=YLSTACK)

PETHETA (JI, IKA)=2.*PETHETA (JI, IKB)-PETHETA (JI, IKB+IKL)
PEMOIST (JI, IKA)=2.*PEMOIST (JI, IKB)-PEMOIST (JI, IKB+IKL)



IF (OOCEAN) THEN

  DO JK=1, IKT
    
    ZWORK1 (JI, JK)=CST%XG*CST%XALPHAOC*PLM (JI, JK)*PLEPS (JI, JK)/PTKEM (JI, JK)
  
  ENDDO

ELSE

  DO JK=1, IKT
    
    ZWORK1 (JI, JK)=CST%XG/PTHVREF (JI, JK)*PLM (JI, JK)*PLEPS (JI, JK)/PTKEM (JI, JK)
  
  ENDDO

ENDIF

CALL MZM_PHY_OPENACC (D, ZWORK1, PBLL_O_E, YDSTACK=YLSTACK)
CALL GZ_M_W_PHY_OPENACC (D, PTHLM, PDZZ, ZWORK1, YDSTACK=YLSTACK)

IF (OOCEAN) THEN

  DO JK=1, IKT
    
    PREDTH1 (JI, JK)=TURBN%XCTV*PBLL_O_E (JI, JK)*ZWORK1 (JI, JK)
  
  ENDDO

  PREDR1 (JI, 1:IKT)=0.
ELSE

  IF (KRR/=0) THEN
    CALL GZ_M_W_PHY_OPENACC (D, PRM (:,:, 1), PDZZ, ZWORK2, YDSTACK=YLSTACK)

    DO JK=1, IKT
      
      PREDTH1 (JI, JK)=TURBN%XCTV*PBLL_O_E (JI, JK)*PETHETA (JI, JK)*ZWORK1 (JI, JK)
      PREDR1 (JI, JK)=TURBN%XCTV*PBLL_O_E (JI, JK)*PEMOIST (JI, JK)*ZWORK2 (JI, JK)
    
    ENDDO

  ELSE

    DO JK=1, IKT
      
      PREDTH1 (JI, JK)=TURBN%XCTV*PBLL_O_E (JI, JK)*ZWORK1 (JI, JK)
      PREDR1 (JI, JK)=0.
    
    ENDDO

  ENDIF

ENDIF

ZMINVAL=(1.-1./CSTURB%XPHI_LIM)

DO JK=1, IKT
  
  ZW1 (JI, JK)=1.
  ZW2 (JI, JK)=1.

  IF (PREDTH1 (JI, JK)+PREDR1 (JI, JK)<-ZMINVAL) THEN
    ZW1 (JI, JK)=(-ZMINVAL)/(PREDTH1 (JI, JK)+PREDR1 (JI, JK))
  ENDIF


  IF (PREDTH1 (JI, JK)<-ZMINVAL) THEN
    ZW2 (JI, JK)=(-ZMINVAL)/(PREDTH1 (JI, JK))
  ENDIF

  ZW2 (JI, JK)=MIN (ZW1 (JI, JK), ZW2 (JI, JK))
  ZW1 (JI, JK)=1.

  IF (PREDR1 (JI, JK)<-ZMINVAL) THEN
    ZW1 (JI, JK)=(-ZMINVAL)/(PREDR1 (JI, JK))
  ENDIF

  ZW1 (JI, JK)=MIN (ZW2 (JI, JK), ZW1 (JI, JK))
  PBLL_O_E (JI, JK)=PBLL_O_E (JI, JK)*ZW1 (JI, JK)
  PREDTH1 (JI, JK)=PREDTH1 (JI, JK)*ZW1 (JI, JK)
  PREDR1 (JI, JK)=PREDR1 (JI, JK)*ZW1 (JI, JK)

  IF (PREDTH1 (JI, JK)<0.) THEN
    ZW2 (JI, JK)=-1.
  ELSE
    ZW2 (JI, JK)=1.
  ENDIF

  PREDTH1 (JI, JK)=ZW2 (JI, JK)*MAX (CST%XMNH_TINY_12, ZW2 (JI, JK)*PREDTH1 (JI, JK))

  IF (KRR/=0) THEN

    IF (PREDR1 (JI, JK)<0.) THEN
      ZW2 (JI, JK)=-1.
    ELSE
      ZW2 (JI, JK)=1.
    ENDIF

    PREDR1 (JI, JK)=ZW2 (JI, JK)*MAX (CST%XMNH_TINY_12, ZW2 (JI, JK)*PREDR1 (JI, JK))
  ENDIF

  
ENDDO


DO JSV=1, KSV
  CALL GZ_M_W_PHY_OPENACC (D, PSVM (:,:, JSV), PDZZ, ZWORK1, YDSTACK=YLSTACK)

  DO JK=1, IKT
    
    PREDS1 (JI, JK, JSV)=TURBN%XCTV*PBLL_O_E (JI, JK)*ZWORK1 (JI, JK)
  
  ENDDO

ENDDO


DO JSV=1, KSV

  DO JK=1, IKT

    

    IF (PREDS1 (JI, JK, JSV)<0.) THEN
      ZW2 (JI, JK)=-1.
    ELSE
      ZW2 (JI, JK)=1.
    ENDIF

    PREDS1 (JI, JK, JSV)=ZW2 (JI, JK)*MAX (CST%XMNH_TINY_12, ZW2 (JI, JK)*PREDS1 (JI, JK, JSV))
  
  ENDDO

ENDDO



DO JK=1, IKT
  
  PRED2TH3 (JI, JK)=PREDTH1 (JI, JK)**2
  PRED2R3 (JI, JK)=PREDR1 (JI, JK)**2
  PRED2THR3 (JI, JK)=PREDTH1 (JI, JK)*PREDR1 (JI, JK)
  
ENDDO



DO JSV=1, KSV

  

  DO JK=1, IKT
    
    PRED2THS3 (JI, JK, JSV)=PREDS1 (JI, JK, JSV)*PREDTH1 (JI, JK)

    IF (KRR/=0) THEN
      PRED2RS3 (JI, JK, JSV)=PREDR1 (JI, JK)*PREDS1 (JI, JK, JSV)
    ELSE
      PRED2RS3 (JI, JK, JSV)=0.
    ENDIF

  
  ENDDO

  
ENDDO




END SUBROUTINE PRANDTL_OPENACC

