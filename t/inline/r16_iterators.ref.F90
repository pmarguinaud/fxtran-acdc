SUBROUTINE R16_ITERATORS (X, N)
INTEGER, INTENT (IN)::N
REAL, INTENT (INOUT)::X (N)
INTEGER::I
INTEGER::K
INTEGER::J
INTEGER::I_S3
INTEGER::K_S2
REAL::Z
DO J=1, N
  X (J)=0.
ENDDO
Z=2.
DO J=1, N
  X (J)=X (J)+Z
ENDDO
DO K=1, 2
  DO K_S2=1, N
    X (K_S2)=X (K_S2)+1.
  ENDDO
ENDDO
I=1
DO I_S3=1, N
  X (I_S3)=X (I_S3)+1.
ENDDO
X (I)=1.
END SUBROUTINE
