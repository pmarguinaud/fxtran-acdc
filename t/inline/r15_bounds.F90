SUBROUTINE R15_BOUNDS (Z, N, N1, N2)
INTEGER, INTENT (IN) :: N, N1, N2
REAL, INTENT (INOUT) :: Z (N, N)
CALL S (Z (:, N1:N2), N, N2-N1+1)
CONTAINS
SUBROUTINE S (P, KL, KM)
INTEGER, INTENT (IN) :: KL, KM
REAL, INTENT (INOUT) :: P (KL, KM)
INTEGER :: JL, JM
DO JM = 1, KM
  DO JL = 1, KL
    P (JL, JM) = 0.
  ENDDO
ENDDO
END SUBROUTINE
END SUBROUTINE
