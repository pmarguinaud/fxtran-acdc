MODULE UTIL_PHYEX_T_LOAD_MOD
USE MODD_PHYEX, ONLY : PHYEX_T
INTERFACE ACDC_LOAD
MODULE PROCEDURE ACDC_LOAD_PHYEX_T
END INTERFACE

CONTAINS
SUBROUTINE ACDC_LOAD_PHYEX_T (SELF, KLUN)
USE UTIL_CLOUDPAR_T_MOD
USE UTIL_CSTURB_T_MOD
USE UTIL_CST_T_MOD
USE UTIL_ELEC_DESCR_T_MOD
USE UTIL_ELEC_PARAM_T_MOD
USE UTIL_NEB_T_MOD
USE UTIL_NSV_T_MOD
USE UTIL_PARAM_ICE_T_MOD
USE UTIL_PARAM_LIMA_COLD_T_MOD
USE UTIL_PARAM_LIMA_MIXED_T_MOD
USE UTIL_PARAM_LIMA_WARM_T_MOD
USE UTIL_PARAM_LIMA_T_MOD
USE UTIL_PARAM_MFSHALL_T_MOD
USE UTIL_RAIN_ICE_DESCR_T_MOD
USE UTIL_RAIN_ICE_PARAM_T_MOD
USE UTIL_TURB_T_MOD
IMPLICIT NONE
TYPE (PHYEX_T), INTENT (OUT), TARGET :: SELF
INTEGER, INTENT (IN) :: KLUN

CALL ACDC_LOAD_CST_T (SELF%CST, KLUN)
CALL ACDC_LOAD_PARAM_ICE_T (SELF%PARAM_ICEN, KLUN)
CALL ACDC_LOAD_RAIN_ICE_DESCR_T (SELF%RAIN_ICE_DESCRN, KLUN)
CALL ACDC_LOAD_RAIN_ICE_PARAM_T (SELF%RAIN_ICE_PARAMN, KLUN)
CALL ACDC_LOAD_CLOUDPAR_T (SELF%CLOUDPARN, KLUN)
CALL ACDC_LOAD_PARAM_MFSHALL_T (SELF%PARAM_MFSHALLN, KLUN)
CALL ACDC_LOAD_CSTURB_T (SELF%CSTURB, KLUN)
CALL ACDC_LOAD_TURB_T (SELF%TURBN, KLUN)
CALL ACDC_LOAD_NEB_T (SELF%NEBN, KLUN)
CALL ACDC_LOAD_PARAM_LIMA_T (SELF%PARAM_LIMA, KLUN)
CALL ACDC_LOAD_PARAM_LIMA_WARM_T (SELF%PARAM_LIMA_WARM, KLUN)
CALL ACDC_LOAD_PARAM_LIMA_COLD_T (SELF%PARAM_LIMA_COLD, KLUN)
CALL ACDC_LOAD_PARAM_LIMA_MIXED_T (SELF%PARAM_LIMA_MIXED, KLUN)
CALL ACDC_LOAD_ELEC_DESCR_T (SELF%ELEC_DESCR, KLUN)
CALL ACDC_LOAD_ELEC_PARAM_T (SELF%ELEC_PARAM, KLUN)
CALL ACDC_LOAD_NSV_T (SELF%TNSV, KLUN)
END SUBROUTINE
END MODULE
