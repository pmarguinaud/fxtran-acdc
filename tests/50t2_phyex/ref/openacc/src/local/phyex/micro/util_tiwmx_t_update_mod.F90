MODULE UTIL_TIWMX_T_UPDATE_MOD
USE MODD_TIWMX, ONLY : TIWMX_T
INTERFACE ACDC_UPDATE
MODULE PROCEDURE ACDC_UPDATE_TIWMX_T
END INTERFACE

CONTAINS
SUBROUTINE ACDC_UPDATE_TIWMX_T (SELF, LDCOMPONENT)


USE FXTRAN_ACDC_IS_PRESENT_MOD
USE UTIL_TIWMX_T_WIPE_MOD
USE UTIL_TIWMX_T_COPY_MOD
IMPLICIT NONE
TYPE (TIWMX_T), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDCOMPONENT

IF (FXTRAN_ACDC_IS_PRESENT (C_LOC (SELF), SIZEOF (SELF))) THEN
CALL ACDC_WIPE_TIWMX_T (SELF, LDDELETED=LDCOMPONENT)
CALL ACDC_COPY_TIWMX_T (SELF, LDCREATED=LDCOMPONENT)
ENDIF


END SUBROUTINE
END MODULE
