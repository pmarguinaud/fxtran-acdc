MODULE UTIL_TFIELDMETADATA_UPDATE_MOD
USE MODD_FIELD, ONLY : TFIELDMETADATA
INTERFACE ACDC_UPDATE
MODULE PROCEDURE ACDC_UPDATE_TFIELDMETADATA
END INTERFACE

CONTAINS
SUBROUTINE ACDC_UPDATE_TFIELDMETADATA (SELF, LDCOMPONENT)


USE FXTRAN_ACDC_IS_PRESENT_MOD
USE UTIL_TFIELDMETADATA_WIPE_MOD
USE UTIL_TFIELDMETADATA_COPY_MOD
IMPLICIT NONE
TYPE (TFIELDMETADATA), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDCOMPONENT

IF (FXTRAN_ACDC_IS_PRESENT (C_LOC (SELF), SIZEOF (SELF))) THEN
CALL ACDC_WIPE_TFIELDMETADATA (SELF, LDDELETED=LDCOMPONENT)
CALL ACDC_COPY_TFIELDMETADATA (SELF, LDCREATED=LDCOMPONENT)
ENDIF


END SUBROUTINE
END MODULE
