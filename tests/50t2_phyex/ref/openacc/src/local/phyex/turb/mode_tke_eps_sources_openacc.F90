USE MODE_IO_FIELD_WRITE_PHY,ONLY:IO_FIELD_WRITE_PHY
USE MODE_LL,ONLY:CLEANLIST_LL, UPDATE_HALO_LL
USE MODE_ARGSLIST_LL_PHY,ONLY:ADD3DFIELD_LL_PHY
USE MODI_GET_HALO,ONLY:GET_HALO_PHY
USE MODI_LES_MEAN_SUBGRID_PHY,ONLY:LES_MEAN_SUBGRID_PHY
USE MODE_TRIDIAG_TKE,ONLY:TRIDIAG_TKE
USE MODE_TRIDIAG_TKE_OPENACC, ONLY : TRIDIAG_TKE_OPENACC
USE MODE_SHUMAN_PHY,ONLY:DZF_PHY
USE MODE_SHUMAN_PHY,ONLY:DZM_PHY
USE MODE_SHUMAN_PHY,ONLY:MZM_PHY
USE MODE_SHUMAN_PHY_OPENACC, ONLY : MZM_PHY_OPENACC
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE

#ifdef MNH_COMPILER_CCE
#endif
TYPE (DIMPHYEX_T), INTENT (IN)::D
TYPE (CST_T), INTENT (IN)::CST
TYPE (CSTURB_T), INTENT (IN)::CSTURB
TYPE (TBUDGETCONF_T), INTENT (IN)::BUCONF
TYPE (TURB_T), INTENT (IN)::TURBN
TYPE (TLES_T), INTENT (INOUT)::TLES
REAL, INTENT (IN)::PTKEM(D%NIJT, D%NKT)
REAL, INTENT (IN)::PLM(D%NIJT, D%NKT)
REAL, INTENT (IN)::PLEPS(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PDP(D%NIJT, D%NKT)
REAL, INTENT (IN)::PTRH(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRHODJ(D%NIJT, D%NKT)
REAL, INTENT (IN)::PDZY(D%NIJT, D%NKT)
REAL, INTENT (IN)::PDZX(D%NIJT, D%NKT)
REAL, INTENT (IN)::PDZZ(D%NIJT, D%NKT)
REAL, INTENT (IN)::PDYY(D%NIJT, D%NKT)
REAL, INTENT (IN)::PDXX(D%NIJT, D%NKT)
REAL, INTENT (IN)::PZZ(D%NIJT, D%NKT)
REAL, INTENT (IN)::PTSTEP
REAL, INTENT (IN)::PEXPL
TYPE (TFILEDATA), INTENT (INOUT)::TPFILE
LOGICAL, INTENT (IN)::ODIAG_IN_RUN
LOGICAL, INTENT (IN)::OOCEAN
REAL, INTENT (IN)::PSFVM(D%NIJT)
REAL, INTENT (IN)::PSFUM(D%NIJT)
REAL, INTENT (IN)::PTP(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PRTKES(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PRTHLS(D%NIJT, D%NKT)
REAL, INTENT (IN)::PCOEF_DISS(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PTDIFF(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PTDISS(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRTKEMS(D%NIJT, D%NKT)
TYPE (TBUDGETDATA_PTR), INTENT (INOUT)::TBUDGETS(KBUDGETS)
INTEGER, INTENT (IN)::KBUDGETS
REAL, INTENT (OUT), OPTIONAL::PEDR(D%NIJT, D%NKT)
REAL, INTENT (OUT), OPTIONAL::PTR(D%NIJT, D%NKT)
REAL, INTENT (OUT), OPTIONAL::PDISS(D%NIJT, D%NKT)
REAL, INTENT (INOUT), OPTIONAL::PCURRENT_TKE_DISS(0, 0)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
TYPE(FXTRAN_ACDC_STACK) :: YLSTACK
fxtran_acdc_temp (REAL, ZWKLES, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZMWORK1, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZTR, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZKEFF, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZSOURCE, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZFLX_PTSTEP, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZFLX, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZRES, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZA, (D%NIJT, D%NKT))
fxtran_acdc_temp (LOGICAL, GTKENEG, (D%NIJT, D%NKT))
INTEGER::IKL
INTEGER::IKA
INTEGER::IKT
INTEGER::IKE
INTEGER::IKB
INTEGER::IIJE
INTEGER::IIJB
TYPE (LIST_LL), POINTER::TZFIELDDISS_LL
INTEGER::IINFO_LL
TYPE (TFIELDMETADATA)::TZFIELD

fxtran_acdc_temp (REAL, ZMZM2D_WORK1, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZMZM2D_WORK2, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZSHUGRADWK1_2D, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZDZM2D_WORK1, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZDZF2D_WORK1, (D%NIJT, D%NKT))
INTEGER::JK
INTEGER::JI
NULLIFY (TZFIELDDISS_LL)

YLSTACK = YDSTACK



IF (KIND (ZWKLES) == 8) THEN
    fxtran_acdc_alloc8 (ZWKLES)
ELSEIF (KIND (ZWKLES) == 4) THEN
    fxtran_acdc_alloc4 (ZWKLES)
ELSE
    STOP 1
ENDIF


IF (KIND (ZMWORK1) == 8) THEN
    fxtran_acdc_alloc8 (ZMWORK1)
ELSEIF (KIND (ZMWORK1) == 4) THEN
    fxtran_acdc_alloc4 (ZMWORK1)
ELSE
    STOP 1
ENDIF


IF (KIND (ZTR) == 8) THEN
    fxtran_acdc_alloc8 (ZTR)
ELSEIF (KIND (ZTR) == 4) THEN
    fxtran_acdc_alloc4 (ZTR)
ELSE
    STOP 1
ENDIF


IF (KIND (ZKEFF) == 8) THEN
    fxtran_acdc_alloc8 (ZKEFF)
ELSEIF (KIND (ZKEFF) == 4) THEN
    fxtran_acdc_alloc4 (ZKEFF)
ELSE
    STOP 1
ENDIF


IF (KIND (ZSOURCE) == 8) THEN
    fxtran_acdc_alloc8 (ZSOURCE)
ELSEIF (KIND (ZSOURCE) == 4) THEN
    fxtran_acdc_alloc4 (ZSOURCE)
ELSE
    STOP 1
ENDIF


IF (KIND (ZFLX_PTSTEP) == 8) THEN
    fxtran_acdc_alloc8 (ZFLX_PTSTEP)
ELSEIF (KIND (ZFLX_PTSTEP) == 4) THEN
    fxtran_acdc_alloc4 (ZFLX_PTSTEP)
ELSE
    STOP 1
ENDIF


IF (KIND (ZFLX) == 8) THEN
    fxtran_acdc_alloc8 (ZFLX)
ELSEIF (KIND (ZFLX) == 4) THEN
    fxtran_acdc_alloc4 (ZFLX)
ELSE
    STOP 1
ENDIF


IF (KIND (ZRES) == 8) THEN
    fxtran_acdc_alloc8 (ZRES)
ELSEIF (KIND (ZRES) == 4) THEN
    fxtran_acdc_alloc4 (ZRES)
ELSE
    STOP 1
ENDIF


IF (KIND (ZA) == 8) THEN
    fxtran_acdc_alloc8 (ZA)
ELSEIF (KIND (ZA) == 4) THEN
    fxtran_acdc_alloc4 (ZA)
ELSE
    STOP 1
ENDIF


IF (KIND (GTKENEG) == 8) THEN
    fxtran_acdc_alloc8 (GTKENEG)
ELSEIF (KIND (GTKENEG) == 4) THEN
    fxtran_acdc_alloc4 (GTKENEG)
ELSE
    STOP 1
ENDIF


IF (KIND (ZMZM2D_WORK1) == 8) THEN
    fxtran_acdc_alloc8 (ZMZM2D_WORK1)
ELSEIF (KIND (ZMZM2D_WORK1) == 4) THEN
    fxtran_acdc_alloc4 (ZMZM2D_WORK1)
ELSE
    STOP 1
ENDIF


IF (KIND (ZMZM2D_WORK2) == 8) THEN
    fxtran_acdc_alloc8 (ZMZM2D_WORK2)
ELSEIF (KIND (ZMZM2D_WORK2) == 4) THEN
    fxtran_acdc_alloc4 (ZMZM2D_WORK2)
ELSE
    STOP 1
ENDIF


IF (KIND (ZSHUGRADWK1_2D) == 8) THEN
    fxtran_acdc_alloc8 (ZSHUGRADWK1_2D)
ELSEIF (KIND (ZSHUGRADWK1_2D) == 4) THEN
    fxtran_acdc_alloc4 (ZSHUGRADWK1_2D)
ELSE
    STOP 1
ENDIF


IF (KIND (ZDZM2D_WORK1) == 8) THEN
    fxtran_acdc_alloc8 (ZDZM2D_WORK1)
ELSEIF (KIND (ZDZM2D_WORK1) == 4) THEN
    fxtran_acdc_alloc4 (ZDZM2D_WORK1)
ELSE
    STOP 1
ENDIF


IF (KIND (ZDZF2D_WORK1) == 8) THEN
    fxtran_acdc_alloc8 (ZDZF2D_WORK1)
ELSEIF (KIND (ZDZF2D_WORK1) == 4) THEN
    fxtran_acdc_alloc4 (ZDZF2D_WORK1)
ELSE
    STOP 1
ENDIF


JI = D%NIB


IKB=D%NKB
IKE=D%NKE
IIJB=D%NIB
IIJE=D%NIE
IKT=D%NKT
IKA=D%NKA
IKL=D%NKL

DO JK=1, IKT
  
  ZKEFF (JI, JK)=PLM (JI, JK)*SQRT (PTKEM (JI, JK))
  
ENDDO


ZTR (JI, 1:IKT)=0.


IF (OOCEAN) THEN
  
  PDP (JI, IKE)=PDP (JI, IKE)*(1.+PDZZ (JI, IKE)/PDZZ (JI, IKE+1))
  
ELSE
  
  PDP (JI, IKB)=PDP (JI, IKB)*(1.+PDZZ (JI, IKB+IKL)/PDZZ (JI, IKB))
  
ENDIF


DO JK=1, IKT
  
  ZFLX (JI, JK)=TURBN%XCED*SQRT (PTKEM (JI, JK))/PLEPS (JI, JK)
  ZSOURCE (JI, JK)=(PRTKES (JI, JK)+PRTKEMS (JI, JK))/PRHODJ (JI, JK)-PTKEM (JI, JK)/PTSTEP&
  &+PDP (JI, JK)+PTP (JI, JK)+ZTR (JI, JK)-PEXPL*ZFLX (JI, JK)*PTKEM (JI, JK)
  
ENDDO


IF (OOCEAN) THEN
  
  ZSOURCE (JI, IKE)=ZSOURCE (JI, IKE)-1.E2*((PSFUM (JI)**2+PSFVM (JI)**2)**1.5)/PDZZ (JI, IKE)
  
ENDIF

CALL MZM_PHY_OPENACC (D, ZKEFF, ZMZM2D_WORK1, YDSTACK=YLSTACK)
CALL MZM_PHY_OPENACC (D, PRHODJ, ZMZM2D_WORK2, YDSTACK=YLSTACK)

DO JK=1, IKT
  
  ZA (JI, JK)=-PTSTEP*CSTURB%XCET*ZMZM2D_WORK1 (JI, JK)*ZMZM2D_WORK2 (JI, JK)/PDZZ (JI, JK)**2
  
ENDDO


DO JK=1, IKT
  
  ZFLX_PTSTEP (JI, JK)=PTSTEP*ZFLX (JI, JK)
  
ENDDO

CALL TRIDIAG_TKE_OPENACC (D, PTKEM, ZA, PTSTEP, PEXPL, TURBN%XIMPL&
&, PRHODJ, ZSOURCE, ZFLX_PTSTEP, ZRES, YDSTACK=YLSTACK)



IF (TURBN%LTKEMINTURB) THEN

  DO JK=1, IKT
    
    GTKENEG (JI, JK)=ZRES (JI, JK)<=TURBN%XTKEMIN

    IF (GTKENEG (JI, JK)) THEN
      ZRES (JI, JK)=TURBN%XTKEMIN
    ENDIF

  
  ENDDO

ENDIF


DO JK=1, IKT
  
  PTDISS (JI, JK)=-ZFLX (JI, JK)*(PEXPL*PTKEM (JI, JK)+TURBN%XIMPL*ZRES (JI, JK))
  
ENDDO




DO JK=1, IKT
  
  PRTKES (JI, JK)=PRTKES (JI, JK)+PRHODJ (JI, JK)*(PDP (JI, JK)+PTP (JI, JK)-TURBN%XCED*SQRT&
  & (PTKEM (JI, JK))/PLEPS (JI, JK)*(PEXPL*PTKEM (JI, JK)+TURBN%XIMPL*ZRES (JI, JK)))
  PTDIFF (JI, JK)=ZRES (JI, JK)/PTSTEP-PRTKES (JI, JK)/PRHODJ&
  & (JI, JK)-PDP (JI, JK)-PTP (JI, JK)-PTDISS (JI, JK)
  
ENDDO



DO JK=1, IKT
  
  PRTKES (JI, JK)=ZRES (JI, JK)*PRHODJ (JI, JK)/PTSTEP-PRTKEMS (JI, JK)
  
ENDDO



DO JK=1, IKT
  
  PRTHLS (JI, JK)=PRTHLS (JI, JK)+TURBN%XCED*SQRT (PTKEM (JI, JK))/PLEPS (JI, JK)*(PEXPL&
  &*PTKEM (JI, JK)+TURBN%XIMPL*ZRES (JI, JK))*PRHODJ (JI, JK)*PCOEF_DISS (JI, JK)
  
ENDDO


IF (PRESENT (PTR)) THEN

  DO JK=1, IKT
    
    PTR (JI, JK)=ZTR (JI, JK)
  
  ENDDO

ENDIF


IF (PRESENT (PDISS)) THEN

  DO JK=1, IKT
    
    PDISS (JI, JK)=-TURBN%XCED*(PTKEM (JI, JK)**1.5)/PLEPS (JI, JK)
  
  ENDDO

ENDIF


IF (PRESENT (PEDR)) THEN

  DO JK=1, IKT
    
    PEDR (JI, JK)=TURBN%XCED*(PTKEM (JI, JK)**1.5)/PLEPS (JI, JK)
  
  ENDDO

ENDIF




END SUBROUTINE TKE_EPS_SOURCES_OPENACC

ENDMODULE MODE_TKE_EPS_SOURCES_OPENACC
