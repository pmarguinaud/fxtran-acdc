TYPE(FXTRAN_ACDC_STACK) :: YLSTACK

INTEGER::JM
INTEGER::JK
INTEGER::JI
INTEGER::IIJT
INTEGER::IIJE
INTEGER::IIJB
INTEGER::IKB
INTEGER::IKTE
INTEGER::IKTB
REAL::ZINV_TSTEP
fxtran_acdc_temp (REAL, ZWKBUD, (D%NIJT, D%NKT))
LOGICAL::GMASK_ELEC(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
INTEGER::IELEC

YLSTACK = YDSTACK



IF (KIND (ZWKBUD) == 8) THEN
    fxtran_acdc_alloc8 (ZWKBUD)
ELSEIF (KIND (ZWKBUD) == 4) THEN
    fxtran_acdc_alloc4 (ZWKBUD)
ELSE
    STOP 1
ENDIF


JI = D%NIB


IKTB=D%NKTB
IKTE=D%NKTE
IKB=D%NKB
IIJB=D%NIB
IIJE=D%NIE
IIJT=D%NIJT
ZINV_TSTEP=1./PTSTEP

IF (BUCONF%LBU_ENABLE.OR.OELEC) THEN

  DO JK=IKTB, IKTE

    

    DO JM=1, IBUNUM-IBUNUM_EXTRA
      ZBUDGETS (JI, JK, JM)=ZBUDGETS (JI, JK, JM)*ZINV_TSTEP
    ENDDO

  
  ENDDO

ENDIF


IF (BUCONF%LBU_ENABLE) THEN
  CALL ICE4_BUDGETS_OPENACC (D, PARAMI, BUCONF, KRR, PLVFACT, PLSFACT, PRHODJ&
  &, PEXNREF, PRVHENI, ZBUDGETS, TBUDGETS, KBUDGETS, YDSTACK=YLSTACK)
ENDIF


IF (OELEC) THEN
  GMASK_ELEC (JI,:)=.FALSE.

  DO JK=IKTB, IKTE

    

    DO JM=1, IBUNUM-IBUNUM_EXTRA
      GMASK_ELEC (JI, JK)=GMASK_ELEC (JI, JK).OR.(ZBUDGETS (JI, JK, JM).NE.0.)
    ENDDO

  
  ENDDO

  IELEC=COUNT (GMASK_ELEC(JI,:))

  IF (KRR==7) THEN
    CALL ELEC_TENDENCIES_OPENACC (D, CST, ICED, ICEP, ELECD, ELECP, LIMAP, LIMAC, LIMAM, KRR, IELEC, PTSTEP&
    &, GMASK_ELEC, BUCONF, TBUDGETS, KBUDGETS,'ICE4', PTHVREFZIKB, PRHODREF, PRHODJ, PT, PCIT, PRT (:,:, IRV&
    &), PRT (:,:, IRC), PRT (:,:, IRR), PRT (:,:, IRI), PRT (:,:, IRS), PRT (:,:, IRG), PQPIT, PQCT, PQRT,&
    & PQIT, PQST, PQGT, PQNIT, PQPIS, PQCS, PQRS, PQIS, PQSS, PQGS, PQNIS, ZBUDGETS (:,:, IRVHENI_MR), ZBUDGETS&
    & (:,:, IRRHONG_MR), ZBUDGETS (:,:, IRIMLTC_MR), ZBUDGETS (:,:, IRCHONI), ZBUDGETS (:,:, IRVDEPS), ZBUDGETS&
    & (:,:, IRIAGGS), ZBUDGETS (:,:, IRIAUTS), ZBUDGETS (:,:, IRVDEPG), ZBUDGETS (:,:, IRCAUTR), ZBUDGETS &
    &(:,:, IRCACCR), ZBUDGETS (:,:, IRREVAV), ZBUDGETS (:,:, IRCRIMSS), ZBUDGETS (:,:, IRCRIMSG), ZBUDGETS&
    & (:,:, IRSRIMCG), ZBUDGETS (:,:, IRRACCSS), ZBUDGETS (:,:, IRRACCSG), ZBUDGETS (:,:, IRSACCRG), ZBUDGETS&
    & (:,:, IRSMLTG), ZBUDGETS (:,:, IRICFRRG), ZBUDGETS (:,:, IRRCFRIG), ZBUDGETS (:,:, IRCWETG), ZBUDGETS&
    & (:,:, IRIWETG), ZBUDGETS (:,:, IRRWETG), ZBUDGETS (:,:, IRSWETG), ZBUDGETS (:,:, IRCDRYG), ZBUDGETS &
    &(:,:, IRIDRYG), ZBUDGETS (:,:, IRRDRYG), ZBUDGETS (:,:, IRSDRYG), ZBUDGETS (:,:, IRGMLTR), ZBUDGETS (&
    &:,:, IRCBERI), PRCMLTSR=ZBUDGETS (:,:, IRCMLTSR), PRICFRR=ZBUDGETS (:,:, IRICFRR), PRWETGH=ZBUDGETS (&
    &:,:, IRWETGH), PRCWETH=ZBUDGETS (:,:, IRCWETH), PRIWETH=ZBUDGETS (:,:, IRIWETH), PRSWETH=ZBUDGETS (:,&
    &:, IRSWETH), PRGWETH=ZBUDGETS (:,:, IRGWETH), PRRWETH=ZBUDGETS (:,:, IRRWETH), PRCDRYH=ZBUDGETS (:,:,&
    & IRCDRYH), PRIDRYH=ZBUDGETS (:,:, IRIDRYH), PRSDRYH=ZBUDGETS (:,:, IRSDRYH), PRRDRYH=ZBUDGETS (:,:, IRRDRYH&
    &), PRGDRYH=ZBUDGETS (:,:, IRGDRYH), PRDRYHG=ZBUDGETS (:,:, IRDRYHG), PRHMLTR=ZBUDGETS (:,:, IRHMLTR),&
    & PRHT=PRT (:,:, IRH), PQHT=PQHT, PQHS=PQHS, YDSTACK=YLSTACK)
  ELSE
    CALL ELEC_TENDENCIES_OPENACC (D, CST, ICED, ICEP, ELECD, ELECP, LIMAP, LIMAC, LIMAM, KRR, IELEC,&
    & PTSTEP, GMASK_ELEC, BUCONF, TBUDGETS, KBUDGETS,'ICE3', PTHVREFZIKB, PRHODREF, PRHODJ, PT, PCIT&
    &, PRT (:,:, IRV), PRT (:,:, IRC), PRT (:,:, IRR), PRT (:,:, IRI), PRT (:,:, IRS), PRT (:,:, IRG&
    &), PQPIT, PQCT, PQRT, PQIT, PQST, PQGT, PQNIT, PQPIS, PQCS, PQRS, PQIS, PQSS, PQGS, PQNIS, ZBUDGETS&
    & (:,:, IRVHENI_MR), ZBUDGETS (:,:, IRRHONG_MR), ZBUDGETS (:,:, IRIMLTC_MR), ZBUDGETS (:,:, IRCHONI&
    &), ZBUDGETS (:,:, IRVDEPS), ZBUDGETS (:,:, IRIAGGS), ZBUDGETS (:,:, IRIAUTS), ZBUDGETS (:,:, IRVDEPG&
    &), ZBUDGETS (:,:, IRCAUTR), ZBUDGETS (:,:, IRCACCR), ZBUDGETS (:,:, IRREVAV), ZBUDGETS (:,:, IRCRIMSS&
    &), ZBUDGETS (:,:, IRCRIMSG), ZBUDGETS (:,:, IRSRIMCG), ZBUDGETS (:,:, IRRACCSS), ZBUDGETS (:,:,&
    & IRRACCSG), ZBUDGETS (:,:, IRSACCRG), ZBUDGETS (:,:, IRSMLTG), ZBUDGETS (:,:, IRICFRRG), ZBUDGETS&
    & (:,:, IRRCFRIG), ZBUDGETS (:,:, IRCWETG), ZBUDGETS (:,:, IRIWETG), ZBUDGETS (:,:, IRRWETG), ZBUDGETS&
    & (:,:, IRSWETG), ZBUDGETS (:,:, IRCDRYG), ZBUDGETS (:,:, IRIDRYG), ZBUDGETS (:,:, IRRDRYG), ZBUDGETS&
    & (:,:, IRSDRYG), ZBUDGETS (:,:, IRGMLTR), ZBUDGETS (:,:, IRCBERI), PRCMLTSR=ZBUDGETS (:,:, IRCMLTSR&
    &), PRICFRR=ZBUDGETS (:,:, IRICFRR), YDSTACK=YLSTACK)
  ENDIF

ENDIF


DO JK=IKTB, IKTE
  
  PLSFACT (JI, JK)=PLSFACT (JI, JK)/PEXNREF (JI, JK)
  PLVFACT (JI, JK)=PLVFACT (JI, JK)/PEXNREF (JI, JK)
  PWR (JI, JK, IRV)=(PWR (JI, JK, IRV)-PRT (JI, JK, IRV))*ZINV_TSTEP
  PWR (JI, JK, IRC)=(PWR (JI, JK, IRC)-PRT (JI, JK, IRC))*ZINV_TSTEP
  PWR (JI, JK, IRR)=(PWR (JI, JK, IRR)-PRT (JI, JK, IRR))*ZINV_TSTEP
  PWR (JI, JK, IRI)=(PWR (JI, JK, IRI)-PRT (JI, JK, IRI))*ZINV_TSTEP
  PWR (JI, JK, IRS)=(PWR (JI, JK, IRS)-PRT (JI, JK, IRS))*ZINV_TSTEP
  PWR (JI, JK, IRG)=(PWR (JI, JK, IRG)-PRT (JI, JK, IRG))*ZINV_TSTEP

  IF (KRR==7) THEN
    PWR (JI, JK, IRH)=(PWR (JI, JK, IRH)-PRT (JI, JK, IRH))*ZINV_TSTEP
  ENDIF

  PWTH (JI, JK)=(PWR (JI, JK, IRC)+PWR (JI, JK, IRR))*PLVFACT (JI, JK)+(PWR (JI, JK&
  &, IRI)+PWR (JI, JK, IRS)+PWR (JI, JK, IRG)+PWR (JI, JK, IRH))*PLSFACT (JI, JK)
  PTHS (JI, JK)=PTHS (JI, JK)+PWTH (JI, JK)+PRVHENI (JI, JK)*PLSFACT (JI, JK)
  PRS (JI, JK, IRV)=PRS (JI, JK, IRV)+PWR (JI, JK, IRV)-PRVHENI (JI, JK)
  PRS (JI, JK, IRC)=PRS (JI, JK, IRC)+PWR (JI, JK, IRC)
  PRS (JI, JK, IRR)=PRS (JI, JK, IRR)+PWR (JI, JK, IRR)
  PRS (JI, JK, IRI)=PRS (JI, JK, IRI)+PWR (JI, JK, IRI)+PRVHENI (JI, JK)
  PRS (JI, JK, IRS)=PRS (JI, JK, IRS)+PWR (JI, JK, IRS)
  PRS (JI, JK, IRG)=PRS (JI, JK, IRG)+PWR (JI, JK, IRG)

  IF (KRR==7) THEN
    PRS (JI, JK, IRH)=PRS (JI, JK, IRH)+PWR (JI, JK, IRH)
  ENDIF

  
ENDDO


IF (BUCONF%LBU_ENABLE) THEN
  
  
  
  
  
  
  
  
  
  
  
  
  
  
  
  
ENDIF

CALL ICE4_CORRECT_NEGATIVITIES_OPENACC (D, ICED, KRR, PRS, PTHS, PLVFACT, PLSFACT, YDSTACK=YLSTACK)

IF (BUCONF%LBU_ENABLE) THEN
  
  
  
  
  
  
  
  
  
  
  
  
  
  
  
  
ENDIF


IF (PARAMI%LSEDIM_AFTER) THEN
  CALL ICE4_SEDIMENTATION_OPENACC (D, CST, ICEP, ICED, PARAMI, ELECP, ELECD, BUCONF, OELEC&
  &, OSEDIM_BEARD, PTSTEP, KRR, PDZZ, PTHVREFZIKB, PLVFACT, PLSFACT, PRHODREF, PPABST, PTHT&
  &, PT, PRHODJ, PTHS, PRT, PRS, PCONC3D, PINPRC, PINPRR, PINPRS, PINPRG, PQCT, PQRT, PQIT&
  &, PQST, PQGT, PQCS, PQRS, PQIS, PQSS, PQGS, PEFIELDW, TBUDGETS, KBUDGETS, PSEA=PSEA, PTOWN&
  &=PTOWN, PINPRH=PINPRH, PFPR=PFPR, PQHT=PQHT, PQHS=PQHS, YDSTACK=YLSTACK)

  DO JK=IKTB, IKTE
    
    PWR (JI, JK, IRR)=PRS (JI, JK, IRR)*PTSTEP
    PWR (JI, JK, IRS)=PRS (JI, JK, IRS)*PTSTEP
    PWR (JI, JK, IRG)=PRS (JI, JK, IRG)*PTSTEP

    IF (KRR==7) THEN
      PWR (JI, JK, IRH)=PRS (JI, JK, IRH)*PTSTEP
    ENDIF

  
  ENDDO


  IF (KRR==7) THEN
    CALL ICE4_RAINFR_VERT_OPENACC (D, ICED, PRAINFR, PWR (:,:, IRR), PWR&
    & (:,:, IRS), PWR (:,:, IRG), PWR (:,:, IRH), YDSTACK=YLSTACK)
  ELSE
    CALL ICE4_RAINFR_VERT_OPENACC (D, ICED, PRAINFR, PWR (:,:,&
    & IRR), PWR (:,:, IRS), PWR (:,:, IRG), YDSTACK=YLSTACK)
  ENDIF

ENDIF


IF (PARAMI%LDEPOSC) THEN
  
  
  PINDEP (JI)=0.
  
  PINDEP (JI)=PARAMI%XVDEPOSC*PRT (JI, IKB, IRC)*PRHODREF (JI, IKB)/CST%XRHOLW
  PRS (JI, IKB, IRC)=PRS (JI, IKB, IRC)-PARAMI%XVDEPOSC*PRT (JI, IKB, IRC)/PDZZ (JI, IKB)
  PINPRC (JI)=PINPRC (JI)+PINDEP (JI)
  
  
  
ENDIF


END SUBROUTINE RAIN_ICE_PART3_OPENACC
