SUBROUTINE L08_ITERATOR (KLON, KLEV, KIDIA, KFDIA, X, Y)
INTEGER, INTENT (IN) :: KLON, KLEV, KIDIA, KFDIA
REAL, INTENT (IN) :: X (KLON, KLEV)
REAL, INTENT (OUT) :: Y (KLON, KLEV)
INTEGER :: JLON, JLEV
DO JLON = KIDIA, KFDIA
  CALL E (X (:, 1), Y (:, 1))
ENDDO
CONTAINS
ELEMENTAL SUBROUTINE E (A, B)
REAL, INTENT (IN) :: A
REAL, INTENT (OUT) :: B
B = 2. * A
END SUBROUTINE
END SUBROUTINE
