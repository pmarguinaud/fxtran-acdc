MODULE UTIL_NSV_T_UPDATE_MOD
USE MODD_NSV, ONLY : NSV_T
INTERFACE ACDC_UPDATE
MODULE PROCEDURE ACDC_UPDATE_NSV_T
END INTERFACE

CONTAINS
SUBROUTINE ACDC_UPDATE_NSV_T (SELF, LDCOMPONENT)


USE FXTRAN_ACDC_IS_PRESENT_MOD
USE UTIL_NSV_T_WIPE_MOD
USE UTIL_NSV_T_COPY_MOD
IMPLICIT NONE
TYPE (NSV_T), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDCOMPONENT

IF (FXTRAN_ACDC_IS_PRESENT (C_LOC (SELF), SIZEOF (SELF))) THEN
CALL ACDC_WIPE_NSV_T (SELF, LDDELETED=LDCOMPONENT)
CALL ACDC_COPY_NSV_T (SELF, LDCREATED=LDCOMPONENT)
ENDIF


END SUBROUTINE
END MODULE
