
MODULE MODE_ICE4_RRHONG_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE ICE4_RRHONG_OPENACC (CST, PARAMI, ICED, D, LDCOMPUTE,&
& PEXN, PLVFACT, PLSFACT, PT, PRRT, PTHT, PRRHONG_MR, YDSTACK)
!$ACC ROUTINE (ICE4_RRHONG_OPENACC) SEQ      

USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_CST,ONLY:CST_T
USE MODD_PARAM_ICE_N,ONLY:PARAM_ICE_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T

#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (CST_T), INTENT (IN)::CST
TYPE (PARAM_ICE_T), INTENT (IN)::PARAMI
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
TYPE (DIMPHYEX_T), INTENT (IN)::D
LOGICAL, INTENT (IN)::LDCOMPUTE(D%NIJT)
REAL, INTENT (IN)::PEXN(D%NIJT)
REAL, INTENT (IN)::PLVFACT(D%NIJT)
REAL, INTENT (IN)::PLSFACT(D%NIJT)
REAL, INTENT (IN)::PT(D%NIJT)
REAL, INTENT (IN)::PRRT(D%NIJT)
REAL, INTENT (IN)::PTHT(D%NIJT)
REAL, INTENT (OUT)::PRRHONG_MR(D%NIJT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK

INTEGER::JI

JI = D%NIB




IF (PT (JI)<CST%XTT-35.0.AND.PRRT (JI)>ICED%XRTMIN (3).AND.LDCOMPUTE (JI)) THEN
  PRRHONG_MR (JI)=PRRT (JI)

  IF (PARAMI%LFEEDBACKT) THEN
    PRRHONG_MR (JI)=MIN (PRRHONG_MR (JI), MAX (0.,((CST%XTT-35&
    &.)/PEXN (JI)-PTHT (JI))/(PLSFACT (JI)-PLVFACT (JI))))
  ENDIF

ELSE
  PRRHONG_MR (JI)=0.
ENDIF



END SUBROUTINE ICE4_RRHONG_OPENACC

ENDMODULE MODE_ICE4_RRHONG_OPENACC
