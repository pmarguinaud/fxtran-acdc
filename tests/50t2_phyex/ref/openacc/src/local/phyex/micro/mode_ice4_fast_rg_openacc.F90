
MODULE MODE_ICE4_FAST_RG_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE ICE4_FAST_RG_OPENACC (CST, PARAMI, ICEP, ICED, D, LDSOFT, LDCOMPUTE, KRR, PRHODREF, PLVFACT&
&, PLSFACT, PPRES, PDV, PKA, PCJ, PCIT, PLBDAR, PLBDAS, PLBDAG, PT, PRVT, PRCT, PRRT, PRIT, PRST&
&, PRGT, PRGSI, PRGSI_MR, LDWETG, PRICFRRG, PRRCFRIG, PRICFRR, PRCWETG, PRIWETG, PRRWETG, PRSWETG&
&, PRCDRYG, PRIDRYG, PRRDRYG, PRSDRYG, PRWETGH, PRWETGH_MR, PRGMLTR, PRG_TEND, YDSTACK)
!$ACC ROUTINE (ICE4_FAST_RG_OPENACC) SEQ      

USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_CST,ONLY:CST_T
USE MODD_PARAM_ICE_N,ONLY:PARAM_ICE_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T
USE MODD_RAIN_ICE_PARAM_N,ONLY:RAIN_ICE_PARAM_T

#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (CST_T), INTENT (IN)::CST
TYPE (PARAM_ICE_T), INTENT (IN)::PARAMI
TYPE (RAIN_ICE_PARAM_T), INTENT (IN)::ICEP
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
TYPE (DIMPHYEX_T), INTENT (IN)::D
LOGICAL, INTENT (IN)::LDSOFT
LOGICAL, INTENT (IN)::LDCOMPUTE(D%NIJT)
INTEGER, INTENT (IN)::KRR
REAL, INTENT (IN)::PRHODREF(D%NIJT)
REAL, INTENT (IN)::PLVFACT(D%NIJT)
REAL, INTENT (IN)::PLSFACT(D%NIJT)
REAL, INTENT (IN)::PPRES(D%NIJT)
REAL, INTENT (IN)::PDV(D%NIJT)
REAL, INTENT (IN)::PKA(D%NIJT)
REAL, INTENT (IN)::PCJ(D%NIJT)
REAL, INTENT (IN)::PCIT(D%NIJT)
REAL, INTENT (IN)::PLBDAR(D%NIJT)
REAL, INTENT (IN)::PLBDAS(D%NIJT)
REAL, INTENT (IN)::PLBDAG(D%NIJT)
REAL, INTENT (IN)::PT(D%NIJT)
REAL, INTENT (IN)::PRVT(D%NIJT)
REAL, INTENT (IN)::PRCT(D%NIJT)
REAL, INTENT (IN)::PRRT(D%NIJT)
REAL, INTENT (IN)::PRIT(D%NIJT)
REAL, INTENT (IN)::PRST(D%NIJT)
REAL, INTENT (IN)::PRGT(D%NIJT)
REAL, INTENT (IN)::PRGSI(D%NIJT)
REAL, INTENT (IN)::PRGSI_MR(D%NIJT)
LOGICAL, INTENT (OUT)::LDWETG(D%NIJT)
REAL, INTENT (INOUT)::PRICFRRG(D%NIJT)
REAL, INTENT (INOUT)::PRRCFRIG(D%NIJT)
REAL, INTENT (INOUT)::PRICFRR(D%NIJT)
REAL, INTENT (OUT)::PRCWETG(D%NIJT)
REAL, INTENT (OUT)::PRIWETG(D%NIJT)
REAL, INTENT (OUT)::PRRWETG(D%NIJT)
REAL, INTENT (OUT)::PRSWETG(D%NIJT)
REAL, INTENT (OUT)::PRCDRYG(D%NIJT)
REAL, INTENT (OUT)::PRIDRYG(D%NIJT)
REAL, INTENT (OUT)::PRRDRYG(D%NIJT)
REAL, INTENT (OUT)::PRSDRYG(D%NIJT)
REAL, INTENT (OUT)::PRWETGH(D%NIJT)
REAL, INTENT (OUT)::PRWETGH_MR(D%NIJT)
REAL, INTENT (INOUT)::PRGMLTR(D%NIJT)
REAL, INTENT (INOUT)::PRG_TEND(D%NIJT, 8)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
INTEGER, PARAMETER::IFREEZ2=8
INTEGER, PARAMETER::IFREEZ1=7
INTEGER, PARAMETER::IRRDRYG=6
INTEGER, PARAMETER::IRSWETG=5
INTEGER, PARAMETER::IRSDRYG=4
INTEGER, PARAMETER::IRIWETG=3
INTEGER, PARAMETER::IRIDRYG=2
INTEGER, PARAMETER::IRCDRYG=1
LOGICAL::LLDRYG
LOGICAL::GDRY
INTEGER::IGDRY
REAL::ZBUF3
REAL::ZBUF2
REAL::ZBUF1
INTEGER::IBUF3
INTEGER::IBUF2
INTEGER::IBUF1
REAL::ZRWETG_INIT
REAL::ZRDRYG_INIT
REAL::ZZW
REAL::ZZW0D
INTEGER::JI

INTEGER::IINDEX2
INTEGER::IINDEX1
REAL::ZINDEX2
REAL::ZINDEX1

JI = D%NIB


#ifdef MNH_COMPILER_CCE
#endif


IF (PRIT (JI)>ICED%XRTMIN (4).AND.PRRT (JI)>ICED%XRTMIN (3).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRICFRRG (JI)=ICEP%XICFRR*PRIT (JI)*PLBDAR (JI)**ICEP%XEXICFRR*PRHODREF (JI)**(-ICED%XCEXVT)
    PRRCFRIG (JI)=ICEP%XRCFRI*PCIT (JI)*PLBDAR (JI)**ICEP%XEXRCFRI*PRHODREF (JI)**(-ICED%XCEXVT-1.)

    IF (PARAMI%LCRFLIMIT) THEN
      ZZW0D=MAX (0., MIN (1.,(PRICFRRG (JI)*CST%XCI+PRRCFRIG (JI)*CST%XCL&
      &)*(CST%XTT-PT (JI))/MAX (1.E-20, CST%XLVTT*PRRCFRIG (JI))))
      PRRCFRIG (JI)=ZZW0D*PRRCFRIG (JI)
      PRICFRR (JI)=(1.-ZZW0D)*PRICFRRG (JI)
      PRICFRRG (JI)=ZZW0D*PRICFRRG (JI)
    ELSE
      PRICFRR (JI)=0.
    ENDIF

  ENDIF

ELSE
  PRICFRRG (JI)=0.
  PRRCFRIG (JI)=0.
  PRICFRR (JI)=0.
ENDIF




IF (PRGT (JI)>ICED%XRTMIN (6).AND.PRCT (JI)>ICED%XRTMIN (2).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRG_TEND (JI, IRCDRYG)=PLBDAG (JI)**(ICED%XCXG-ICED%XDG-2.)*PRHODREF (JI)**(-ICED%XCEXVT)
    PRG_TEND (JI, IRCDRYG)=ICEP%XFCDRYG*PRCT (JI)*PRG_TEND (JI, IRCDRYG)
  ENDIF

ELSE
  PRG_TEND (JI, IRCDRYG)=0.
ENDIF


IF (PRGT (JI)>ICED%XRTMIN (6).AND.PRIT (JI)>ICED%XRTMIN (4).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRG_TEND (JI, IRIDRYG)=PLBDAG (JI)**(ICED%XCXG-ICED%XDG-2.)*PRHODREF (JI)**(-ICED%XCEXVT)
    PRG_TEND (JI, IRIDRYG)=ICEP%XFIDRYG*EXP (ICEP%XCOLEXIG*&
    &(PT (JI)-CST%XTT))*PRIT (JI)*PRG_TEND (JI, IRIDRYG)
    PRG_TEND (JI, IRIWETG)=PRG_TEND (JI, IRIDRYG)/(ICEP%XCOLIG*EXP (ICEP%XCOLEXIG*(PT (JI)-CST%XTT)))
  ENDIF

ELSE
  PRG_TEND (JI, IRIDRYG)=0.
  PRG_TEND (JI, IRIWETG)=0.
ENDIF




IF (PRST (JI)>ICED%XRTMIN (5).AND.PRGT (JI)>ICED%XRTMIN (6).AND.LDCOMPUTE (JI)) THEN
  GDRY =.TRUE.

  IF (PARAMI%LOCND2) THEN
    PRG_TEND (JI, IRSDRYG)=0.
    PRG_TEND (JI, IRSWETG)=0.
  ENDIF

ELSE
  GDRY =.FALSE.
  PRG_TEND (JI, IRSDRYG)=0.
  PRG_TEND (JI, IRSWETG)=0.
ENDIF



IF (.NOT.LDSOFT) THEN

  

  IF (PARAMI%LPACK_INTERP) THEN
    IGDRY=0

    

    IF (GDRY ) THEN
      IGDRY=IGDRY+1
      ZBUF1 =PLBDAG (JI)
      ZBUF2 =PLBDAS (JI)
      IBUF3 =JI
    ENDIF


    

    IF (IGDRY>0) THEN
      
      ZBUF1 =MAX (1.00001, MIN (REAL (ICEP%NDRYLBDAG)-0.00001&
      &, ICEP%XDRYINTP1G*LOG (ZBUF1 )+ICEP%XDRYINTP2G))
      IBUF1 =INT (ZBUF1 )
      ZBUF1 =ZBUF1 -REAL (IBUF1 )
      ZBUF2 =MAX (1.00001, MIN (REAL (ICEP%NDRYLBDAS)-0.00001&
      &, ICEP%XDRYINTP1S*LOG (ZBUF2 )+ICEP%XDRYINTP2S))
      IBUF2 =INT (ZBUF2 )
      ZBUF2 =ZBUF2 -REAL (IBUF2 )
      
      
      ZBUF3 =(ICEP %XKER_SDRYG(IBUF1 +1, IBUF2 +1)*ZBUF2 -ICEP %XKER_SDRYG(IBUF1&
      & +1, IBUF2 )*(ZBUF2 -1.0))*ZBUF1 -(ICEP %XKER_SDRYG(IBUF1 , IBUF2 +1)*ZBUF2&
      & -ICEP %XKER_SDRYG(IBUF1 , IBUF2 )*(ZBUF2 -1.0))*(ZBUF1 -1.0)
      
      ZZW =0.
      
      ZZW =ZBUF3 
    
    
    
    ENDIF

  ELSE
    IGDRY=0

    

    IF (GDRY ) THEN
      IGDRY=IGDRY+1
      ZINDEX1=MAX (1.00001, MIN (REAL (ICEP%NDRYLBDAG)-0.00001&
      &, ICEP%XDRYINTP1G*LOG (PLBDAG (JI))+ICEP%XDRYINTP2G))
      IINDEX1=INT (ZINDEX1)
      ZINDEX1=ZINDEX1-REAL (IINDEX1)
      ZINDEX2=MAX (1.00001, MIN (REAL (ICEP%NDRYLBDAG)-0.00001&
      &, ICEP%XDRYINTP1S*LOG (PLBDAS (JI))+ICEP%XDRYINTP2S))
      IINDEX2=INT (ZINDEX2)
      ZINDEX2=ZINDEX2-REAL (IINDEX2)
      ZZW =(ICEP %XKER_SDRYG(IINDEX1+1, IINDEX2+1)*ZINDEX2-ICEP %XKER_SDRYG(IINDEX1&
      &+1, IINDEX2)*(ZINDEX2-1.0))*ZINDEX1-(ICEP %XKER_SDRYG(IINDEX1, IINDEX2+1)*ZINDEX2&
      &-ICEP %XKER_SDRYG(IINDEX1, IINDEX2)*(ZINDEX2-1.0))*(ZINDEX1-1.0)
    
    
    ELSE
      ZZW =0.
    
    
    ENDIF

  
  ENDIF


  

  

  IF (IGDRY>0) THEN

    

    IF (.NOT.ICEP%LNEWCOEFF) THEN

      IF (.NOT.PARAMI%LOCND2) THEN

        IF (GDRY ) THEN
          PRG_TEND (JI, IRSWETG)=ICEP%XFSDRYG*ZZW /ICEP%XCOLSG*(PLBDAS (JI)**(ICED%XCXS-ICED%XBS)&
          &)*(PLBDAG (JI)**ICED%XCXG)*(PRHODREF (JI)**(-ICED%XCEXVT-1.))*(ICEP%XLBSDRYG1/(PLBDAG &
          &(JI)**2)+ICEP%XLBSDRYG2/(PLBDAG (JI)*PLBDAS (JI))+ICEP%XLBSDRYG3/(PLBDAS (JI)**2))
        ENDIF

      ENDIF

    ELSE

      IF (GDRY ) THEN
        PRG_TEND (JI, IRSWETG)=ICEP%XFSDRYG*ZZW /ICEP%XCOLSG*(PRST (JI))*(PLBDAG (JI)*&
        &*ICED%XCXG)*(PRHODREF (JI)**(-ICED%XCEXVT))*(ICEP%XLBSDRYG1/(PLBDAG (JI)**2)+ICEP&
        &%XLBSDRYG2/(PLBDAG (JI)*PLBDAS (JI))+ICEP%XLBSDRYG3/(PLBDAS (JI)**2))
      ENDIF

    ENDIF


    IF (GDRY ) THEN
      PRG_TEND (JI, IRSDRYG)=PRG_TEND (JI, IRSWETG)*ICEP%XCOLSG*EXP (ICEP%XCOLEXSG*(PT (JI)-CST%XTT))
    ENDIF

  
  ENDIF

ENDIF



IF (PRRT (JI)>ICED%XRTMIN (3).AND.PRGT (JI)>ICED%XRTMIN (6).AND.LDCOMPUTE (JI)) THEN
  GDRY =.TRUE.
ELSE
  GDRY =.FALSE.
  PRG_TEND (JI, IRRDRYG)=0.
ENDIF



IF (.NOT.LDSOFT) THEN

  

  IF (PARAMI%LPACK_INTERP) THEN
    IGDRY=0

    

    IF (GDRY ) THEN
      IGDRY=IGDRY+1
      ZBUF1 =PLBDAG (JI)
      ZBUF2 =PLBDAR (JI)
      IBUF3 =JI
    ENDIF


    

    IF (IGDRY>0) THEN
      
      ZBUF1 =MAX (1.00001, MIN (REAL (ICEP%NDRYLBDAG)-0.00001&
      &, ICEP%XDRYINTP1G*LOG (ZBUF1 )+ICEP%XDRYINTP2G))
      IBUF1 =INT (ZBUF1 )
      ZBUF1 =ZBUF1 -REAL (IBUF1 )
      ZBUF2 =MAX (1.00001, MIN (REAL (ICEP%NDRYLBDAR)-0.00001&
      &, ICEP%XDRYINTP1R*LOG (ZBUF2 )+ICEP%XDRYINTP2R))
      IBUF2 =INT (ZBUF2 )
      ZBUF2 =ZBUF2 -REAL (IBUF2 )
      
      
      ZBUF3 =(ICEP %XKER_RDRYG(IBUF1 +1, IBUF2 +1)*ZBUF2 -ICEP %XKER_RDRYG(IBUF1&
      & +1, IBUF2 )*(ZBUF2 -1.0))*ZBUF1 -(ICEP %XKER_RDRYG(IBUF1 , IBUF2 +1)*ZBUF2&
      & -ICEP %XKER_RDRYG(IBUF1 , IBUF2 )*(ZBUF2 -1.0))*(ZBUF1 -1.0)
      
      ZZW =0.
      
      ZZW =ZBUF3 
    
    
    
    ENDIF

  ELSE
    IGDRY=0

    

    IF (GDRY ) THEN
      IGDRY=IGDRY+1
      ZINDEX1=MAX (1.00001, MIN (REAL (ICEP%NDRYLBDAG)-0.00001&
      &, ICEP%XDRYINTP1G*LOG (PLBDAG (JI))+ICEP%XDRYINTP2G))
      IINDEX1=INT (ZINDEX1)
      ZINDEX1=ZINDEX1-REAL (IINDEX1)
      ZINDEX2=MAX (1.00001, MIN (REAL (ICEP%NDRYLBDAG)-0.00001&
      &, ICEP%XDRYINTP1R*LOG (PLBDAR (JI))+ICEP%XDRYINTP2R))
      IINDEX2=INT (ZINDEX2)
      ZINDEX2=ZINDEX2-REAL (IINDEX2)
      ZZW =(ICEP %XKER_RDRYG(IINDEX1+1, IINDEX2+1)*ZINDEX2-ICEP %XKER_RDRYG(IINDEX1&
      &+1, IINDEX2)*(ZINDEX2-1.0))*ZINDEX1-(ICEP %XKER_RDRYG(IINDEX1, IINDEX2+1)*ZINDEX2&
      &-ICEP %XKER_RDRYG(IINDEX1, IINDEX2)*(ZINDEX2-1.0))*(ZINDEX1-1.0)
    
    
    ELSE
      ZZW =0.
    
    
    ENDIF

  
  ENDIF


  

  

  IF (IGDRY>0) THEN

    

    IF (GDRY ) THEN
      PRG_TEND (JI, IRRDRYG)=ICEP%XFRDRYG*ZZW *(PLBDAR (JI)**(-4))*(PLBDAG (JI)**ICED&
      &%XCXG)*(PRHODREF (JI)**(-ICED%XCEXVT-1.))*(ICEP%XLBRDRYG1/(PLBDAG (JI)**2)+ICEP&
      &%XLBRDRYG2/(PLBDAG (JI)*PLBDAR (JI))+ICEP%XLBRDRYG3/(PLBDAR (JI)**2))
    ENDIF

  
  ENDIF

ENDIF


ZRDRYG_INIT =PRG_TEND (JI, IRCDRYG)+PRG_TEND (JI, IRIDRYG&
&)+PRG_TEND (JI, IRSDRYG)+PRG_TEND (JI, IRRDRYG)



IF (PRGT (JI)>ICED%XRTMIN (6).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRG_TEND (JI, IFREEZ1)=PRVT (JI)*PPRES (JI)/(CST%XEPSILO+PRVT (JI))

    IF (PARAMI%LEVLIMIT) THEN
      PRG_TEND (JI, IFREEZ1)=MIN (PRG_TEND (JI, IFREEZ1), EXP (CST&
      &%XALPI-CST%XBETAI/PT (JI)-CST%XGAMI*LOG (PT (JI))))
    ENDIF

    PRG_TEND (JI, IFREEZ1)=PKA (JI)*(CST%XTT-PT (JI))+(PDV (JI)*(CST%XLVTT+(CST%XCPV-CST&
    &%XCL)*(PT (JI)-CST%XTT))*(CST%XESTT-PRG_TEND (JI, IFREEZ1))/(CST%XRV*PT (JI)))
    PRG_TEND (JI, IFREEZ1)=PRG_TEND (JI, IFREEZ1)*(ICEP%X0DEPG*PLBDAG (JI)**ICEP%XEX0DEPG+ICEP%X1DEPG&
    &*PCJ (JI)*PLBDAG (JI)**ICEP%XEX1DEPG)/(PRHODREF (JI)*(CST%XLMTT-CST%XCL*(CST%XTT-PT (JI))))
    PRG_TEND (JI, IFREEZ2)=(PRHODREF (JI)*(CST%XLMTT+(CST%XCI-CST%XCL)*(CST%XTT&
    &-PT (JI))))/(PRHODREF (JI)*(CST%XLMTT-CST%XCL*(CST%XTT-PT (JI))))
  ENDIF

  ZRWETG_INIT =MAX (PRG_TEND (JI, IRIWETG)+PRG_TEND (JI, IRSWETG), MAX (0., PRG_TEND (JI&
  &, IFREEZ1)+PRG_TEND (JI, IFREEZ2)*(PRG_TEND (JI, IRIWETG)+PRG_TEND (JI, IRSWETG))))
  LDWETG (JI)=MAX (0., ZRWETG_INIT -PRG_TEND (JI, IRIWETG)-PRG_TEND (JI, IRSWETG&
  &))<=MAX (0., ZRDRYG_INIT -PRG_TEND (JI, IRIDRYG)-PRG_TEND (JI, IRSDRYG))

  IF (PARAMI%LNULLWETG) THEN
    LDWETG (JI)=LDWETG (JI).AND.ZRDRYG_INIT >0.
  ELSE
    LDWETG (JI)=LDWETG (JI).AND.ZRWETG_INIT >0.
  ENDIF


  IF (.NOT.PARAMI%LWETGPOST) THEN
    LDWETG (JI)=LDWETG (JI).AND.PT (JI)<CST%XTT
  ENDIF

  LLDRYG =PT (JI)<CST%XTT.AND.ZRDRYG_INIT >1.E-20.AND.MAX (0., ZRWETG_INIT -PRG_TEND (JI, IRIWETG)&
  &-PRG_TEND (JI, IRSWETG))>MAX (0., ZRDRYG_INIT -PRG_TEND (JI, IRIDRYG)-PRG_TEND (JI, IRSDRYG))
ELSE
  PRG_TEND (JI, IFREEZ1)=0.
  PRG_TEND (JI, IFREEZ2)=0.
  ZRWETG_INIT =0.
  LDWETG (JI)=.FALSE.
  LLDRYG =.FALSE.
ENDIF



IF (KRR==7) THEN

  

  IF (LDWETG (JI)) THEN
    PRWETGH (JI)=(MAX (0., PRGSI (JI)+PRICFRRG (JI)+PRRCFRIG (JI&
    &))+ZRWETG_INIT )*ZRDRYG_INIT /(ZRWETG_INIT +ZRDRYG_INIT )
    PRWETGH_MR (JI)=MAX (0., PRGSI_MR (JI))*ZRDRYG_INIT /(ZRWETG_INIT +ZRDRYG_INIT )
  ELSE
    PRWETGH (JI)=0.
    PRWETGH_MR (JI)=0.
  ENDIF

  
ELSE
  PRWETGH (JI)=0.
  PRWETGH_MR (JI)=0.
ENDIF



IF (LDWETG (JI)) THEN
  PRRWETG (JI)=-(PRG_TEND (JI, IRIWETG)+PRG_TEND (JI, IRSWETG)+PRG_TEND (JI, IRCDRYG)-ZRWETG_INIT )
  PRCWETG (JI)=PRG_TEND (JI, IRCDRYG)
  PRIWETG (JI)=PRG_TEND (JI, IRIWETG)
  PRSWETG (JI)=PRG_TEND (JI, IRSWETG)
ELSE
  PRRWETG (JI)=0.
  PRCWETG (JI)=0.
  PRIWETG (JI)=0.
  PRSWETG (JI)=0.
ENDIF


IF (LLDRYG ) THEN
  PRCDRYG (JI)=PRG_TEND (JI, IRCDRYG)
  PRRDRYG (JI)=PRG_TEND (JI, IRRDRYG)
  PRIDRYG (JI)=PRG_TEND (JI, IRIDRYG)
  PRSDRYG (JI)=PRG_TEND (JI, IRSDRYG)
ELSE
  PRCDRYG (JI)=0.
  PRRDRYG (JI)=0.
  PRIDRYG (JI)=0.
  PRSDRYG (JI)=0.
ENDIF




IF (PRGT (JI)>ICED%XRTMIN (6).AND.PT (JI)>CST%XTT.AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRGMLTR (JI)=PRVT (JI)*PPRES (JI)/(CST%XEPSILO+PRVT (JI))

    IF (PARAMI%LEVLIMIT) THEN
      PRGMLTR (JI)=MIN (PRGMLTR (JI), EXP (CST%XALPW-CST%XBETAW/PT (JI)-CST%XGAMW*LOG (PT (JI))))
    ENDIF

    PRGMLTR (JI)=PKA (JI)*(CST%XTT-PT (JI))+PDV (JI)*(CST%XLVTT+(CST%XCPV-CST&
    &%XCL)*(PT (JI)-CST%XTT))*(CST%XESTT-PRGMLTR (JI))/(CST%XRV*PT (JI))
    PRGMLTR (JI)=MAX (0.,(-PRGMLTR (JI)*(ICEP%X0DEPG*PLBDAG (JI)**ICEP%XEX0DEPG+ICEP%X1DEPG&
    &*PCJ (JI)*PLBDAG (JI)**ICEP%XEX1DEPG)-(PRG_TEND (JI, IRCDRYG)+PRG_TEND (JI, IRRDRYG&
    &))*(PRHODREF (JI)*CST%XCL*(CST%XTT-PT (JI))))/(PRHODREF (JI)*CST%XLMTT))
  ENDIF

ELSE
  PRGMLTR (JI)=0.
ENDIF







END SUBROUTINE ICE4_FAST_RG_OPENACC

ENDMODULE MODE_ICE4_FAST_RG_OPENACC
