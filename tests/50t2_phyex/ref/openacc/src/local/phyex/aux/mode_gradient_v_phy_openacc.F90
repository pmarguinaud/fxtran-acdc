MODULE MODE_GRADIENT_V_PHY_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE GZ_V_VW_PHY_OPENACC (D, PA, PDZZ, PGZ_V_VW, YDSTACK)
!$ACC ROUTINE (GZ_V_VW_PHY_OPENACC) SEQ      

USE MODE_SHUMAN_PHY,ONLY:DZM_PHY, MYM_PHY
USE MODE_SHUMAN_PHY_OPENACC, ONLY : MYM_PHY_OPENACC
USE MODE_SHUMAN_PHY_OPENACC, ONLY : DZM_PHY_OPENACC
USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE

TYPE (DIMPHYEX_T), INTENT (IN)::D
REAL, INTENT (IN)::PA(D%NIT, D%NJT, D%NKT)
REAL, INTENT (IN)::PDZZ(D%NIT, D%NJT, D%NKT)
REAL, INTENT (OUT)::PGZ_V_VW(D%NIT, D%NJT, D%NKT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
TYPE(FXTRAN_ACDC_STACK) :: YLSTACK
fxtran_acdc_temp (REAL, PDZZ_WORK, (D%NIT, D%NJT, D%NKT))
fxtran_acdc_temp (REAL, PA_WORK, (D%NIT, D%NJT, D%NKT))
INTEGER::JK
INTEGER::JJ
INTEGER::JI
INTEGER::IKT
INTEGER::IJE
INTEGER::IIE
INTEGER::IJB
INTEGER::IIB

YLSTACK = YDSTACK



IF (KIND (PDZZ_WORK) == 8) THEN
    fxtran_acdc_alloc8 (PDZZ_WORK)
ELSEIF (KIND (PDZZ_WORK) == 4) THEN
    fxtran_acdc_alloc4 (PDZZ_WORK)
ELSE
    STOP 1
ENDIF


IF (KIND (PA_WORK) == 8) THEN
    fxtran_acdc_alloc8 (PA_WORK)
ELSEIF (KIND (PA_WORK) == 4) THEN
    fxtran_acdc_alloc4 (PA_WORK)
ELSE
    STOP 1
ENDIF


JI = D%NIB


IIE=D%NIEC
IIB=D%NIBC
IJE=D%NJEC
IJB=D%NJBC
IKT=D%NKT
CALL DZM_PHY_OPENACC (D, PA, PA_WORK, YDSTACK=YLSTACK)
CALL MYM_PHY_OPENACC (D, PDZZ, PDZZ_WORK, YDSTACK=YLSTACK)

DO JK=1, IKT

  DO JJ=IJB, IJE
    
    PGZ_V_VW (JI, JJ, JK)=PA_WORK (JI, JJ, JK)/PDZZ_WORK (JI, JJ, JK)
  
  ENDDO

ENDDO

END SUBROUTINE GZ_V_VW_PHY_OPENACC

SUBROUTINE GY_V_M_PHY_OPENACC (D, OFLAT, PA, PDYY, PDZZ, PDZY, PGY_V_M, YDSTACK)
!$ACC ROUTINE (GY_V_M_PHY_OPENACC) SEQ      


USE MODE_SHUMAN_PHY,ONLY:DZM_PHY, DYF_PHY, MYF_PHY, MZF_PHY
USE MODE_SHUMAN_PHY_OPENACC, ONLY : MZF_PHY_OPENACC
USE MODE_SHUMAN_PHY_OPENACC, ONLY : MYF_PHY_OPENACC
USE MODE_SHUMAN_PHY_OPENACC, ONLY : DZM_PHY_OPENACC
USE MODE_SHUMAN_PHY_OPENACC, ONLY : DYF_PHY_OPENACC
USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE

TYPE (DIMPHYEX_T), INTENT (IN)::D
LOGICAL, INTENT (IN)::OFLAT
REAL, INTENT (IN)::PA(D%NIT, D%NJT, D%NKT)
REAL, INTENT (IN)::PDYY(D%NIT, D%NJT, D%NKT)
REAL, INTENT (IN)::PDZZ(D%NIT, D%NJT, D%NKT)
REAL, INTENT (IN)::PDZY(D%NIT, D%NJT, D%NKT)
REAL, INTENT (OUT)::PGY_V_M(D%NIT, D%NJT, D%NKT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
TYPE(FXTRAN_ACDC_STACK) :: YLSTACK
fxtran_acdc_temp (REAL, ZWORK4, (D%NIT, D%NJT, D%NKT))
fxtran_acdc_temp (REAL, ZWORK3, (D%NIT, D%NJT, D%NKT))
fxtran_acdc_temp (REAL, ZWORK2, (D%NIT, D%NJT, D%NKT))
fxtran_acdc_temp (REAL, ZWORK1, (D%NIT, D%NJT, D%NKT))
INTEGER::IKT
INTEGER::IJE
INTEGER::IIE
INTEGER::IJB
INTEGER::IIB
INTEGER::JK
INTEGER::JJ
INTEGER::JI


YLSTACK = YDSTACK



IF (KIND (ZWORK4) == 8) THEN
    fxtran_acdc_alloc8 (ZWORK4)
ELSEIF (KIND (ZWORK4) == 4) THEN
    fxtran_acdc_alloc4 (ZWORK4)
ELSE
    STOP 1
ENDIF


IF (KIND (ZWORK3) == 8) THEN
    fxtran_acdc_alloc8 (ZWORK3)
ELSEIF (KIND (ZWORK3) == 4) THEN
    fxtran_acdc_alloc4 (ZWORK3)
ELSE
    STOP 1
ENDIF


IF (KIND (ZWORK2) == 8) THEN
    fxtran_acdc_alloc8 (ZWORK2)
ELSEIF (KIND (ZWORK2) == 4) THEN
    fxtran_acdc_alloc4 (ZWORK2)
ELSE
    STOP 1
ENDIF


IF (KIND (ZWORK1) == 8) THEN
    fxtran_acdc_alloc8 (ZWORK1)
ELSEIF (KIND (ZWORK1) == 4) THEN
    fxtran_acdc_alloc4 (ZWORK1)
ELSE
    STOP 1
ENDIF


JI = D%NIB


IIE=D%NIEC
IIB=D%NIBC
IJE=D%NJEC
IJB=D%NJBC
IKT=D%NKT
CALL DYF_PHY_OPENACC (D, PA, ZWORK1, YDSTACK=YLSTACK)
CALL MYF_PHY_OPENACC (D, PDYY, ZWORK2, YDSTACK=YLSTACK)

CALL DZM_PHY_OPENACC (D, PA, ZWORK3, YDSTACK=YLSTACK)

DO JK=1, IKT

  DO JJ=IJB, IJE
    
    ZWORK3 (JI, JJ, JK)=ZWORK3 (JI, JJ, JK)*PDZY (JI, JJ, JK)
  
  ENDDO

ENDDO

CALL MYF_PHY_OPENACC (D, ZWORK3, ZWORK4, YDSTACK=YLSTACK)

DO JK=1, IKT

  DO JJ=IJB, IJE
    
    ZWORK4 (JI, JJ, JK)=ZWORK4 (JI, JJ, JK)/PDZZ (JI, JJ, JK)
  
  ENDDO

ENDDO

CALL MZF_PHY_OPENACC (D, ZWORK4, ZWORK3, YDSTACK=YLSTACK)

DO JK=1, IKT

  DO JJ=IJB, IJE
    
    PGY_V_M (JI, JJ, JK)=(ZWORK1 (JI, JJ, JK)-ZWORK3 (JI, JJ, JK))/ZWORK2 (JI, JJ, JK)
  
  ENDDO

ENDDO



END SUBROUTINE GY_V_M_PHY_OPENACC

ENDMODULE MODE_GRADIENT_V_PHY_OPENACC
