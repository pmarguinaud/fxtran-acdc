SUBROUTINE SUMCOUNTIDIOM_OPENACC (KIDIA, KFDIA, KLON, PQ, PT, PY, KC, LDA, PL, YDSTACK)
!$ACC ROUTINE (SUMCOUNTIDIOM_OPENACC) SEQ      

USE PARKIND1,ONLY:JPIM, JPRB
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


INTEGER (KIND=JPIM), INTENT (IN)::KLON
INTEGER (KIND=JPIM), INTENT (IN)::KFDIA
INTEGER (KIND=JPIM), INTENT (IN)::KIDIA
REAL (KIND=JPRB), INTENT (IN)::PQ (KLON)
REAL (KIND=JPRB), INTENT (INOUT)::PT (KLON)
REAL (KIND=JPRB), INTENT (OUT)::PY
REAL (KIND=JPRB), INTENT (IN)::PL (KLON, 3)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
INTEGER (KIND=JPIM), INTENT (OUT)::KC
LOGICAL, INTENT (IN)::LDA (KLON)
INTEGER (KIND=JPIM) :: JL

JL = KIDIA


PY=PQ (JL)
PY=1._JPRB-PQ (JL)
PY=PQ (JL)-PT (JL)
PY=2._JPRB*PQ (JL)

IF ((PQ (JL)*PT (JL))>0._JPRB)  THEN
  PT (JL)=1._JPRB
ENDIF

KC=MERGE (1, 0, LDA (JL))
KC=MERGE (1, 0, PQ (JL)>0._JPRB)
KC=MERGE (1, 0, LDA (JL).AND.PQ (JL)>0._JPRB)
KC=1+MERGE (1, 0, LDA (JL))

IF (MERGE (1, 0, LDA (JL))>0)  THEN
  PT (JL)=2._JPRB
ENDIF

PY=1._JPRB-(PQ (JL)-PT (JL))
PY=2._JPRB*(PQ (JL)+PT (JL))
PY=1._JPRB-(-PQ (JL))
PY=PL (JL, 2)
PY=SUM (PL (JL,:))
PY=SUM (PQ (JL), MASK=LDA (JL))
KC=COUNT (PL (JL,:)>0._JPRB)
KC=MERGE (1, 0, LDA (JL).OR.PQ (JL)>0._JPRB)*2

END SUBROUTINE SUMCOUNTIDIOM_OPENACC
