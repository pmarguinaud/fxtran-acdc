MODULE UTIL_CST_T_UPDATE_MOD
USE MODD_CST, ONLY : CST_T
INTERFACE ACDC_UPDATE
MODULE PROCEDURE ACDC_UPDATE_CST_T
END INTERFACE

CONTAINS
SUBROUTINE ACDC_UPDATE_CST_T (SELF, LDCOMPONENT)


USE FXTRAN_ACDC_IS_PRESENT_MOD
USE UTIL_CST_T_WIPE_MOD
USE UTIL_CST_T_COPY_MOD
IMPLICIT NONE
TYPE (CST_T), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDCOMPONENT

IF (FXTRAN_ACDC_IS_PRESENT (C_LOC (SELF), SIZEOF (SELF))) THEN
CALL ACDC_WIPE_CST_T (SELF, LDDELETED=LDCOMPONENT)
CALL ACDC_COPY_CST_T (SELF, LDCREATED=LDCOMPONENT)
ENDIF


END SUBROUTINE
END MODULE
