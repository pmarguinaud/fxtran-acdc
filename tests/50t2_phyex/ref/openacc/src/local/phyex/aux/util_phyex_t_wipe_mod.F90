MODULE UTIL_PHYEX_T_WIPE_MOD
USE MODD_PHYEX, ONLY : PHYEX_T
INTERFACE ACDC_WIPE
MODULE PROCEDURE ACDC_WIPE_PHYEX_T
END INTERFACE

CONTAINS
SUBROUTINE ACDC_WIPE_PHYEX_T (SELF, LDDELETED, LDFIELDAPI)
USE UTIL_CLOUDPAR_T_MOD
USE UTIL_CSTURB_T_MOD
USE UTIL_CST_T_MOD
USE UTIL_ELEC_DESCR_T_MOD
USE UTIL_ELEC_PARAM_T_MOD
USE UTIL_NEB_T_MOD
USE UTIL_NSV_T_MOD
USE UTIL_PARAM_ICE_T_MOD
USE UTIL_PARAM_LIMA_COLD_T_MOD
USE UTIL_PARAM_LIMA_MIXED_T_MOD
USE UTIL_PARAM_LIMA_WARM_T_MOD
USE UTIL_PARAM_LIMA_T_MOD
USE UTIL_PARAM_MFSHALL_T_MOD
USE UTIL_RAIN_ICE_DESCR_T_MOD
USE UTIL_RAIN_ICE_PARAM_T_MOD
USE UTIL_TURB_T_MOD
IMPLICIT NONE
TYPE (PHYEX_T), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDDELETED, LDFIELDAPI
LOGICAL :: LLDELETED
LOGICAL :: LLFIELDAPI
LLFIELDAPI = .FALSE.
IF (PRESENT (LDFIELDAPI)) THEN
  LLFIELDAPI = LDFIELDAPI
ENDIF
CALL ACDC_WIPE_CST_T (SELF%CST, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_PARAM_ICE_T (SELF%PARAM_ICEN, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_RAIN_ICE_DESCR_T (SELF%RAIN_ICE_DESCRN, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_RAIN_ICE_PARAM_T (SELF%RAIN_ICE_PARAMN, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_CLOUDPAR_T (SELF%CLOUDPARN, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_PARAM_MFSHALL_T (SELF%PARAM_MFSHALLN, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_CSTURB_T (SELF%CSTURB, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_TURB_T (SELF%TURBN, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_NEB_T (SELF%NEBN, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_PARAM_LIMA_T (SELF%PARAM_LIMA, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_PARAM_LIMA_WARM_T (SELF%PARAM_LIMA_WARM, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_PARAM_LIMA_COLD_T (SELF%PARAM_LIMA_COLD, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_PARAM_LIMA_MIXED_T (SELF%PARAM_LIMA_MIXED, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_ELEC_DESCR_T (SELF%ELEC_DESCR, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_ELEC_PARAM_T (SELF%ELEC_PARAM, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_WIPE_NSV_T (SELF%TNSV, LDDELETED=.TRUE., LDFIELDAPI=LDFIELDAPI)

LLDELETED = .FALSE.
IF (PRESENT (LDDELETED)) THEN
  LLDELETED = LDDELETED
ENDIF
IF (.NOT. LLDELETED) THEN
  !$ACC EXIT DATA DELETE (SELF)
ENDIF
END SUBROUTINE
END MODULE
