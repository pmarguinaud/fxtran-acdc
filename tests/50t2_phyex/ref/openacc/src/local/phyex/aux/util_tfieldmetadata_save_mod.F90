MODULE UTIL_TFIELDMETADATA_SAVE_MOD
USE MODD_FIELD, ONLY : TFIELDMETADATA
INTERFACE ACDC_SAVE
MODULE PROCEDURE ACDC_SAVE_TFIELDMETADATA
END INTERFACE

CONTAINS
SUBROUTINE ACDC_SAVE_TFIELDMETADATA (SELF, KLUN)

IMPLICIT NONE
TYPE (TFIELDMETADATA), INTENT (IN), TARGET :: SELF
INTEGER, INTENT (IN) :: KLUN

WRITE (KLUN) SELF%CMNHNAME
WRITE (KLUN) SELF%CSTDNAME
WRITE (KLUN) SELF%CLONGNAME
WRITE (KLUN) SELF%CUNITS
WRITE (KLUN) SELF%CCOMMENT
WRITE (KLUN) SELF%NGRID
WRITE (KLUN) SELF%NTYPE
WRITE (KLUN) SELF%NDIMS
WRITE (KLUN) SELF%CDIR
WRITE (KLUN) SELF%LTIMEDEP
END SUBROUTINE
END MODULE
