SUBROUTINE L04_LOWER_BOUND (KLON, KLEV, KIDIA, KFDIA, X, Y)
INTEGER, INTENT (IN)::KFDIA
INTEGER, INTENT (IN)::KIDIA
INTEGER, INTENT (IN)::KLEV
INTEGER, INTENT (IN)::KLON
REAL, INTENT (IN)::X (0:KLEV)
REAL, INTENT (OUT)::Y (0:KLEV)
INTEGER::JLEV
DO JLEV = 0, KLEV
  Y(JLEV)=2.*X(JLEV)
ENDDO
END SUBROUTINE
