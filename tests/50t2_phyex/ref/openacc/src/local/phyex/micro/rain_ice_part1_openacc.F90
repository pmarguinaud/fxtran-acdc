
SUBROUTINE RAIN_ICE_PART1_OPENACC (D, CST, PARAMI, ICEP, ICED, ELECP, ELECD, BUCONF, OELEC&
&, OSEDIM_BEARD, PTHVREFZIKB, PTSTEP, KRR, PEXN, PDZZ, PRHODJ, PRHODREF, PPABST, PCIT, PCLDFR&
&, PICLDFR, PSSIO, PHLC_HRC, PHLC_HCF, PHLI_HRI, PHLI_HCF, PTHT, PRT, PTHS, PRS, PINPRC, PINPRR&
&, PEVAP3D, PINPRS, PINPRG, PRAINFR, PSIGS, TBUDGETS, KBUDGETS, PQCT, PQRT, PQIT, PQST, PQGT&
&, PQCS, PQRS, PQIS, PQSS, PQGS, PEFIELDW, PSEA, PTOWN, PCONC3D, PINPRH, PFPR, PQHT, PQHS,&
& PT, PLVFACT, PLSFACT, PWR, PWTH, PZCONC3D, OMICRO, PRVHENI, PZZZZ, YDSTACK)
!$ACC ROUTINE (RAIN_ICE_PART1_OPENACC) SEQ      


USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_BUDGET,ONLY:TBUDGETDATA_PTR, TBUDGETCONF_T
USE MODD_CST,ONLY:CST_T
USE MODD_PARAM_ICE_N,ONLY:PARAM_ICE_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T
USE MODD_RAIN_ICE_PARAM_N,ONLY:RAIN_ICE_PARAM_T
USE MODD_ELEC_PARAM,ONLY:ELEC_PARAM_T
USE MODD_ELEC_DESCR,ONLY:ELEC_DESCR_T
USE MODD_FIELDS_ADDRESS,ONLY:IRC, IRG, IRH, IRI, IRR, IRS, IRV
USE MODE_MSG,ONLY:PRINT_MSG, NVERB_FATAL
USE MODE_ICE4_RAINFR_VERT,ONLY:ICE4_RAINFR_VERT
USE MODE_ICE4_COMPUTE_PDF,ONLY:ICE4_COMPUTE_PDF
USE MODE_ICE4_SEDIMENTATION,ONLY:ICE4_SEDIMENTATION
USE MODE_ICE4_SEDIMENTATION_OPENACC, ONLY : ICE4_SEDIMENTATION_OPENACC
USE MODE_TIWMX,ONLY:AM3, REDIN
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (DIMPHYEX_T), INTENT (IN)::D
TYPE (CST_T), INTENT (IN)::CST
TYPE (PARAM_ICE_T), INTENT (IN)::PARAMI
TYPE (RAIN_ICE_PARAM_T), INTENT (IN)::ICEP
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
TYPE (ELEC_PARAM_T), INTENT (IN)::ELECP
TYPE (ELEC_DESCR_T), INTENT (IN)::ELECD
TYPE (TBUDGETCONF_T), INTENT (IN)::BUCONF
LOGICAL, INTENT (IN)::OELEC
LOGICAL, INTENT (IN)::OSEDIM_BEARD
REAL, INTENT (IN)::PTHVREFZIKB
REAL, INTENT (IN)::PTSTEP
INTEGER, INTENT (IN)::KRR
REAL, INTENT (IN)::PEXN(D%NIJT, D%NKT)
REAL, INTENT (IN)::PDZZ(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRHODJ(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRHODREF(D%NIJT, D%NKT)
REAL, INTENT (IN)::PPABST(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PCIT(D%NIJT, D%NKT)
REAL, INTENT (IN)::PCLDFR(D%NIJT, D%NKT)
REAL, INTENT (IN)::PICLDFR(D%NIJT, D%NKT)
REAL, INTENT (IN)::PSSIO(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PHLC_HRC(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PHLC_HCF(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PHLI_HRI(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PHLI_HCF(D%NIJT, D%NKT)
REAL, INTENT (IN)::PTHT(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRT(D%NIJT, D%NKT, KRR)
REAL, INTENT (INOUT)::PTHS(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PRS(D%NIJT, D%NKT, KRR)
REAL, INTENT (OUT)::PINPRC(D%NIJT)
REAL, INTENT (OUT)::PINPRR(D%NIJT)
REAL, INTENT (OUT)::PEVAP3D(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PINPRS(D%NIJT)
REAL, INTENT (OUT)::PINPRG(D%NIJT)
REAL, INTENT (OUT)::PRAINFR(D%NIJT, D%NKT)
REAL, INTENT (IN)::PSIGS(D%NIJT, D%NKT)
TYPE (TBUDGETDATA_PTR), INTENT (INOUT)::TBUDGETS(KBUDGETS)
INTEGER, INTENT (IN)::KBUDGETS
REAL, OPTIONAL, INTENT (INOUT)::PQCT(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, OPTIONAL, INTENT (INOUT)::PQRT(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, OPTIONAL, INTENT (INOUT)::PQIT(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, OPTIONAL, INTENT (INOUT)::PQST(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, OPTIONAL, INTENT (INOUT)::PQGT(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, OPTIONAL, INTENT (INOUT)::PQCS(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, OPTIONAL, INTENT (INOUT)::PQRS(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, OPTIONAL, INTENT (INOUT)::PQIS(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, OPTIONAL, INTENT (INOUT)::PQSS(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, OPTIONAL, INTENT (INOUT)::PQGS(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, OPTIONAL, INTENT (IN)::PEFIELDW(MERGE (D%NIJT, 0&
&, OSEDIM_BEARD), MERGE (D%NKT, 0, OSEDIM_BEARD))
REAL, OPTIONAL, INTENT (IN)::PSEA(D%NIJT)
REAL, OPTIONAL, INTENT (IN)::PTOWN(D%NIJT)
REAL, OPTIONAL, INTENT (IN)::PCONC3D(D%NIJT, D%NKT)
REAL, OPTIONAL, INTENT (OUT)::PINPRH(D%NIJT)
REAL, OPTIONAL, INTENT (OUT)::PFPR(D%NIJT, D%NKT, KRR)
REAL, OPTIONAL, INTENT (INOUT)::PQHT(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, OPTIONAL, INTENT (INOUT)::PQHS(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, INTENT (OUT)::PT(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PLVFACT(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PLSFACT(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PWR(D%NIJT, D%NKT, 7)
REAL, INTENT (OUT)::PWTH(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PZCONC3D(D%NIJT, D%NKT)
LOGICAL, INTENT (OUT)::OMICRO(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PRVHENI(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PZZZZ(D%NIJT, D%NKT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
TYPE(FXTRAN_ACDC_STACK) :: YLSTACK

LOGICAL::LLCONC
LOGICAL::LLSEA_AND_TOWN
INTEGER::JK
INTEGER::JI
INTEGER::IIJT
INTEGER::IIJE
INTEGER::IIJB
INTEGER::IKB
INTEGER::IKTE
INTEGER::IKTB
fxtran_acdc_temp (REAL, ZSIGMA_RC, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZHLC_LCF, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZHLC_LRC, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZHLI_LCF, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZHLI_LRI, (D%NIJT, D%NKT))
REAL::ZINV_TSTEP
REAL::ZICEDRTMIN(KRR)
REAL::ZZSUM
REAL::ZRICE
REAL::ZDEVIDE
fxtran_acdc_temp (REAL, ZW3D, (D%NIJT, D%NKT))
REAL::ZCONC_TMP
fxtran_acdc_temp (LOGICAL, LLW3D, (D%NIJT, D%NKT))
TYPE (DIMPHYEX_T)::DD
INTEGER::ISIZE
REAL::ZW
LOGICAL::GNEGT
REAL::ZSSI
REAL::ZUSW
REAL::ZZW
REAL::ZREDIN
REAL::ZAM3

YLSTACK = YDSTACK



IF (KIND (ZSIGMA_RC) == 8) THEN
    fxtran_acdc_alloc8 (ZSIGMA_RC)
ELSEIF (KIND (ZSIGMA_RC) == 4) THEN
    fxtran_acdc_alloc4 (ZSIGMA_RC)
ELSE
    STOP 1
ENDIF


IF (KIND (ZHLC_LCF) == 8) THEN
    fxtran_acdc_alloc8 (ZHLC_LCF)
ELSEIF (KIND (ZHLC_LCF) == 4) THEN
    fxtran_acdc_alloc4 (ZHLC_LCF)
ELSE
    STOP 1
ENDIF


IF (KIND (ZHLC_LRC) == 8) THEN
    fxtran_acdc_alloc8 (ZHLC_LRC)
ELSEIF (KIND (ZHLC_LRC) == 4) THEN
    fxtran_acdc_alloc4 (ZHLC_LRC)
ELSE
    STOP 1
ENDIF


IF (KIND (ZHLI_LCF) == 8) THEN
    fxtran_acdc_alloc8 (ZHLI_LCF)
ELSEIF (KIND (ZHLI_LCF) == 4) THEN
    fxtran_acdc_alloc4 (ZHLI_LCF)
ELSE
    STOP 1
ENDIF


IF (KIND (ZHLI_LRI) == 8) THEN
    fxtran_acdc_alloc8 (ZHLI_LRI)
ELSEIF (KIND (ZHLI_LRI) == 4) THEN
    fxtran_acdc_alloc4 (ZHLI_LRI)
ELSE
    STOP 1
ENDIF


IF (KIND (ZW3D) == 8) THEN
    fxtran_acdc_alloc8 (ZW3D)
ELSEIF (KIND (ZW3D) == 4) THEN
    fxtran_acdc_alloc4 (ZW3D)
ELSE
    STOP 1
ENDIF


IF (KIND (LLW3D) == 8) THEN
    fxtran_acdc_alloc8 (LLW3D)
ELSEIF (KIND (LLW3D) == 4) THEN
    fxtran_acdc_alloc4 (LLW3D)
ELSE
    STOP 1
ENDIF


JI = D%NIB


IKTB=D%NKTB
IKTE=D%NKTE
IKB=D%NKB
IIJB=D%NIB
IIJE=D%NIE
IIJT=D%NIJT
ZICEDRTMIN (1:KRR)=ICED%XRTMIN (1:KRR)
ZINV_TSTEP=1./PTSTEP
LLSEA_AND_TOWN=PRESENT (PSEA).AND.PRESENT (PTOWN)
LLCONC=PRESENT (PCONC3D)
OMICRO (JI,:)=.FALSE.

DO JK=IKTB, IKTE

  

  IF (KRR==7) THEN
    ZRICE=PRT (JI, JK, IRI)+PRT (JI, JK, IRS)+PRT (JI, JK, IRG)+PRT (JI, JK, IRH)
  ELSE
    ZRICE=PRT (JI, JK, IRI)+PRT (JI, JK, IRS)+PRT (JI, JK, IRG)
  ENDIF

  ZDEVIDE=CST%XCPD+CST%XCPV*PRT (JI, JK, IRV)+CST%XCL*(PRT&
  & (JI, JK, IRC)+PRT (JI, JK, IRR))+CST%XCI*ZRICE
  PT (JI, JK)=PTHT (JI, JK)*PEXN (JI, JK)
  PLSFACT (JI, JK)=(CST%XLSTT+(CST%XCPV-CST%XCI)*(PT (JI, JK)-CST%XTT))/ZDEVIDE
  PLVFACT (JI, JK)=(CST%XLVTT+(CST%XCPV-CST%XCL)*(PT (JI, JK)-CST%XTT))/ZDEVIDE

  IF (PARAMI%LOCND2) THEN

    IF (KRR==7) THEN
      OMICRO (JI, JK)=PSSIO (JI, JK)>ICEP%XFRMIN (12).OR.PRT (JI, JK, IRC)>ICEP%XFRMIN (13).OR.PRT &
      &(JI, JK, IRR)>ICEP%XFRMIN (13).OR.PRT (JI, JK, IRI)>ICEP%XFRMIN (13).OR.PRT (JI, JK, IRS)>ICEP&
      &%XFRMIN (13).OR.PRT (JI, JK, IRG)>ICEP%XFRMIN (13).OR.PRT (JI, JK, IRH)>ICEP%XFRMIN (13)
    ELSE
      OMICRO (JI, JK)=PSSIO (JI, JK)>ICEP%XFRMIN (12).OR.PRT (JI, JK, IRC)>ICEP%XFRMIN &
      &(13).OR.PRT (JI, JK, IRR)>ICEP%XFRMIN (13).OR.PRT (JI, JK, IRI)>ICEP%XFRMIN (13)&
      &.OR.PRT (JI, JK, IRS)>ICEP%XFRMIN (13).OR.PRT (JI, JK, IRG)>ICEP%XFRMIN (13)
    ENDIF

  ELSE

    IF (KRR==7) THEN
      OMICRO (JI, JK)=PRT (JI, JK, IRC)>ICED%XRTMIN (IRC).OR.PRT (JI, JK, IRR)>ICED%XRTMIN&
      & (IRR).OR.PRT (JI, JK, IRI)>ICED%XRTMIN (IRI).OR.PRT (JI, JK, IRS)>ICED%XRTMIN (IRS&
      &).OR.PRT (JI, JK, IRG)>ICED%XRTMIN (IRG).OR.PRT (JI, JK, IRH)>ICED%XRTMIN (IRH)
    ELSE
      OMICRO (JI, JK)=PRT (JI, JK, IRC)>ICED%XRTMIN (IRC).OR.PRT (JI, JK, IRR&
      &)>ICED%XRTMIN (IRR).OR.PRT (JI, JK, IRI)>ICED%XRTMIN (IRI).OR.PRT (JI,&
      & JK, IRS)>ICED%XRTMIN (IRS).OR.PRT (JI, JK, IRG)>ICED%XRTMIN (IRG)
    ENDIF

  ENDIF

  
ENDDO


ZZSUM=0.

DO JK=IKTE, IKTB,-1
  ZZSUM=ZZSUM+PDZZ (JI, JK)
  PZZZZ (JI, JK)=ZZSUM-PDZZ (JI, JK)*0.5
ENDDO


PZCONC3D (JI,:)=ICED%XCONC_LAND

IF (LLCONC.AND.PARAMI%LEXCLDROP) THEN

  DO JK=IKTB, IKTE
    
    PZCONC3D (JI, JK)=PCONC3D (JI, JK)
  
  ENDDO

ELSE

  IF (PARAMI%LEXCLDROP) THEN
    CALL FXTRAN_ACDC_ABORT ('WITH LEXCLDROP=TRUE CLOUD DROPLET FIELDS MUST BE PRESENT IN RAIN_ICE')
  ENDIF


  IF (LLSEA_AND_TOWN.AND.ICEP%XFRMIN (26)<0.001) THEN

    DO JK=IKTB, IKTE
      
      ZCONC_TMP =PSEA (JI)*ICED%XCONC_SEA+(1.-PSEA (JI))*ICED%XCONC_LAND
      PZCONC3D (JI, JK)=(1.-PTOWN (JI))*ZCONC_TMP +PTOWN (JI)*ICED%XCONC_URBAN
    
    ENDDO

  ENDIF


  IF (ICEP%XFRMIN (26)>0.001) THEN

    DO JK=IKTB, IKTE
      
      PZCONC3D (JI, JK)=ICEP%XFRMIN (26)*PPABST (JI, JK)/CST%XP00

      IF (ICEP%XFRMIN (22)>0.001.AND.LLSEA_AND_TOWN) THEN
        ZCONC_TMP =MAX (0., MIN (1.,(PZZZZ (JI, JK)-PZZZZ (JI, IKTE&
        &))/(MAX (0.01, ICEP%XFRMIN (29)-PZZZZ (JI, IKTE)))))
        PZCONC3D (JI, JK)=PZCONC3D (JI, JK)*(ICEP%XFRMIN (22)*(PSEA (JI)&
        &*ICEP%XFRMIN (30)+(1.-PSEA (JI)))*(1.-ZCONC_TMP )+ZCONC_TMP )
      ENDIF

    
    ENDDO

  ENDIF

ENDIF


IF (.NOT.PARAMI%LSEDIM_AFTER) THEN
  CALL ICE4_SEDIMENTATION_OPENACC (D, CST, ICEP, ICED, PARAMI, ELECP, ELECD, BUCONF, OELEC&
  &, OSEDIM_BEARD, PTSTEP, KRR, PDZZ, PTHVREFZIKB, PLVFACT, PLSFACT, PRHODREF, PPABST, PTHT&
  &, PT, PRHODJ, PTHS, PRT, PRS, PZCONC3D, PINPRC, PINPRR, PINPRS, PINPRG, PQCT, PQRT, PQIT&
  &, PQST, PQGT, PQCS, PQRS, PQIS, PQSS, PQGS, PEFIELDW, TBUDGETS, KBUDGETS, PSEA=PSEA, PTOWN&
  &=PTOWN, PINPRH=PINPRH, PFPR=PFPR, PQHT=PQHT, PQHS=PQHS, YDSTACK=YLSTACK)
ENDIF


DO JK=IKTB, IKTE
  
  PWTH (JI, JK)=PTHT (JI, JK)
  PWR (JI, JK, IRV)=PRT (JI, JK, IRV)
  PWR (JI, JK, IRC)=PRT (JI, JK, IRC)
  PWR (JI, JK, IRR)=PRT (JI, JK, IRR)
  PWR (JI, JK, IRI)=PRT (JI, JK, IRI)
  PWR (JI, JK, IRS)=PRT (JI, JK, IRS)
  PWR (JI, JK, IRG)=PRT (JI, JK, IRG)

  IF (KRR==7) THEN
    PWR (JI, JK, IRH)=PRT (JI, JK, IRH)
  ELSE
    PWR (JI, JK, IRH)=0.
  ENDIF


  IF (PARAMI%LWARM) THEN
    PEVAP3D (JI, JK)=0.
  ENDIF

  PRAINFR (JI, JK)=0.
  
ENDDO

LLW3D (JI,:)=.FALSE.

DO JK=IKTB, IKTE

  

  IF (.NOT.OMICRO (JI, JK)) THEN
    LLW3D (JI, JK)=.TRUE.
    ZW3D (JI, JK)=PLSFACT (JI, JK)/PEXN (JI, JK)
    PCIT (JI, JK)=0.
  ELSE
    LLW3D (JI, JK)=.FALSE.
  ENDIF

  
ENDDO


DO JK=IKTB, IKTE

  

  

  IF (LLW3D (JI, JK)) THEN
    GNEGT=PT (JI, JK)<CST%XTT.AND.PRT (JI, JK, IRV)>ICED%XRTMIN (1)
  ELSE
    GNEGT=.FALSE.
  ENDIF

  ZUSW=0.
  ZZW=0.

  IF (GNEGT) THEN
    ZZW=LOG (PT (JI, JK))
    ZUSW=EXP (CST%XALPW-CST%XBETAW/PT (JI, JK)-CST%XGAMW*ZZW)
    ZZW=EXP (CST%XALPI-CST%XBETAI/PT (JI, JK)-CST%XGAMI*ZZW)
  ENDIF

  ZSSI=0.

  IF (.NOT.PARAMI%LOCND2) THEN

    IF (GNEGT) THEN
      ZZW=MIN (PPABST (JI, JK)/2., ZZW)
      ZSSI=PRT (JI, JK, IRV)*(PPABST (JI, JK)-ZZW)/(CST%XEPSILO*ZZW)-1.0
      ZUSW=MIN (PPABST (JI, JK)/2., ZUSW)
      ZUSW=(ZUSW/ZZW)*((PPABST (JI, JK)-ZZW)/(PPABST (JI, JK)-ZUSW))-1.0
      ZSSI=MIN (ZSSI, ZUSW)
    ENDIF

    ZZW=0.

    IF (GNEGT) THEN

      IF (PT (JI, JK)<CST%XTT-5.0.AND.ZSSI>0.0) THEN
        ZZW=ICEP%XNU20*EXP (ICEP%XALPHA2*ZSSI-ICEP%XBETA2)
      ELSEIF (PT (JI, JK)<=CST%XTT-2.0.AND.PT (JI, JK)>=CST%XTT-5.0.AND.ZSSI>0.0) THEN
        ZZW=MAX (ICEP%XNU20*EXP (-ICEP%XBETA2), ICEP%XNU10*EXP (-ICEP&
        &%XBETA1*(PT (JI, JK)-CST%XTT))*(ZSSI/ZUSW)**ICEP%XALPHA1)
      ENDIF

    ENDIF


    IF (GNEGT) THEN
      ZZW=ZZW-PCIT (JI, JK)
      ZZW=MIN (ZZW, 50.E3)
    ENDIF

    PRVHENI (JI, JK)=0.

    IF (GNEGT) THEN
      PRVHENI (JI, JK)=MAX (ZZW, 0.0)*ICEP%XMNU0/PRHODREF (JI, JK)
      PRVHENI (JI, JK)=MIN (PRT (JI, JK, IRV), PRVHENI (JI, JK))
    ENDIF


    IF (PARAMI%LFEEDBACKT) THEN
      ZW=0.

      IF (GNEGT) THEN
        ZW=MIN (PRVHENI (JI, JK), MAX (0.,(CST%XTT/PEXN (JI, JK)-PTHT&
        & (JI, JK))/ZW3D (JI, JK)))/MAX (PRVHENI (JI, JK), 1.E-20)
      ENDIF

      PRVHENI (JI, JK)=PRVHENI (JI, JK)*ZW
      ZZW=ZZW*ZW
    ENDIF

  ELSE

    IF (GNEGT) THEN
      ZZW=MIN (PPABST (JI, JK)/2., ZZW)
      ZREDIN=REDIN (ICEP%TIWMX, PT (JI, JK))
      ZAM3=AM3 (ICEP%TIWMX, MAX (ICEP%XFRMIN (27), PT (JI, JK)))
      ZZW=ZREDIN*MAX (0.1,((20000.-MIN (20000., PZZZZ (JI, JK)&
      &))/20000.)**4)*ZAM3*(0.0001+0.9999*PICLDFR (JI, JK))
      ZZW=MIN (ZZW, 50.E3)
    ENDIF

    PRVHENI (JI, JK)=0.
  ENDIF


  IF (GNEGT) THEN
    PCIT (JI, JK)=MAX (ZZW+PCIT (JI, JK), PCIT (JI, JK))
  ENDIF

  
  
  
ENDDO


DO JK=IKTB, IKTE
  
  PRVHENI (JI, JK)=MIN (PRS (JI, JK, IRV), PRVHENI (JI, JK)/PTSTEP)
  
ENDDO


IF (PARAMI%CSUBG_RC_RR_ACCR=='PRFR'.OR.PARAMI%CSUBG_RR_EVAP=='PRFR') THEN
  CALL FXTRAN_ACDC_ABORT ('ERROR: WRONG SETTINGS')
  
ELSE
  PRAINFR (JI,:)=1.
ENDIF





END SUBROUTINE RAIN_ICE_PART1_OPENACC
