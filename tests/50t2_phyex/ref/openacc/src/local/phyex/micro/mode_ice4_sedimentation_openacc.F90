
MODULE MODE_ICE4_SEDIMENTATION_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE ICE4_SEDIMENTATION_OPENACC (D, CST, ICEP, ICED, PARAMI, ELECP, ELECD, BUCONF, OELEC, OSEDIM_BEARD&
&, PTSTEP, KRR, PDZZ, PTHVREFZIKB, PLVFACT, PLSFACT, PRHODREF, PPABST, PTHT, PT, PRHODJ, PTHS, PRT,&
& PRS, PCONC3D, PINPRC, PINPRR, PINPRS, PINPRG, PQCT, PQRT, PQIT, PQST, PQGT, PQCS, PQRS, PQIS, PQSS&
&, PQGS, PEFIELDW, TBUDGETS, KBUDGETS, PSEA, PTOWN, PINPRH, PFPR, PQHT, PQHS, YDSTACK)
!$ACC ROUTINE (ICE4_SEDIMENTATION_OPENACC) SEQ      


USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_BUDGET,ONLY:TBUDGETDATA_PTR, TBUDGETCONF_T, NBUDGET_RC, NBUDGET_SV1&
&, NBUDGET_RI, NBUDGET_RR, NBUDGET_RS, NBUDGET_RG, NBUDGET_RH
USE MODD_CST,ONLY:CST_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T
USE MODD_RAIN_ICE_PARAM_N,ONLY:RAIN_ICE_PARAM_T
USE MODD_PARAM_ICE_N,ONLY:PARAM_ICE_T
USE MODD_ELEC_DESCR,ONLY:ELEC_DESCR_T
USE MODD_ELEC_PARAM,ONLY:ELEC_PARAM_T
USE MODD_NSV,ONLY:NSV_ELECBEG
USE MODD_FIELDS_ADDRESS,ONLY:IRC, IRG, IRH, IRI, IRR, IRS
USE MODE_MSG,ONLY:PRINT_MSG, NVERB_FATAL
USE MODE_ICE4_SEDIMENTATION_STAT,ONLY:ICE4_SEDIMENTATION_STAT
USE MODE_ICE4_SEDIMENTATION_STAT_OPENACC, ONLY : ICE4_SEDIMENTATION_STAT_OPENACC
USE MODE_ICE4_SEDIMENTATION_SPLIT,ONLY:ICE4_SEDIMENTATION_SPLIT
USE MODE_ICE4_SEDIMENTATION_SPLIT_OPENACC, ONLY : ICE4_SEDIMENTATION_SPLIT_OPENACC
USE MODE_ICE4_CORRECT_NEGATIVITIES,ONLY:ICE4_CORRECT_NEGATIVITIES
USE MODE_ICE4_CORRECT_NEGATIVITIES_OPENACC, ONLY : ICE4_CORRECT_NEGATIVITIES_OPENACC
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (DIMPHYEX_T), INTENT (IN)::D
TYPE (CST_T), INTENT (IN)::CST
TYPE (RAIN_ICE_PARAM_T), INTENT (IN)::ICEP
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
TYPE (PARAM_ICE_T), INTENT (IN)::PARAMI
TYPE (ELEC_PARAM_T), INTENT (IN)::ELECP
TYPE (ELEC_DESCR_T), INTENT (IN)::ELECD
TYPE (TBUDGETCONF_T), INTENT (IN)::BUCONF
LOGICAL, INTENT (IN)::OELEC
LOGICAL, INTENT (IN)::OSEDIM_BEARD
REAL, INTENT (IN)::PTSTEP
INTEGER, INTENT (IN)::KRR
REAL, INTENT (IN)::PDZZ(D%NIJT, D%NKT)
REAL, INTENT (IN)::PLVFACT(D%NIJT, D%NKT)
REAL, INTENT (IN)::PLSFACT(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRHODREF(D%NIJT, D%NKT)
REAL, INTENT (IN)::PPABST(D%NIJT, D%NKT)
REAL, INTENT (IN)::PTHT(D%NIJT, D%NKT)
REAL, INTENT (IN)::PT(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRHODJ(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PTHS(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRT(D%NIJT, D%NKT, KRR)
REAL, INTENT (INOUT)::PRS(D%NIJT, D%NKT, KRR)
REAL, INTENT (IN)::PCONC3D(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PINPRC(D%NIJT)
REAL, INTENT (OUT)::PINPRR(D%NIJT)
REAL, INTENT (OUT)::PINPRS(D%NIJT)
REAL, INTENT (OUT)::PINPRG(D%NIJT)
TYPE (TBUDGETDATA_PTR), INTENT (INOUT)::TBUDGETS(KBUDGETS)
INTEGER, INTENT (IN)::KBUDGETS
REAL, INTENT (IN)::PTHVREFZIKB
REAL, INTENT (IN)::PQCT(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, INTENT (IN)::PQRT(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, INTENT (IN)::PQIT(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, INTENT (IN)::PQST(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, INTENT (IN)::PQGT(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, INTENT (INOUT)::PQCS(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, INTENT (INOUT)::PQRS(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, INTENT (INOUT)::PQIS(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, INTENT (INOUT)::PQSS(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, INTENT (INOUT)::PQGS(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, INTENT (IN)::PEFIELDW(MERGE (D%NIJT, 0, OSEDIM_BEARD), MERGE (D%NKT, 0, OSEDIM_BEARD))
REAL, OPTIONAL, INTENT (IN)::PSEA(D%NIJT)
REAL, OPTIONAL, INTENT (IN)::PTOWN(D%NIJT)
REAL, OPTIONAL, INTENT (OUT)::PINPRH(D%NIJT)
REAL, OPTIONAL, INTENT (OUT)::PFPR(D%NIJT, D%NKT, KRR)
REAL, OPTIONAL, INTENT (IN)::PQHT(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
REAL, OPTIONAL, INTENT (INOUT)::PQHS(MERGE (D%NIJT, 0, OELEC), MERGE (D%NKT, 0, OELEC))
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
TYPE(FXTRAN_ACDC_STACK) :: YLSTACK
fxtran_acdc_temp (REAL, ZRT, (D%NIJT, D%NKT, KRR))
fxtran_acdc_temp (REAL, ZINPRI, (D%NIJT))
fxtran_acdc_temp (REAL, ZWKBUD, (D%NIJT, D%NKT))
INTEGER::JRR
INTEGER::IIJE
INTEGER::IIJB
INTEGER::IKTE
INTEGER::IKTB
INTEGER::JI
INTEGER::JK

CHARACTER (LEN=100)::CTEMP

YLSTACK = YDSTACK



IF (KIND (ZRT) == 8) THEN
    fxtran_acdc_alloc8 (ZRT)
ELSEIF (KIND (ZRT) == 4) THEN
    fxtran_acdc_alloc4 (ZRT)
ELSE
    STOP 1
ENDIF


IF (KIND (ZINPRI) == 8) THEN
    fxtran_acdc_alloc8 (ZINPRI)
ELSEIF (KIND (ZINPRI) == 4) THEN
    fxtran_acdc_alloc4 (ZINPRI)
ELSE
    STOP 1
ENDIF


IF (KIND (ZWKBUD) == 8) THEN
    fxtran_acdc_alloc8 (ZWKBUD)
ELSEIF (KIND (ZWKBUD) == 4) THEN
    fxtran_acdc_alloc4 (ZWKBUD)
ELSE
    STOP 1
ENDIF


JI = D%NIB


IKTB=D%NKTB
IKTE=D%NKTE
IIJB=D%NIB
IIJE=D%NIE














IF (PARAMI%CSEDIM=='STAT') THEN

  IF (OELEC) THEN
    CALL FXTRAN_ACDC_ABORT ("OELEC=.T. not allowed with CSEDIM='STAT'")
  ENDIF


  DO JRR=2, KRR

    DO JK=IKTB, IKTE
      
      ZRT (JI, JK, JRR)=PRS (JI, JK, JRR)*PTSTEP
    
    ENDDO

  ENDDO

  CALL ICE4_SEDIMENTATION_STAT_OPENACC (D, CST, ICEP, ICED, PARAMI, PTSTEP, KRR, PDZZ,&
  & PRHODREF, PPABST, PTHT, PT, PRHODJ, PRS, ZRT, PCONC3D, PINPRC, PINPRR, ZINPRI, PINPRS&
  &, PINPRG, PSEA=PSEA, PTOWN=PTOWN, PINPRH=PINPRH, PFPR=PFPR, YDSTACK=YLSTACK)
  PINPRS (JI)=PINPRS (JI)+ZINPRI (JI)
ELSEIF (PARAMI%CSEDIM=='SPLI') THEN
  CALL ICE4_SEDIMENTATION_SPLIT_OPENACC (D, CST, ICEP, ICED, PARAMI, ELECP, ELECD, OELEC, OSEDIM_BEARD&
  &, PTHVREFZIKB, PTSTEP, KRR, PDZZ, PRHODREF, PPABST, PTHT, PT, PRHODJ, PRS, PRT, PCONC3D, PINPRC, PINPRR&
  &, ZINPRI, PINPRS, PINPRG, PQCT, PQRT, PQIT, PQST, PQGT, PQCS, PQRS, PQIS, PQSS, PQGS, PEFIELDW, PSEA&
  &=PSEA, PTOWN=PTOWN, PINPRH=PINPRH, PFPR=PFPR, PQHT=PQHT, PQHS=PQHS, YDSTACK=YLSTACK)
  PINPRS (JI)=PINPRS (JI)+ZINPRI (JI)
  CALL ICE4_CORRECT_NEGATIVITIES_OPENACC (D, ICED, KRR, PRS, PTHS, PLVFACT, PLSFACT, YDSTACK=YLSTACK)
ELSEIF (PARAMI%CSEDIM=='NONE') THEN
ELSE
  CTEMP='no sedimentation scheme for PARAMI%CSEDIM='//PARAMI%CSEDIM
  CALL FXTRAN_ACDC_ABORT (CTEMP)
ENDIF















END SUBROUTINE ICE4_SEDIMENTATION_OPENACC

ENDMODULE MODE_ICE4_SEDIMENTATION_OPENACC
