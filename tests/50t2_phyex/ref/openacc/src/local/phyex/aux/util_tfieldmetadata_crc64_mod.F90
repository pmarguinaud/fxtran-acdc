MODULE UTIL_TFIELDMETADATA_CRC64_MOD
USE MODD_FIELD, ONLY : TFIELDMETADATA
INTERFACE ACDC_CRC64
MODULE PROCEDURE ACDC_CRC64_TFIELDMETADATA
END INTERFACE

CONTAINS
SUBROUTINE ACDC_CRC64_TFIELDMETADATA (SELF, KLUN, CDPATH)
USE FXTRAN_ACDC_CRC64_INTRINSIC_MOD, ONLY : FCRC64 => FXTRAN_ACDC_CRC64
IMPLICIT NONE
TYPE (TFIELDMETADATA), TARGET :: SELF
INTEGER, INTENT (IN) :: KLUN
CHARACTER(LEN=*), INTENT (IN) :: CDPATH
CHARACTER(LEN=128) :: CLIND
WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%CMNHNAME), CDPATH//'%CMNHNAME'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%CSTDNAME), CDPATH//'%CSTDNAME'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%CLONGNAME), CDPATH//'%CLONGNAME'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%CUNITS), CDPATH//'%CUNITS'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%CCOMMENT), CDPATH//'%CCOMMENT'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%NGRID), CDPATH//'%NGRID'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%NTYPE), CDPATH//'%NTYPE'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%NDIMS), CDPATH//'%NDIMS'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%CDIR), CDPATH//'%CDIR'

WRITE (KLUN, '(Z16.16," ",A)') FCRC64 (SELF%LTIMEDEP), CDPATH//'%LTIMEDEP'

END SUBROUTINE
END MODULE
