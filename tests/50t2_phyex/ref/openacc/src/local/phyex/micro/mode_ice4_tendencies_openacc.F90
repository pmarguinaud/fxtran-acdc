DO JV=1, KRR
  ZVART (JI, JV)=PVART (JI, JV)
  PA (JI, JV)=0.
  PB (JI, JV)=0.
ENDDO


IF (ODSOFT) THEN
  PBU_INST (JI, IRVHENI_MR)=0.
  PBU_INST (JI, IRRHONG_MR)=0.
  PBU_INST (JI, IRIMLTC_MR)=0.
  PBU_INST (JI, IRSRIMCG_MR)=0.
ELSE

  

  

  IF (LDCOMPUTE (JI)) THEN
    GNEGT=ZT (JI)<CST%XTT.AND.ZVART (JI, IRV)>ICED%XRTMIN (1)
  ELSE
    GNEGT=.FALSE.
  ENDIF

  ZUSW=0.
  ZZW_ICE4_NUCLEATION=0.

  IF (GNEGT) THEN
    ZZW_ICE4_NUCLEATION=LOG (ZT (JI))
    ZUSW=EXP (CST%XALPW-CST%XBETAW/ZT (JI)-CST%XGAMW*ZZW_ICE4_NUCLEATION)
    ZZW_ICE4_NUCLEATION=EXP (CST%XALPI-CST%XBETAI/ZT (JI)-CST%XGAMI*ZZW_ICE4_NUCLEATION)
  ENDIF

  ZSSI=0.

  IF (.NOT.PARAMI%LOCND2) THEN

    IF (GNEGT) THEN
      ZZW_ICE4_NUCLEATION=MIN (PPRES (JI)/2., ZZW_ICE4_NUCLEATION)
      ZSSI=ZVART (JI, IRV)*(PPRES (JI)-ZZW_ICE4_NUCLEATION)/(CST%XEPSILO*ZZW_ICE4_NUCLEATION)-1.0
      ZUSW=MIN (PPRES (JI)/2., ZUSW)
      ZUSW=(ZUSW/ZZW_ICE4_NUCLEATION)*((PPRES (JI)-ZZW_ICE4_NUCLEATION)/(PPRES (JI)-ZUSW))-1.0
      ZSSI=MIN (ZSSI, ZUSW)
    ENDIF

    ZZW_ICE4_NUCLEATION=0.

    IF (GNEGT) THEN

      IF (ZT (JI)<CST%XTT-5.0.AND.ZSSI>0.0) THEN
        ZZW_ICE4_NUCLEATION=ICEP%XNU20*EXP (ICEP%XALPHA2*ZSSI-ICEP%XBETA2)
      ELSEIF (ZT (JI)<=CST%XTT-2.0.AND.ZT (JI)>=CST%XTT-5.0.AND.ZSSI>0.0) THEN
        ZZW_ICE4_NUCLEATION=MAX (ICEP%XNU20*EXP (-ICEP%XBETA2), ICEP%XNU10*EXP&
        & (-ICEP%XBETA1*(ZT (JI)-CST%XTT))*(ZSSI/ZUSW)**ICEP%XALPHA1)
      ENDIF

    ENDIF


    IF (GNEGT) THEN
      ZZW_ICE4_NUCLEATION=ZZW_ICE4_NUCLEATION-PCIT (JI)
      ZZW_ICE4_NUCLEATION=MIN (ZZW_ICE4_NUCLEATION, 50.E3)
    ENDIF

    PBU_INST (JI, IRVHENI_MR)=0.

    IF (GNEGT) THEN
      PBU_INST (JI, IRVHENI_MR)=MAX (ZZW_ICE4_NUCLEATION, 0.0)*ICEP%XMNU0/PRHODREF (JI)
      PBU_INST (JI, IRVHENI_MR)=MIN (ZVART (JI, IRV), PBU_INST (JI, IRVHENI_MR))
    ENDIF


    IF (PARAMI%LFEEDBACKT) THEN
      ZW=0.

      IF (GNEGT) THEN
        ZW=MIN (PBU_INST (JI, IRVHENI_MR), MAX (0.,(CST%XTT/PEXN (JI)-ZTH&
        & (JI))/PLSFACT (JI)))/MAX (PBU_INST (JI, IRVHENI_MR), 1.E-20)
      ENDIF

      PBU_INST (JI, IRVHENI_MR)=PBU_INST (JI, IRVHENI_MR)*ZW
      ZZW_ICE4_NUCLEATION=ZZW_ICE4_NUCLEATION*ZW
    ENDIF

  ELSE

    IF (GNEGT) THEN
      ZZW_ICE4_NUCLEATION=MIN (PPRES (JI)/2., ZZW_ICE4_NUCLEATION)
      ZREDIN=REDIN (ICEP%TIWMX, ZT (JI))
      ZAM3=AM3 (ICEP%TIWMX, MAX (ICEP%XFRMIN (27), ZT (JI)))
      ZZW_ICE4_NUCLEATION=ZREDIN*MAX (0.1,((20000.-MIN (20000., PZZZ&
      & (JI)))/20000.)**4)*ZAM3*(0.0001+0.9999*PICLDFR (JI))
      ZZW_ICE4_NUCLEATION=MIN (ZZW_ICE4_NUCLEATION, 50.E3)
    ENDIF

    PBU_INST (JI, IRVHENI_MR)=0.
  ENDIF


  IF (GNEGT) THEN
    PCIT (JI)=MAX (ZZW_ICE4_NUCLEATION+PCIT (JI), PCIT (JI))
  ENDIF

  
  
  
  
  ZTH (JI)=ZTH (JI)+PBU_INST (JI, IRVHENI_MR)*PLSFACT (JI)
  ZT (JI)=ZTH (JI)*PEXN (JI)
  ZVART (JI, IRV)=ZVART (JI, IRV)-PBU_INST (JI, IRVHENI_MR)
  ZVART (JI, IRI)=ZVART (JI, IRI)+PBU_INST (JI, IRVHENI_MR)
  
  CALL ICE4_RRHONG_OPENACC (CST, PARAMI, ICED, D, LDCOMPUTE, PEXN, PLVFACT, PLSFACT&
  &, ZT, ZVART (:, IRR), ZTH, PBU_INST (:, IRRHONG_MR), YDSTACK=YLSTACK)
  
  ZTH (JI)=ZTH (JI)+PBU_INST (JI, IRRHONG_MR)*(PLSFACT (JI)-PLVFACT (JI))
  ZT (JI)=ZTH (JI)*PEXN (JI)
  ZVART (JI, IRR)=ZVART (JI, IRR)-PBU_INST (JI, IRRHONG_MR)
  ZVART (JI, IRG)=ZVART (JI, IRG)+PBU_INST (JI, IRRHONG_MR)
  
  CALL ICE4_RIMLTC_OPENACC (CST, PARAMI, D, LDCOMPUTE, PEXN, PLVFACT, PLSFACT&
  &, ZT, ZTH, ZVART (:, IRI), PBU_INST (:, IRIMLTC_MR), YDSTACK=YLSTACK)
  
  ZTH (JI)=ZTH (JI)-PBU_INST (JI, IRIMLTC_MR)*(PLSFACT (JI)-PLVFACT (JI))
  ZT (JI)=ZTH (JI)*PEXN (JI)
  ZVART (JI, IRC)=ZVART (JI, IRC)+PBU_INST (JI, IRIMLTC_MR)
  ZVART (JI, IRI)=ZVART (JI, IRI)-PBU_INST (JI, IRIMLTC_MR)

  

  IF (PARAMI%CSNOWRIMING=='OLD ') THEN

    

    IF (PARAMI%LSNOW_T) THEN
      ZLBDAS (JI)=0.

      IF (ZVART (JI, IRS)>0..AND.ZT (JI)>263.15) THEN
        ZLBDAS (JI)=MAX (MIN (ICED%XLBDAS_MAX, 10**(14.554-0.0423&
        &*ZT (JI))), ICED%XLBDAS_MIN)*ICED%XTRANS_MP_GAMMAS
      ENDIF


      IF (ZVART (JI, IRS)>0..AND.ZT (JI)<=263.15) THEN
        ZLBDAS (JI)=MAX (MIN (ICED%XLBDAS_MAX, 10**(6.226-0.0106&
        &*ZT (JI))), ICED%XLBDAS_MIN)*ICED%XTRANS_MP_GAMMAS
      ENDIF

    ELSE

      IF (ZVART (JI, IRS)>0.) THEN
        ZLBDAS (JI)=MIN (ICED%XLBDAS_MAX, ICED%XLBS*(PRHODREF (JI)&
        &*MAX (ZVART (JI, IRS), ICED%XRTMIN (5)))**ICED%XLBEXS)
      ELSE
        ZLBDAS (JI)=0.
      ENDIF

    ENDIF

    
    CALL ICE4_RSRIMCG_OLD_OPENACC (CST, PARAMI, ICEP, ICED, D, ODSOFT, LDCOMPUTE, PRHODREF, ZLBDAS&
    &, ZT, ZVART (:, IRC), ZVART (:, IRS), PBU_INST (:, IRSRIMCG_MR), YDSTACK=YLSTACK)
    
    ZVART (JI, IRS)=ZVART (JI, IRS)-PBU_INST (JI, IRSRIMCG_MR)
    ZVART (JI, IRG)=ZVART (JI, IRG)+PBU_INST (JI, IRSRIMCG_MR)
  
  ELSE
    PBU_INST (JI, IRSRIMCG_MR)=0.
  ENDIF

  
  PBTH (JI)=PBTH (JI)+PBU_INST (JI, IRVHENI_MR)*PLSFACT (JI)
  PBTH (JI)=PBTH (JI)+PBU_INST (JI, IRRHONG_MR)*(PLSFACT (JI)-PLVFACT (JI))
  PBTH (JI)=PBTH (JI)-PBU_INST (JI, IRIMLTC_MR)*(PLSFACT (JI)-PLVFACT (JI))
  PB (JI, IRV)=PB (JI, IRV)-PBU_INST (JI, IRVHENI_MR)
  PB (JI, IRC)=PB (JI, IRC)+PBU_INST (JI, IRIMLTC_MR)
  PB (JI, IRR)=PB (JI, IRR)-PBU_INST (JI, IRRHONG_MR)
  PB (JI, IRI)=PB (JI, IRI)+PBU_INST (JI, IRVHENI_MR)
  PB (JI, IRI)=PB (JI, IRI)-PBU_INST (JI, IRIMLTC_MR)
  PB (JI, IRS)=PB (JI, IRS)-PBU_INST (JI, IRSRIMCG_MR)
  PB (JI, IRG)=PB (JI, IRG)+PBU_INST (JI, IRRHONG_MR)
  PB (JI, IRG)=PB (JI, IRG)+PBU_INST (JI, IRSRIMCG_MR)

  

  

  IF (LLTAB.AND.PARAMI%LOCND2) THEN
    ZESI (JI)=ESATI (ICEP%TIWMX, ZT (JI))
    PSSI (JI)=ZVART (JI, IRV)*(PPRES (JI)-ZESI (JI))/(CST%XEPSILO*ZESI (JI))-1.0
