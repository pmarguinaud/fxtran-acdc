REAL, INTENT (INOUT)::PWTH(D%NIJT, D%NKT)
REAL, INTENT (IN)::PCONC3D(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRVHENI(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::ZBUDGETS(MERGE (D%NIJT, 0, OELEC.OR.BUCONF%LBU_ENABLE), MERGE (D%NKT, 0&
&, OELEC.OR.BUCONF%LBU_ENABLE), MERGE (IBUNUM-IBUNUM_EXTRA, 0, OELEC.OR.BUCONF%LBU_ENABLE))
