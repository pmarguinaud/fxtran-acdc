
MODULE MODE_TKE_EPS_SOURCES_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE TKE_EPS_SOURCES_OPENACC (D, CST, CSTURB, BUCONF, TURBN, TLES, PTKEM, PLM,&
& PLEPS, PDP, PTRH, PRHODJ, PDZZ, PDXX, PDYY, PDZX, PDZY, PZZ, PTSTEP, PEXPL, TPFILE&
&, ODIAG_IN_RUN, OOCEAN, PSFUM, PSFVM, PTP, PRTKES, PRTHLS, PCOEF_DISS, PTDIFF, PTDISS&
&, PRTKEMS, TBUDGETS, KBUDGETS, PEDR, PTR, PDISS, PCURRENT_TKE_DISS, YDSTACK)
!$ACC ROUTINE (TKE_EPS_SOURCES_OPENACC) SEQ      

USE MODE_SHUMAN_PHY,ONLY:MZF_PHY

USE MODD_ARGSLIST_LL,ONLY:LIST_LL
USE MODD_BUDGET,ONLY:TBUDGETCONF_T, NBUDGET_TKE, TBUDGETDATA_PTR
USE MODD_CST,ONLY:CST_T
USE MODD_CTURB,ONLY:CSTURB_T
USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
