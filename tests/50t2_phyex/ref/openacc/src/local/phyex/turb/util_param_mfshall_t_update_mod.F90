MODULE UTIL_PARAM_MFSHALL_T_UPDATE_MOD
USE MODD_PARAM_MFSHALL_N, ONLY : PARAM_MFSHALL_T
INTERFACE ACDC_UPDATE
MODULE PROCEDURE ACDC_UPDATE_PARAM_MFSHALL_T
END INTERFACE

CONTAINS
SUBROUTINE ACDC_UPDATE_PARAM_MFSHALL_T (SELF, LDCOMPONENT)


USE FXTRAN_ACDC_IS_PRESENT_MOD
USE UTIL_PARAM_MFSHALL_T_WIPE_MOD
USE UTIL_PARAM_MFSHALL_T_COPY_MOD
IMPLICIT NONE
TYPE (PARAM_MFSHALL_T), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDCOMPONENT

IF (FXTRAN_ACDC_IS_PRESENT (C_LOC (SELF), SIZEOF (SELF))) THEN
CALL ACDC_WIPE_PARAM_MFSHALL_T (SELF, LDDELETED=LDCOMPONENT)
CALL ACDC_COPY_PARAM_MFSHALL_T (SELF, LDCREATED=LDCOMPONENT)
ENDIF


END SUBROUTINE
END MODULE
