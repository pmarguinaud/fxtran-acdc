MODULE UTIL_CONVPAREXT_UPDATE_MOD
USE MODD_CONVPAREXT, ONLY : CONVPAREXT
INTERFACE ACDC_UPDATE
MODULE PROCEDURE ACDC_UPDATE_CONVPAREXT
END INTERFACE

CONTAINS
SUBROUTINE ACDC_UPDATE_CONVPAREXT (SELF, LDCOMPONENT)


USE FXTRAN_ACDC_IS_PRESENT_MOD
USE UTIL_CONVPAREXT_WIPE_MOD
USE UTIL_CONVPAREXT_COPY_MOD
IMPLICIT NONE
TYPE (CONVPAREXT), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDCOMPONENT

IF (FXTRAN_ACDC_IS_PRESENT (C_LOC (SELF), SIZEOF (SELF))) THEN
CALL ACDC_WIPE_CONVPAREXT (SELF, LDDELETED=LDCOMPONENT)
CALL ACDC_COPY_CONVPAREXT (SELF, LDCREATED=LDCOMPONENT)
ENDIF


END SUBROUTINE
END MODULE
