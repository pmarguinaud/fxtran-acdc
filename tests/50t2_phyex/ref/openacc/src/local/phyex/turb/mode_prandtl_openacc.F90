IF (KIND (ZGXMM_PSV) == 8) THEN
    fxtran_acdc_alloc8 (ZGXMM_PSV)
ELSEIF (KIND (ZGXMM_PSV) == 4) THEN
    fxtran_acdc_alloc4 (ZGXMM_PSV)
