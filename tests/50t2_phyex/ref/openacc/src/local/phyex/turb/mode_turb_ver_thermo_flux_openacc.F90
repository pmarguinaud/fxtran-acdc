  & PBLL_O_E, PBETA, PLEPS, PEMOIST, PDTH_DZ, ZWORK1, YDSTACK=YLSTACK)
  CALL MZM_PHY_OPENACC (D, PFR2, ZWORK2, YDSTACK=YLSTACK)
  CALL D_M3_WTH_WR2_O_DDTDZ_OPENACC (D, CSTURB, TURBN, PREDTH1, PREDR1, PD, ZKEFF,&
  & PTKEM, PSQRT_TKE, PBLL_O_E, PBETA, PLEPS, PEMOIST, ZWORK3, YDSTACK=YLSTACK)

  DO JK=1, IKT
    
    ZF (JI, JK)=ZF (JI, JK)+ZWORK1 (JI, JK)*ZWORK2 (JI, JK)
    ZDFDDTDZ (JI, JK)=ZDFDDTDZ (JI, JK)+ZWORK3 (JI, JK)*ZWORK2 (JI, JK)
  
  ENDDO

ENDIF


IF (GFTHR) THEN
  CALL M3_WTH_WTHR_OPENACC (D, CSTURB, TURBN, PREDR1, PD, ZKEFF, PTKEM&
  &, PSQRT_TKE, PBETA, PLEPS, PEMOIST, Z3RDMOMENT, YDSTACK=YLSTACK)
  CALL D_M3_WTH_WTHR_O_DDTDZ_OPENACC (D, CSTURB, TURBN, Z3RDMOMENT, PREDTH1&
  &, PREDR1, PD, PBLL_O_E, PETHETA, ZWORK1, YDSTACK=YLSTACK)
  CALL MZM_PHY_OPENACC (D, PFTHR, ZWORK2, YDSTACK=YLSTACK)

  DO JK=1, IKT
    
    ZF (JI, JK)=ZF (JI, JK)+Z3RDMOMENT (JI, JK)*ZWORK2 (JI, JK)
    ZDFDDTDZ (JI, JK)=ZDFDDTDZ (JI, JK)+ZWORK1 (JI, JK)*ZWORK2 (JI, JK)
  
  ENDDO

ENDIF


IF (OOCEAN) THEN
  
  ZF (JI, IKE+1)=PSFTHM (JI)*0.5*(1.+PRHODJ (JI, IKU)/PRHODJ (JI, IKE))
  
ELSE
  
  
  ZF (JI, IKB)=(TURBN%XIMPL*PSFTHP (JI)+PEXPL*PSFTHM (JI))/PDIRCOSZW&
  & (JI)*0.5*(1.+PRHODJ (JI, IKA)/PRHODJ (JI, IKB))
  
  
  ZF (JI, IKE+1)=0.
ENDIF

CALL TRIDIAG_THERMO_OPENACC (D, PTHLM, ZF, ZDFDDTDZ, PTSTEP&
&, TURBN%XIMPL, PDZZ, PRHODJ, PTHLP, YDSTACK=YLSTACK)

DO JK=1, IKT
  
  ZRWTHL (JI, JK)=PRHODJ (JI, JK)*(PTHLP (JI, JK)-PTHLM (JI, JK))/PTSTEP
  
ENDDO



DO JK=1, IKT
  
  ZWORK1 (JI, JK)=PTHLP (JI, JK)-PTHLM (JI, JK)
  
ENDDO

CALL DZM_PHY_OPENACC (D, ZWORK1, ZWORK2, YDSTACK=YLSTACK)

DO JK=1, IKT
  
  PRTHLS (JI, JK)=PRTHLS (JI, JK)+ZRWTHL (JI, JK)
  ZFLXZ (JI, JK)=ZF (JI, JK)+TURBN%XIMPL*ZDFDDTDZ (JI, JK)*ZWORK2 (JI, JK)/PDZZ (JI, JK)
  
ENDDO



IF (OOCEAN) THEN
  
  ZFLXZ (JI, IKE+1)=ZFLXZ (JI, IKE)
  
ELSE
  
  ZFLXZ (JI, IKA)=ZFLXZ (JI, IKB)
  
ENDIF




IF (OOCEAN) THEN
  CALL MZF_PHY_OPENACC (D, ZFLXZ, ZMZF2D_WORK1, YDSTACK=YLSTACK)

  DO JK=1, IKT
    
    PTP (JI, JK)=CST%XG*CST%XALPHAOC*ZMZF2D_WORK1 (JI, JK)
  
  ENDDO

ELSE

  IF (KRR/=0) THEN
    CALL MZM_PHY_OPENACC (D, PETHETA, ZMZM2D_WORK1, YDSTACK=YLSTACK)

    DO JK=1, IKT
      
      ZSHUGRADWK1_2D (JI, JK)=ZMZM2D_WORK1 (JI, JK)*ZFLXZ (JI, JK)
    
    ENDDO

    CALL MZF_PHY_OPENACC (D, ZSHUGRADWK1_2D, ZMZF2D_WORK1, YDSTACK=YLSTACK)

    DO JK=1, IKT
      
      PTP (JI, JK)=PBETA (JI, JK)*ZMZF2D_WORK1 (JI, JK)
    
    ENDDO

    
    PTP (JI, IKB)=PBETA (JI, IKB)*PETHETA (JI, IKB)*0.5*(ZFLXZ (JI, IKB)+ZFLXZ (JI, IKB+IKL))
  
  ELSE
    CALL MZF_PHY_OPENACC (D, ZFLXZ, ZMZF2D_WORK1, YDSTACK=YLSTACK)

    DO JK=1, IKT
      
      PTP (JI, JK)=PBETA (JI, JK)*ZMZF2D_WORK1 (JI, JK)
    
    ENDDO

  ENDIF

ENDIF

CALL MZM_PHY_OPENACC (D, PETHETA, ZMZM2D_WORK1, YDSTACK=YLSTACK)

DO JK=1, IKT
  
  PWTHV (JI, JK)=ZMZM2D_WORK1 (JI, JK)*ZFLXZ (JI, JK)
  
ENDDO


PWTHV (JI, IKB)=PETHETA (JI, IKB)*ZFLXZ (JI, IKB)


IF (OOCEAN) THEN
  
  PWTHV (JI, IKE)=PETHETA (JI, IKE)*ZFLXZ (JI, IKE)
  
ENDIF


IF (TURBN%LPROJQITURB) THEN

  IF (KRRL>=1) THEN

    DO JK=1, IKT
      
      ZWORK1 (JI, JK)=ZFLXZ (JI, JK)/PDZZ (JI, JK)
    
    ENDDO

    CALL DZF_PHY_OPENACC (D, ZWORK1, ZWORK2, YDSTACK=YLSTACK)

    IF (KRRI>=1) THEN

      DO JK=1, IKT
        
        PRRS (JI, JK, 2)=PRRS (JI, JK, 2)-PRHODJ (JI, JK)*PATHETA (JI, JK&
        &)*2.*PSRCM (JI, JK)*ZWORK2 (JI, JK)*(1.0-PFRAC_ICE (JI, JK))
        PRRS (JI, JK, 4)=PRRS (JI, JK, 4)-PRHODJ (JI, JK)*PATHETA (JI&
        &, JK)*2.*PSRCM (JI, JK)*ZWORK2 (JI, JK)*PFRAC_ICE (JI, JK)
      
      ENDDO

    ELSE

      DO JK=1, IKT
        
        PRRS (JI, JK, 2)=PRRS (JI, JK, 2)-PRHODJ (JI, JK)*PATHETA (JI, JK)*2.*PSRCM (JI, JK)*ZWORK2 (JI, JK)
      
      ENDDO

    ENDIF

  ENDIF

ENDIF




IF (KRR/=0) THEN
  CALL DZM_PHY_OPENACC (D, PRM (:,:, 1), ZWORK1, YDSTACK=YLSTACK)
  
  CALL D_PSI3DRDZ_O_DDRDZ_OPENACC (D, CSTURB, TURBN, PPSI3, PREDR1, PREDTH1&
  &, PRED2R3, PRED2THR3, "1DIM", GUSERV, ZWORK2, YDSTACK=YLSTACK)

  DO JK=1, IKT
    
    ZF (JI, JK)=-TURBN%XCSHF*PPSI3 (JI, JK)*ZKEFF (JI, JK)*ZWORK1 (JI, JK)/PDZZ (JI, JK)
    ZDFDDRDZ (JI, JK)=-TURBN%XCSHF*ZKEFF (JI, JK)*ZWORK2 (JI, JK)
  
  ENDDO


  

  

  IF (GFWR) THEN
    CALL M3_WR_W2R_OPENACC (D, CSTURB, TURBN, PREDR1, PREDTH1&
    &, PD, ZKEFF, PTKEM, Z3RDMOMENT, YDSTACK=YLSTACK)
    CALL D_M3_WR_W2R_O_DDRDZ_OPENACC (D, CSTURB, TURBN, PREDR1, PREDTH1&
    &, PD, PBLL_O_E, PEMOIST, ZKEFF, PTKEM, ZWORK1, YDSTACK=YLSTACK)

    DO JK=1, IKT
      
      ZF (JI, JK)=ZF (JI, JK)+Z3RDMOMENT (JI, JK)*PFWR (JI, JK)
      ZDFDDRDZ (JI, JK)=ZDFDDRDZ (JI, JK)+ZWORK1 (JI, JK)*PFWR (JI, JK)
    
    ENDDO

  ENDIF


  IF (GFR2) THEN
    CALL M3_WR_WR2_OPENACC (D, CSTURB, TURBN, PREDR1, PREDTH1&
    &, PD, PBLL_O_E, PEMOIST, Z3RDMOMENT, YDSTACK=YLSTACK)
    CALL MZM_PHY_OPENACC (D, PFR2, ZWORK1, YDSTACK=YLSTACK)
    CALL D_M3_WR_WR2_O_DDRDZ_OPENACC (D, CSTURB, TURBN, Z3RDMOMENT, PREDR1&
    &, PREDTH1, PD, PBLL_O_E, PEMOIST, ZWORK2, YDSTACK=YLSTACK)

    DO JK=1, IKT
      
      ZF (JI, JK)=ZF (JI, JK)+Z3RDMOMENT (JI, JK)*ZWORK1 (JI, JK)
      ZDFDDRDZ (JI, JK)=ZDFDDRDZ (JI, JK)+ZWORK2 (JI, JK)*ZWORK1 (JI, JK)
    
    ENDDO

  ENDIF


  IF (GFWTH) THEN
    CALL M3_WR_W2TH_OPENACC (D, CSTURB, TURBN, PD, ZKEFF, PTKEM&
    &, PBLL_O_E, PETHETA, PDR_DZ, ZWORK1, YDSTACK=YLSTACK)
    CALL D_M3_WR_W2TH_O_DDRDZ_OPENACC (D, CSTURB, TURBN, PREDR1, PREDTH1&
    &, PD, ZKEFF, PTKEM, PBLL_O_E, PETHETA, ZWORK2, YDSTACK=YLSTACK)

    DO JK=1, IKT
      
      ZF (JI, JK)=ZF (JI, JK)+ZWORK1 (JI, JK)*PFWTH (JI, JK)
      ZDFDDRDZ (JI, JK)=ZDFDDRDZ (JI, JK)+ZWORK2 (JI, JK)*PFWTH (JI, JK)
    
    ENDDO

  ENDIF


  IF (GFTH2) THEN
    CALL MZM_PHY_OPENACC (D, PFTH2, ZWORK1, YDSTACK=YLSTACK)
    CALL M3_WR_WTH2_OPENACC (D, CSTURB, TURBN, PD, ZKEFF, PTKEM, PSQRT_TKE&
    &, PBLL_O_E, PBETA, PLEPS, PETHETA, PDR_DZ, ZWORK2, YDSTACK=YLSTACK)
    CALL D_M3_WR_WTH2_O_DDRDZ_OPENACC (D, CSTURB, TURBN, PREDR1, PREDTH1, PD, ZKEFF,&
    & PTKEM, PSQRT_TKE, PBLL_O_E, PBETA, PLEPS, PETHETA, ZWORK3, YDSTACK=YLSTACK)

    DO JK=1, IKT
      
      ZF (JI, JK)=ZF (JI, JK)+ZWORK2 (JI, JK)*ZWORK1 (JI, JK)
      ZDFDDRDZ (JI, JK)=ZDFDDRDZ (JI, JK)+ZWORK3 (JI, JK)*ZWORK1 (JI, JK)
    
    ENDDO

  ENDIF


  IF (GFTHR) THEN
    CALL M3_WR_WTHR_OPENACC (D, CSTURB, TURBN, PREDTH1, PD, ZKEFF, PTKEM&
    &, PSQRT_TKE, PBETA, PLEPS, PETHETA, Z3RDMOMENT, YDSTACK=YLSTACK)
    CALL MZM_PHY_OPENACC (D, PFTHR, ZWORK1, YDSTACK=YLSTACK)
    CALL D_M3_WR_WTHR_O_DDRDZ_OPENACC (D, CSTURB, TURBN, Z3RDMOMENT, PREDR1&
    &, PREDTH1, PD, PBLL_O_E, PEMOIST, ZWORK2, YDSTACK=YLSTACK)

    DO JK=1, IKT
      
      ZF (JI, JK)=ZF (JI, JK)+Z3RDMOMENT (JI, JK)*ZWORK1 (JI, JK)
      ZDFDDRDZ (JI, JK)=ZDFDDRDZ (JI, JK)+ZWORK2 (JI, JK)*ZWORK1 (JI, JK)
    
    ENDDO

  ENDIF


  IF (OOCEAN) THEN
    ZF (JI, IKE)=0.
  ELSE
    
    
    ZF (JI, IKB)=(TURBN%XIMPL*PSFRP (JI)+PEXPL*PSFRM (JI))/PDIRCOSZW&
    & (JI)*0.5*(1.+PRHODJ (JI, IKA)/PRHODJ (JI, IKB))
    
    
    ZF (JI, IKE+1)=0.
  ENDIF

  CALL TRIDIAG_THERMO_OPENACC (D, PRM (:,:, 1), ZF, ZDFDDRDZ, PTSTEP&
  &, TURBN%XIMPL, PDZZ, PRHODJ, PRP, YDSTACK=YLSTACK)

  DO JK=1, IKT
    
    ZRWRNP (JI, JK)=PRHODJ (JI, JK)*(PRP (JI, JK)-PRM (JI, JK, 1))/PTSTEP
  
  ENDDO


  

  DO JK=1, IKT
    
    ZWORK1 (JI, JK)=PRP (JI, JK)-PRM (JI, JK, 1)
  
  ENDDO

  CALL DZM_PHY_OPENACC (D, ZWORK1, ZWORK2, YDSTACK=YLSTACK)

  DO JK=1, IKT
    
    PRRS (JI, JK, 1)=PRRS (JI, JK, 1)+ZRWRNP (JI, JK)
    ZFLXZ (JI, JK)=ZF (JI, JK)+TURBN%XIMPL*ZDFDDRDZ (JI, JK)*ZWORK2 (JI, JK)/PDZZ (JI, JK)
  
  ENDDO

  
  
  ZFLXZ (JI, IKA)=ZFLXZ (JI, IKB)

  

  IF (OOCEAN) THEN
    
    ZFLXZ (JI, IKU)=ZFLXZ (JI, IKE)
  
  ENDIF


  

  

  IF (OOCEAN) THEN
    CALL MZF_PHY_OPENACC (D, ZFLXZ, ZMZF2D_WORK1, YDSTACK=YLSTACK)

    DO JK=1, IKT
      
      ZA (JI, JK)=-CST%XG*CST%XBETAOC*ZMZF2D_WORK1 (JI, JK)
    
    ENDDO

  ELSE
    CALL MZM_PHY_OPENACC (D, PEMOIST, ZMZM2D_WORK1, YDSTACK=YLSTACK)

    DO JK=1, IKT
      
      ZSHUGRADWK1_2D (JI, JK)=ZMZM2D_WORK1 (JI, JK)*ZFLXZ (JI, JK)
    
    ENDDO

    CALL MZF_PHY_OPENACC (D, ZSHUGRADWK1_2D, ZMZF2D_WORK1, YDSTACK=YLSTACK)

    DO JK=1, IKT
      
      ZA (JI, JK)=PBETA (JI, JK)*ZMZF2D_WORK1 (JI, JK)
    
    ENDDO

    
    ZA (JI, IKB)=PBETA (JI, IKB)*PEMOIST (JI, IKB)*0.5*(ZFLXZ (JI, IKB)+ZFLXZ (JI, IKB+IKL))

    

    DO JK=1, IKT
      
      PTP (JI, JK)=PTP (JI, JK)+ZA (JI, JK)
    
    ENDDO

  ENDIF

  CALL MZM_PHY_OPENACC (D, PEMOIST, ZMZM2D_WORK1, YDSTACK=YLSTACK)

  DO JK=1, IKT
    
    PWTHV (JI, JK)=PWTHV (JI, JK)+ZMZM2D_WORK1 (JI, JK)*ZFLXZ (JI, JK)
  
  ENDDO

  
  PWTHV (JI, IKB)=PWTHV (JI, IKB)+PEMOIST (JI, IKB)*ZFLXZ (JI, IKB)

  

  IF (OOCEAN) THEN
    
    PWTHV (JI, IKE)=PWTHV (JI, IKE)+PEMOIST (JI, IKE)*ZFLXZ (JI, IKE)
  
  ENDIF


  IF (TURBN%LPROJQITURB) THEN

    IF (KRRL>=1) THEN

      DO JK=1, IKT
        
        ZWORK2 (JI, JK)=ZFLXZ (JI, JK)/PDZZ (JI, JK)
      
      ENDDO

      CALL DZF_PHY_OPENACC (D, ZWORK2, ZWORK1, YDSTACK=YLSTACK)

      IF (KRRI>=1) THEN

        DO JK=1, IKT
          
          PRRS (JI, JK, 2)=PRRS (JI, JK, 2)-PRHODJ (JI, JK)*PAMOIST (JI, JK&
          &)*2.*PSRCM (JI, JK)*ZWORK1 (JI, JK)*(1.0-PFRAC_ICE (JI, JK))
          PRRS (JI, JK, 4)=PRRS (JI, JK, 4)-PRHODJ (JI, JK)*PAMOIST (JI&
          &, JK)*2.*PSRCM (JI, JK)*ZWORK1 (JI, JK)*PFRAC_ICE (JI, JK)
        
        ENDDO

      ELSE

        DO JK=1, IKT
          
          PRRS (JI, JK, 2)=PRRS (JI, JK, 2)-PRHODJ (JI, JK)*PAMOIST (JI, JK)*2.*PSRCM (JI, JK)*ZWORK1 (JI, JK)
        
        ENDDO

      ENDIF

    ENDIF

  ENDIF

  
ENDIF



END SUBROUTINE TURB_VER_THERMO_FLUX_OPENACC

ENDMODULE MODE_TURB_VER_THERMO_FLUX_OPENACC
