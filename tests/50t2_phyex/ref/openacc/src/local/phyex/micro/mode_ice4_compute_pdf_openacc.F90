
MODULE MODE_ICE4_COMPUTE_PDF_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE ICE4_COMPUTE_PDF_OPENACC (CST, ICEP, ICED, D, HSUBG_AUCV_RC, HSUBG_AUCV_RI&
&, HSUBG_PR_PDF, LDMICRO, PRHODREF, PRCT, PRIT, PCF, PT, PSIGMA_RC, PHLC_HCF, PHLC_LCF&
&, PHLC_HRC, PHLC_LRC, PHLI_HCF, PHLI_LCF, PHLI_HRI, PHLI_LRI, PRF, YDSTACK)
!$ACC ROUTINE (ICE4_COMPUTE_PDF_OPENACC) SEQ      

USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_CST,ONLY:CST_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T
USE MODD_RAIN_ICE_PARAM_N,ONLY:RAIN_ICE_PARAM_T

USE MODE_MSG,ONLY:NVERB_FATAL, PRINT_MSG
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (CST_T), INTENT (IN)::CST
TYPE (RAIN_ICE_PARAM_T), INTENT (IN)::ICEP
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
TYPE (DIMPHYEX_T), INTENT (IN)::D
CHARACTER (LEN=4), INTENT (IN)::HSUBG_AUCV_RC
CHARACTER (LEN=80), INTENT (IN)::HSUBG_AUCV_RI
CHARACTER (LEN=80), INTENT (IN)::HSUBG_PR_PDF
LOGICAL, INTENT (IN)::LDMICRO(D%NIJT)
REAL, INTENT (IN)::PRHODREF(D%NIJT)
REAL, INTENT (IN)::PRCT(D%NIJT)
REAL, INTENT (IN)::PRIT(D%NIJT)
REAL, INTENT (IN)::PCF(D%NIJT)
REAL, INTENT (IN)::PT(D%NIJT)
REAL, INTENT (IN)::PSIGMA_RC(D%NIJT)
REAL, INTENT (INOUT)::PHLC_HCF(D%NIJT)
REAL, INTENT (INOUT)::PHLC_LCF(D%NIJT)
REAL, INTENT (INOUT)::PHLC_HRC(D%NIJT)
REAL, INTENT (INOUT)::PHLC_LRC(D%NIJT)
REAL, INTENT (INOUT)::PHLI_HCF(D%NIJT)
REAL, INTENT (INOUT)::PHLI_LCF(D%NIJT)
REAL, INTENT (INOUT)::PHLI_HRI(D%NIJT)
REAL, INTENT (INOUT)::PHLI_LRI(D%NIJT)
REAL, INTENT (OUT)::PRF(D%NIJT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
REAL::ZSUMRI
REAL::ZSUMRC
REAL::ZHLC_HRCLOCAL
REAL::ZHLC_LRCLOCAL
REAL::ZHLC_RCMAX
REAL::ZCRIAUTI
REAL::ZRCRAUTC
REAL::ZCOEFFRCM

INTEGER::JI

JI = D%NIB


#ifdef MNH_COMPILER_CCE
#endif


IF (LDMICRO (JI)) THEN
  ZRCRAUTC =ICEP%XCRIAUTC/PRHODREF (JI)
ELSE
  ZRCRAUTC =0.
ENDIF



IF (HSUBG_AUCV_RC=='NONE') THEN

  

  IF (.NOT.LDMICRO (JI)) THEN
    PHLC_HCF (JI)=0.
    PHLC_LCF (JI)=0.
    PHLC_HRC (JI)=0.
    PHLC_LRC (JI)=0.
  ELSEIF (PRCT (JI)>ZRCRAUTC .AND.LDMICRO (JI)) THEN
    PHLC_HCF (JI)=1.
    PHLC_LCF (JI)=0.
    PHLC_HRC (JI)=PRCT (JI)
    PHLC_LRC (JI)=0.
  ELSEIF (PRCT (JI)>ICED%XRTMIN (2).AND.LDMICRO (JI)) THEN
    PHLC_HCF (JI)=0.
    PHLC_LCF (JI)=1.
    PHLC_HRC (JI)=0.
    PHLC_LRC (JI)=PRCT (JI)
  ELSE
    PHLC_HCF (JI)=0.
    PHLC_LCF (JI)=0.
    PHLC_HRC (JI)=0.
    PHLC_LRC (JI)=0.
  ENDIF

  
ELSEIF (HSUBG_AUCV_RC=='CLFR') THEN

  

  IF (.NOT.LDMICRO (JI)) THEN
    PHLC_HCF (JI)=0.
    PHLC_LCF (JI)=0.
    PHLC_HRC (JI)=0.
    PHLC_LRC (JI)=0.
  ELSEIF (PCF (JI)>0..AND.PRCT (JI)>ZRCRAUTC *PCF (JI).AND.LDMICRO (JI)) THEN
    PHLC_HCF (JI)=PCF (JI)
    PHLC_LCF (JI)=0.
    PHLC_HRC (JI)=PRCT (JI)
    PHLC_LRC (JI)=0.
  ELSEIF (PCF (JI)>0..AND.PRCT (JI)>ICED%XRTMIN (2).AND.LDMICRO (JI)) THEN
    PHLC_HCF (JI)=0.
    PHLC_LCF (JI)=PCF (JI)
    PHLC_HRC (JI)=0.0
    PHLC_LRC (JI)=PRCT (JI)
  ELSE
    PHLC_HCF (JI)=0.
    PHLC_LCF (JI)=0.
    PHLC_HRC (JI)=0.
    PHLC_LRC (JI)=0.
  ENDIF

  
ELSEIF (HSUBG_AUCV_RC=='ADJU') THEN

  

  IF (LDMICRO (JI)) THEN
    ZSUMRC =PHLC_LRC (JI)+PHLC_HRC (JI)
  ELSE
    ZSUMRC =0.
  ENDIF


  IF (ZSUMRC .GT.1.E-20.AND.LDMICRO (JI)) THEN
    PHLC_LRC (JI)=PHLC_LRC (JI)*PRCT (JI)/ZSUMRC 
    PHLC_HRC (JI)=PHLC_HRC (JI)*PRCT (JI)/ZSUMRC 
  ELSE
    PHLC_LRC (JI)=0.
    PHLC_HRC (JI)=0.
  ENDIF

  
ELSEIF (HSUBG_AUCV_RC=='PDF') THEN

  IF (HSUBG_PR_PDF=='SIGM') THEN

    

    IF (.NOT.LDMICRO (JI)) THEN
      PHLC_HCF (JI)=0.
      PHLC_LCF (JI)=0.
      PHLC_HRC (JI)=0.
      PHLC_LRC (JI)=0.
    ELSEIF (PRCT (JI)>ZRCRAUTC +PSIGMA_RC (JI).AND.LDMICRO (JI)) THEN
      PHLC_HCF (JI)=1.
      PHLC_LCF (JI)=0.
      PHLC_HRC (JI)=PRCT (JI)
      PHLC_LRC (JI)=0.
    ELSEIF (PRCT (JI)>(ZRCRAUTC -PSIGMA_RC (JI)).AND.PRCT (JI&
      &)<=(ZRCRAUTC +PSIGMA_RC (JI)).AND.LDMICRO (JI)) THEN
      PHLC_HCF (JI)=(PRCT (JI)+PSIGMA_RC (JI)-ZRCRAUTC )/(2.*PSIGMA_RC (JI))
      PHLC_LCF (JI)=MAX (0., PCF (JI)-PHLC_HCF (JI))
      PHLC_HRC (JI)=(PRCT (JI)+PSIGMA_RC (JI)-ZRCRAUTC )*(PRCT&
      & (JI)+PSIGMA_RC (JI)+ZRCRAUTC )/(4.*PSIGMA_RC (JI))
      PHLC_LRC (JI)=MAX (0., PRCT (JI)-PHLC_HRC (JI))
    ELSEIF (PRCT (JI)>ICED%XRTMIN (2).AND.PCF (JI)>0..AND.LDMICRO (JI)) THEN
      PHLC_HCF (JI)=0.
      PHLC_LCF (JI)=PCF (JI)
      PHLC_HRC (JI)=0.
      PHLC_LRC (JI)=PRCT (JI)
    ELSE
      PHLC_HCF (JI)=0.
      PHLC_LCF (JI)=0.
      PHLC_HRC (JI)=0.
      PHLC_LRC (JI)=0.
    ENDIF

  
  ELSEIF (HSUBG_PR_PDF=='HLCRECTPDF'.OR.HSUBG_PR_PDF=='HLCISOTRIPDF'.OR.HSUBG_PR_PDF&
    &=='HLCTRIANGPDF'.OR.HSUBG_PR_PDF=='HLCQUADRAPDF') THEN

    IF (HSUBG_PR_PDF=='HLCRECTPDF'.OR.HSUBG_PR_PDF=='HLCISOTRIPDF') THEN
      ZCOEFFRCM=2.
    ELSEIF (HSUBG_PR_PDF=='HLCTRIANGPDF') THEN
      ZCOEFFRCM=3.
    ELSEIF (HSUBG_PR_PDF=='HLCQUADRAPDF') THEN
      ZCOEFFRCM=4.
    ENDIF


    

    IF (.NOT.LDMICRO (JI)) THEN
      ZHLC_RCMAX =0.
    ELSEIF (PRCT (JI).GT.0..AND.PCF (JI).GT.0..AND.LDMICRO (JI)) THEN
      ZHLC_RCMAX =ZCOEFFRCM*PRCT (JI)/PCF (JI)
    ELSE
      ZHLC_RCMAX =0.
    ENDIF


    

    IF (HSUBG_PR_PDF=='HLCRECTPDF') THEN

      

      IF (.NOT.LDMICRO (JI)) THEN
        ZHLC_LRCLOCAL =0.
        ZHLC_HRCLOCAL =0
      ELSEIF (PRCT (JI).GT.0..AND.PCF (JI).GT.0..AND.ZHLC_RCMAX .GT.ZRCRAUTC .AND.LDMICRO (JI)) THEN
        ZHLC_LRCLOCAL =0.5*ZRCRAUTC 
        ZHLC_HRCLOCAL =(ZHLC_RCMAX +ZRCRAUTC )/2.0
      ELSE
        ZHLC_LRCLOCAL =0.
        ZHLC_HRCLOCAL =0.
      ENDIF

    
    ELSEIF (HSUBG_PR_PDF=='HLCTRIANGPDF') THEN

      

      IF (.NOT.LDMICRO (JI)) THEN
        ZHLC_LRCLOCAL =0.
        ZHLC_HRCLOCAL =0
      ELSEIF (PRCT (JI).GT.0..AND.PCF (JI).GT.0..AND.ZHLC_RCMAX .GT.ZRCRAUTC .AND.LDMICRO (JI)) THEN
        ZHLC_LRCLOCAL =(ZRCRAUTC *(3.0*ZHLC_RCMAX -2.0*ZRCRAUTC ))/(3.0*(2.0*ZHLC_RCMAX -ZRCRAUTC ))
        ZHLC_HRCLOCAL =(ZHLC_RCMAX +2.0*ZRCRAUTC )/3.0
      ELSE
        ZHLC_LRCLOCAL =0.
        ZHLC_HRCLOCAL =0.
      ENDIF

    
    ELSEIF (HSUBG_PR_PDF=='HLCQUADRAPDF') THEN

      

      IF (.NOT.LDMICRO (JI)) THEN
        ZHLC_LRCLOCAL =0.
        ZHLC_HRCLOCAL =0
      ELSEIF (PRCT (JI).GT.0..AND.PCF (JI).GT.0..AND.ZHLC_RCMAX .GT.ZRCRAUTC .AND.LDMICRO (JI)) THEN
        ZHLC_LRCLOCAL =(3.0*ZRCRAUTC **3-8.0*ZRCRAUTC **2*ZHLC_RCMAX +6.0*ZRCRAUTC *ZHLC_RCMAX&
        & **2)/(4.0*ZRCRAUTC **2-12.0*ZRCRAUTC *ZHLC_RCMAX +12.0*ZHLC_RCMAX **2)
        ZHLC_HRCLOCAL =(ZHLC_RCMAX +3.0*ZRCRAUTC )/4.0
      ELSE
        ZHLC_LRCLOCAL =0.
        ZHLC_HRCLOCAL =0.
      ENDIF

    
    ELSEIF (HSUBG_PR_PDF=='HLCISOTRIPDF') THEN

      

      IF (.NOT.LDMICRO (JI)) THEN
        ZHLC_LRCLOCAL =0.
        ZHLC_HRCLOCAL =0
      ELSEIF (PRCT (JI).LE.ZRCRAUTC *PCF (JI).AND.PRCT (JI).GT.0..AND.PCF&
        & (JI).GT.0..AND.ZHLC_RCMAX .GT.ZRCRAUTC .AND.LDMICRO (JI)) THEN
        ZHLC_LRCLOCAL =((ZHLC_RCMAX )**3-(12.0*(ZHLC_RCMAX )*(ZRCRAUTC )**2)+(8.0*ZRCRAUTC *&
        &*3))/((6.0*(ZHLC_RCMAX )**2)-(24.0*(ZHLC_RCMAX )*ZRCRAUTC )+(12.0*ZRCRAUTC **2))
        ZHLC_HRCLOCAL =(ZHLC_RCMAX +2.0*ZRCRAUTC )/3.0
      ELSEIF (PRCT (JI).GT.0..AND.PCF (JI).GT.0..AND.ZHLC_RCMAX .GT.ZRCRAUTC .AND.LDMICRO (JI)) THEN
        ZHLC_LRCLOCAL =(2.0/3.0)*ZRCRAUTC 
        ZHLC_HRCLOCAL =(3.0*ZHLC_RCMAX **3-8.0*ZRCRAUTC **3)/(6.0*ZHLC_RCMAX **2-12.0*ZRCRAUTC **2)
      ELSE
        ZHLC_LRCLOCAL =0.
        ZHLC_HRCLOCAL =0.
      ENDIF

    
    ENDIF


    

    IF (.NOT.LDMICRO (JI)) THEN
      PHLC_HCF (JI)=0.
      PHLC_LCF (JI)=0.
      PHLC_HRC (JI)=0.
      PHLC_LRC (JI)=0.
    ELSEIF (PRCT (JI).GT.0..AND.PCF (JI).GT.0..AND.ZHLC_RCMAX .GT.ZRCRAUTC .AND.LDMICRO (JI)) THEN
      PHLC_LCF (JI)=PCF (JI)*(ZHLC_HRCLOCAL -(PRCT (JI)/PCF (JI)))/(ZHLC_HRCLOCAL -ZHLC_LRCLOCAL )
      PHLC_HCF (JI)=MAX (0., PCF (JI)-PHLC_LCF (JI))
      PHLC_LRC (JI)=ZHLC_LRCLOCAL *PHLC_LCF (JI)
      PHLC_HRC (JI)=MAX (0., PRCT (JI)-PHLC_LRC (JI))
    ELSEIF (PRCT (JI).GT.0..AND.PCF (JI).GT.0..AND.ZHLC_RCMAX .LE.ZRCRAUTC .AND.LDMICRO (JI)) THEN
      PHLC_LCF (JI)=PCF (JI)
      PHLC_HCF (JI)=0.
      PHLC_LRC (JI)=PRCT (JI)
      PHLC_HRC (JI)=0.
    ELSE
      PHLC_LCF (JI)=0.
      PHLC_HCF (JI)=0.
      PHLC_LRC (JI)=0.
      PHLC_HRC (JI)=0.
    ENDIF

  
  ELSE
    CALL FXTRAN_ACDC_ABORT ('wrong HSUBG_PR_PDF case')
  ENDIF

ELSE
  CALL FXTRAN_ACDC_ABORT ('wrong HSUBG_AUCV case')
ENDIF



IF (LDMICRO (JI)) THEN
  ZCRIAUTI =MIN (ICEP%XCRIAUTI, 10**(ICEP%XACRIAUTI*(PT (JI)-CST%XTT)+ICEP%XBCRIAUTI))
ELSE
  ZCRIAUTI =0.
ENDIF



IF (HSUBG_AUCV_RI=='NONE') THEN

  

  IF (.NOT.LDMICRO (JI)) THEN
    PHLI_HCF (JI)=0.
    PHLI_LCF (JI)=0.
    PHLI_HRI (JI)=0.
    PHLI_LRI (JI)=0.
  ELSEIF (PRIT (JI)>ZCRIAUTI .AND.LDMICRO (JI)) THEN
    PHLI_HCF (JI)=1.
    PHLI_LCF (JI)=0.
    PHLI_HRI (JI)=PRIT (JI)
    PHLI_LRI (JI)=0.
  ELSEIF (PRIT (JI)>ICED%XRTMIN (4).AND.LDMICRO (JI)) THEN
    PHLI_HCF (JI)=0.
    PHLI_LCF (JI)=1.
    PHLI_HRI (JI)=0.
    PHLI_LRI (JI)=PRIT (JI)
  ELSE
    PHLI_HCF (JI)=0.
    PHLI_LCF (JI)=0.
    PHLI_HRI (JI)=0.
    PHLI_LRI (JI)=0.
  ENDIF

  
ELSEIF (HSUBG_AUCV_RI=='CLFR') THEN

  

  IF (.NOT.LDMICRO (JI)) THEN
    PHLI_HCF (JI)=0.
    PHLI_LCF (JI)=0.
    PHLI_HRI (JI)=0.
    PHLI_LRI (JI)=0.
  ELSEIF (PCF (JI)>0..AND.PRIT (JI)>ZCRIAUTI *PCF (JI).AND.LDMICRO (JI)) THEN
    PHLI_HCF (JI)=PCF (JI)
    PHLI_LCF (JI)=0.
    PHLI_HRI (JI)=PRIT (JI)
    PHLI_LRI (JI)=0.
  ELSEIF (PCF (JI)>0..AND.PRIT (JI)>ICED%XRTMIN (4).AND.LDMICRO (JI)) THEN
    PHLI_HCF (JI)=0.
    PHLI_LCF (JI)=PCF (JI)
    PHLI_HRI (JI)=0.0
    PHLI_LRI (JI)=PRIT (JI)
  ELSE
    PHLI_HCF (JI)=0.
    PHLI_LCF (JI)=0.
    PHLI_HRI (JI)=0.
    PHLI_LRI (JI)=0.
  ENDIF

  
ELSEIF (HSUBG_AUCV_RI=='ADJU') THEN

  

  IF (LDMICRO (JI)) THEN
    ZSUMRI =PHLI_LRI (JI)+PHLI_HRI (JI)
  ELSE
    ZSUMRI =0.
  ENDIF


  IF (ZSUMRI .GT.1.E-20.AND.LDMICRO (JI)) THEN
    PHLI_LRI (JI)=PHLI_LRI (JI)*PRIT (JI)/ZSUMRI 
    PHLI_HRI (JI)=PHLI_HRI (JI)*PRIT (JI)/ZSUMRI 
  ELSE
    PHLI_LRI (JI)=0.
    PHLI_HRI (JI)=0.
  ENDIF

  
ELSE
  CALL FXTRAN_ACDC_ABORT ('wrong HSUBG_AUCV_RI case')
ENDIF



IF (LDMICRO (JI)) THEN
  PRF (JI)=MAX (PHLC_HCF (JI), PHLI_HCF (JI))
ELSE
  PRF (JI)=0.
ENDIF



END SUBROUTINE ICE4_COMPUTE_PDF_OPENACC

ENDMODULE MODE_ICE4_COMPUTE_PDF_OPENACC
