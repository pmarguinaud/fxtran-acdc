MODULE UTIL_CONVPAREXT_SIZE_MOD
USE MODD_CONVPAREXT, ONLY : CONVPAREXT
INTERFACE ACDC_SIZE
MODULE PROCEDURE ACDC_SIZE_CONVPAREXT
END INTERFACE

CONTAINS
FUNCTION ACDC_SIZE_CONVPAREXT (SELF, CDPATH, LDPRINT) RESULT (KSIZE)

IMPLICIT NONE
TYPE (CONVPAREXT),     INTENT (IN), TARGET :: SELF
CHARACTER(LEN=*), INTENT (IN), OPTIONAL :: CDPATH
LOGICAL,          INTENT (IN), OPTIONAL :: LDPRINT
INTEGER*8 :: KSIZE
INTEGER*8 :: ISIZE, JSIZE
LOGICAL :: LLPRINT
CHARACTER(LEN=128) :: CLPATH
LLPRINT = .FALSE.
IF (PRESENT (LDPRINT)) THEN
  LLPRINT = LDPRINT
ENDIF
CLPATH=''
IF (PRESENT (CDPATH)) THEN
  CLPATH = CDPATH
ENDIF
KSIZE = 0
ISIZE = KIND (SELF%JCVEXB)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%JCVEXB'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%JCVEXT)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%JCVEXT'
ENDIF
KSIZE = KSIZE + ISIZE
END FUNCTION
END MODULE
