MODULE UTIL_TFIELDMETADATA_SIZE_MOD
USE MODD_FIELD, ONLY : TFIELDMETADATA
INTERFACE ACDC_SIZE
MODULE PROCEDURE ACDC_SIZE_TFIELDMETADATA
END INTERFACE

CONTAINS
FUNCTION ACDC_SIZE_TFIELDMETADATA (SELF, CDPATH, LDPRINT) RESULT (KSIZE)

IMPLICIT NONE
TYPE (TFIELDMETADATA),     INTENT (IN), TARGET :: SELF
CHARACTER(LEN=*), INTENT (IN), OPTIONAL :: CDPATH
LOGICAL,          INTENT (IN), OPTIONAL :: LDPRINT
INTEGER*8 :: KSIZE
INTEGER*8 :: ISIZE, JSIZE
LOGICAL :: LLPRINT
CHARACTER(LEN=128) :: CLPATH
LLPRINT = .FALSE.
IF (PRESENT (LDPRINT)) THEN
  LLPRINT = LDPRINT
ENDIF
CLPATH=''
IF (PRESENT (CDPATH)) THEN
  CLPATH = CDPATH
ENDIF
KSIZE = 0
ISIZE = KIND (SELF%CMNHNAME) * LEN (SELF%CMNHNAME)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%CMNHNAME'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%CSTDNAME) * LEN (SELF%CSTDNAME)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%CSTDNAME'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%CLONGNAME) * LEN (SELF%CLONGNAME)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%CLONGNAME'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%CUNITS) * LEN (SELF%CUNITS)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%CUNITS'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%CCOMMENT) * LEN (SELF%CCOMMENT)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%CCOMMENT'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%NGRID)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%NGRID'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%NTYPE)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%NTYPE'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%NDIMS)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%NDIMS'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%CDIR) * LEN (SELF%CDIR)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%CDIR'
ENDIF
KSIZE = KSIZE + ISIZE
ISIZE = KIND (SELF%LTIMEDEP)
IF (LLPRINT) THEN
  WRITE (*, '(I10," ")', ADVANCE='NO') ISIZE
  WRITE (*, *) TRIM (CLPATH)//'%LTIMEDEP'
ENDIF
KSIZE = KSIZE + ISIZE
END FUNCTION
END MODULE
