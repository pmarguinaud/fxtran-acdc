SUBROUTINE ANYIDIOM (KIDIA, KFDIA, KLON, PQ, PT, LDA, LDB, LDX)

!$ACDC singlecolumn

! Removing ANY must not change the grouping of its argument

USE PARKIND1, ONLY : JPIM, JPRB

IMPLICIT NONE

INTEGER(KIND=JPIM),INTENT(IN)    :: KIDIA
INTEGER(KIND=JPIM),INTENT(IN)    :: KFDIA
INTEGER(KIND=JPIM),INTENT(IN)    :: KLON
REAL(KIND=JPRB)   ,INTENT(IN)    :: PQ(KLON)
REAL(KIND=JPRB)   ,INTENT(INOUT) :: PT(KLON)
LOGICAL           ,INTENT(IN)    :: LDA(KLON)
LOGICAL           ,INTENT(IN)    :: LDB(KLON)
LOGICAL           ,INTENT(IN)    :: LDX

! Parentheses are required

IF (.NOT. ANY (LDA (KIDIA:KFDIA) .AND. LDB (KIDIA:KFDIA))) PT (KIDIA:KFDIA) = 1._JPRB
IF (.NOT. ANY (LDA (KIDIA:KFDIA) .OR. PQ (KIDIA:KFDIA) > 0._JPRB)) PT (KIDIA:KFDIA) = 2._JPRB
IF (.NOT. ANY (.NOT. LDA (KIDIA:KFDIA))) PT (KIDIA:KFDIA) = 3._JPRB
IF (LDX .AND. ANY (LDA (KIDIA:KFDIA) .OR. LDB (KIDIA:KFDIA))) PT (KIDIA:KFDIA) = 4._JPRB
IF (ANY (LDA (KIDIA:KFDIA) .OR. LDB (KIDIA:KFDIA)) .AND. LDX) PT (KIDIA:KFDIA) = 5._JPRB
IF (ANY (LDA (KIDIA:KFDIA) .EQV. LDB (KIDIA:KFDIA)) .AND. LDX) PT (KIDIA:KFDIA) = 6._JPRB

! Parentheses are not needed, but the argument is a logical operation

IF (LDX .OR. ANY (LDA (KIDIA:KFDIA) .AND. LDB (KIDIA:KFDIA))) PT (KIDIA:KFDIA) = 7._JPRB

! The argument is not a logical operation, or ANY is not an operand: no parentheses

IF (ANY (LDA (KIDIA:KFDIA) .OR. LDB (KIDIA:KFDIA))) PT (KIDIA:KFDIA) = 8._JPRB
IF (LDX .AND. ANY (LDA (KIDIA:KFDIA))) PT (KIDIA:KFDIA) = 9._JPRB
IF (LDX .AND. ANY (PQ (KIDIA:KFDIA) > 0._JPRB)) PT (KIDIA:KFDIA) = 10._JPRB
IF (.NOT. ANY (PQ (KIDIA:KFDIA) > 0._JPRB)) PT (KIDIA:KFDIA) = 11._JPRB

! ANY is not the operand of .NOT.: the rest of the expression must be kept

IF (.NOT. (ANY (PQ (KIDIA:KFDIA) > 0._JPRB) .AND. LDX)) PT (KIDIA:KFDIA) = 12._JPRB
IF (.NOT. (LDX .OR. ANY (PQ (KIDIA:KFDIA) > 0._JPRB))) PT (KIDIA:KFDIA) = 13._JPRB
IF (.NOT. (LDX .AND. ANY (LDA (KIDIA:KFDIA) .OR. LDB (KIDIA:KFDIA)))) PT (KIDIA:KFDIA) = 14._JPRB

! ANY is the operand of .NOT., inside a larger expression

IF (LDX .AND. .NOT. ANY (PQ (KIDIA:KFDIA) > 0._JPRB)) PT (KIDIA:KFDIA) = 15._JPRB
IF (LDX .AND. .NOT. ANY (LDA (KIDIA:KFDIA) .OR. LDB (KIDIA:KFDIA))) PT (KIDIA:KFDIA) = 16._JPRB

END SUBROUTINE ANYIDIOM
