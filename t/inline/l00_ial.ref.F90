SUBROUTINE L00_IAL (KLON, KLEV, KIDIA, KFDIA, X, Y)
INTEGER, INTENT (IN)::KFDIA
INTEGER, INTENT (IN)::KIDIA
INTEGER, INTENT (IN)::KLEV
INTEGER, INTENT (IN)::KLON
REAL, INTENT (IN)::X (KLON, KLEV)
REAL, INTENT (OUT)::Y (KLON, KLEV)
INTEGER::JLEV
INTEGER::JLON
DO JLEV = 1, KLEV
  DO JLON = KIDIA, KFDIA
    Y(JLON,JLEV)=2.*X(JLON,JLEV)
  ENDDO
ENDDO
DO JLON = KIDIA, KFDIA
  Y (JLON, KLEV)=2.*X (JLON, 1)
ENDDO
END SUBROUTINE
