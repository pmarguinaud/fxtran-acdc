
MODULE MODE_CONVECT_TRIGGER_SHAL_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE CONVECT_TRIGGER_SHAL_OPENACC (CVP_SHAL, CVPEXT, CST, D, PPRES, PTH, PTHV, PTHES, PRV, PW&
&, PZ, PTKECLS, PTHLCL, PTLCL, PRVLCL, PWLCL, PZLCL, PTHVELCL, KLCL, KDPL, KPBL, OTRIG, YDSTACK)
!$ACC ROUTINE (CONVECT_TRIGGER_SHAL_OPENACC) SEQ      


USE MODD_CST,ONLY:CST_T
USE MODD_CONVPAR_SHAL,ONLY:CONVPAR_SHAL
USE MODD_CONVPAREXT,ONLY:CONVPAREXT
USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (CONVPAR_SHAL), INTENT (IN)::CVP_SHAL
TYPE (CONVPAREXT), INTENT (IN)::CVPEXT
TYPE (CST_T), INTENT (IN)::CST
TYPE (DIMPHYEX_T), INTENT (IN)::D
REAL, INTENT (IN)::PTKECLS(D%NIJT)
REAL, INTENT (IN)::PTHV(D%NIJT, D%NKT)
REAL, INTENT (IN)::PTH(D%NIJT, D%NKT)
REAL, INTENT (IN)::PTHES(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRV(D%NIJT, D%NKT)
REAL, INTENT (IN)::PPRES(D%NIJT, D%NKT)
REAL, INTENT (IN)::PZ(D%NIJT, D%NKT)
REAL, INTENT (IN)::PW(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PTHLCL(D%NIJT)
REAL, INTENT (OUT)::PTLCL(D%NIJT)
REAL, INTENT (OUT)::PRVLCL(D%NIJT)
REAL, INTENT (OUT)::PWLCL(D%NIJT)
REAL, INTENT (OUT)::PZLCL(D%NIJT)
REAL, INTENT (OUT)::PTHVELCL(D%NIJT)
LOGICAL, INTENT (OUT)::OTRIG(D%NIJT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
TYPE(FXTRAN_ACDC_STACK) :: YLSTACK
INTEGER, INTENT (INOUT)::KLCL(D%NIJT)
INTEGER, INTENT (INOUT)::KDPL(D%NIJT)
INTEGER, INTENT (INOUT)::KPBL(D%NIJT)
INTEGER::JT
INTEGER::JL
INTEGER::JKM
INTEGER::JK
INTEGER::JKK
INTEGER::JI
INTEGER::IKE
INTEGER::IKB
REAL::ZEPSA
REAL::ZEPS
REAL::ZRDOCP
REAL::ZCPORD
REAL::ZX2
REAL::ZX1
REAL::ZTHVELCL
REAL::ZZLCL
REAL::ZWLCL
REAL::ZRVLCL
REAL::ZTLCL
REAL::ZTHLCL
INTEGER::ILCL
INTEGER::IPBL
INTEGER::IDPL
REAL::ZPLCL
REAL::ZZDPL
REAL::ZTHVLCL
REAL::ZTMIX
REAL::ZEVMIX
REAL::ZPRESMIX
REAL::ZDPTHMIX
REAL::ZCAPE
REAL::ZCAP
REAL::ZTHEUL
REAL::ZCPHA
REAL::ZLVA
REAL::ZCPHB
REAL::ZLVB
REAL::ZEWB
REAL::ZEWA
REAL::ZLSB
REAL::ZLSA
REAL::ZDP
REAL::ZTOPP
REAL::ZTOP
REAL::ZWORK3
LOGICAL::GTRIG2
LOGICAL::GWORK1

fxtran_acdc_temp (REAL, ZZPRV, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZZPTH, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZZPPRES, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZZZX1, (D%NIJT, D%NKT))
REAL::ZWLCLSQRENT
INTEGER::JLSTART
INTEGER::JLSIZE
INTEGER::JLSTEP
INTEGER::JLCLMIN
INTEGER::IJIMAX2
INTEGER::IJIMIN2
INTEGER::IJIMAX
INTEGER::IJIMIN
LOGICAL::LLCOMPUTE
REAL::ZT

YLSTACK = YDSTACK



IF (KIND (ZZPRV) == 8) THEN
    fxtran_acdc_alloc8 (ZZPRV)
ELSEIF (KIND (ZZPRV) == 4) THEN
    fxtran_acdc_alloc4 (ZZPRV)
ELSE
    STOP 1
ENDIF


IF (KIND (ZZPTH) == 8) THEN
    fxtran_acdc_alloc8 (ZZPTH)
ELSEIF (KIND (ZZPTH) == 4) THEN
    fxtran_acdc_alloc4 (ZZPTH)
ELSE
    STOP 1
ENDIF


IF (KIND (ZZPPRES) == 8) THEN
    fxtran_acdc_alloc8 (ZZPPRES)
ELSEIF (KIND (ZZPPRES) == 4) THEN
    fxtran_acdc_alloc4 (ZZPPRES)
ELSE
    STOP 1
ENDIF


IF (KIND (ZZZX1) == 8) THEN
    fxtran_acdc_alloc8 (ZZZX1)
ELSEIF (KIND (ZZZX1) == 4) THEN
    fxtran_acdc_alloc4 (ZZZX1)
ELSE
    STOP 1
ENDIF


JI = D%NIB


IKB=1+CVPEXT%JCVEXB
IKE=D%NKT-CVPEXT%JCVEXT
ZEPS=CST%XRD/CST%XRV
ZEPSA=CST%XRV/CST%XRD
ZCPORD=CST%XCPD/CST%XRD
ZRDOCP=CST%XRD/CST%XCPD
OTRIG (JI)=.FALSE.
IDPL =KDPL (JI)
IPBL =KPBL (JI)
ILCL =KLCL (JI)
PWLCL (JI)=0.
ZWLCL =0.
PTHLCL (JI)=1.
PTHVELCL (JI)=1.
PTLCL (JI)=1.
PRVLCL (JI)=0.
PWLCL (JI)=0.
PZLCL (JI)=PZ (JI, IKB)
ZZDPL =PZ (JI, IKB)
GTRIG2 =.TRUE.

DO JK=IKB+1, IKE-1
  
  ZZZX1 (JI, JK)=PPRES (JI, JK)-PPRES (JI, JK+1)
  ZZPPRES (JI, JK)=PPRES (JI, JK)*ZZZX1 (JI, JK)
  ZZPTH (JI, JK)=PTH (JI, JK)*ZZZX1 (JI, JK)
  ZZPRV (JI, JK)=MAX (0., PRV (JI, JK))*ZZZX1 (JI, JK)
  
ENDDO

JT=IKE-2

DO JKK=IKB+1, IKE-2
  
  GWORK1 =ZZDPL -PZ (JI, IKB)<CVP_SHAL%XZLCL

  

  

  IF (GWORK1 ) THEN
    ZDPTHMIX =0.
    ZPRESMIX =0.
    ZTHLCL =0.
    ZRVLCL =0.
    ZZDPL =PZ (JI, JKK)
    IDPL =JKK
  ENDIF


  

  DO JK=JKK, IKE-1
    JKM=JK+1

    

    IF (GWORK1 .AND.ZDPTHMIX <CVP_SHAL%XZPBL) THEN
      IPBL =JK
      ZDPTHMIX =ZDPTHMIX +ZZZX1 (JI, JK)
      ZPRESMIX =ZPRESMIX +ZZPPRES (JI, JK)
      ZTHLCL =ZTHLCL +ZZPTH (JI, JK)
      ZRVLCL =ZRVLCL +ZZPRV (JI, JK)
    ENDIF

  
  ENDDO


  

  IF (GWORK1 ) THEN
    ZPRESMIX =ZPRESMIX /ZDPTHMIX 
    ZTHLCL =ZTHLCL /ZDPTHMIX +(CVP_SHAL%XATPERT*MIN (3., PTKECLS&
    & (JI))/CST%XCPD+CVP_SHAL%XBTPERT)*CVP_SHAL%XDTPERT
    ZRVLCL =ZRVLCL /ZDPTHMIX 
    ZTHVLCL =ZTHLCL *(1.+ZEPSA*ZRVLCL )/(1.+ZRVLCL )
    ZTMIX =ZTHLCL *(ZPRESMIX /CST%XP00)**ZRDOCP
    ZEVMIX =ZRVLCL *ZPRESMIX /(ZRVLCL +ZEPS)
    ZEVMIX =MAX (1.E-8, ZEVMIX )
    ZX1=LOG (ZEVMIX /613.3)
    ZX1=(4780.8-32.19*ZX1)/(17.502-ZX1)
    ZTLCL =ZX1-(.212+1.571E-3*(ZX1-CST%XTT)-4.36E-4*(ZTMIX -CST%XTT))*(ZTMIX -ZX1)
    ZTLCL =MIN (ZTLCL , ZTMIX )
    ZPLCL =CST%XP00*(ZTLCL /ZTHLCL )**ZCPORD
  ENDIF


  

  

  IF (GWORK1 ) THEN
    
    ZT=MIN (400., MAX (ZTLCL , 10.))
    ZEWA =EXP (CST%XALPW-CST%XBETAW/ZT-CST%XGAMW*LOG (ZT))
    ZEWA =ZEPS*ZEWA /(ZPLCL -ZEWA )
    ZLVA =CST%XLVTT+(CST%XCPV-CST%XCL)*(ZT-CST%XTT)
    ZLSA =CST%XLSTT+(CST%XCPV-CST%XCI)*(ZT-CST%XTT)
    ZCPHA =CST%XCPD+CST%XCPV*ZEWA 
    
    
    
    ZT=MIN (400., MAX (ZTMIX , 10.))
    ZEWB =EXP (CST%XALPW-CST%XBETAW/ZT-CST%XGAMW*LOG (ZT))
    ZEWB =ZEPS*ZEWB /(ZPRESMIX -ZEWB )
    ZLVB =CST%XLVTT+(CST%XCPV-CST%XCL)*(ZT-CST%XTT)
    ZLSB =CST%XLSTT+(CST%XCPV-CST%XCI)*(ZT-CST%XTT)
    ZCPHB =CST%XCPD+CST%XCPV*ZEWB 
  
  
  ENDIF


  

  

  IF (GWORK1 ) THEN
    ZLSA =ZEWA /ZTLCL *(CST%XBETAW/ZTLCL -CST%XGAMW)
    ZLSA =(ZEWA -ZRVLCL )/(1.+ZLVA /ZCPHA *ZLSA )
    ZTLCL =ZTLCL -ZLVA /ZCPHA *ZLSA 
  ENDIF


  

  

  IF (GWORK1 .AND.ZRVLCL >ZEWB ) THEN
    ZLSB =ZEWB /ZTMIX *(CST%XBETAW/ZTMIX -CST%XGAMW)
    ZLSB =(ZEWB -ZRVLCL )/(1.+ZLVB /ZCPHB *ZLSB )
    ZTLCL =ZTMIX -ZLVB /ZCPHB *ZLSB 
    ZRVLCL =ZRVLCL -ZLSB 
    ZPLCL =ZPRESMIX 
    ZTHLCL =ZTLCL *(CST%XP00/ZPLCL )**ZRDOCP
    ZTHVLCL =ZTHLCL *(1.+ZEPSA*ZRVLCL )/(1.+ZRVLCL )
  ENDIF

  
  JLSTEP=4

  DO JLSTART=JKK, IKE-1, JLSTEP
    JLSIZE=MIN (JLSTEP, JT-JLSTART+1)

    IF (JLSTART.EQ.JKK) THEN
      IJIMIN=D%NIB
      IJIMAX=D%NIE
      LLCOMPUTE=.TRUE.
    ELSE

      IF (LLCOMPUTE) THEN
        LLCOMPUTE=.FALSE.
        IJIMIN2=IJIMIN
        IJIMAX2=IJIMAX

        

        IF ((JI.GE.IJIMIN2).AND.(JI.LE.IJIMAX2).AND.GWORK1 .AND.(ZPLCL <=PPRES (JI, JLSTART))) THEN

          IF (.NOT.LLCOMPUTE)  THEN
            IJIMIN=JI
          ENDIF

          IJIMAX=JI
          LLCOMPUTE=.TRUE.
        ENDIF

      
      ENDIF

    ENDIF


    IF (LLCOMPUTE) THEN

      DO JK=JLSTART, JLSTART+JLSIZE-1

        

        IF ((JI.GE.IJIMIN).AND.(JI.LE.IJIMAX).AND.ZPLCL <=PPRES (JI, JK).AND.GWORK1 )  THEN
          ILCL =JK+1
        ENDIF

      
      ENDDO

    ENDIF

  ENDDO

  JLCLMIN=ILCL 

  

  IF (GWORK1 ) THEN
    JK=ILCL 
    JKM=JK-1
    ZDP =LOG (ZPLCL /PPRES (JI, JKM))/LOG (PPRES (JI, JK)/PPRES (JI, JKM))
    ZTHVELCL =PTHV (JI, JKM)+(PTHV (JI, JK)-PTHV (JI, JKM))*ZDP 
    ZZLCL =PZ (JI, JKM)+(PZ (JI, JK)-PZ (JI, JKM))*ZDP 
  ENDIF

  
  
  JLCLMIN=MIN (JLCLMIN, ILCL )
  ZWLCL =CVP_SHAL%XAW*MAX (0., PW (JI, IKB))+CVP_SHAL%XBW
  ZWLCLSQRENT =1.05*ZWLCL *ZWLCL 
  ZTHEUL =ZTLCL *(ZTHLCL /ZTLCL )**(1.-0.28*ZRVLCL )*EXP (&
  &(3374.6525/ZTLCL -2.5403)*ZRVLCL *(1.+0.81*ZRVLCL ))
  
  ZCAPE =MAX (JLCLMIN-1-IKB, 0)*CST%XG
  ZCAP =0.
  ZTOP =0.
  ZWORK3 =0.
  JKM=MAX (IKB, JLCLMIN-1)
  JLSTEP=4

  DO JLSTART=JKM, JT, JLSTEP
    JLSIZE=MIN (JLSTEP, JT-JLSTART+1)

    IF (JLSTART.EQ.JKM) THEN
      LLCOMPUTE=.TRUE.
    ELSE

      IF (LLCOMPUTE) THEN
        LLCOMPUTE=.FALSE.

        

        IF (GTRIG2 .AND.((ZWORK3 .GT.-0.5).OR.(ZCAPE .LE.10.)))  THEN
          LLCOMPUTE=.TRUE.
        ENDIF

      
      ENDIF

    ENDIF


    IF (LLCOMPUTE) THEN

      DO JL=JLSTART, JLSTART+JLSIZE-1
        JK=JL+1
        
        ZX1=(2.*ZTHEUL /(PTHES (JI, JK)+PTHES (JI, JL))-1.)*(PZ (JI, JK)-PZ (JI, JL))

        IF ((JL<ILCL ))  THEN
          ZX1=0.
        ENDIF

        ZCAPE =ZCAPE +CST%XG*MAX (1., ZX1)
        ZCAP =ZCAP +ZX1
        ZX2=SIGN (1.,(CVP_SHAL%XNHGAM*CST%XG*ZCAP +ZWLCLSQRENT ))
        ZWORK3 =MAX (-1.,(ZWORK3 +MIN (0., ZX2)))
        ZTOPP =ZTOP 
        ZTOP =PZ (JI, JL)*.5*(1.+ZX2)*(1.+ZWORK3 )+ZTOP *.5*(1.-ZX2)
        ZTOP =MAX (ZTOP , ZTOPP )
      
      ENDDO

    ENDIF

  ENDDO


  

  IF ((ZTOP -ZZLCL ).GE.CVP_SHAL%XCDEPTH.AND.GTRIG2 .AND.ZCAPE >10.) THEN
    GTRIG2 =.FALSE.
    OTRIG (JI)=.TRUE.
    PTHLCL (JI)=ZTHLCL 
    PRVLCL (JI)=ZRVLCL 
    PTLCL (JI)=ZTLCL 
    PWLCL (JI)=ZWLCL 
    PZLCL (JI)=ZZLCL 
    PTHVELCL (JI)=ZTHVELCL 
    KDPL (JI)=IDPL 
    KPBL (JI)=IPBL 
    KLCL (JI)=ILCL 
  ENDIF

  
ENDDO





END SUBROUTINE CONVECT_TRIGGER_SHAL_OPENACC

ENDMODULE MODE_CONVECT_TRIGGER_SHAL_OPENACC
