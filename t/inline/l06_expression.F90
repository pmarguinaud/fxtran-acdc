SUBROUTINE L06_EXPRESSION (KLON, KLEV, KIDIA, KFDIA, X, Y)
INTEGER, INTENT (IN) :: KLON, KLEV, KIDIA, KFDIA
REAL, INTENT (IN) :: X (KLON)
REAL, INTENT (OUT) :: Y (KLON)
INTEGER :: JLON
CALL E (X + 1., Y)
CALL E (SQRT (X (KIDIA:KFDIA)), Y (KIDIA:KFDIA))
CONTAINS
ELEMENTAL SUBROUTINE E (A, B)
REAL, INTENT (IN) :: A
REAL, INTENT (OUT) :: B
B = 2. * A
END SUBROUTINE
END SUBROUTINE
