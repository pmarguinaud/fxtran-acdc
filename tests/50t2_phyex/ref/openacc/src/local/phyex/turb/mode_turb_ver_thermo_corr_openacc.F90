      CALL D_M3_R2_WTH2_O_DDRDZ_OPENACC (D, CSTURB, TURBN, PREDR1, PREDTH1, PD,&
      & PLEPS, PSQRT_TKE, PBLL_O_E, PETHETA, PDR_DZ, ZWORK2, YDSTACK=YLSTACK)

      DO JK=1, IKT
        
        ZF (JI, JK)=ZF (JI, JK)+ZWORK1 (JI, JK)*PFTH2 (JI, JK)
        ZDFDDRDZ (JI, JK)=ZDFDDRDZ (JI, JK)+ZWORK2 (JI, JK)*PFTH2 (JI, JK)
      
      ENDDO

    ENDIF


    IF (GFWTH) THEN
      CALL MZF_PHY_OPENACC (D, PFWTH, ZWORK1, YDSTACK=YLSTACK)
      CALL M3_R2_W2TH_OPENACC (D, CSTURB, TURBN, PD, PLM, PLEPS, PTKEM&
      &, PBLL_O_E, PETHETA, PDR_DZ, ZWORK2, YDSTACK=YLSTACK)
      CALL D_M3_R2_W2TH_O_DDRDZ_OPENACC (D, CSTURB, TURBN, PREDR1, PREDTH1, PD, PLM&
      &, PLEPS, PTKEM, PBLL_O_E, PETHETA, PDR_DZ, ZWORK3, YDSTACK=YLSTACK)

      DO JK=1, IKT
        
        ZF (JI, JK)=ZF (JI, JK)+ZWORK2 (JI, JK)*ZWORK1 (JI, JK)
        ZDFDDRDZ (JI, JK)=ZDFDDRDZ (JI, JK)+ZWORK3 (JI, JK)*ZWORK1 (JI, JK)
      
      ENDDO

    ENDIF


    IF (GFTHR) THEN
      CALL M3_R2_WTHR_OPENACC (D, CSTURB, TURBN, PREDTH1, PD, PLEPS, PSQRT_TKE&
      &, PBLL_O_E, PETHETA, PDR_DZ, ZWORK1, YDSTACK=YLSTACK)
      CALL D_M3_R2_WTHR_O_DDRDZ_OPENACC (D, CSTURB, TURBN, PREDR1, PREDTH1, PD,&
      & PLEPS, PSQRT_TKE, PBLL_O_E, PETHETA, PDR_DZ, ZWORK2, YDSTACK=YLSTACK)

      DO JK=1, IKT
        
        ZF (JI, JK)=ZF (JI, JK)+ZWORK1 (JI, JK)*PFTHR (JI, JK)
        ZDFDDRDZ (JI, JK)=ZDFDDRDZ (JI, JK)+ZWORK2 (JI, JK)*PFTHR (JI, JK)
      
      ENDDO

    ENDIF

  ENDIF


  DO JK=1, IKT
    
    ZWORK1 (JI, JK)=PRP (JI, JK)-PRM (JI, JK, 1)
  
  ENDDO

  CALL DZM_PHY_OPENACC (D, ZWORK1, ZWORK2, YDSTACK=YLSTACK)
  
  CALL D_PSI3DRDZ2_O_DDRDZ_OPENACC (D, CSTURB, TURBN, PPSI3, PREDR1, PREDTH1, PRED2R3&
  &, PRED2THR3, PDR_DZ, "1DIM", GUSERV, ZWKPHIPSI1, YDSTACK=YLSTACK)

  DO JK=1, IKT
    
    ZSHUGRADWK2_2D (JI, JK)=PRP (JI, JK)-PRM (JI, JK, 1)
  
  ENDDO

  CALL DZM_PHY_OPENACC (D, ZSHUGRADWK2_2D, ZDZM2D_WORK1, YDSTACK=YLSTACK)

  DO JK=1, IKT
    
    ZSHUGRADWK1_2D (JI, JK)=ZWKPHIPSI1 (JI, JK)*ZDZM2D_WORK1 (JI, JK)/PDZZ (JI, JK)
  
  ENDDO

  CALL MZF_PHY_OPENACC (D, ZSHUGRADWK1_2D, ZMZF2D_WORK1, YDSTACK=YLSTACK)

  DO JK=1, IKT
    
    ZSHUGRADWK2_2D (JI, JK)=PRP (JI, JK)-PRM (JI, JK, 1)
  
  ENDDO

  CALL DZM_PHY_OPENACC (D, ZSHUGRADWK2_2D, ZDZM2D_WORK2, YDSTACK=YLSTACK)

  DO JK=1, IKT
    
    ZSHUGRADWK1_2D (JI, JK)=ZDZM2D_WORK2 (JI, JK)/PDZZ (JI, JK)
  
  ENDDO

  CALL MZF_PHY_OPENACC (D, ZSHUGRADWK1_2D, ZMZF2D_WORK2, YDSTACK=YLSTACK)

  DO JK=1, IKT
    
    ZFLXZ (JI, JK)=ZF (JI, JK)+TURBN%XIMPL*TURBN%XCTV*PLM (JI, JK)*PLEPS (JI, JK)&
    &*ZMZF2D_WORK1 (JI, JK)+TURBN%XIMPL*ZDFDDRDZ (JI, JK)*ZMZF2D_WORK2 (JI, JK)
  
  ENDDO

  
  
  
  ZFLXZ (JI, IKB)=TURBN%XCHV*PPSI3 (JI, IKB+IKL)*PLM (JI, IKB)*PLEPS (JI, IKB)*(PEXPL*(ZCOEFF&
  & (JI, IKB+2*IKL)*PRM (JI, IKB+2*IKL, 1)+ZCOEFF (JI, IKB+IKL)*PRM (JI, IKB+IKL, 1)+ZCOEFF&
  & (JI, IKB)*PRM (JI, IKB, 1))**2+TURBN%XIMPL*(ZCOEFF (JI, IKB+2*IKL)*PRP (JI, IKB+2*IKL&
  &)+ZCOEFF (JI, IKB+IKL)*PRP (JI, IKB+IKL)+ZCOEFF (JI, IKB)*PRP (JI, IKB))**2)
  
  
  
  ZFLXZ (JI, IKA)=ZFLXZ (JI, IKB)

  

  IF (NEBN%LSTATNW) THEN

    DO JK=1, IKT
      
      ZFLXZ (JI, JK)=MAX (0., 2.*ZFLXZ (JI, JK))
    
    ENDDO

  ENDIF


  IF (KRRL>0) THEN

    DO JK=1, IKT
      
      PSIGS (JI, JK)=PSIGS (JI, JK)+PAMOIST (JI, JK)**2*ZFLXZ (JI, JK)
    
    ENDDO

  ENDIF

  
  
ENDIF


IF (KRRL>0) THEN
  
  PSIGS (JI, IKA)=PSIGS (JI, IKB)
  PSIGS (JI, IKU)=PSIGS (JI, IKE)

  

  DO JK=1, IKT
    
    PSIGS (JI, JK)=SQRT (MAX (PSIGS (JI, JK), TURBN%XMINSIGS))
  
  ENDDO

ENDIF


END SUBROUTINE TURB_VER_THERMO_CORR_OPENACC

