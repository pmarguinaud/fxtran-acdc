END INTERFACE

CONTAINS
SUBROUTINE ACDC_WIPE_TFIELDMETADATA (SELF, LDDELETED, LDFIELDAPI)

IMPLICIT NONE
TYPE (TFIELDMETADATA), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDDELETED, LDFIELDAPI
LOGICAL :: LLDELETED
LOGICAL :: LLFIELDAPI
LLFIELDAPI = .FALSE.
IF (PRESENT (LDFIELDAPI)) THEN
  LLFIELDAPI = LDFIELDAPI
ENDIF

