MODULE UTIL_PHYEX_T_COPY_MOD
USE MODD_PHYEX, ONLY : PHYEX_T
INTERFACE ACDC_COPY
MODULE PROCEDURE ACDC_COPY_PHYEX_T
END INTERFACE

CONTAINS
SUBROUTINE ACDC_COPY_PHYEX_T (SELF, LDCREATED, LDFIELDAPI)
USE UTIL_CLOUDPAR_T_MOD
USE UTIL_CSTURB_T_MOD
USE UTIL_CST_T_MOD
USE UTIL_ELEC_DESCR_T_MOD
USE UTIL_ELEC_PARAM_T_MOD
USE UTIL_NEB_T_MOD
USE UTIL_NSV_T_MOD
USE UTIL_PARAM_ICE_T_MOD
USE UTIL_PARAM_LIMA_COLD_T_MOD
USE UTIL_PARAM_LIMA_MIXED_T_MOD
USE UTIL_PARAM_LIMA_WARM_T_MOD
USE UTIL_PARAM_LIMA_T_MOD
USE UTIL_PARAM_MFSHALL_T_MOD
USE UTIL_RAIN_ICE_DESCR_T_MOD
USE UTIL_RAIN_ICE_PARAM_T_MOD
USE UTIL_TURB_T_MOD
IMPLICIT NONE
TYPE (PHYEX_T), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDCREATED, LDFIELDAPI
LOGICAL :: LLCREATED
LOGICAL :: LLFIELDAPI
LLFIELDAPI = .FALSE.
IF (PRESENT (LDFIELDAPI)) THEN
  LLFIELDAPI = LDFIELDAPI
ENDIF
LLCREATED = .FALSE.
IF (PRESENT (LDCREATED)) THEN
  LLCREATED = LDCREATED
ENDIF
IF (.NOT. LLCREATED) THEN
  !$ACC ENTER DATA CREATE (SELF)
  !$ACC UPDATE DEVICE (SELF)
ENDIF
CALL ACDC_COPY_CST_T (SELF%CST, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_PARAM_ICE_T (SELF%PARAM_ICEN, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_RAIN_ICE_DESCR_T (SELF%RAIN_ICE_DESCRN, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_RAIN_ICE_PARAM_T (SELF%RAIN_ICE_PARAMN, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_CLOUDPAR_T (SELF%CLOUDPARN, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_PARAM_MFSHALL_T (SELF%PARAM_MFSHALLN, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_CSTURB_T (SELF%CSTURB, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_TURB_T (SELF%TURBN, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_NEB_T (SELF%NEBN, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_PARAM_LIMA_T (SELF%PARAM_LIMA, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_PARAM_LIMA_WARM_T (SELF%PARAM_LIMA_WARM, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_PARAM_LIMA_COLD_T (SELF%PARAM_LIMA_COLD, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_PARAM_LIMA_MIXED_T (SELF%PARAM_LIMA_MIXED, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_ELEC_DESCR_T (SELF%ELEC_DESCR, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_ELEC_PARAM_T (SELF%ELEC_PARAM, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

CALL ACDC_COPY_NSV_T (SELF%TNSV, LDCREATED=.TRUE., LDFIELDAPI=LDFIELDAPI)

END SUBROUTINE
END MODULE
