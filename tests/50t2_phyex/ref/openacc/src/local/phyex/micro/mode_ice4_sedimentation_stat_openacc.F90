
MODULE MODE_ICE4_SEDIMENTATION_STAT_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE ICE4_SEDIMENTATION_STAT_OPENACC (D, CST, ICEP, ICED, PARAMI, PTSTEP&
&, KRR, PDZZ, PRHODREF, PPABST, PTHT, PT, PRHODJ, PRS, PRT, PCONC3D, PINPRC&
&, PINPRR, PINPRI, PINPRS, PINPRG, PSEA, PTOWN, PINPRH, PFPR, YDSTACK)
!$ACC ROUTINE (ICE4_SEDIMENTATION_STAT_OPENACC) SEQ      


USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_CST,ONLY:CST_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T
USE MODD_RAIN_ICE_PARAM_N,ONLY:RAIN_ICE_PARAM_T
USE MODD_PARAM_ICE_N,ONLY:PARAM_ICE_T
USE MODD_FIELDS_ADDRESS,ONLY:IRC, IRG, IRH, IRI, IRR, IRS
USE MODI_GAMMA,ONLY:GAMMA
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (DIMPHYEX_T), INTENT (IN)::D
TYPE (CST_T), INTENT (IN)::CST
TYPE (RAIN_ICE_PARAM_T), INTENT (IN)::ICEP
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
TYPE (PARAM_ICE_T), INTENT (IN)::PARAMI
REAL, INTENT (IN)::PTSTEP
INTEGER, INTENT (IN)::KRR
REAL, INTENT (IN)::PDZZ(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRHODREF(D%NIJT, D%NKT)
REAL, INTENT (IN)::PPABST(D%NIJT, D%NKT)
REAL, INTENT (IN)::PTHT(D%NIJT, D%NKT)
REAL, INTENT (IN)::PT(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRHODJ(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PRS(D%NIJT, D%NKT, KRR)
REAL, INTENT (IN)::PRT(D%NIJT, D%NKT, KRR)
REAL, INTENT (IN)::PCONC3D(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PINPRC(D%NIJT)
REAL, INTENT (OUT)::PINPRR(D%NIJT)
REAL, INTENT (OUT)::PINPRI(D%NIJT)
REAL, INTENT (OUT)::PINPRS(D%NIJT)
REAL, INTENT (OUT)::PINPRG(D%NIJT)
REAL, OPTIONAL, INTENT (IN)::PSEA(D%NIJT)
REAL, OPTIONAL, INTENT (IN)::PTOWN(D%NIJT)
REAL, OPTIONAL, INTENT (OUT)::PINPRH(D%NIJT)
REAL, OPTIONAL, INTENT (OUT)::PFPR(D%NIJT, D%NKT, KRR)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
TYPE(FXTRAN_ACDC_STACK) :: YLSTACK
LOGICAL::LLSEA_AND_TOWN
INTEGER::IKTE
INTEGER::IKTB
INTEGER::IIJE
INTEGER::IIJB
INTEGER::IKL
INTEGER::IKE
INTEGER::IKB
INTEGER::JK
INTEGER::JI
INTEGER::JRR
INTEGER::IKPLUS
INTEGER::IK
INTEGER::ISHIFT
REAL::ZRAYDEFO
REAL::ZGC2
REAL::ZGAC2
REAL::ZGC
REAL::ZGAC
REAL::ZINVTSTEP
REAL::ZTSORHODZ
fxtran_acdc_temp (REAL, ZSED, (D%NIJT, 0:1, 2:KRR))

REAL::FWSED1TMP
REAL::FWSED2TMP
REAL::ZQP
REAL::ZWSEDW2
REAL::ZWSEDW1
REAL::ZLBDAS
REAL::ZLBC
REAL::ZFSEDC
REAL::ZCONC3D
REAL::ZRAY
REAL::ZZCC
REAL::ZZWLBDC
REAL::ZZWLBDA

YLSTACK = YDSTACK



IF (KIND (ZSED) == 8) THEN
    fxtran_acdc_alloc8 (ZSED)
ELSEIF (KIND (ZSED) == 4) THEN
    fxtran_acdc_alloc4 (ZSED)
ELSE
    STOP 1
ENDIF


JI = D%NIB


IKB=D%NKB
IKE=D%NKE
IKL=D%NKL
IIJB=D%NIB
IIJE=D%NIE
IKTB=D%NKTB
IKTE=D%NKTE

IF (PRESENT (PFPR)) THEN
  PFPR (JI,:IKTB,:)=0.
  PFPR (JI, IKTE:,:)=0.
ENDIF

ZINVTSTEP=1./PTSTEP
ZGAC=GAMMA (ICED%XNUC+1.0/ICED%XALPHAC)
ZGC=GAMMA (ICED%XNUC)
ZGAC2=GAMMA (ICED%XNUC2+1.0/ICED%XALPHAC2)
ZGC2=GAMMA (ICED%XNUC2)
ZRAYDEFO=MAX (1., 0.5*(ZGAC/ZGC))
LLSEA_AND_TOWN=PRESENT (PSEA).AND.PRESENT (PTOWN)
ISHIFT=0

IKPLUS=ISHIFT
IK=1-ISHIFT
ISHIFT=1-ISHIFT



DO JRR=IRC, KRR
  ZSED (JI, IKPLUS, JRR)=0.
ENDDO


DO JK=IKE, IKB,-1*IKL
  
  ZTSORHODZ =PTSTEP/(PRHODREF (JI, JK)*PDZZ (JI, JK))

  

  DO JRR=IRC, KRR

    IF (JRR==IRC) THEN

      IF (PARAMI%LSEDIC) THEN
        
        
        ZQP=ZSED (JI, IKPLUS, JRR)*ZTSORHODZ 

        IF ((PRT (JI, JK, IRC)>ICED%XRTMIN (JRR)).OR.(ZQP>ICED%XRTMIN (JRR))) THEN

          IF (LLSEA_AND_TOWN) THEN
            ZRAY=MAX (1., 0.5*((1.-PSEA (JI))*ZGAC/ZGC+PSEA (JI)*ZGAC2/ZGC2))
            ZLBC=MAX (MIN (ICED%XLBC (1), ICED%XLBC (2)),(PSEA (JI)*ICED%XLBC (2)+(1.-PSEA (JI))*ICED%XLBC (1)))
            ZFSEDC=MAX (MIN (ICEP%XFSEDC (1), ICEP%XFSEDC (2)),(PSEA &
            &(JI)*ICEP%XFSEDC (2)+(1.-PSEA (JI))*ICEP%XFSEDC (1)))
          ELSE
            ZRAY=ZRAYDEFO
            ZLBC=ICED%XLBC (1)
            ZFSEDC=ICEP%XFSEDC (1)
          ENDIF

          ZCONC3D=PCONC3D (JI, JK)

          IF (PRT (JI, JK, IRC)>ICED%XRTMIN (JRR)) THEN
            ZZWLBDA=6.6E-8*(101325./PPABST (JI, JK))*(PTHT (JI, JK)/293.15)
            ZZWLBDC=(ZLBC*ZCONC3D/(PRHODREF (JI, JK)*PRT (JI, JK, IRC)))**ICED%XLBEXC
            ZZCC=ICED%XCC*(1.+1.26*ZZWLBDA*ZZWLBDC/ZRAY)
            ZWSEDW1=PRHODREF (JI, JK)**(-ICED%XCEXVT)*ZZWLBDC**(-ICED%XDC)*ZZCC*ZFSEDC
          ELSE
            ZWSEDW1=0.
          ENDIF


          IF (ZQP>ICED%XRTMIN (JRR)) THEN
            ZZWLBDA=6.6E-8*(101325./PPABST (JI, JK))*(PTHT (JI, JK)/293.15)
            ZZWLBDC=(ZLBC*ZCONC3D/(PRHODREF (JI, JK)*ZQP))**ICED%XLBEXC
            ZZCC=ICED%XCC*(1.+1.26*ZZWLBDA*ZZWLBDC/ZRAY)
            ZWSEDW2=PRHODREF (JI, JK)**(-ICED%XCEXVT)*ZZWLBDC**(-ICED%XDC)*ZZCC*ZFSEDC
          ELSE
            ZWSEDW2=0.
          ENDIF

        ELSE
          ZWSEDW1=0.
          ZWSEDW2=0.
        ENDIF


        IF (ZWSEDW2/=0.) THEN
          
          FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRC&
          &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRC))
          
          
          
          FWSED2TMP=MAX (0., 1.-PDZZ (JI, JK)/(PTSTEP*ZWSEDW2))*ZSED (JI, IKPLUS, JRR)
          
          
          ZSED (JI, IK, JRR)=FWSED1TMP+FWSED2TMP
        ELSE
          
          FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRC&
          &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRC))
          
          
          ZSED (JI, IK, JRR)=FWSED1TMP
        ENDIF

      
      
      
      ELSE
        ZSED (JI, IK, JRR)=0.
      ENDIF

    ELSEIF (JRR==IRR) THEN
      
      
      ZQP=ZSED (JI, IKPLUS, JRR)*ZTSORHODZ 

      IF ((PRT (JI, JK, IRR)>ICED%XRTMIN (JRR)).OR.(ZQP>ICED%XRTMIN (JRR))) THEN

        IF (PRT (JI, JK, IRR)>ICED%XRTMIN (JRR)) THEN
          ZWSEDW1=ICEP%XFSEDR*PRT (JI, JK, IRR)**(ICEP%XEXSEDR-1&
          &)*PRHODREF (JI, JK)**(ICEP%XEXSEDR-ICED%XCEXVT-1)
        ELSE
          ZWSEDW1=0.
        ENDIF


        IF (ZQP>ICED%XRTMIN (JRR)) THEN
          ZWSEDW2=ICEP%XFSEDR*ZQP**(ICEP%XEXSEDR-1)*PRHODREF (JI, JK)**(ICEP%XEXSEDR-ICED%XCEXVT-1)
        ELSE
          ZWSEDW2=0.
        ENDIF

      ELSE
        ZWSEDW1=0.
        ZWSEDW2=0.
      ENDIF


      IF (ZWSEDW2/=0.) THEN
        
        FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRR&
        &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRR))
        
        
        
        FWSED2TMP=MAX (0., 1.-PDZZ (JI, JK)/(PTSTEP*ZWSEDW2))*ZSED (JI, IKPLUS, JRR)
        
        
        ZSED (JI, IK, JRR)=FWSED1TMP+FWSED2TMP
      ELSE
        
        FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRR&
        &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRR))
        
        
        ZSED (JI, IK, JRR)=FWSED1TMP
      ENDIF

    
    
    
    ELSEIF (JRR==IRI) THEN
      
      
      ZQP=ZSED (JI, IKPLUS, JRR)*ZTSORHODZ 

      IF ((PRT (JI, JK, IRI)>ICED%XRTMIN (JRR)).OR.(ZQP>ICED%XRTMIN (JRR))) THEN

        IF (PRT (JI, JK, IRI)>MAX (ICED%XRTMIN (JRR), 1.0E-7)) THEN
          ZWSEDW1=ICEP%XFSEDI*PRHODREF (JI, JK)**(-ICED%XCEXVT)*MAX (0.05E6,-0.15319E6&
          &-0.021454E6*LOG (PRHODREF (JI, JK)*PRT (JI, JK, IRI)))**ICEP%XEXCSEDI
        ELSE
          ZWSEDW1=0.
        ENDIF


        IF (ZQP>MAX (ICED%XRTMIN (JRR), 1.0E-7)) THEN
          ZWSEDW2=ICEP%XFSEDI*PRHODREF (JI, JK)**(-ICED%XCEXVT)*MAX (0.05E6,-0&
          &.15319E6-0.021454E6*LOG (PRHODREF (JI, JK)*ZQP))**ICEP%XEXCSEDI
        ELSE
          ZWSEDW2=0.
        ENDIF

      ELSE
        ZWSEDW1=0.
        ZWSEDW2=0.
      ENDIF


      IF (ZWSEDW2/=0.) THEN
        
        FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRI&
        &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRI))
        
        
        
        FWSED2TMP=MAX (0., 1.-PDZZ (JI, JK)/(PTSTEP*ZWSEDW2))*ZSED (JI, IKPLUS, JRR)
        
        
        ZSED (JI, IK, JRR)=FWSED1TMP+FWSED2TMP
      ELSE
        
        FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRI&
        &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRI))
        
        
        ZSED (JI, IK, JRR)=FWSED1TMP
      ENDIF

    
    
    
    ELSEIF (JRR==IRS) THEN

      IF (.NOT.ICEP%LNEWCOEFF) THEN
        
        
        ZQP=ZSED (JI, IKPLUS, JRR)*ZTSORHODZ 

        IF ((PRT (JI, JK, IRS)>ICED%XRTMIN (JRR)).OR.(ZQP>ICED%XRTMIN (JRR))) THEN

          IF (PRT (JI, JK, IRS)>ICED%XRTMIN (JRR)) THEN
            ZWSEDW1=ICEP%XFSEDS*PRT (JI, JK, IRS)**(ICEP%XEXSEDS-1&
            &)*PRHODREF (JI, JK)**(ICEP%XEXSEDS-ICED%XCEXVT-1)
          ELSE
            ZWSEDW1=0.
          ENDIF


          IF (ZQP>ICED%XRTMIN (JRR)) THEN
            ZWSEDW2=ICEP%XFSEDS*ZQP**(ICEP%XEXSEDS-1)*PRHODREF (JI, JK)**(ICEP%XEXSEDS-ICED%XCEXVT-1)
          ELSE
            ZWSEDW2=0.
          ENDIF

        ELSE
          ZWSEDW1=0.
          ZWSEDW2=0.
        ENDIF


        IF (ZWSEDW2/=0.) THEN
          
          FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRS&
          &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRS))
          
          
          
          FWSED2TMP=MAX (0., 1.-PDZZ (JI, JK)/(PTSTEP*ZWSEDW2))*ZSED (JI, IKPLUS, JRR)
          
          
          ZSED (JI, IK, JRR)=FWSED1TMP+FWSED2TMP
        ELSE
          
          FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRS&
          &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRS))
          
          
          ZSED (JI, IK, JRR)=FWSED1TMP
        ENDIF

      
      
      
      ELSE
        
        
        ZQP=ZSED (JI, IKPLUS, JRR)*ZTSORHODZ 

        IF ((PRT (JI, JK, IRS)>ICED%XRTMIN (JRR))) THEN

          IF (PARAMI%LSNOW_T) THEN

            IF (PT (JI, JK)>CST%XTT-10.0) THEN
              ZLBDAS=MAX (MIN (ICED%XLBDAS_MAX, 10**(14.554-0.0423*PT&
              & (JI, JK))), ICED%XLBDAS_MIN)*ICED%XTRANS_MP_GAMMAS
            ELSE
              ZLBDAS=MAX (MIN (ICED%XLBDAS_MAX, 10**(6.226-0.0106*PT&
              & (JI, JK))), ICED%XLBDAS_MIN)*ICED%XTRANS_MP_GAMMAS
            ENDIF

          ELSE
            ZLBDAS=MAX (MIN (ICED%XLBDAS_MAX, ICED%XLBS*(PRHODREF (JI,&
            & JK)*PRT (JI, JK, IRS))**ICED%XLBEXS), ICED%XLBDAS_MIN)
          ENDIF


          IF (PRT (JI, JK, IRS)>ICED%XRTMIN (JRR)) THEN
            ZWSEDW1=ICEP%XFSEDS*PRHODREF (JI, JK)**(-ICED%XCEXVT)*(1+(ICED%XFVELOS/ZLBDAS)**ICED&
            &%XALPHAS)**(-ICED%XNUS+ICEP%XEXSEDS/ICED%XALPHAS)*ZLBDAS**(ICED%XBS+ICEP%XEXSEDS)
          ELSE
            ZWSEDW1=0.
          ENDIF


          IF (ZQP>ICED%XRTMIN (JRR)) THEN
            ZWSEDW2=ICEP%XFSEDS*PRHODREF (JI, JK)**(-ICED%XCEXVT)*(1+(ICED%XFVELOS/ZLBDAS)**ICED&
            &%XALPHAS)**(-ICED%XNUS+ICEP%XEXSEDS/ICED%XALPHAS)*ZLBDAS**(ICED%XBS+ICEP%XEXSEDS)
          ELSE
            ZWSEDW2=0.
          ENDIF

        ELSE
          ZWSEDW1=0.
          ZWSEDW2=0.
        ENDIF


        IF (ZWSEDW2/=0.) THEN
          
          FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRS&
          &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRS))
          
          
          
          FWSED2TMP=MAX (0., 1.-PDZZ (JI, JK)/(PTSTEP*ZWSEDW2))*ZSED (JI, IKPLUS, JRR)
          
          
          ZSED (JI, IK, JRR)=FWSED1TMP+FWSED2TMP
        ELSE
          
          FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRS&
          &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRS))
          
          
          ZSED (JI, IK, JRR)=FWSED1TMP
        ENDIF

      
      
      
      ENDIF

    ELSEIF (JRR==IRG) THEN
      
      
      ZQP=ZSED (JI, IKPLUS, JRR)*ZTSORHODZ 

      IF ((PRT (JI, JK, IRG)>ICED%XRTMIN (JRR)).OR.(ZQP>ICED%XRTMIN (JRR))) THEN

        IF (PRT (JI, JK, IRG)>ICED%XRTMIN (JRR)) THEN
          ZWSEDW1=ICEP%XFSEDG*PRT (JI, JK, IRG)**(ICEP%XEXSEDG-1&
          &)*PRHODREF (JI, JK)**(ICEP%XEXSEDG-ICED%XCEXVT-1)
        ELSE
          ZWSEDW1=0.
        ENDIF


        IF (ZQP>ICED%XRTMIN (JRR)) THEN
          ZWSEDW2=ICEP%XFSEDG*ZQP**(ICEP%XEXSEDG-1)*PRHODREF (JI, JK)**(ICEP%XEXSEDG-ICED%XCEXVT-1)
        ELSE
          ZWSEDW2=0.
        ENDIF

      ELSE
        ZWSEDW1=0.
        ZWSEDW2=0.
      ENDIF


      IF (ZWSEDW2/=0.) THEN
        
        FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRG&
        &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRG))
        
        
        
        FWSED2TMP=MAX (0., 1.-PDZZ (JI, JK)/(PTSTEP*ZWSEDW2))*ZSED (JI, IKPLUS, JRR)
        
        
        ZSED (JI, IK, JRR)=FWSED1TMP+FWSED2TMP
      ELSE
        
        FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRG&
        &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRG))
        
        
        ZSED (JI, IK, JRR)=FWSED1TMP
      ENDIF

    
    
    
    ELSEIF (JRR==IRH) THEN
      
      
      ZQP=ZSED (JI, IKPLUS, JRR)*ZTSORHODZ 

      IF ((PRT (JI, JK, IRH)>ICED%XRTMIN (JRR)).OR.(ZQP>ICED%XRTMIN (JRR))) THEN

        IF (PRT (JI, JK, IRH)>ICED%XRTMIN (JRR)) THEN
          ZWSEDW1=ICEP%XFSEDH*PRT (JI, JK, IRH)**(ICEP%XEXSEDH-1&
          &)*PRHODREF (JI, JK)**(ICEP%XEXSEDH-ICED%XCEXVT-1)
        ELSE
          ZWSEDW1=0.
        ENDIF


        IF (ZQP>ICED%XRTMIN (JRR)) THEN
          ZWSEDW2=ICEP%XFSEDH*ZQP**(ICEP%XEXSEDH-1)*PRHODREF (JI, JK)**(ICEP%XEXSEDH-ICED%XCEXVT-1)
        ELSE
          ZWSEDW2=0.
        ENDIF

      ELSE
        ZWSEDW1=0.
        ZWSEDW2=0.
      ENDIF


      IF (ZWSEDW2/=0.) THEN
        
        FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRH&
        &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRH))
        
        
        
        FWSED2TMP=MAX (0., 1.-PDZZ (JI, JK)/(PTSTEP*ZWSEDW2))*ZSED (JI, IKPLUS, JRR)
        
        
        ZSED (JI, IK, JRR)=FWSED1TMP+FWSED2TMP
      ELSE
        
        FWSED1TMP=MIN (PRHODREF (JI, JK)*PDZZ (JI, JK)*PRT (JI, JK, IRH&
        &)*ZINVTSTEP, ZWSEDW1*PRHODREF (JI, JK)*PRT (JI, JK, IRH))
        
        
        ZSED (JI, IK, JRR)=FWSED1TMP
      ENDIF

    
    
    
    ENDIF

  ENDDO


  IF (PRESENT (PFPR)) THEN

    DO JRR=IRC, KRR
      PFPR (JI, JK, JRR)=ZSED (JI, IK, JRR)
    ENDDO

  ENDIF


  DO JRR=IRC, KRR
    
    PRS (JI, JK, JRR)=PRS (JI, JK, JRR)+ZTSORHODZ *(ZSED (JI, IKPLUS, JRR)-ZSED (JI, IK, JRR))*ZINVTSTEP
  
  ENDDO


  IF (JK==IKB) THEN

    

    IF (PARAMI%LSEDIC)  THEN
      PINPRC (JI)=ZSED (JI, IK, 2)/CST%XRHOLW
    ENDIF

    PINPRR (JI)=ZSED (JI, IK, 3)/CST%XRHOLW
    PINPRI (JI)=ZSED (JI, IK, 4)/CST%XRHOLW
    PINPRS (JI)=ZSED (JI, IK, 5)/CST%XRHOLW
    PINPRG (JI)=ZSED (JI, IK, 6)/CST%XRHOLW

    IF (PRESENT (PINPRH).AND.KRR==7) THEN
      PINPRH (JI)=ZSED (JI, IK, 7)/CST%XRHOLW
    ENDIF

  
  ENDIF

  
  IKPLUS=ISHIFT
  IK=1-ISHIFT
  ISHIFT=1-ISHIFT
  
  
ENDDO










END SUBROUTINE ICE4_SEDIMENTATION_STAT_OPENACC

ENDMODULE MODE_ICE4_SEDIMENTATION_STAT_OPENACC
