
MODULE MODE_CONVECT_CONDENS_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE CONVECT_CONDENS_OPENACC (CST, D, CONVPAR, PICE, PEPS0, PPRES, PTHL&
&, PRW, PRCO, PRIO, PZ, PT, PEW, PRC, PRI, PLV, PLS, PCPH, YDSTACK)
!$ACC ROUTINE (CONVECT_CONDENS_OPENACC) SEQ      


USE MODD_CST,ONLY:CST_T
USE MODD_CONVPAR,ONLY:CONVPAR_T
USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (CST_T), INTENT (IN)::CST
TYPE (DIMPHYEX_T), INTENT (IN)::D
TYPE (CONVPAR_T), INTENT (IN)::CONVPAR
REAL, INTENT (IN)::PICE
REAL, INTENT (IN)::PEPS0
REAL, INTENT (IN)::PPRES(D%NIJT)
REAL, INTENT (IN)::PTHL(D%NIJT)
REAL, INTENT (IN)::PRW(D%NIJT)
REAL, INTENT (IN)::PRCO(D%NIJT)
REAL, INTENT (IN)::PRIO(D%NIJT)
REAL, INTENT (IN)::PZ(D%NIJT)
REAL, INTENT (OUT)::PT(D%NIJT)
REAL, INTENT (OUT)::PEW(D%NIJT)
REAL, INTENT (OUT)::PRC(D%NIJT)
REAL, INTENT (OUT)::PRI(D%NIJT)
REAL, INTENT (OUT)::PLV(D%NIJT)
REAL, INTENT (OUT)::PLS(D%NIJT)
REAL, INTENT (OUT)::PCPH(D%NIJT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
INTEGER::JI
INTEGER::JITER
REAL::ZEI
REAL::ZWORK1
REAL::ZCPVMCI
REAL::ZCPVMCL
REAL::ZXTFRDZ
REAL::ZTMP
REAL::ZWORK2


JI = D%NIB



PCPH (JI)=CST%XCPD+CST%XCPV*PRW (JI)
ZWORK1 =(1.+PRW (JI))*CST%XG*PZ (JI)
PT (JI)=MAX (180., MIN (330.,(PTHL (JI)+PRCO (JI)*CST%XLVTT+PRIO (JI)*CST%XLSTT-ZWORK1 )/PCPH (JI)))

ZXTFRDZ=CONVPAR%XTFRZ1-CONVPAR%XTFRZ2
ZCPVMCL=CST%XCPV-CST%XCL
ZCPVMCI=CST%XCPV-CST%XCI

DO JITER=1, 6
  
  ZTMP=LOG (PT (JI))
  PEW (JI)=EXP (CST%XALPW-CST%XBETAW/PT (JI)-CST%XGAMW*ZTMP)
  PEW (JI)=PEPS0*PEW (JI)/(PPRES (JI)-PEW (JI))
  ZEI=EXP (CST%XALPI-CST%XBETAI/PT (JI)-CST%XGAMI*ZTMP)
  ZEI=PEPS0*ZEI/(PPRES (JI)-ZEI)
  ZWORK2=MAX (0., MIN (1.,(CONVPAR%XTFRZ1-PT (JI))/ZXTFRDZ))*PICE
  ZTMP=PRW (JI)-((1.-ZWORK2)*PEW (JI)+ZWORK2*ZEI)
  PRC (JI)=MAX (0.,(1.-ZWORK2)*ZTMP)
  PRI (JI)=MAX (0., ZWORK2*ZTMP)
  ZTMP=PT (JI)-CST%XTT
  PLV (JI)=CST%XLVTT+ZCPVMCL*ZTMP
  PLS (JI)=CST%XLSTT+ZCPVMCI*ZTMP
  ZTMP=(PTHL (JI)+PRC (JI)*PLV (JI)+PRI (JI)*PLS (JI)-ZWORK1 )/PCPH (JI)
  PT (JI)=MAX (175., MIN (330., PT (JI)+(ZTMP-PT (JI))*0.4))
  
ENDDO


END SUBROUTINE CONVECT_CONDENS_OPENACC

ENDMODULE MODE_CONVECT_CONDENS_OPENACC
