SUBROUTINE ANYIDIOM_OPENACC (KIDIA, KFDIA, KLON, PQ, PT, LDA, LDB, LDX, YDSTACK)
!$ACC ROUTINE (ANYIDIOM_OPENACC) SEQ      

USE PARKIND1,ONLY:JPIM, JPRB
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


INTEGER (KIND=JPIM), INTENT (IN)::KIDIA
INTEGER (KIND=JPIM), INTENT (IN)::KFDIA
INTEGER (KIND=JPIM), INTENT (IN)::KLON
REAL (KIND=JPRB), INTENT (IN)::PQ (KLON)
REAL (KIND=JPRB), INTENT (INOUT)::PT (KLON)
LOGICAL, INTENT (IN)::LDA (KLON)
LOGICAL, INTENT (IN)::LDB (KLON)
LOGICAL, INTENT (IN)::LDX
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
INTEGER (KIND=JPIM) :: JL

JL = KIDIA



IF (.NOT.(LDA (JL).AND.LDB (JL)))  THEN
  PT (JL)=1._JPRB
ENDIF


IF (.NOT.(LDA (JL).OR.PQ (JL)>0._JPRB))  THEN
  PT (JL)=2._JPRB
ENDIF


IF (.NOT.(.NOT.LDA (JL)))  THEN
  PT (JL)=3._JPRB
ENDIF


IF (LDX.AND.(LDA (JL).OR.LDB (JL)))  THEN
  PT (JL)=4._JPRB
ENDIF


IF ((LDA (JL).OR.LDB (JL)).AND.LDX)  THEN
  PT (JL)=5._JPRB
ENDIF


IF ((LDA (JL).EQV.LDB (JL)).AND.LDX)  THEN
  PT (JL)=6._JPRB
ENDIF


IF (LDX.OR.(LDA (JL).AND.LDB (JL)))  THEN
  PT (JL)=7._JPRB
ENDIF


IF (LDA (JL).OR.LDB (JL))  THEN
  PT (JL)=8._JPRB
ENDIF


IF (LDX.AND.LDA (JL))  THEN
  PT (JL)=9._JPRB
ENDIF


IF (LDX.AND.PQ (JL)>0._JPRB)  THEN
  PT (JL)=10._JPRB
ENDIF


IF (PQ (JL)<=0._JPRB)  THEN
  PT (JL)=11._JPRB
ENDIF


IF (.NOT.(PQ (JL)>0._JPRB.AND.LDX))  THEN
  PT (JL)=12._JPRB
ENDIF


IF (.NOT.(LDX.OR.PQ (JL)>0._JPRB))  THEN
  PT (JL)=13._JPRB
ENDIF


IF (.NOT.(LDX.AND.(LDA (JL).OR.LDB (JL))))  THEN
  PT (JL)=14._JPRB
ENDIF


IF (LDX.AND.PQ (JL)<=0._JPRB)  THEN
  PT (JL)=15._JPRB
ENDIF


IF (LDX.AND..NOT.(LDA (JL).OR.LDB (JL)))  THEN
  PT (JL)=16._JPRB
ENDIF


END SUBROUTINE ANYIDIOM_OPENACC
