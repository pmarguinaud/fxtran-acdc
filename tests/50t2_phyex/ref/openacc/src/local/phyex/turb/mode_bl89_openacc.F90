
MODULE MODE_BL89_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE BL89_OPENACC (D, CST, CSTURB, TURBN, PZZ, PDZZ, PTHVREF&
&, PTHLM, KRR, PRM, PTKEM, PSHEAR, PLM, OOCEAN, YDSTACK)
!$ACC ROUTINE (BL89_OPENACC) SEQ      


USE MODD_CST,ONLY:CST_T
USE MODD_CTURB,ONLY:CSTURB_T
USE MODD_TURB_N,ONLY:TURB_T
USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_PRECISION,ONLY:MNHREAL
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE

TYPE (DIMPHYEX_T), INTENT (IN)::D
TYPE (CST_T), INTENT (IN)::CST
TYPE (CSTURB_T), INTENT (IN)::CSTURB
TYPE (TURB_T), INTENT (IN)::TURBN
REAL, INTENT (IN)::PZZ(D%NIJT, D%NKT)
REAL, INTENT (IN)::PDZZ(D%NIJT, D%NKT)
REAL, INTENT (IN)::PTHVREF(D%NIJT, D%NKT)
REAL, INTENT (IN)::PTHLM(D%NIJT, D%NKT)
INTEGER, INTENT (IN)::KRR
REAL, INTENT (IN)::PRM(D%NIJT, D%NKT, KRR)
REAL, INTENT (IN)::PTKEM(D%NIJT, D%NKT)
REAL, INTENT (IN)::PSHEAR(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PLM(D%NIJT, D%NKT)
LOGICAL, INTENT (IN)::OOCEAN
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
TYPE(FXTRAN_ACDC_STACK) :: YLSTACK
INTEGER::IKU
INTEGER::IKA
INTEGER::IKB
INTEGER::IKT
fxtran_acdc_temp (REAL, ZVPT, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZDELTVPT, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZHLVPT, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZLWORKUP, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZLWORK, (D%NIJT, D%NKT))
REAL::ZTMP
REAL::ZINTE
fxtran_acdc_temp (REAL, ZSUM, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZG_O_THVREF, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZSQRT_TKE, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, PLMDN, (D%NIJT, D%NKT))
INTEGER::IIJE
INTEGER::IIJB
INTEGER::IKL
INTEGER::IKE
INTEGER::IKTE
INTEGER::IKTB
INTEGER::JI
INTEGER::JKK
INTEGER::JK
INTEGER::JRR
REAL::ZRVORD
REAL::ZLWORK2
REAL::ZLWORK1
REAL::ZPOTE
REAL::ZTESTM
REAL::ZTEST0
REAL::ZTEST


YLSTACK = YDSTACK



IF (KIND (ZVPT) == 8) THEN
    fxtran_acdc_alloc8 (ZVPT)
ELSEIF (KIND (ZVPT) == 4) THEN
    fxtran_acdc_alloc4 (ZVPT)
ELSE
    STOP 1
ENDIF


IF (KIND (ZDELTVPT) == 8) THEN
    fxtran_acdc_alloc8 (ZDELTVPT)
ELSEIF (KIND (ZDELTVPT) == 4) THEN
    fxtran_acdc_alloc4 (ZDELTVPT)
ELSE
    STOP 1
ENDIF


IF (KIND (ZHLVPT) == 8) THEN
    fxtran_acdc_alloc8 (ZHLVPT)
ELSEIF (KIND (ZHLVPT) == 4) THEN
    fxtran_acdc_alloc4 (ZHLVPT)
ELSE
    STOP 1
ENDIF


IF (KIND (ZLWORKUP) == 8) THEN
    fxtran_acdc_alloc8 (ZLWORKUP)
ELSEIF (KIND (ZLWORKUP) == 4) THEN
    fxtran_acdc_alloc4 (ZLWORKUP)
ELSE
    STOP 1
ENDIF


IF (KIND (ZLWORK) == 8) THEN
    fxtran_acdc_alloc8 (ZLWORK)
ELSEIF (KIND (ZLWORK) == 4) THEN
    fxtran_acdc_alloc4 (ZLWORK)
ELSE
    STOP 1
ENDIF


IF (KIND (ZSUM) == 8) THEN
    fxtran_acdc_alloc8 (ZSUM)
ELSEIF (KIND (ZSUM) == 4) THEN
    fxtran_acdc_alloc4 (ZSUM)
ELSE
    STOP 1
ENDIF


IF (KIND (ZG_O_THVREF) == 8) THEN
    fxtran_acdc_alloc8 (ZG_O_THVREF)
ELSEIF (KIND (ZG_O_THVREF) == 4) THEN
    fxtran_acdc_alloc4 (ZG_O_THVREF)
ELSE
    STOP 1
ENDIF


IF (KIND (ZSQRT_TKE) == 8) THEN
    fxtran_acdc_alloc8 (ZSQRT_TKE)
ELSEIF (KIND (ZSQRT_TKE) == 4) THEN
    fxtran_acdc_alloc4 (ZSQRT_TKE)
ELSE
    STOP 1
ENDIF


IF (KIND (PLMDN) == 8) THEN
    fxtran_acdc_alloc8 (PLMDN)
ELSEIF (KIND (PLMDN) == 4) THEN
    fxtran_acdc_alloc4 (PLMDN)
ELSE
    STOP 1
ENDIF


JI = D%NIB


ZRVORD=CST%XRV/CST%XRD
IIJB=D%NIB
IIJE=D%NIE
IKTB=D%NKTB
IKTE=D%NKTE
IKT=D%NKT
IKB=D%NKB
IKE=D%NKE
IKA=D%NKA
IKU=D%NKU
IKL=D%NKL

IF (OOCEAN) THEN

  DO JK=1, IKT
    
    ZG_O_THVREF (JI, JK)=CST%XG*CST%XALPHAOC
  
  ENDDO

ELSE

  DO JK=1, IKT
    
    ZG_O_THVREF (JI, JK)=CST%XG/PTHVREF (JI, JK)
  
  ENDDO

ENDIF


DO JK=1, IKT
  
  ZSQRT_TKE (JI, JK)=SQRT (PTKEM (JI, JK))
  
ENDDO


IF (KRR/=0) THEN

  DO JK=1, IKT
    
    ZSUM (JI, JK)=0.
  
  ENDDO


  DO JRR=1, KRR

    DO JK=1, IKT
      
      ZSUM (JI, JK)=ZSUM (JI, JK)+PRM (JI, JK, JRR)
    
    ENDDO

  ENDDO


  DO JK=1, IKT
    
    ZVPT (JI, JK)=PTHLM (JI, JK)*(1.+ZRVORD*PRM (JI, JK, 1))/(1.+ZSUM (JI, JK))
  
  ENDDO

ELSE

  DO JK=1, IKT
    
    ZVPT (JI, JK)=PTHLM (JI, JK)
  
  ENDDO

ENDIF


DO JK=IKTB, IKTE
  
  ZDELTVPT (JI, JK)=ZVPT (JI, JK)-ZVPT (JI, JK-IKL)
  ZHLVPT (JI, JK)=0.5*(ZVPT (JI, JK)+ZVPT (JI, JK-IKL))
  
ENDDO


ZDELTVPT (JI, IKU)=ZVPT (JI, IKU)-ZVPT (JI, IKU-IKL)
ZDELTVPT (JI, IKA)=0.
ZHLVPT (JI, IKU)=0.5*(ZVPT (JI, IKU)+ZVPT (JI, IKU-IKL))
ZHLVPT (JI, IKA)=ZVPT (JI, IKA)


DO JK=1, IKT

  

  IF (ABS (ZDELTVPT (JI, JK))<CSTURB%XLINF) THEN
    ZDELTVPT (JI, JK)=CSTURB%XLINF
  ENDIF

  
ENDDO

ZLWORKUP (JI,:)=0.
ZTMP =0.

DO JK=IKTB, IKTE
  ZINTE =PTKEM (JI, JK)
  ZLWORK(JI,:)=0.
  ZTESTM=1.

  DO JKK=JK, IKB,-IKL

    IF (ZTESTM>0.) THEN
      ZTESTM=0.
      
      ZTEST0=0.5+SIGN (0.5, ZINTE )
      ZPOTE=ZTEST0*(-ZG_O_THVREF (JI, JK)*(ZHLVPT (JI, JKK)-ZVPT (JI, JK))&
      &+CSTURB%XRM17*PSHEAR (JI, JKK)*ZSQRT_TKE (JI, JK))*PDZZ (JI, JKK)
      ZTEST=0.5+SIGN (0.5, ZINTE -ZPOTE)
      ZTESTM=ZTESTM+ZTEST0
      ZLWORK1=PDZZ (JI, JKK)
      ZLWORK2=(ZG_O_THVREF (JI, JK)*(ZVPT (JI, JKK)-ZVPT (JI, JK))-CSTURB%XRM17*PSHEAR (JI, JKK)*ZSQRT_TKE&
      & (JI, JK)+SQRT (ABS ((CSTURB%XRM17*PSHEAR (JI, JKK)*ZSQRT_TKE (JI, JK)+(-ZG_O_THVREF (JI, JK&
      &)*(ZVPT (JI, JKK)-ZVPT (JI, JK))))**2.0+2.*ZINTE *(ZG_O_THVREF (JI, JK)*ZDELTVPT (JI, JKK)&
      &/PDZZ (JI, JKK)))))/(ZG_O_THVREF (JI, JK)*ZDELTVPT (JI, JKK)/PDZZ (JI, JKK))
      ZLWORK (JI, JK)=ZLWORK (JI, JK)+ZTEST0*(ZTEST*ZLWORK1+(1-ZTEST)*ZLWORK2)
      ZINTE =ZINTE -ZPOTE
    
    ENDIF

  ENDDO

  
  PLMDN (JI, JK)=MIN (ZLWORK (JI, JK), 0.5*(PZZ (JI, JK)+PZZ (JI, JK+IKL))-PZZ (JI, IKB))
  
  ZINTE =PTKEM (JI, JK)
  ZLWORKUP (JI, JK)=0.
  ZTESTM=1.

  DO JKK=JK+IKL, IKE, IKL

    IF (ZTESTM>0.) THEN
      ZTESTM=0.
      
      ZTEST0=0.5+SIGN (0.5, ZINTE )
      ZPOTE=ZTEST0*(ZG_O_THVREF (JI, JK)*(ZHLVPT (JI, JKK)-ZVPT (JI, JK))+CSTURB&
      &%XRM17*PSHEAR (JI, JKK)*ZSQRT_TKE (JI, JK))*PDZZ (JI, JKK)
      ZTEST=0.5+SIGN (0.5, ZINTE -ZPOTE)
      ZTESTM=ZTESTM+ZTEST0
      ZLWORK1=PDZZ (JI, JKK)
      ZLWORK2=(-ZG_O_THVREF (JI, JK)*(ZVPT (JI, JKK-IKL)-ZVPT (JI, JK))-CSTURB%XRM17*PSHEAR (JI, JKK&
      &)*ZSQRT_TKE (JI, JK)+SQRT (ABS ((CSTURB%XRM17*PSHEAR (JI, JKK)*ZSQRT_TKE (JI, JK)+(ZG_O_THVREF&
      & (JI, JK)*(ZVPT (JI, JKK-IKL)-ZVPT (JI, JK))))**2+2.*ZINTE *(ZG_O_THVREF (JI, JK)*ZDELTVPT (JI&
      &, JKK)/PDZZ (JI, JKK)))))/(ZG_O_THVREF (JI, JK)*ZDELTVPT (JI, JKK)/PDZZ (JI, JKK))
      ZLWORKUP (JI, JK)=ZLWORKUP (JI, JK)+ZTEST0*(ZTEST*ZLWORK1+(1-ZTEST)*ZLWORK2)
      ZINTE =ZINTE -ZPOTE
    
    ENDIF

  ENDDO

ENDDO


IF (TURBN%LBL89TOP) THEN

  DO JK=IKTE, IKTB, IKL
    
    ZTMP =ZLWORKUP (JI, JK-IKL)-PDZZ (JI, JK)
    
    
    ZLWORKUP (JI, JK)=MAX (ZLWORKUP (JI, JK), ZTMP )
  
  ENDDO

ENDIF


DO JK=IKTB, IKTE
  
  ZLWORK1=MAX (PLMDN (JI, JK), 1.E-10_MNHREAL)
  ZLWORK2=MAX (ZLWORKUP (JI, JK), 1.E-10_MNHREAL)
  ZPOTE=ZLWORK1/ZLWORK2
  ZLWORK2=1.d0+ZPOTE**TURBN%XBL89EXP
  PLM (JI, JK)=ZLWORK1*(2./ZLWORK2)**TURBN%XUSRBL89
  PLM (JI, JK)=MAX (PLM (JI, JK), TURBN%XLINI)
  
ENDDO

PLM (JI, IKA)=PLM (JI, IKB)
PLM (JI, IKE)=PLM (JI, IKE-IKL)
PLM (JI, IKU)=PLM (JI, IKE-IKL)

END SUBROUTINE BL89_OPENACC

ENDMODULE MODE_BL89_OPENACC
