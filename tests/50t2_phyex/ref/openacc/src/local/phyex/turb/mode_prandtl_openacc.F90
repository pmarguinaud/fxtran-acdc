TYPE(FXTRAN_ACDC_STACK) :: YLSTACK
fxtran_acdc_temp (REAL, ZGYMM_PSV, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZGXMM_PSV, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZGYMM_PRM, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZGXMM_PRM, (D%NIJT, D%NKT))
