
MODULE MODE_COMPUTE_FUNCTION_THERMO_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE COMPUTE_FUNCTION_THERMO_OPENACC (D, CST, PALP, PBETA, PGAM, PLTT, PC&
&, PT, PEXN, PCP, PLOCPEXN, PAMOIST, PATHETA, PRT, PPABST, KRR, YDSTACK)
!$ACC ROUTINE (COMPUTE_FUNCTION_THERMO_OPENACC) SEQ      


USE MODD_CST,ONLY:CST_T
USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE

#ifdef MNH_COMPILER_CCE
#endif
TYPE (DIMPHYEX_T), INTENT (IN)::D
INTEGER, INTENT (IN)::KRR
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
TYPE(FXTRAN_ACDC_STACK) :: YLSTACK
REAL, INTENT (IN)::PC
REAL, INTENT (IN)::PLTT
REAL, INTENT (IN)::PGAM
REAL, INTENT (IN)::PBETA
REAL, INTENT (IN)::PALP
REAL, INTENT (IN)::PCP(D%NIJT, D%NKT)
REAL, INTENT (IN)::PEXN(D%NIJT, D%NKT)
REAL, INTENT (IN)::PT(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PLOCPEXN(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PATHETA(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PAMOIST(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PRT (D%NIJT, D%NKT, KRR)
TYPE (CST_T), INTENT (IN)::CST
REAL, INTENT (IN)::PPABST (D%NIJT, D%NKT)
fxtran_acdc_temp (REAL, ZDRVSATDT, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZRVSAT, (D%NIJT, D%NKT))
REAL::ZEPS

INTEGER::IKT
INTEGER::IIJE
INTEGER::IIJB
INTEGER::JI
INTEGER::JK

YLSTACK = YDSTACK



IF (KIND (ZDRVSATDT) == 8) THEN
    fxtran_acdc_alloc8 (ZDRVSATDT)
ELSEIF (KIND (ZDRVSATDT) == 4) THEN
    fxtran_acdc_alloc4 (ZDRVSATDT)
ELSE
    STOP 1
ENDIF


IF (KIND (ZRVSAT) == 8) THEN
    fxtran_acdc_alloc8 (ZRVSAT)
ELSEIF (KIND (ZRVSAT) == 4) THEN
    fxtran_acdc_alloc4 (ZRVSAT)
ELSE
    STOP 1
ENDIF


JI = D%NIB


IKT=D%NKT
IIJE=D%NIE
IIJB=D%NIB
ZEPS=CST%XMV/CST%XMD

DO JK=1, IKT
  
  PLOCPEXN (JI, JK)=(PLTT+(CST%XCPV-PC)*(PT (JI, JK)-CST%XTT))/PCP (JI, JK)
  
ENDDO


DO JK=1, IKT
  
  ZRVSAT (JI, JK)=EXP (PALP-PBETA/PT (JI, JK)-PGAM*LOG (PT (JI, JK)))
  ZRVSAT (JI, JK)=ZRVSAT (JI, JK)*ZEPS/MAX (1.E-3, PPABST (JI, JK)-ZRVSAT (JI, JK))
  ZDRVSATDT (JI, JK)=(PBETA/PT (JI, JK)-PGAM)/PT (JI, JK)*ZRVSAT (JI, JK)*(1.+ZRVSAT (JI, JK)/ZEPS)
  PAMOIST (JI, JK)=0.5/(1.0+ZDRVSATDT (JI, JK)*PLOCPEXN (JI, JK))
  
ENDDO


DO JK=1, IKT
  
  PATHETA (JI, JK)=PAMOIST (JI, JK)*PEXN (JI, JK)*((ZRVSAT (JI, JK)-PRT (JI, JK, 1))*PLOCPEXN&
  & (JI, JK)/(1.+ZDRVSATDT (JI, JK)*PLOCPEXN (JI, JK))*(ZRVSAT (JI, JK)*(1.+ZRVSAT (JI,&
  & JK)/ZEPS)*(-2.*PBETA/PT (JI, JK)+PGAM)/PT (JI, JK)**2+ZDRVSATDT (JI, JK)*(1.+2.*ZRVSAT&
  & (JI, JK)/ZEPS)*(PBETA/PT (JI, JK)-PGAM)/PT (JI, JK))-ZDRVSATDT (JI, JK))
  
ENDDO


DO JK=1, IKT
  
  PLOCPEXN (JI, JK)=PLOCPEXN (JI, JK)/PEXN (JI, JK)
  
ENDDO


END SUBROUTINE COMPUTE_FUNCTION_THERMO_OPENACC

ENDMODULE MODE_COMPUTE_FUNCTION_THERMO_OPENACC
