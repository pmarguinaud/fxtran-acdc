
MODULE MODE_ICE4_SLOW_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE ICE4_SLOW_OPENACC (CST, PARAMI, ICEP, ICED, D, LDSOFT, OELEC, LDCOMPUTE, PRHODREF&
&, PT, PSSI, PLVFACT, PLSFACT, PRVT, PRCT, PRIT, PRST, PRGT, PLBDAS, PLBDAG, PAI, PCJ, PHLI_HCF&
&, PHLI_HRI, PLATHAM_IAGGS, PRCHONI, PRVDEPS, PRIAGGS, PRIAUTS, PRVDEPG, YDSTACK)
!$ACC ROUTINE (ICE4_SLOW_OPENACC) SEQ      

USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_CST,ONLY:CST_T
USE MODD_PARAM_ICE_N,ONLY:PARAM_ICE_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T
USE MODD_RAIN_ICE_PARAM_N,ONLY:RAIN_ICE_PARAM_T

#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (CST_T), INTENT (IN)::CST
TYPE (PARAM_ICE_T), INTENT (IN)::PARAMI
TYPE (RAIN_ICE_PARAM_T), INTENT (IN)::ICEP
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
TYPE (DIMPHYEX_T), INTENT (IN)::D
LOGICAL, INTENT (IN)::LDSOFT
LOGICAL, INTENT (IN)::OELEC
LOGICAL, INTENT (IN)::LDCOMPUTE(D%NIJT)
REAL, INTENT (IN)::PRHODREF(D%NIJT)
REAL, INTENT (IN)::PT(D%NIJT)
REAL, INTENT (IN)::PSSI(D%NIJT)
REAL, INTENT (IN)::PLVFACT(D%NIJT)
REAL, INTENT (IN)::PLSFACT(D%NIJT)
REAL, INTENT (IN)::PRVT(D%NIJT)
REAL, INTENT (IN)::PRCT(D%NIJT)
REAL, INTENT (IN)::PRIT(D%NIJT)
REAL, INTENT (IN)::PRST(D%NIJT)
REAL, INTENT (IN)::PRGT(D%NIJT)
REAL, INTENT (IN)::PLBDAS(D%NIJT)
REAL, INTENT (IN)::PLBDAG(D%NIJT)
REAL, INTENT (IN)::PAI(D%NIJT)
REAL, INTENT (IN)::PCJ(D%NIJT)
REAL, INTENT (IN)::PHLI_HCF(D%NIJT)
REAL, INTENT (IN)::PHLI_HRI(D%NIJT)
REAL, INTENT (IN)::PLATHAM_IAGGS(MERGE (D%NIJT, 0, OELEC))
REAL, INTENT (INOUT)::PRCHONI(D%NIJT)
REAL, INTENT (INOUT)::PRVDEPS(D%NIJT)
REAL, INTENT (INOUT)::PRIAGGS(D%NIJT)
REAL, INTENT (INOUT)::PRIAUTS(D%NIJT)
REAL, INTENT (INOUT)::PRVDEPG(D%NIJT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
REAL::ZCRIAUTI
INTEGER::JI
REAL::ZREDSN
REAL::ZREDGR


JI = D%NIB


ZREDGR=1.
ZREDSN=1.

IF (PARAMI%LOCND2) THEN

  IF (.NOT.PARAMI%LMODICEDEP) THEN
    ZREDGR=ICEP%XFRMIN (39)
    ZREDSN=ICEP%XFRMIN (40)
  ENDIF

ENDIF

#ifdef MNH_COMPILER_CCE
#endif


IF (PT (JI)<CST%XTT-35.0.AND.PRCT (JI)>ICED%XRTMIN (2).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRCHONI (JI)=MIN (1000., ICEP%XHON*PRHODREF (JI)*PRCT (JI&
    &)*EXP (ICEP%XALPHA3*(PT (JI)-CST%XTT)-ICEP%XBETA3))
  ENDIF

ELSE
  PRCHONI (JI)=0.
ENDIF




IF (PRVT (JI)>ICED%XRTMIN (1).AND.PRST (JI)>ICED%XRTMIN (5).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN

    IF (.NOT.ICEP%LNEWCOEFF) THEN
      PRVDEPS (JI)=(PSSI (JI)/(PRHODREF (JI)*PAI (JI)))*(ICEP%X0DEPS*PLBDAS (JI&
      &)**ICEP%XEX0DEPS+ICEP%X1DEPS*PCJ (JI)*PLBDAS (JI)**ICEP%XEX1DEPS)
      PRVDEPS (JI)=PRVDEPS (JI)*ZREDSN
    ELSE
      PRVDEPS (JI)=(PRST (JI)*(PSSI (JI)/PAI (JI)))*(ICEP%X0DEPS*PLBDAS (JI)**(ICED%XBS+ICEP&
      &%XEX0DEPS)+ICEP%X1DEPS*PCJ (JI)*(1+0.5*(ICED%XFVELOS/PLBDAS (JI))**ICED%XALPHAS)**(&
      &-ICED%XNUS+ICEP%XEX1DEPS/ICED%XALPHAS)*(PLBDAS (JI))**(ICED%XBS+ICEP%XEX1DEPS))
    ENDIF

  ENDIF

ELSE
  PRVDEPS (JI)=0.
ENDIF




IF (PRIT (JI)>ICED%XRTMIN (4).AND.PRST (JI)>ICED%XRTMIN (5).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN

    IF (.NOT.ICEP%LNEWCOEFF) THEN
      PRIAGGS (JI)=ICEP%XFIAGGS*EXP (ICEP%XCOLEXIS*(PT (JI)-CST%XTT))*PRIT&
      & (JI)*PLBDAS (JI)**ICEP%XEXIAGGS*PRHODREF (JI)**(-ICED%XCEXVT)
    ELSE
      PRIAGGS (JI)=ICEP%XFIAGGS*EXP (ICEP%XCOLEXIS*(PT (JI)-CST%XTT))*PRIT (JI)*PRST (JI)&
      &*(1.+(ICED%XFVELOS/PLBDAS (JI))**ICED%XALPHAS)**(-ICED%XNUS+ICEP%XEXIAGGS/ICED%XALPHAS&
      &)*PRHODREF (JI)**(-ICED%XCEXVT+1.)*((PLBDAS (JI))**(ICED%XBS+ICEP%XEXIAGGS))
    ENDIF


    IF (OELEC)  THEN
      PRIAGGS (JI)=PRIAGGS (JI)*PLATHAM_IAGGS (JI)
    ENDIF

  ENDIF

ELSE
  PRIAGGS (JI)=0.
ENDIF




IF (PHLI_HRI (JI)>ICED%XRTMIN (4).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    ZCRIAUTI =MIN (ICEP%XCRIAUTI, 10**(ICEP%XACRIAUTI*(PT (JI)-CST%XTT)+ICEP%XBCRIAUTI))
    PRIAUTS (JI)=ICEP%XTIMAUTI*EXP (ICEP%XTEXAUTI*(PT (JI)-CST&
    &%XTT))*MAX (PHLI_HRI (JI)-ZCRIAUTI *PHLI_HCF (JI), 0.)
  ENDIF

ELSE
  PRIAUTS (JI)=0.
ENDIF




IF (PRVT (JI)>ICED%XRTMIN (1).AND.PRGT (JI)>ICED%XRTMIN (6).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRVDEPG (JI)=(PSSI (JI)/(PRHODREF (JI)*PAI (JI)))*(ICEP%X0DEPG*PLBDAG (JI&
    &)**ICEP%XEX0DEPG+ICEP%X1DEPG*PCJ (JI)*PLBDAG (JI)**ICEP%XEX1DEPG)
    PRVDEPG (JI)=PRVDEPG (JI)*ZREDGR
  ENDIF

ELSE
  PRVDEPG (JI)=0.
ENDIF



END SUBROUTINE ICE4_SLOW_OPENACC

ENDMODULE MODE_ICE4_SLOW_OPENACC
