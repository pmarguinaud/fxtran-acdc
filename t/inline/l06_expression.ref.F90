SUBROUTINE L06_EXPRESSION (KLON, KLEV, KIDIA, KFDIA, X, Y)
INTEGER, INTENT (IN)::KFDIA
INTEGER, INTENT (IN)::KIDIA
INTEGER, INTENT (IN)::KLEV
INTEGER, INTENT (IN)::KLON
REAL, INTENT (IN)::X (KLON)
REAL, INTENT (OUT)::Y (KLON)
INTEGER::JLON
DO JLON = KIDIA, KFDIA
  Y(JLON)=2.*(X(JLON)+1.)
ENDDO
DO JLON = KIDIA, KFDIA
  Y (JLON)=2.*SQRT (X (JLON))
ENDDO
END SUBROUTINE
