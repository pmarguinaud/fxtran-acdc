MODULE UTIL_CSTURB_T_UPDATE_MOD
USE MODD_CTURB, ONLY : CSTURB_T
INTERFACE ACDC_UPDATE
MODULE PROCEDURE ACDC_UPDATE_CSTURB_T
END INTERFACE

CONTAINS
SUBROUTINE ACDC_UPDATE_CSTURB_T (SELF, LDCOMPONENT)


USE FXTRAN_ACDC_IS_PRESENT_MOD
USE UTIL_CSTURB_T_WIPE_MOD
USE UTIL_CSTURB_T_COPY_MOD
IMPLICIT NONE
TYPE (CSTURB_T), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDCOMPONENT

IF (FXTRAN_ACDC_IS_PRESENT (C_LOC (SELF), SIZEOF (SELF))) THEN
CALL ACDC_WIPE_CSTURB_T (SELF, LDDELETED=LDCOMPONENT)
CALL ACDC_COPY_CSTURB_T (SELF, LDCREATED=LDCOMPONENT)
ENDIF


END SUBROUTINE
END MODULE
