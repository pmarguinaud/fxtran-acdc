    fxtran_acdc_alloc8 (ZGYMM_PRM)
ELSEIF (KIND (ZGYMM_PRM) == 4) THEN
    fxtran_acdc_alloc4 (ZGYMM_PRM)
ELSE
    STOP 1
ENDIF


IF (KIND (ZGXMM_PRM) == 8) THEN
    fxtran_acdc_alloc8 (ZGXMM_PRM)
ELSEIF (KIND (ZGXMM_PRM) == 4) THEN
    fxtran_acdc_alloc4 (ZGXMM_PRM)
ELSE
    STOP 1
ENDIF


IF (KIND (ZGYMM_PTH) == 8) THEN
    fxtran_acdc_alloc8 (ZGYMM_PTH)
ELSEIF (KIND (ZGYMM_PTH) == 4) THEN
