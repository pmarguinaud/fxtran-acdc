
MODULE MODE_ICE4_FAST_RH_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE ICE4_FAST_RH_OPENACC (CST, PARAMI, ICEP, ICED, D, LDSOFT, LDCOMPUTE, LDWETG,&
& PRHODREF, PLVFACT, PLSFACT, PPRES, PDV, PKA, PCJ, PLBDAS, PLBDAG, PLBDAR, PLBDAH, PT,&
& PRVT, PRCT, PRRT, PRIT, PRST, PRGT, PRHT, PRCWETH, PRIWETH, PRSWETH, PRGWETH, PRRWETH&
&, PRCDRYH, PRIDRYH, PRSDRYH, PRRDRYH, PRGDRYH, PRDRYHG, PRHMLTR, PRH_TEND, YDSTACK)
!$ACC ROUTINE (ICE4_FAST_RH_OPENACC) SEQ      

USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_CST,ONLY:CST_T
USE MODD_PARAM_ICE_N,ONLY:PARAM_ICE_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T
USE MODD_RAIN_ICE_PARAM_N,ONLY:RAIN_ICE_PARAM_T

#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (CST_T), INTENT (IN)::CST
TYPE (PARAM_ICE_T), INTENT (IN)::PARAMI
TYPE (RAIN_ICE_PARAM_T), INTENT (IN)::ICEP
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
TYPE (DIMPHYEX_T), INTENT (IN)::D
LOGICAL, INTENT (IN)::LDSOFT
LOGICAL, INTENT (IN)::LDCOMPUTE(D%NIJT)
LOGICAL, INTENT (IN)::LDWETG(D%NIJT)
REAL, INTENT (IN)::PRHODREF(D%NIJT)
REAL, INTENT (IN)::PLVFACT(D%NIJT)
REAL, INTENT (IN)::PLSFACT(D%NIJT)
REAL, INTENT (IN)::PPRES(D%NIJT)
REAL, INTENT (IN)::PDV(D%NIJT)
REAL, INTENT (IN)::PKA(D%NIJT)
REAL, INTENT (IN)::PCJ(D%NIJT)
REAL, INTENT (IN)::PLBDAS(D%NIJT)
REAL, INTENT (IN)::PLBDAG(D%NIJT)
REAL, INTENT (IN)::PLBDAR(D%NIJT)
REAL, INTENT (IN)::PLBDAH(D%NIJT)
REAL, INTENT (IN)::PT(D%NIJT)
REAL, INTENT (IN)::PRVT(D%NIJT)
REAL, INTENT (IN)::PRCT(D%NIJT)
REAL, INTENT (IN)::PRRT(D%NIJT)
REAL, INTENT (IN)::PRIT(D%NIJT)
REAL, INTENT (IN)::PRST(D%NIJT)
REAL, INTENT (IN)::PRGT(D%NIJT)
REAL, INTENT (IN)::PRHT(D%NIJT)
REAL, INTENT (OUT)::PRCWETH(D%NIJT)
REAL, INTENT (OUT)::PRIWETH(D%NIJT)
REAL, INTENT (OUT)::PRSWETH(D%NIJT)
REAL, INTENT (OUT)::PRGWETH(D%NIJT)
REAL, INTENT (OUT)::PRRWETH(D%NIJT)
REAL, INTENT (OUT)::PRCDRYH(D%NIJT)
REAL, INTENT (OUT)::PRIDRYH(D%NIJT)
REAL, INTENT (OUT)::PRSDRYH(D%NIJT)
REAL, INTENT (OUT)::PRRDRYH(D%NIJT)
REAL, INTENT (OUT)::PRGDRYH(D%NIJT)
REAL, INTENT (OUT)::PRDRYHG(D%NIJT)
REAL, INTENT (INOUT)::PRHMLTR(D%NIJT)
REAL, INTENT (INOUT)::PRH_TEND(D%NIJT, 10)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
INTEGER, PARAMETER::IFREEZ2=10
INTEGER, PARAMETER::IFREEZ1=9
INTEGER, PARAMETER::IRGWETH=8
INTEGER, PARAMETER::IRGDRYH=7
INTEGER, PARAMETER::IRSWETH=6
INTEGER, PARAMETER::IRSDRYH=5
INTEGER, PARAMETER::IRIWETH=4
INTEGER, PARAMETER::IRIDRYH=3
INTEGER, PARAMETER::IRRWETH=2
INTEGER, PARAMETER::IRCWETH=1
LOGICAL::GWET
INTEGER::IGWET
REAL::ZBUF3
REAL::ZBUF2
REAL::ZBUF1
INTEGER::IBUF3
INTEGER::IBUF2
INTEGER::IBUF1
REAL::ZRDRYHG
REAL::ZRWETH_INIT
REAL::ZRDRYH_INIT
REAL::ZZW
INTEGER::JI

LOGICAL::LLDRYH
LOGICAL::LLWETH
INTEGER::IINDEX2
INTEGER::IINDEX1
REAL::ZINDEX2
REAL::ZINDEX1

JI = D%NIB


#ifdef MNH_COMPILER_CCE
#endif


IF (PRHT (JI)>ICED%XRTMIN (7).AND.PRCT (JI)>ICED%XRTMIN (2).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRH_TEND (JI, IRCWETH)=PLBDAH (JI)**(ICED%XCXH-ICED%XDH-2.0)*PRHODREF (JI)**(-ICED%XCEXVT)
    PRH_TEND (JI, IRCWETH)=ICEP%XFWETH*PRCT (JI)*PRH_TEND (JI, IRCWETH)
  ENDIF

ELSE
  PRH_TEND (JI, IRCWETH)=0.
ENDIF


IF (PRHT (JI)>ICED%XRTMIN (7).AND.PRIT (JI)>ICED%XRTMIN (4).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRH_TEND (JI, IRIWETH)=PLBDAH (JI)**(ICED%XCXH-ICED%XDH-2.0)*PRHODREF (JI)**(-ICED%XCEXVT)
    PRH_TEND (JI, IRIWETH)=ICEP%XFWETH*PRIT (JI)*PRH_TEND (JI, IRIWETH)
    PRH_TEND (JI, IRIDRYH)=PRH_TEND (JI, IRIWETH)*(ICEP%XCOLIH*EXP (ICEP%XCOLEXIH*(PT (JI)-CST%XTT)))
  ENDIF

ELSE
  PRH_TEND (JI, IRIWETH)=0.
  PRH_TEND (JI, IRIDRYH)=0.
ENDIF




IF (PRHT (JI)>ICED%XRTMIN (7).AND.PRST (JI)>ICED%XRTMIN (5).AND.LDCOMPUTE (JI)) THEN
  GWET =.TRUE.
ELSE
  GWET =.FALSE.
  PRH_TEND (JI, IRSWETH)=0.
  PRH_TEND (JI, IRSDRYH)=0.
ENDIF



IF (.NOT.LDSOFT) THEN

  

  IF (PARAMI%LPACK_INTERP) THEN
    IGWET=0

    

    IF (GWET ) THEN
      IGWET=IGWET+1
      ZBUF1 =PLBDAH (JI)
      ZBUF2 =PLBDAS (JI)
      IBUF3 =JI
    ENDIF


    

    IF (IGWET>0) THEN
      
      ZBUF1 =MAX (1.00001, MIN (REAL (ICEP%NWETLBDAH)-0.00001&
      &, ICEP%XWETINTP1H*LOG (ZBUF1 )+ICEP%XWETINTP2H))
      IBUF1 =INT (ZBUF1 )
      ZBUF1 =ZBUF1 -REAL (IBUF1 )
      ZBUF2 =MAX (1.00001, MIN (REAL (ICEP%NWETLBDAS)-0.00001&
      &, ICEP%XWETINTP1S*LOG (ZBUF2 )+ICEP%XWETINTP2S))
      IBUF2 =INT (ZBUF2 )
      ZBUF2 =ZBUF2 -REAL (IBUF2 )
      
      
      ZBUF3 =(ICEP %XKER_SWETH(IBUF1 +1, IBUF2 +1)*ZBUF2 -ICEP %XKER_SWETH(IBUF1&
      & +1, IBUF2 )*(ZBUF2 -1.0))*ZBUF1 -(ICEP %XKER_SWETH(IBUF1 , IBUF2 +1)*ZBUF2&
      & -ICEP %XKER_SWETH(IBUF1 , IBUF2 )*(ZBUF2 -1.0))*(ZBUF1 -1.0)
      
      ZZW =0.
      
      ZZW =ZBUF3 
    
    
    
    ENDIF

  ELSE
    IGWET=0

    

    IF (GWET ) THEN
      IGWET=IGWET+1
      ZINDEX1=MAX (1.00001, MIN (REAL (ICEP%NWETLBDAH)-0.00001&
      &, ICEP%XWETINTP1H*LOG (PLBDAH (JI))+ICEP%XWETINTP2H))
      IINDEX1=INT (ZINDEX1)
      ZINDEX1=ZINDEX1-REAL (IINDEX1)
      ZINDEX2=MAX (1.00001, MIN (REAL (ICEP%NWETLBDAH)-0.00001&
      &, ICEP%XWETINTP1S*LOG (PLBDAS (JI))+ICEP%XWETINTP2S))
      IINDEX2=INT (ZINDEX2)
      ZINDEX2=ZINDEX2-REAL (IINDEX2)
      ZZW =(ICEP %XKER_SWETH(IINDEX1+1, IINDEX2+1)*ZINDEX2-ICEP %XKER_SWETH(IINDEX1&
      &+1, IINDEX2)*(ZINDEX2-1.0))*ZINDEX1-(ICEP %XKER_SWETH(IINDEX1, IINDEX2+1)*ZINDEX2&
      &-ICEP %XKER_SWETH(IINDEX1, IINDEX2)*(ZINDEX2-1.0))*(ZINDEX1-1.0)
    
    
    ELSE
      ZZW =0.
    
    
    ENDIF

  
  ENDIF


  

  

  IF (IGWET>0) THEN

    

    IF (.NOT.ICEP%LNEWCOEFF) THEN

      IF (GWET ) THEN
        PRH_TEND (JI, IRSWETH)=ICEP%XFSWETH*ZZW *(PLBDAS (JI)**(ICED%XCXS-ICED%XBS))*(PLBDAH&
        & (JI)**ICED%XCXH)*(PRHODREF (JI)**(-ICED%XCEXVT-1.))*(ICEP%XLBSWETH1/(PLBDAH (JI)*&
        &*2)+ICEP%XLBSWETH2/(PLBDAH (JI)*PLBDAS (JI))+ICEP%XLBSWETH3/(PLBDAS (JI)**2))
      ENDIF

    ELSE

      IF (GWET ) THEN
        PRH_TEND (JI, IRSWETH)=ICEP%XFSWETH*ZZW *(PRST (JI))*(PLBDAH (JI)**ICED%XCXH&
        &)*(PRHODREF (JI)**(-ICED%XCEXVT))*(ICEP%XLBSWETH1/(PLBDAH (JI)**2)+ICEP%XLBSWETH2&
        &/(PLBDAH (JI)*PLBDAS (JI))+ICEP%XLBSWETH3/(PLBDAS (JI)**2))
      ENDIF

    ENDIF


    IF (GWET ) THEN
      PRH_TEND (JI, IRSDRYH)=PRH_TEND (JI, IRSWETH)*(ICEP%XCOLSH*EXP (ICEP%XCOLEXSH*(PT (JI)-CST%XTT)))
    ENDIF

  
  ENDIF

ENDIF



IF (PRHT (JI)>ICED%XRTMIN (7).AND.PRGT (JI)>ICED%XRTMIN (6).AND.LDCOMPUTE (JI)) THEN
  GWET =.TRUE.
ELSE
  GWET =.FALSE.
  PRH_TEND (JI, IRGWETH)=0.
  PRH_TEND (JI, IRGDRYH)=0.
ENDIF



IF (.NOT.LDSOFT) THEN

  

  IF (PARAMI%LPACK_INTERP) THEN
    IGWET=0

    

    IF (GWET ) THEN
      IGWET=IGWET+1
      ZBUF1 =PLBDAH (JI)
      ZBUF2 =PLBDAG (JI)
      IBUF3 =JI
    ENDIF


    

    IF (IGWET>0) THEN
      
      ZBUF1 =MAX (1.00001, MIN (REAL (ICEP%NWETLBDAH)-0.00001&
      &, ICEP%XWETINTP1H*LOG (ZBUF1 )+ICEP%XWETINTP2H))
      IBUF1 =INT (ZBUF1 )
      ZBUF1 =ZBUF1 -REAL (IBUF1 )
      ZBUF2 =MAX (1.00001, MIN (REAL (ICEP%NWETLBDAG)-0.00001&
      &, ICEP%XWETINTP1G*LOG (ZBUF2 )+ICEP%XWETINTP2G))
      IBUF2 =INT (ZBUF2 )
      ZBUF2 =ZBUF2 -REAL (IBUF2 )
      
      
      ZBUF3 =(ICEP %XKER_GWETH(IBUF1 +1, IBUF2 +1)*ZBUF2 -ICEP %XKER_GWETH(IBUF1&
      & +1, IBUF2 )*(ZBUF2 -1.0))*ZBUF1 -(ICEP %XKER_GWETH(IBUF1 , IBUF2 +1)*ZBUF2&
      & -ICEP %XKER_GWETH(IBUF1 , IBUF2 )*(ZBUF2 -1.0))*(ZBUF1 -1.0)
      
      ZZW =0.
      
      ZZW =ZBUF3 
    
    
    
    ENDIF

  ELSE
    IGWET=0

    

    IF (GWET ) THEN
      IGWET=IGWET+1
      ZINDEX1=MAX (1.00001, MIN (REAL (ICEP%NWETLBDAH)-0.00001&
      &, ICEP%XWETINTP1H*LOG (PLBDAH (JI))+ICEP%XWETINTP2H))
      IINDEX1=INT (ZINDEX1)
      ZINDEX1=ZINDEX1-REAL (IINDEX1)
      ZINDEX2=MAX (1.00001, MIN (REAL (ICEP%NWETLBDAH)-0.00001&
      &, ICEP%XWETINTP1G*LOG (PLBDAG (JI))+ICEP%XWETINTP2G))
      IINDEX2=INT (ZINDEX2)
      ZINDEX2=ZINDEX2-REAL (IINDEX2)
      ZZW =(ICEP %XKER_GWETH(IINDEX1+1, IINDEX2+1)*ZINDEX2-ICEP %XKER_GWETH(IINDEX1&
      &+1, IINDEX2)*(ZINDEX2-1.0))*ZINDEX1-(ICEP %XKER_GWETH(IINDEX1, IINDEX2+1)*ZINDEX2&
      &-ICEP %XKER_GWETH(IINDEX1, IINDEX2)*(ZINDEX2-1.0))*(ZINDEX1-1.0)
    
    
    ELSE
      ZZW =0.
    
    
    ENDIF

  
  ENDIF


  

  

  IF (IGWET>0) THEN

    

    IF (GWET ) THEN
      PRH_TEND (JI, IRGWETH)=ICEP%XFGWETH*ZZW *(PLBDAG (JI)**(ICED%XCXG-ICED%XBG))*(PLBDAH&
      & (JI)**ICED%XCXH)*(PRHODREF (JI)**(-ICED%XCEXVT-1.))*(ICEP%XLBGWETH1/(PLBDAH (JI)*&
      &*2)+ICEP%XLBGWETH2/(PLBDAH (JI)*PLBDAG (JI))+ICEP%XLBGWETH3/(PLBDAG (JI)**2))
      PRH_TEND (JI, IRGDRYH)=PRH_TEND (JI, IRGWETH)
    ENDIF


    IF (GWET .AND..NOT.LDWETG (JI)) THEN
      PRH_TEND (JI, IRGDRYH)=PRH_TEND (JI, IRGDRYH)*(ICEP%XCOLGH*EXP (ICEP%XCOLEXGH*(PT (JI)-CST%XTT)))
    ENDIF

  
  ENDIF

ENDIF



IF (PRHT (JI)>ICED%XRTMIN (7).AND.PRRT (JI)>ICED%XRTMIN (3).AND.LDCOMPUTE (JI)) THEN
  GWET =.TRUE.
ELSE
  GWET =.FALSE.
  PRH_TEND (JI, IRRWETH)=0.
ENDIF



IF (.NOT.LDSOFT) THEN

  

  IF (PARAMI%LPACK_INTERP) THEN
    IGWET=0

    

    IF (GWET ) THEN
      IGWET=IGWET+1
      ZBUF1 =PLBDAH (JI)
      ZBUF2 =PLBDAR (JI)
      IBUF3 =JI
    ENDIF


    

    IF (IGWET>0) THEN
      
      ZBUF1 =MAX (1.00001, MIN (REAL (ICEP%NWETLBDAH)-0.00001&
      &, ICEP%XWETINTP1H*LOG (ZBUF1 )+ICEP%XWETINTP2H))
      IBUF1 =INT (ZBUF1 )
      ZBUF1 =ZBUF1 -REAL (IBUF1 )
      ZBUF2 =MAX (1.00001, MIN (REAL (ICEP%NWETLBDAR)-0.00001&
      &, ICEP%XWETINTP1R*LOG (ZBUF2 )+ICEP%XWETINTP2R))
      IBUF2 =INT (ZBUF2 )
      ZBUF2 =ZBUF2 -REAL (IBUF2 )
      
      
      ZBUF3 =(ICEP %XKER_RWETH(IBUF1 +1, IBUF2 +1)*ZBUF2 -ICEP %XKER_RWETH(IBUF1&
      & +1, IBUF2 )*(ZBUF2 -1.0))*ZBUF1 -(ICEP %XKER_RWETH(IBUF1 , IBUF2 +1)*ZBUF2&
      & -ICEP %XKER_RWETH(IBUF1 , IBUF2 )*(ZBUF2 -1.0))*(ZBUF1 -1.0)
      
      ZZW =0.
      
      ZZW =ZBUF3 
    
    
    
    ENDIF

  ELSE
    IGWET=0

    

    IF (GWET ) THEN
      IGWET=IGWET+1
      ZINDEX1=MAX (1.00001, MIN (REAL (ICEP%NWETLBDAH)-0.00001&
      &, ICEP%XWETINTP1H*LOG (PLBDAH (JI))+ICEP%XWETINTP2H))
      IINDEX1=INT (ZINDEX1)
      ZINDEX1=ZINDEX1-REAL (IINDEX1)
      ZINDEX2=MAX (1.00001, MIN (REAL (ICEP%NWETLBDAH)-0.00001&
      &, ICEP%XWETINTP1R*LOG (PLBDAR (JI))+ICEP%XWETINTP2R))
      IINDEX2=INT (ZINDEX2)
      ZINDEX2=ZINDEX2-REAL (IINDEX2)
      ZZW =(ICEP %XKER_RWETH(IINDEX1+1, IINDEX2+1)*ZINDEX2-ICEP %XKER_RWETH(IINDEX1&
      &+1, IINDEX2)*(ZINDEX2-1.0))*ZINDEX1-(ICEP %XKER_RWETH(IINDEX1, IINDEX2+1)*ZINDEX2&
      &-ICEP %XKER_RWETH(IINDEX1, IINDEX2)*(ZINDEX2-1.0))*(ZINDEX1-1.0)
    
    
    ELSE
      ZZW =0.
    
    
    ENDIF

  
  ENDIF


  

  

  IF (IGWET>0) THEN

    

    IF (GWET ) THEN
      PRH_TEND (JI, IRRWETH)=ICEP%XFRWETH*ZZW *(PLBDAR (JI)**(-4))*(PLBDAH (JI)**ICED&
      &%XCXH)*(PRHODREF (JI)**(-ICED%XCEXVT-1.))*(ICEP%XLBRWETH1/(PLBDAH (JI)**2)+ICEP&
      &%XLBRWETH2/(PLBDAH (JI)*PLBDAR (JI))+ICEP%XLBRWETH3/(PLBDAR (JI)**2))
    ENDIF

  
  ENDIF

ENDIF


ZRDRYH_INIT =PRH_TEND (JI, IRCWETH)+PRH_TEND (JI, IRIDRYH)+PRH_TEND&
& (JI, IRSDRYH)+PRH_TEND (JI, IRRWETH)+PRH_TEND (JI, IRGDRYH)



IF (PRHT (JI)>ICED%XRTMIN (7).AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRH_TEND (JI, IFREEZ1)=PRVT (JI)*PPRES (JI)/(CST%XEPSILO+PRVT (JI))

    IF (PARAMI%LEVLIMIT) THEN
      PRH_TEND (JI, IFREEZ1)=MIN (PRH_TEND (JI, IFREEZ1), EXP (CST&
      &%XALPI-CST%XBETAI/PT (JI)-CST%XGAMI*LOG (PT (JI))))
    ENDIF

    PRH_TEND (JI, IFREEZ1)=PKA (JI)*(CST%XTT-PT (JI))+(PDV (JI)*(CST%XLVTT+(CST%XCPV-CST&
    &%XCL)*(PT (JI)-CST%XTT))*(CST%XESTT-PRH_TEND (JI, IFREEZ1))/(CST%XRV*PT (JI)))
    PRH_TEND (JI, IFREEZ1)=PRH_TEND (JI, IFREEZ1)*(ICEP%X0DEPH*PLBDAH (JI)**ICEP%XEX0DEPH+ICEP%X1DEPH&
    &*PCJ (JI)*PLBDAH (JI)**ICEP%XEX1DEPH)/(PRHODREF (JI)*(CST%XLMTT-CST%XCL*(CST%XTT-PT (JI))))
    PRH_TEND (JI, IFREEZ2)=(PRHODREF (JI)*(CST%XLMTT+(CST%XCI-CST%XCL)*(CST%XTT&
    &-PT (JI))))/(PRHODREF (JI)*(CST%XLMTT-CST%XCL*(CST%XTT-PT (JI))))
  ENDIF

  ZRWETH_INIT =MAX (PRH_TEND (JI, IRIWETH)+PRH_TEND (JI, IRSWETH)+PRH_TEND &
  &(JI, IRGWETH), MAX (0., PRH_TEND (JI, IFREEZ1)+PRH_TEND (JI, IFREEZ2)*(PRH_TEND&
  & (JI, IRIWETH)+PRH_TEND (JI, IRSWETH)+PRH_TEND (JI, IRGWETH))))
  LLWETH =MAX (0., ZRWETH_INIT -PRH_TEND (JI, IRIWETH)-PRH_TEND (JI, IRSWETH)-PRH_TEND (JI, IRGWETH)&
  &)<=MAX (0., ZRDRYH_INIT -PRH_TEND (JI, IRIDRYH)-PRH_TEND (JI, IRSDRYH)-PRH_TEND (JI, IRGDRYH))

  IF (PARAMI%LNULLWETH) THEN
    LLWETH =LLWETH .AND.ZRDRYH_INIT >0.
  ELSE
    LLWETH =LLWETH .AND.ZRWETH_INIT >0.
  ENDIF


  IF (.NOT.PARAMI%LWETHPOST) THEN
    LLWETH =LLWETH .AND.PT (JI)<CST%XTT
  ENDIF

  LLDRYH =PT (JI)<CST%XTT.AND.ZRDRYH_INIT >1.E-20.AND.MAX (0., ZRWETH_INIT -PRH_TEND (JI, IRIWETH)&
  &-PRH_TEND (JI, IRSWETH))>MAX (0., ZRDRYH_INIT -PRH_TEND (JI, IRIDRYH)-PRH_TEND (JI, IRSDRYH))
ELSE
  PRH_TEND (JI, IFREEZ1)=0.
  PRH_TEND (JI, IFREEZ2)=0.
  ZRWETH_INIT =0.
  LLWETH =.FALSE.
  LLDRYH =.FALSE.
ENDIF



IF (PARAMI%LCONVHG) THEN

  

  IF (LLDRYH ) THEN
    ZRDRYHG =ZRDRYH_INIT *ZRWETH_INIT /(ZRDRYH_INIT +ZRWETH_INIT )
  ELSE
    ZRDRYHG =0.
  ENDIF

  
ELSE
  ZRDRYHG =0.
ENDIF



IF (LLWETH ) THEN
  PRCWETH (JI)=PRH_TEND (JI, IRCWETH)
  PRIWETH (JI)=PRH_TEND (JI, IRIWETH)
  PRSWETH (JI)=PRH_TEND (JI, IRSWETH)
  PRGWETH (JI)=PRH_TEND (JI, IRGWETH)
  PRRWETH (JI)=(ZRWETH_INIT -PRH_TEND (JI, IRIWETH)-PRH_TEND (JI&
  &, IRSWETH)-PRH_TEND (JI, IRGWETH)-PRH_TEND (JI, IRCWETH))
ELSE
  PRCWETH (JI)=0.
  PRIWETH (JI)=0.
  PRSWETH (JI)=0.
  PRGWETH (JI)=0.
  PRRWETH (JI)=0.
ENDIF


IF (LLDRYH ) THEN
  PRCDRYH (JI)=PRH_TEND (JI, IRCWETH)
  PRIDRYH (JI)=PRH_TEND (JI, IRIDRYH)
  PRSDRYH (JI)=PRH_TEND (JI, IRSDRYH)
  PRRDRYH (JI)=PRH_TEND (JI, IRRWETH)
  PRGDRYH (JI)=PRH_TEND (JI, IRGDRYH)
  PRDRYHG (JI)=ZRDRYHG 
ELSE
  PRCDRYH (JI)=0.
  PRIDRYH (JI)=0.
  PRSDRYH (JI)=0.
  PRRDRYH (JI)=0.
  PRGDRYH (JI)=0.
  PRDRYHG (JI)=0.
ENDIF




IF (PRHT (JI)>ICED%XRTMIN (7).AND.PT (JI)>CST%XTT.AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRHMLTR (JI)=PRVT (JI)*PPRES (JI)/(CST%XEPSILO+PRVT (JI))

    IF (PARAMI%LEVLIMIT) THEN
      PRHMLTR (JI)=MIN (PRHMLTR (JI), EXP (CST%XALPW-CST%XBETAW/PT (JI)-CST%XGAMW*LOG (PT (JI))))
    ENDIF

    PRHMLTR (JI)=PKA (JI)*(CST%XTT-PT (JI))+PDV (JI)*(CST%XLVTT+(CST%XCPV-CST&
    &%XCL)*(PT (JI)-CST%XTT))*(CST%XESTT-PRHMLTR (JI))/(CST%XRV*PT (JI))
    PRHMLTR (JI)=MAX (0.,(-PRHMLTR (JI)*(ICEP%X0DEPH*PLBDAH (JI)**ICEP%XEX0DEPH+ICEP%X1DEPH&
    &*PCJ (JI)*PLBDAH (JI)**ICEP%XEX1DEPH)-(PRH_TEND (JI, IRCWETH)+PRH_TEND (JI, IRRWETH&
