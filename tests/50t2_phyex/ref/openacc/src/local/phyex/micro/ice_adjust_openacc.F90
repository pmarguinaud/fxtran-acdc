
SUBROUTINE ICE_ADJUST_OPENACC (D, CST, ICEP, NEBN, TURBN, PARAMI, BUCONF, KRR, HBUNAME, PTSTEP&
&, PSIGQSAT, PRHODJ, PEXNREF, PRHODREF, PSIGS, LMFCONV, PMFCONV, PPABST, PZZ, PEXN, PCF_MF&
&, PRC_MF, PRI_MF, PWEIGHT_MF_CLOUD, PICLDFR, PWCLDFR, PSSIO, PSSIU, PIFR, PRV, PRC, PRVS&
&, PRCS, PTH, PTHS, OCOMPUTE_SRC, PSRCS, PCLDFR, PRR, PRI, PRIS, PRS, PRG, TBUDGETS, KBUDGETS&
&, PICE_CLD_WGT, PRH, POUT_RV, POUT_RC, POUT_RI, POUT_TH, PHLC_HRC, PHLC_HCF, PHLI_HRI, PHLI_HCF&
&, PHLC_HRC_MF, PHLC_HCF_MF, PHLI_HRI_MF, PHLI_HCF_MF, YDSTACK)
!$ACC ROUTINE (ICE_ADJUST_OPENACC) SEQ      


USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_CST,ONLY:CST_T
USE MODD_NEB_N,ONLY:NEB_T
USE MODD_TURB_N,ONLY:TURB_T
USE MODD_PARAM_ICE_N,ONLY:PARAM_ICE_T
USE MODD_BUDGET,ONLY:TBUDGETDATA_PTR, TBUDGETCONF_T, NBUDGET_TH, NBUDGET_RV, NBUDGET_RC, NBUDGET_RI
USE MODD_RAIN_ICE_PARAM_N,ONLY:RAIN_ICE_PARAM_T
USE MODI_CONDENSATION,ONLY:CONDENSATION
USE MODI_CONDENSATION_OPENACC, ONLY : CONDENSATION_OPENACC
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


#ifdef MNH_COMPILER_CCE
#endif
TYPE (DIMPHYEX_T), INTENT (IN)::D
TYPE (CST_T), INTENT (IN)::CST
TYPE (RAIN_ICE_PARAM_T), INTENT (IN)::ICEP
TYPE (NEB_T), INTENT (IN)::NEBN
TYPE (TURB_T), INTENT (IN)::TURBN
TYPE (PARAM_ICE_T), INTENT (IN)::PARAMI
TYPE (TBUDGETCONF_T), INTENT (IN)::BUCONF
INTEGER, INTENT (IN)::KRR
CHARACTER (LEN=4), INTENT (IN)::HBUNAME
REAL, INTENT (IN)::PTSTEP
REAL, INTENT (IN)::PSIGQSAT(D%NIJT)
REAL, INTENT (IN)::PRHODJ(D%NIJT, D%NKT)
REAL, INTENT (IN)::PEXNREF(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRHODREF(D%NIJT, D%NKT)
REAL, INTENT (IN)::PSIGS(MERGE (D%NIJT, 0, NEBN%LSUBG_COND), MERGE (D%NKT, 0, NEBN%LSUBG_COND))
LOGICAL, INTENT (IN)::LMFCONV
REAL, INTENT (IN)::PMFCONV(MERGE (D%NIJT, 0, LMFCONV), MERGE (D%NKT, 0, LMFCONV))
REAL, INTENT (IN)::PPABST(D%NIJT, D%NKT)
REAL, INTENT (IN)::PZZ(D%NIJT, D%NKT)
REAL, INTENT (IN)::PEXN(D%NIJT, D%NKT)
REAL, INTENT (IN)::PCF_MF(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRC_MF(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRI_MF(D%NIJT, D%NKT)
REAL, INTENT (IN)::PWEIGHT_MF_CLOUD(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRV(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRC(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PRVS(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PRCS(D%NIJT, D%NKT)
REAL, INTENT (IN)::PTH(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PTHS(D%NIJT, D%NKT)
LOGICAL, INTENT (IN)::OCOMPUTE_SRC
REAL, INTENT (OUT)::PSRCS(MERGE (D%NIJT, 0, OCOMPUTE_SRC), MERGE (D%NKT, 0, OCOMPUTE_SRC))
REAL, INTENT (OUT)::PCLDFR(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PICLDFR(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PWCLDFR(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PSSIO(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PSSIU(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PIFR(D%NIJT, D%NKT)
REAL, INTENT (INOUT)::PRIS(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRR(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRI(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRS(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRG(D%NIJT, D%NKT)
TYPE (TBUDGETDATA_PTR), INTENT (INOUT)::TBUDGETS(KBUDGETS)
INTEGER, INTENT (IN)::KBUDGETS
REAL, OPTIONAL, INTENT (IN)::PICE_CLD_WGT(D%NIJT)
REAL, OPTIONAL, INTENT (IN)::PRH(D%NIJT, D%NKT)
REAL, OPTIONAL, INTENT (OUT)::POUT_RV(D%NIJT, D%NKT)
REAL, OPTIONAL, INTENT (OUT)::POUT_RC(D%NIJT, D%NKT)
REAL, OPTIONAL, INTENT (OUT)::POUT_RI(D%NIJT, D%NKT)
REAL, OPTIONAL, INTENT (OUT)::POUT_TH(D%NIJT, D%NKT)
REAL, OPTIONAL, INTENT (OUT)::PHLC_HRC(D%NIJT, D%NKT)
REAL, OPTIONAL, INTENT (OUT)::PHLC_HCF(D%NIJT, D%NKT)
REAL, OPTIONAL, INTENT (OUT)::PHLI_HRI(D%NIJT, D%NKT)
REAL, OPTIONAL, INTENT (OUT)::PHLI_HCF(D%NIJT, D%NKT)
REAL, OPTIONAL, INTENT (IN)::PHLC_HRC_MF(D%NIJT, D%NKT)
REAL, OPTIONAL, INTENT (IN)::PHLC_HCF_MF(D%NIJT, D%NKT)
REAL, OPTIONAL, INTENT (IN)::PHLI_HRI_MF(D%NIJT, D%NKT)
REAL, OPTIONAL, INTENT (IN)::PHLI_HCF_MF(D%NIJT, D%NKT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
TYPE(FXTRAN_ACDC_STACK) :: YLSTACK
REAL::ZW2
REAL::ZW1
fxtran_acdc_temp (REAL, ZLS, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZLV, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZCPH, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZRI, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZRC, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZRV, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZT, (D%NIJT, D%NKT))
REAL::ZHR
REAL::ZHCF
REAL::ZCRIAUT
INTEGER::ITERMAX
INTEGER::JITER
INTEGER::JK
INTEGER::JI
INTEGER::IIJE
INTEGER::IIJB
INTEGER::IKTE
INTEGER::IKTB
fxtran_acdc_temp (REAL, ZWKBUD, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZSRCS, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZSIGS, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZSIGQSAT, (D%NIJT))
LOGICAL::LLHLI_H
LOGICAL::LLHLC_H
LOGICAL::LLBIGA
LOGICAL::LLTRIANGLE
LOGICAL::LLNONE


YLSTACK = YDSTACK



IF (KIND (ZLS) == 8) THEN
    fxtran_acdc_alloc8 (ZLS)
ELSEIF (KIND (ZLS) == 4) THEN
    fxtran_acdc_alloc4 (ZLS)
ELSE
    STOP 1
ENDIF


IF (KIND (ZLV) == 8) THEN
    fxtran_acdc_alloc8 (ZLV)
ELSEIF (KIND (ZLV) == 4) THEN
    fxtran_acdc_alloc4 (ZLV)
ELSE
    STOP 1
ENDIF


IF (KIND (ZCPH) == 8) THEN
    fxtran_acdc_alloc8 (ZCPH)
ELSEIF (KIND (ZCPH) == 4) THEN
    fxtran_acdc_alloc4 (ZCPH)
ELSE
    STOP 1
ENDIF


IF (KIND (ZRI) == 8) THEN
    fxtran_acdc_alloc8 (ZRI)
ELSEIF (KIND (ZRI) == 4) THEN
    fxtran_acdc_alloc4 (ZRI)
ELSE
    STOP 1
ENDIF


IF (KIND (ZRC) == 8) THEN
    fxtran_acdc_alloc8 (ZRC)
ELSEIF (KIND (ZRC) == 4) THEN
    fxtran_acdc_alloc4 (ZRC)
ELSE
    STOP 1
ENDIF


IF (KIND (ZRV) == 8) THEN
    fxtran_acdc_alloc8 (ZRV)
ELSEIF (KIND (ZRV) == 4) THEN
    fxtran_acdc_alloc4 (ZRV)
ELSE
    STOP 1
ENDIF


IF (KIND (ZT) == 8) THEN
    fxtran_acdc_alloc8 (ZT)
ELSEIF (KIND (ZT) == 4) THEN
    fxtran_acdc_alloc4 (ZT)
ELSE
    STOP 1
ENDIF


IF (KIND (ZWKBUD) == 8) THEN
    fxtran_acdc_alloc8 (ZWKBUD)
ELSEIF (KIND (ZWKBUD) == 4) THEN
    fxtran_acdc_alloc4 (ZWKBUD)
ELSE
    STOP 1
ENDIF


IF (KIND (ZSRCS) == 8) THEN
    fxtran_acdc_alloc8 (ZSRCS)
ELSEIF (KIND (ZSRCS) == 4) THEN
    fxtran_acdc_alloc4 (ZSRCS)
ELSE
    STOP 1
ENDIF


IF (KIND (ZSIGS) == 8) THEN
    fxtran_acdc_alloc8 (ZSIGS)
ELSEIF (KIND (ZSIGS) == 4) THEN
    fxtran_acdc_alloc4 (ZSIGS)
ELSE
    STOP 1
ENDIF


IF (KIND (ZSIGQSAT) == 8) THEN
    fxtran_acdc_alloc8 (ZSIGQSAT)
ELSEIF (KIND (ZSIGQSAT) == 4) THEN
    fxtran_acdc_alloc4 (ZSIGQSAT)
ELSE
    STOP 1
ENDIF


JI = D%NIB


IKTB=D%NKTB
IKTE=D%NKTE
IIJB=D%NIB
IIJE=D%NIE
ITERMAX=1









DO JITER=1, ITERMAX

  DO JK=IKTB, IKTE

    

    IF (JITER==1)  THEN
      ZT (JI, JK)=PTH (JI, JK)*PEXN (JI, JK)
    ENDIF

    ZLV (JI, JK)=CST%XLVTT+(CST%XCPV-CST%XCL)*(ZT (JI, JK)-CST%XTT)
    ZLS (JI, JK)=CST%XLSTT+(CST%XCPV-CST%XCI)*(ZT (JI, JK)-CST%XTT)
  
  ENDDO


  IF (JITER==1) THEN

    

    DO JK=IKTB, IKTE

      

      SELECTCASE (KRR)
      CASE (7)
        ZCPH (JI, JK)=CST%XCPD+CST%XCPV*PRV (JI, JK)+CST%XCL*(PRC (JI, JK)+PRR (JI&
        &, JK))+CST%XCI*(PRI (JI, JK)+PRS (JI, JK)+PRG (JI, JK)+PRH (JI, JK))
      CASE (6)
        ZCPH (JI, JK)=CST%XCPD+CST%XCPV*PRV (JI, JK)+CST%XCL*(PRC (JI, JK)&
        &+PRR (JI, JK))+CST%XCI*(PRI (JI, JK)+PRS (JI, JK)+PRG (JI, JK))
      CASE (5)
        ZCPH (JI, JK)=CST%XCPD+CST%XCPV*PRV (JI, JK)+CST%XCL*(PRC (JI&
        &, JK)+PRR (JI, JK))+CST%XCI*(PRI (JI, JK)+PRS (JI, JK))
      CASE (3)
        ZCPH (JI, JK)=CST%XCPD+CST%XCPV*PRV (JI, JK)+CST%XCL*(PRC (JI, JK)+PRR (JI, JK))
      CASE (2)
        ZCPH (JI, JK)=CST%XCPD+CST%XCPV*PRV (JI, JK)+CST%XCL*PRC (JI, JK)
      ENDSELECT

    
    ENDDO


    IF (NEBN%LSUBG_COND) THEN
      CALL CONDENSATION_OPENACC (D, CST, ICEP, NEBN, TURBN, NEBN%CFRAC_ICE_ADJUST, NEBN%CCONDENS, NEBN&
      &%CLAMBDA3, PPABST, PZZ, PRHODREF, ZT, PRV, ZRV, PRC, ZRC, PRI, ZRI, PRR, PRS, PRG, PSIGS, LMFCONV&
      &, PMFCONV, PCLDFR, ZSRCS,.TRUE., NEBN%LSIGMAS, PARAMI%LOCND2, PICLDFR, PWCLDFR, PSSIO, PSSIU&
      &, PIFR, PSIGQSAT, PLV=ZLV, PLS=ZLS, PCPH=ZCPH, PHLC_HRC=PHLC_HRC, PHLC_HCF=PHLC_HCF, PHLI_HRI&
      &=PHLI_HRI, PHLI_HCF=PHLI_HCF, PICE_CLD_WGT=PICE_CLD_WGT, YDSTACK=YLSTACK)
    ELSE
      ZSIGS (JI,:)=0.
      ZSIGQSAT (JI)=0.
      CALL CONDENSATION_OPENACC (D, CST, ICEP, NEBN, TURBN, NEBN%CFRAC_ICE_ADJUST, NEBN%CCONDENS&
      &, NEBN%CLAMBDA3, PPABST, PZZ, PRHODREF, ZT, PRV, ZRV, PRC, ZRC, PRI, ZRI, PRR, PRS, PRG, ZSIGS&
      &, LMFCONV, PMFCONV, PCLDFR, ZSRCS,.TRUE.,.TRUE., PARAMI%LOCND2, PICLDFR, PWCLDFR, PSSIO, PSSIU&
      &, PIFR, ZSIGQSAT, PLV=ZLV, PLS=ZLS, PCPH=ZCPH, PHLC_HRC=PHLC_HRC, PHLC_HCF=PHLC_HCF, PHLI_HRI&
      &=PHLI_HRI, PHLI_HCF=PHLI_HCF, PICE_CLD_WGT=PICE_CLD_WGT, YDSTACK=YLSTACK)
    ENDIF

  
  
  ELSE

    

    DO JK=IKTB, IKTE

      

      SELECTCASE (KRR)
      CASE (7)
        ZCPH (JI, JK)=CST%XCPD+CST%XCPV*ZRV (JI, JK)+CST%XCL*(ZRC (JI, JK)+PRR (JI&
        &, JK))+CST%XCI*(ZRI (JI, JK)+PRS (JI, JK)+PRG (JI, JK)+PRH (JI, JK))
      CASE (6)
        ZCPH (JI, JK)=CST%XCPD+CST%XCPV*ZRV (JI, JK)+CST%XCL*(ZRC (JI, JK)&
        &+PRR (JI, JK))+CST%XCI*(ZRI (JI, JK)+PRS (JI, JK)+PRG (JI, JK))
      CASE (5)
        ZCPH (JI, JK)=CST%XCPD+CST%XCPV*ZRV (JI, JK)+CST%XCL*(ZRC (JI&
        &, JK)+PRR (JI, JK))+CST%XCI*(ZRI (JI, JK)+PRS (JI, JK))
      CASE (3)
        ZCPH (JI, JK)=CST%XCPD+CST%XCPV*ZRV (JI, JK)+CST%XCL*(ZRC (JI, JK)+PRR (JI, JK))
      CASE (2)
        ZCPH (JI, JK)=CST%XCPD+CST%XCPV*ZRV (JI, JK)+CST%XCL*ZRC (JI, JK)
      ENDSELECT

    
    ENDDO


    IF (NEBN%LSUBG_COND) THEN
      CALL CONDENSATION_OPENACC (D, CST, ICEP, NEBN, TURBN, NEBN%CFRAC_ICE_ADJUST, NEBN%CCONDENS, NEBN&
      &%CLAMBDA3, PPABST, PZZ, PRHODREF, ZT, ZRV, ZRV, ZRC, ZRC, ZRI, ZRI, PRR, PRS, PRG, PSIGS, LMFCONV&
      &, PMFCONV, PCLDFR, ZSRCS,.TRUE., NEBN%LSIGMAS, PARAMI%LOCND2, PICLDFR, PWCLDFR, PSSIO, PSSIU&
      &, PIFR, PSIGQSAT, PLV=ZLV, PLS=ZLS, PCPH=ZCPH, PHLC_HRC=PHLC_HRC, PHLC_HCF=PHLC_HCF, PHLI_HRI&
      &=PHLI_HRI, PHLI_HCF=PHLI_HCF, PICE_CLD_WGT=PICE_CLD_WGT, YDSTACK=YLSTACK)
    ELSE
      ZSIGS (JI,:)=0.
      ZSIGQSAT (JI)=0.
      CALL CONDENSATION_OPENACC (D, CST, ICEP, NEBN, TURBN, NEBN%CFRAC_ICE_ADJUST, NEBN%CCONDENS&
      &, NEBN%CLAMBDA3, PPABST, PZZ, PRHODREF, ZT, ZRV, ZRV, ZRC, ZRC, ZRI, ZRI, PRR, PRS, PRG, ZSIGS&
      &, LMFCONV, PMFCONV, PCLDFR, ZSRCS,.TRUE.,.TRUE., PARAMI%LOCND2, PICLDFR, PWCLDFR, PSSIO, PSSIU&
      &, PIFR, ZSIGQSAT, PLV=ZLV, PLS=ZLS, PCPH=ZCPH, PHLC_HRC=PHLC_HRC, PHLC_HCF=PHLC_HCF, PHLI_HRI&
      &=PHLI_HRI, PHLI_HCF=PHLI_HCF, PICE_CLD_WGT=PICE_CLD_WGT, YDSTACK=YLSTACK)
    ENDIF

  
  
  ENDIF

ENDDO

LLHLC_H=PRESENT (PHLC_HRC).AND.PRESENT (PHLC_HCF)
LLHLI_H=PRESENT (PHLI_HRI).AND.PRESENT (PHLI_HCF)

DO JK=IKTB, IKTE
  
  ZRC (JI, JK)=ZRC (JI, JK)*(1.-PWEIGHT_MF_CLOUD (JI, JK))
  ZRI (JI, JK)=ZRI (JI, JK)*(1.-PWEIGHT_MF_CLOUD (JI, JK))
  PCLDFR (JI, JK)=PCLDFR (JI, JK)*(1.-PWEIGHT_MF_CLOUD (JI, JK))
  ZSRCS (JI, JK)=ZSRCS (JI, JK)*(1.-PWEIGHT_MF_CLOUD (JI, JK))

  IF (LLHLC_H) THEN
    PHLC_HRC (JI, JK)=PHLC_HRC (JI, JK)*(1.-PWEIGHT_MF_CLOUD (JI, JK))
    PHLC_HCF (JI, JK)=PHLC_HCF (JI, JK)*(1.-PWEIGHT_MF_CLOUD (JI, JK))
  ENDIF


  IF (LLHLI_H) THEN
    PHLI_HRI (JI, JK)=PHLI_HRI (JI, JK)*(1.-PWEIGHT_MF_CLOUD (JI, JK))
    PHLI_HCF (JI, JK)=PHLI_HCF (JI, JK)*(1.-PWEIGHT_MF_CLOUD (JI, JK))
  ENDIF

  
ENDDO


DO JK=IKTB, IKTE
  
  ZW1=(ZRC (JI, JK)-PRC (JI, JK))/PTSTEP
  ZW2=(ZRI (JI, JK)-PRI (JI, JK))/PTSTEP

  IF (ZW1<0.0) THEN
    ZW1=MAX (ZW1,-PRCS (JI, JK))
  ELSE
    ZW1=MIN (ZW1, PRVS (JI, JK))
  ENDIF

  PRVS (JI, JK)=PRVS (JI, JK)-ZW1
  PRCS (JI, JK)=PRCS (JI, JK)+ZW1
  PTHS (JI, JK)=PTHS (JI, JK)+ZW1*ZLV (JI, JK)/(ZCPH (JI, JK)*PEXNREF (JI, JK))

  IF (ZW2<0.0) THEN
    ZW2=MAX (ZW2,-PRIS (JI, JK))
  ELSE
    ZW2=MIN (ZW2, PRVS (JI, JK))
  ENDIF

  PRVS (JI, JK)=PRVS (JI, JK)-ZW2
  PRIS (JI, JK)=PRIS (JI, JK)+ZW2
  PTHS (JI, JK)=PTHS (JI, JK)+ZW2*ZLS (JI, JK)/(ZCPH (JI, JK)*PEXNREF (JI, JK))
  
ENDDO


IF (.NOT.NEBN%LSUBG_COND) THEN

  DO JK=IKTB, IKTE

    

    IF (PRCS (JI, JK)+PRIS (JI, JK)>1.E-12/PTSTEP) THEN
      PCLDFR (JI, JK)=1.
    ELSE
      PCLDFR (JI, JK)=0.
    ENDIF

    ZSRCS (JI, JK)=PCLDFR (JI, JK)
  
  ENDDO

ELSE
  LLNONE=PARAMI%CSUBG_MF_PDF=='NONE'
  LLTRIANGLE=PARAMI%CSUBG_MF_PDF=='TRIANGLE'
  LLBIGA=PARAMI%CSUBG_MF_PDF=='BIGA'

  DO JK=IKTB, IKTE
    
    ZW1=PRC_MF (JI, JK)/PTSTEP
    ZW2=PRI_MF (JI, JK)/PTSTEP

    IF (ZW1+ZW2>PRVS (JI, JK)) THEN
      ZW1=ZW1*PRVS (JI, JK)/(ZW1+ZW2)
      ZW2=PRVS (JI, JK)-ZW1
    ENDIF

    PCLDFR (JI, JK)=MIN (1., PCLDFR (JI, JK)+PCF_MF (JI, JK))
    PRCS (JI, JK)=PRCS (JI, JK)+ZW1
    PRIS (JI, JK)=PRIS (JI, JK)+ZW2
    PRVS (JI, JK)=PRVS (JI, JK)-(ZW1+ZW2)
    PTHS (JI, JK)=PTHS (JI, JK)+(ZW1*ZLV (JI, JK)+ZW2*ZLS (JI, JK))/ZCPH (JI, JK)/PEXNREF (JI, JK)

    IF (LLHLC_H) THEN
      ZCRIAUT=ICEP%XCRIAUTC/PRHODREF (JI, JK)

      IF (LLNONE) THEN

        IF (ZW1*PTSTEP>PCF_MF (JI, JK)*ZCRIAUT) THEN
          PHLC_HRC (JI, JK)=PHLC_HRC (JI, JK)+ZW1*PTSTEP
          PHLC_HCF (JI, JK)=MIN (1., PHLC_HCF (JI, JK)+PCF_MF (JI, JK))
        ENDIF

      ELSEIF (LLTRIANGLE) THEN

        IF (ZW1*PTSTEP>PCF_MF (JI, JK)*ZCRIAUT) THEN
          ZHCF=1.-.5*(ZCRIAUT*PCF_MF (JI, JK)/MAX (1.E-20, ZW1*PTSTEP))**2
          ZHR=ZW1*PTSTEP-(ZCRIAUT*PCF_MF (JI, JK))**3/(3*MAX (1.E-20, ZW1*PTSTEP)**2)
        ELSEIF (2.*ZW1*PTSTEP<=PCF_MF (JI, JK)*ZCRIAUT) THEN
          ZHCF=0.
          ZHR=0.
        ELSE
          ZHCF=(2.*ZW1*PTSTEP-ZCRIAUT*PCF_MF (JI, JK))**2/(2.*MAX (1.E-20, ZW1*PTSTEP)**2)
          ZHR=(4.*(ZW1*PTSTEP)**3-3.*ZW1*PTSTEP*(ZCRIAUT*PCF_MF (JI, JK))**2&
          &+(ZCRIAUT*PCF_MF (JI, JK))**3)/(3*MAX (1.E-20, ZW1*PTSTEP)**2)
        ENDIF

        ZHCF=ZHCF*PCF_MF (JI, JK)
        PHLC_HCF (JI, JK)=MIN (1., PHLC_HCF (JI, JK)+ZHCF)
        PHLC_HRC (JI, JK)=PHLC_HRC (JI, JK)+ZHR
      ELSEIF (LLBIGA) THEN
        PHLC_HCF (JI, JK)=MIN (1., PHLC_HCF (JI, JK)+PHLC_HCF_MF (JI, JK))
        PHLC_HRC (JI, JK)=PHLC_HRC (JI, JK)+PHLC_HRC_MF (JI, JK)
      ENDIF

    ENDIF


    IF (LLHLI_H) THEN
      ZCRIAUT=MIN (ICEP%XCRIAUTI, 10**(ICEP%XACRIAUTI*(ZT (JI, JK)-CST%XTT)+ICEP%XBCRIAUTI))

      IF (LLNONE) THEN

        IF (ZW2*PTSTEP>PCF_MF (JI, JK)*ZCRIAUT) THEN
          PHLI_HRI (JI, JK)=PHLI_HRI (JI, JK)+ZW2*PTSTEP
          PHLI_HCF (JI, JK)=MIN (1., PHLI_HCF (JI, JK)+PCF_MF (JI, JK))
        ENDIF

      ELSEIF (LLTRIANGLE) THEN

        IF (ZW2*PTSTEP>PCF_MF (JI, JK)*ZCRIAUT) THEN
          ZHCF=1.-.5*(ZCRIAUT*PCF_MF (JI, JK)/(ZW2*PTSTEP))**2
          ZHR=ZW2*PTSTEP-(ZCRIAUT*PCF_MF (JI, JK))**3/(3*(ZW2*PTSTEP)**2)
        ELSEIF (2.*ZW2*PTSTEP<=PCF_MF (JI, JK)*ZCRIAUT) THEN
          ZHCF=0.
          ZHR=0.
        ELSE
          ZHCF=(2.*ZW2*PTSTEP-ZCRIAUT*PCF_MF (JI, JK))**2/(2.*(ZW2*PTSTEP)**2)
          ZHR=(4.*(ZW2*PTSTEP)**3-3.*ZW2*PTSTEP*(ZCRIAUT*PCF_MF (JI, JK&
          &))**2+(ZCRIAUT*PCF_MF (JI, JK))**3)/(3*(ZW2*PTSTEP)**2)
        ENDIF

        ZHCF=ZHCF*PCF_MF (JI, JK)
        PHLI_HCF (JI, JK)=MIN (1., PHLI_HCF (JI, JK)+ZHCF)
        PHLI_HRI (JI, JK)=PHLI_HRI (JI, JK)+ZHR
      ELSEIF (LLBIGA) THEN
        PHLI_HCF (JI, JK)=MIN (1., PHLI_HCF (JI, JK)+PHLI_HCF_MF (JI, JK))
        PHLI_HRI (JI, JK)=PHLI_HRI (JI, JK)+PHLI_HRI_MF (JI, JK)
      ENDIF

    ENDIF


    IF (PRESENT (POUT_RV).OR.PRESENT (POUT_RC).OR.PRESENT (POUT_RI).OR.PRESENT (POUT_TH)) THEN
      ZW1=PRC_MF (JI, JK)
      ZW2=PRI_MF (JI, JK)

      IF (ZW1+ZW2>ZRV (JI, JK)) THEN
        ZW1=ZW1*ZRV (JI, JK)/(ZW1+ZW2)
        ZW2=ZRV (JI, JK)-ZW1
      ENDIF

      ZRC (JI, JK)=ZRC (JI, JK)+ZW1
      ZRI (JI, JK)=ZRI (JI, JK)+ZW2
      ZRV (JI, JK)=ZRV (JI, JK)-(ZW1+ZW2)
      ZT (JI, JK)=ZT (JI, JK)+(ZW1*ZLV (JI, JK)+ZW2*ZLS (JI, JK))/ZCPH (JI, JK)
    ENDIF

  
  ENDDO

ENDIF


IF (OCOMPUTE_SRC)  THEN
  PSRCS(JI,:)=ZSRCS(JI,:)
ENDIF


IF (PRESENT (POUT_RV))  THEN
  POUT_RV(JI,:)=ZRV(JI,:)
ENDIF


IF (PRESENT (POUT_RC))  THEN
  POUT_RC(JI,:)=ZRC(JI,:)
ENDIF


IF (PRESENT (POUT_RI))  THEN
  POUT_RI(JI,:)=ZRI(JI,:)
ENDIF


IF (PRESENT (POUT_TH))  THEN
  POUT_TH(JI,:)=ZT(JI,:)/PEXN (JI,:)
ENDIF












END SUBROUTINE ICE_ADJUST_OPENACC
