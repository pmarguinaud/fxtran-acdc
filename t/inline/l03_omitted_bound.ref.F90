SUBROUTINE L03_OMITTED_BOUND (KLON, KLEV, KIDIA, KFDIA, X, Y)
INTEGER, INTENT (IN)::KFDIA
INTEGER, INTENT (IN)::KIDIA
INTEGER, INTENT (IN)::KLEV
INTEGER, INTENT (IN)::KLON
REAL, INTENT (IN)::X (KLON)
REAL, INTENT (OUT)::Y (KLON)
INTEGER::JLON
DO JLON = 2, KLON
  Y (JLON)=2.*X (JLON)
ENDDO
DO JLON = 1, KFDIA
  Y (JLON)=2.*X (JLON)
ENDDO
END SUBROUTINE
