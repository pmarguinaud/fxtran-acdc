CONTAINS
SUBROUTINE ACDC_UPDATE_RAIN_ICE_DESCR_T (SELF, LDCOMPONENT)


USE FXTRAN_ACDC_IS_PRESENT_MOD
USE UTIL_RAIN_ICE_DESCR_T_WIPE_MOD
USE UTIL_RAIN_ICE_DESCR_T_COPY_MOD
IMPLICIT NONE
TYPE (RAIN_ICE_DESCR_T), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDCOMPONENT

IF (FXTRAN_ACDC_IS_PRESENT (C_LOC (SELF), SIZEOF (SELF))) THEN
CALL ACDC_WIPE_RAIN_ICE_DESCR_T (SELF, LDDELETED=LDCOMPONENT)
