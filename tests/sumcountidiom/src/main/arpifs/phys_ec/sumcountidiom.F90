SUBROUTINE SUMCOUNTIDIOM (KIDIA, KFDIA, KLON, PQ, PT, PY, KC, LDA, PL)

!$ACDC singlecolumn

! Removing SUM or COUNT must keep the whole argument and its grouping;
! calls which remain reductions (other sections, MASK) are left unchanged

USE PARKIND1, ONLY : JPIM, JPRB
IMPLICIT NONE

INTEGER(KIND=JPIM),INTENT(IN)    :: KIDIA, KFDIA, KLON
REAL(KIND=JPRB)   ,INTENT(IN)    :: PQ(KLON)
REAL(KIND=JPRB)   ,INTENT(INOUT) :: PT(KLON)
REAL(KIND=JPRB)   ,INTENT(OUT)   :: PY
REAL(KIND=JPRB)   ,INTENT(IN)    :: PL(KLON,3)
INTEGER(KIND=JPIM),INTENT(OUT)   :: KC
LOGICAL           ,INTENT(IN)    :: LDA(KLON)

PY = SUM (PQ (KIDIA:KFDIA))
PY = 1._JPRB - SUM (PQ (KIDIA:KFDIA))
PY = SUM (PQ (KIDIA:KFDIA) - PT (KIDIA:KFDIA))
PY = SUM (2._JPRB * PQ (KIDIA:KFDIA))
IF (SUM (PQ (KIDIA:KFDIA) * PT (KIDIA:KFDIA)) > 0._JPRB) PT (KIDIA:KFDIA) = 1._JPRB
KC = COUNT (LDA (KIDIA:KFDIA))
KC = COUNT (PQ (KIDIA:KFDIA) > 0._JPRB)
KC = COUNT (LDA (KIDIA:KFDIA) .AND. PQ (KIDIA:KFDIA) > 0._JPRB)
KC = 1 + COUNT (LDA (KIDIA:KFDIA))
IF (COUNT (LDA (KIDIA:KFDIA)) > 0) PT (KIDIA:KFDIA) = 2._JPRB
PY = 1._JPRB - SUM (PQ (KIDIA:KFDIA) - PT (KIDIA:KFDIA))
PY = 2._JPRB * SUM (PQ (KIDIA:KFDIA) + PT (KIDIA:KFDIA))
PY = 1._JPRB - SUM (- PQ (KIDIA:KFDIA))
PY = SUM (PL (KIDIA:KFDIA,2))
PY = SUM (PL (KIDIA:KFDIA,:))
PY = SUM (PQ (KIDIA:KFDIA), MASK=LDA (KIDIA:KFDIA))
KC = COUNT (PL (KIDIA:KFDIA,:) > 0._JPRB)
KC = COUNT (LDA (KIDIA:KFDIA) .OR. PQ (KIDIA:KFDIA) > 0._JPRB) * 2

END SUBROUTINE SUMCOUNTIDIOM
