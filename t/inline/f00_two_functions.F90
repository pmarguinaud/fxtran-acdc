SUBROUTINE F00_TWO_FUNCTIONS (X, Y, Z)
REAL, INTENT (IN) :: X, Y
REAL, INTENT (OUT) :: Z
! As FWSED1 / FWSED2 in PHYEX ICE4_SEDIMENTATION_STAT
Z = F1 (X) + F2 (Y)
CONTAINS
ELEMENTAL FUNCTION F1 (A) RESULT (R)
REAL, INTENT (IN) :: A
REAL :: R
R = 2. * A
END FUNCTION
ELEMENTAL FUNCTION F2 (A) RESULT (R)
REAL, INTENT (IN) :: A
REAL :: R
R = 3. * A
END FUNCTION
END SUBROUTINE
