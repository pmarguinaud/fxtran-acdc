MODULE UTIL_ELEC_PARAM_T_UPDATE_MOD
USE MODD_ELEC_PARAM, ONLY : ELEC_PARAM_T
INTERFACE ACDC_UPDATE
MODULE PROCEDURE ACDC_UPDATE_ELEC_PARAM_T
END INTERFACE

CONTAINS
SUBROUTINE ACDC_UPDATE_ELEC_PARAM_T (SELF, LDCOMPONENT)


USE FXTRAN_ACDC_IS_PRESENT_MOD
USE UTIL_ELEC_PARAM_T_WIPE_MOD
USE UTIL_ELEC_PARAM_T_COPY_MOD
IMPLICIT NONE
TYPE (ELEC_PARAM_T), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDCOMPONENT

IF (FXTRAN_ACDC_IS_PRESENT (C_LOC (SELF), SIZEOF (SELF))) THEN
CALL ACDC_WIPE_ELEC_PARAM_T (SELF, LDDELETED=LDCOMPONENT)
CALL ACDC_COPY_ELEC_PARAM_T (SELF, LDCREATED=LDCOMPONENT)
ENDIF


END SUBROUTINE
END MODULE
