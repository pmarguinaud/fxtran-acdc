SUBROUTINE L03_OMITTED_BOUND (KLON, KLEV, KIDIA, KFDIA, X, Y)
INTEGER, INTENT (IN) :: KLON, KLEV, KIDIA, KFDIA
REAL, INTENT (IN) :: X (KLON)
REAL, INTENT (OUT) :: Y (KLON)
INTEGER :: JLON
CALL E (X (2:), Y (2:))
CALL E (X (:KFDIA), Y (:KFDIA))
CONTAINS
ELEMENTAL SUBROUTINE E (A, B)
REAL, INTENT (IN) :: A
REAL, INTENT (OUT) :: B
B = 2. * A
END SUBROUTINE
END SUBROUTINE
