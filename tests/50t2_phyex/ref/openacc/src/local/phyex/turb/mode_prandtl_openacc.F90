SUBROUTINE PHI3_OPENACC (D, CSTURB, TURBN, PREDTH1, PREDR1, PRED2TH3&
&, PRED2R3, PRED2THR3, HTURBDIM, OUSERV, PPHI3, YDSTACK)
!$ACC ROUTINE (PHI3_OPENACC) SEQ      


#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

TYPE (CSTURB_T), INTENT (IN)::CSTURB
TYPE (TURB_T), INTENT (IN)::TURBN
TYPE (DIMPHYEX_T), INTENT (IN)::D
REAL, INTENT (IN)::PREDTH1(D%NIJT, D%NKT)
REAL, INTENT (IN)::PREDR1(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRED2TH3(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRED2R3(D%NIJT, D%NKT)
REAL, INTENT (IN)::PRED2THR3(D%NIJT, D%NKT)
CHARACTER (LEN=4), INTENT (IN)::HTURBDIM
LOGICAL, INTENT (IN)::OUSERV
REAL, INTENT (OUT)::PPHI3(D%NIJT, D%NKT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
TYPE(FXTRAN_ACDC_STACK) :: YLSTACK
fxtran_acdc_temp (REAL, ZW2, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZW1, (D%NIJT, D%NKT))
INTEGER::IKT
INTEGER::IIJE
INTEGER::IIJB
INTEGER::JK
INTEGER::JI
INTEGER::IKE
INTEGER::IKB
LOGICAL::GHTURBDIM_3DIM


YLSTACK = YDSTACK



IF (KIND (ZW2) == 8) THEN
    fxtran_acdc_alloc8 (ZW2)
ELSEIF (KIND (ZW2) == 4) THEN
    fxtran_acdc_alloc4 (ZW2)
ELSE
    STOP 1
ENDIF


IF (KIND (ZW1) == 8) THEN
    fxtran_acdc_alloc8 (ZW1)
ELSEIF (KIND (ZW1) == 4) THEN
    fxtran_acdc_alloc4 (ZW1)
ELSE
    STOP 1
ENDIF


JI = D%NIB


IKB=D%NKTB
IKE=D%NKTE
IIJE=D%NIE
IIJB=D%NIB
IKT=D%NKT
GHTURBDIM_3DIM=.FALSE.

IF (GHTURBDIM_3DIM) THEN

  DO JK=1, IKT

    

    IF (OUSERV) THEN
      ZW1 (JI, JK)=1.+1.5*(PREDTH1 (JI, JK)+PREDR1 (JI, JK))+(0.5*(PREDTH1 &
      &(JI, JK)**2+PREDR1 (JI, JK)**2)+PREDTH1 (JI, JK)*PREDR1 (JI, JK))
      ZW2 (JI, JK)=0.5*(PRED2TH3 (JI, JK)-PRED2R3 (JI, JK))
      PPHI3 (JI, JK)=1.-(((1.+PREDR1 (JI, JK))*(PRED2THR3 (JI, JK)+PRED2TH3&
      & (JI, JK))/PREDTH1 (JI, JK))+ZW2 (JI, JK))/ZW1 (JI, JK)
    ELSE
      ZW1 (JI, JK)=1.+1.5*PREDTH1 (JI, JK)+0.5*PREDTH1 (JI, JK)**2
      ZW2 (JI, JK)=0.5*PRED2TH3 (JI, JK)
      PPHI3 (JI, JK)=1.-(PRED2TH3 (JI, JK)/PREDTH1 (JI, JK)+ZW2 (JI, JK))/ZW1 (JI, JK)
    ENDIF

  
  ENDDO


  DO JK=1, IKT

    

    IF (PPHI3 (JI, JK)<=0..OR.PPHI3 (JI, JK)>CSTURB%XPHI_LIM) THEN
      PPHI3 (JI, JK)=CSTURB%XPHI_LIM
    ENDIF

  
  ENDDO

ELSE

  DO JK=1, IKT

    

    IF (OUSERV) THEN
      PPHI3 (JI, JK)=1./(1.+PREDTH1 (JI, JK)+PREDR1 (JI, JK))
    ELSE
      PPHI3 (JI, JK)=1./(1.+PREDTH1 (JI, JK))
    ENDIF

  
  ENDDO

ENDIF

PPHI3 (JI, IKB-1)=PPHI3 (JI, IKB)
PPHI3 (JI, IKE+1)=PPHI3 (JI, IKE)

END SUBROUTINE PHI3_OPENACC

SUBROUTINE PSI_SV_OPENACC (D, CSTURB, TURBN, KSV, PREDTH1, PREDR1&
&, PREDS1, PRED2THS, PRED2RS, PPHI3, PPSI3, PPSI_SV, YDSTACK)
!$ACC ROUTINE (PSI_SV_OPENACC) SEQ      


#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

TYPE (CSTURB_T), INTENT (IN)::CSTURB
TYPE (TURB_T), INTENT (IN)::TURBN
TYPE (DIMPHYEX_T), INTENT (IN)::D
INTEGER, INTENT (IN)::KSV
REAL, INTENT (IN)::PREDTH1(D%NIJT, D%NKT)
REAL, INTENT (IN)::PREDR1(D%NIJT, D%NKT)
REAL, INTENT (IN)::PREDS1(D%NIJT, D%NKT, KSV)
REAL, INTENT (IN)::PRED2THS(D%NIJT, D%NKT, KSV)
REAL, INTENT (IN)::PRED2RS(D%NIJT, D%NKT, KSV)
REAL, INTENT (IN)::PPHI3(D%NIJT, D%NKT)
