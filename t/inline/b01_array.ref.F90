SUBROUTINE B01_ARRAY (KLON, KLEV, KGPBLKS, PZ, PW)
INTEGER, INTENT (IN)::KGPBLKS
INTEGER, INTENT (IN)::KLEV
INTEGER, INTENT (IN)::KLON
REAL, INTENT (INOUT)::PZ (KLON, KLEV)
REAL, INTENT (INOUT)::PW (KLON, KLEV, KGPBLKS)
INTEGER::JB
INTEGER::JLEV
INTEGER::JLON
DO JB=1, KGPBLKS
  DO JLEV=1, KLEV
    DO JLON=1, KLON
      PW (JLON,JLEV, JB)=PZ (JLON, JLEV)+1.
    ENDDO
  ENDDO
ENDDO
END SUBROUTINE
