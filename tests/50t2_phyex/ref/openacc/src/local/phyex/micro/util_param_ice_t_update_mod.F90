MODULE UTIL_PARAM_ICE_T_UPDATE_MOD
USE MODD_PARAM_ICE_N, ONLY : PARAM_ICE_T
INTERFACE ACDC_UPDATE
MODULE PROCEDURE ACDC_UPDATE_PARAM_ICE_T
END INTERFACE

CONTAINS
SUBROUTINE ACDC_UPDATE_PARAM_ICE_T (SELF, LDCOMPONENT)


USE FXTRAN_ACDC_IS_PRESENT_MOD
USE UTIL_PARAM_ICE_T_WIPE_MOD
USE UTIL_PARAM_ICE_T_COPY_MOD
IMPLICIT NONE
TYPE (PARAM_ICE_T), INTENT (IN), TARGET :: SELF
LOGICAL, OPTIONAL, INTENT (IN) :: LDCOMPONENT

IF (FXTRAN_ACDC_IS_PRESENT (C_LOC (SELF), SIZEOF (SELF))) THEN
CALL ACDC_WIPE_PARAM_ICE_T (SELF, LDDELETED=LDCOMPONENT)
CALL ACDC_COPY_PARAM_ICE_T (SELF, LDCREATED=LDCOMPONENT)
ENDIF


END SUBROUTINE
END MODULE
