MODULE UTIL_TFIELDMETADATA_LOAD_MOD
USE MODD_FIELD, ONLY : TFIELDMETADATA
INTERFACE ACDC_LOAD
MODULE PROCEDURE ACDC_LOAD_TFIELDMETADATA
END INTERFACE

CONTAINS
SUBROUTINE ACDC_LOAD_TFIELDMETADATA (SELF, KLUN)

IMPLICIT NONE
TYPE (TFIELDMETADATA), INTENT (OUT), TARGET :: SELF
INTEGER, INTENT (IN) :: KLUN

READ (KLUN) SELF%CMNHNAME
READ (KLUN) SELF%CSTDNAME
READ (KLUN) SELF%CLONGNAME
READ (KLUN) SELF%CUNITS
READ (KLUN) SELF%CCOMMENT
READ (KLUN) SELF%NGRID
READ (KLUN) SELF%NTYPE
READ (KLUN) SELF%NDIMS
READ (KLUN) SELF%CDIR
READ (KLUN) SELF%LTIMEDEP
END SUBROUTINE
END MODULE
