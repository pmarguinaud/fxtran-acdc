SUBROUTINE L00_MESONH (D, X, Y)
USE MODD_DIMPHYEX, ONLY : DIMPHYEX_T
TYPE (DIMPHYEX_T), INTENT (IN) :: D
REAL, INTENT (IN) :: X (D%NIJT, D%NKT)
REAL, INTENT (OUT) :: Y (D%NIJT, D%NKT)
INTEGER :: JI, JK, IKT
IKT = D%NKT
! As COMPUTE_FRAC_ICE in PHYEX SHALLOW_MF
CALL E (X (D%NIJB:D%NIJE, 1:IKT), Y (D%NIJB:D%NIJE, 1:IKT))
CALL E (X, Y)
CONTAINS
ELEMENTAL SUBROUTINE E (A, B)
REAL, INTENT (IN) :: A
REAL, INTENT (OUT) :: B
B = 2. * A
END SUBROUTINE
END SUBROUTINE
