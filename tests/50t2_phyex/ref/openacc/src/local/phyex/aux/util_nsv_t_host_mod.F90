MODULE UTIL_NSV_T_HOST_MOD
USE MODD_NSV, ONLY : NSV_T
INTERFACE ACDC_HOST
MODULE PROCEDURE ACDC_HOST_NSV_T
END INTERFACE

CONTAINS
SUBROUTINE ACDC_HOST_NSV_T (SELF)
USE UTIL_TFIELDMETADATA_MOD
IMPLICIT NONE
TYPE (NSV_T), TARGET :: SELF
INTEGER :: J1, J2
LOGICAL :: LCSV, LCSV_A, LCSV_CHEM_LIST, LCSV_CHEM_LIST_A, LTSVLIST, LTSVLIST_A

LTSVLIST_A = ALLOCATED (SELF%TSVLIST_A)
IF (LTSVLIST_A) THEN
  DO J2 = LBOUND (SELF%TSVLIST_A, 2), UBOUND (SELF%TSVLIST_A, 2)
    DO J1 = LBOUND (SELF%TSVLIST_A, 1), UBOUND (SELF%TSVLIST_A, 1)
      CALL ACDC_HOST_TFIELDMETADATA (SELF%TSVLIST_A (J1, J2))
    ENDDO
  ENDDO
ENDIF

LTSVLIST = ASSOCIATED (SELF%TSVLIST)
IF (LTSVLIST) THEN
  DO J1 = LBOUND (SELF%TSVLIST, 1), UBOUND (SELF%TSVLIST, 1)
    CALL ACDC_HOST_TFIELDMETADATA (SELF%TSVLIST (J1))
  ENDDO
ENDIF

END SUBROUTINE
END MODULE
