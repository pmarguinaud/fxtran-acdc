SUBROUTINE L01_LOOKUP (KLON, KLEV, KIDIA, KFDIA, X, Y)
USE M,ONLY:Z
INTEGER, INTENT (IN)::KFDIA
INTEGER, INTENT (IN)::KIDIA
INTEGER, INTENT (IN)::KLEV
INTEGER, INTENT (IN)::KLON
REAL, INTENT (IN)::X (KLON)
REAL, INTENT (OUT)::Y (KLON)
INTEGER::JLON
REAL::Z_T (10)
DO JLON = KIDIA, KFDIA
  Y(JLON)=2.*X(JLON)
ENDDO
Z=2.*X (1)
Z_T=0.
END SUBROUTINE
