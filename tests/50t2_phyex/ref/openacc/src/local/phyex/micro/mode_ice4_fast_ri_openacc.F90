
MODULE MODE_ICE4_FAST_RI_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE ICE4_FAST_RI_OPENACC (ICEP, ICED, D, LDSOFT, LDCOMPUTE, PRHODREF&
&, PLVFACT, PLSFACT, PAI, PCJ, PCIT, PSSI, PRCT, PRIT, PRCBERI, YDSTACK)
!$ACC ROUTINE (ICE4_FAST_RI_OPENACC) SEQ      

USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T
USE MODD_RAIN_ICE_PARAM_N,ONLY:RAIN_ICE_PARAM_T

#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (RAIN_ICE_PARAM_T), INTENT (IN)::ICEP
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
TYPE (DIMPHYEX_T), INTENT (IN)::D
LOGICAL, INTENT (IN)::LDSOFT
LOGICAL, INTENT (IN)::LDCOMPUTE(D%NIJT)
REAL, INTENT (IN)::PRHODREF(D%NIJT)
REAL, INTENT (IN)::PLVFACT(D%NIJT)
REAL, INTENT (IN)::PLSFACT(D%NIJT)
REAL, INTENT (IN)::PAI(D%NIJT)
REAL, INTENT (IN)::PCJ(D%NIJT)
REAL, INTENT (IN)::PCIT(D%NIJT)
REAL, INTENT (IN)::PSSI(D%NIJT)
REAL, INTENT (IN)::PRCT(D%NIJT)
REAL, INTENT (IN)::PRIT(D%NIJT)
REAL, INTENT (INOUT)::PRCBERI(D%NIJT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK

INTEGER::JI

JI = D%NIB


#ifdef MNH_COMPILER_CCE
#endif


IF (PSSI (JI)>0..AND.PRCT (JI)>ICED%XRTMIN (2).AND.PRIT (JI)>ICED&
  &%XRTMIN (4).AND.PCIT (JI)>1.E-20.AND.LDCOMPUTE (JI)) THEN

  IF (.NOT.LDSOFT) THEN
    PRCBERI (JI)=MIN (1.E8, ICED%XLBI*(PRHODREF (JI)*PRIT (JI)/PCIT (JI))**ICED%XLBEXI)
    PRCBERI (JI)=(PSSI (JI)/(PRHODREF (JI)*PAI (JI)))*PCIT (JI)*(ICEP%X0DEPI/PRCBERI&
    & (JI)+ICEP%X2DEPI*PCJ (JI)*PCJ (JI)/PRCBERI (JI)**(ICED%XDI+2.0))
  ENDIF

ELSE
  PRCBERI (JI)=0.
ENDIF



END SUBROUTINE ICE4_FAST_RI_OPENACC

ENDMODULE MODE_ICE4_FAST_RI_OPENACC
