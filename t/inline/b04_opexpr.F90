SUBROUTINE B04_OPEXPR (KTDIA, KLEV, PZ, PS)
INTEGER, INTENT (IN) :: KTDIA, KLEV
REAL, INTENT (IN) :: PZ (KLEV)
REAL, INTENT (OUT) :: PS
CALL S (KTDIA-1, KLEV, PZ, PS)
CONTAINS
SUBROUTINE S (KL, KLEV, P, PSUM)
INTEGER, INTENT (IN) :: KL, KLEV
REAL, INTENT (IN) :: P (KLEV)
REAL, INTENT (OUT) :: PSUM
INTEGER :: JLEV
PSUM = 0.
DO JLEV = 1, KL
  PSUM = PSUM + P (JLEV) * REAL (KL)
ENDDO
END SUBROUTINE
END SUBROUTINE
