SUBROUTINE B01_ARRAY (KLON, KLEV, KGPBLKS, PZ, PW)
INTEGER, INTENT (IN) :: KLON, KLEV, KGPBLKS
REAL, INTENT (INOUT) :: PZ (KLON, KLEV)
REAL, INTENT (INOUT) :: PW (KLON, KLEV, KGPBLKS)
INTEGER :: JB
DO JB = 1, KGPBLKS
  CALL S (KLON, KLEV, PZ, PW (:, :, JB))
ENDDO
CONTAINS
SUBROUTINE S (KLON, KLEV, PT, PSIZE)
INTEGER, INTENT (IN) :: KLON, KLEV
REAL, INTENT (INOUT) :: PT (KLON, KLEV)
REAL, INTENT (INOUT) :: PSIZE (KLON, KLEV)
INTEGER :: JLON, JLEV
DO JLEV = 1, KLEV
  DO JLON = 1, KLON
    PSIZE (JLON, JLEV) = PT (JLON, JLEV) + 1.
  ENDDO
ENDDO
END SUBROUTINE
END SUBROUTINE
