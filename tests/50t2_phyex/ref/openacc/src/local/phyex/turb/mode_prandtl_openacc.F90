IF (KIND (ZGXMM_PTH) == 8) THEN
    fxtran_acdc_alloc8 (ZGXMM_PTH)
ELSEIF (KIND (ZGXMM_PTH) == 4) THEN
    fxtran_acdc_alloc4 (ZGXMM_PTH)
