
MODULE MODE_ICE4_RIMLTC_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE ICE4_RIMLTC_OPENACC (CST, PARAMI, D, LDCOMPUTE, PEXN&
&, PLVFACT, PLSFACT, PT, PTHT, PRIT, PRIMLTC_MR, YDSTACK)
!$ACC ROUTINE (ICE4_RIMLTC_OPENACC) SEQ      

USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_CST,ONLY:CST_T
USE MODD_PARAM_ICE_N,ONLY:PARAM_ICE_T

#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (CST_T), INTENT (IN)::CST
TYPE (PARAM_ICE_T), INTENT (IN)::PARAMI
TYPE (DIMPHYEX_T), INTENT (IN)::D
LOGICAL, INTENT (IN)::LDCOMPUTE(D%NIJT)
REAL, INTENT (IN)::PEXN(D%NIJT)
REAL, INTENT (IN)::PLVFACT(D%NIJT)
REAL, INTENT (IN)::PLSFACT(D%NIJT)
REAL, INTENT (IN)::PT(D%NIJT)
REAL, INTENT (IN)::PTHT(D%NIJT)
REAL, INTENT (IN)::PRIT(D%NIJT)
REAL, INTENT (OUT)::PRIMLTC_MR(D%NIJT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK

INTEGER::JI

JI = D%NIB




IF (PRIT (JI)>0..AND.PT (JI)>CST%XTT.AND.LDCOMPUTE (JI)) THEN
  PRIMLTC_MR (JI)=PRIT (JI)

  IF (PARAMI%LFEEDBACKT) THEN
    PRIMLTC_MR (JI)=MIN (PRIMLTC_MR (JI), MAX (0.,(PTHT (JI&
    &)-CST%XTT/PEXN (JI))/(PLSFACT (JI)-PLVFACT (JI))))
  ENDIF

ELSE
  PRIMLTC_MR (JI)=0.
ENDIF



END SUBROUTINE ICE4_RIMLTC_OPENACC

ENDMODULE MODE_ICE4_RIMLTC_OPENACC
