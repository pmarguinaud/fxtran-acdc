SUBROUTINE B02_COMPONENT (KIDIA, KFDIA, KLEV, YDCFU, YDMF)
USE TYPES_MOD,ONLY:TCFU, TMF
INTEGER, INTENT (IN)::KLEV
INTEGER, INTENT (IN)::KFDIA
INTEGER, INTENT (IN)::KIDIA
TYPE (TCFU), INTENT (INOUT)::YDCFU
TYPE (TMF), INTENT (INOUT)::YDMF
INTEGER::JLEV
YDCFU %QTOT(KIDIA:KFDIA)=0.
DO JLEV=1, KLEV
  YDCFU %QTOT(KIDIA:KFDIA)=YDCFU %QTOT(KIDIA:KFDIA)+REAL (YDCFU%YSTRDU%INUMLEV (JLEV))
ENDDO
YDMF %FEVL(KIDIA:KFDIA, 1)=REAL (YDCFU%NFRRC)
END SUBROUTINE
