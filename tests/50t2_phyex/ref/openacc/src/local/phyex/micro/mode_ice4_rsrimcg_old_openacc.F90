
MODULE MODE_ICE4_RSRIMCG_OLD_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE ICE4_RSRIMCG_OLD_OPENACC (CST, PARAMI, ICEP, ICED, D, LDSOFT&
&, LDCOMPUTE, PRHODREF, PLBDAS, PT, PRCT, PRST, PRSRIMCG_MR, YDSTACK)
!$ACC ROUTINE (ICE4_RSRIMCG_OLD_OPENACC) SEQ      

USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
USE MODD_CST,ONLY:CST_T
USE MODD_PARAM_ICE_N,ONLY:PARAM_ICE_T
USE MODD_RAIN_ICE_DESCR_N,ONLY:RAIN_ICE_DESCR_T
USE MODD_RAIN_ICE_PARAM_N,ONLY:RAIN_ICE_PARAM_T

#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE


TYPE (CST_T), INTENT (IN)::CST
TYPE (PARAM_ICE_T), INTENT (IN)::PARAMI
TYPE (RAIN_ICE_PARAM_T), INTENT (IN)::ICEP
TYPE (RAIN_ICE_DESCR_T), INTENT (IN)::ICED
TYPE (DIMPHYEX_T), INTENT (IN)::D
LOGICAL, INTENT (IN)::LDSOFT
LOGICAL, INTENT (IN)::LDCOMPUTE(D%NIJT)
REAL, INTENT (IN)::PRHODREF(D%NIJT)
REAL, INTENT (IN)::PLBDAS(D%NIJT)
REAL, INTENT (IN)::PT(D%NIJT)
REAL, INTENT (IN)::PRCT(D%NIJT)
REAL, INTENT (IN)::PRST(D%NIJT)
REAL, INTENT (OUT)::PRSRIMCG_MR(D%NIJT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
LOGICAL::GRIM
INTEGER::IGRIM
REAL::ZBUF2
REAL::ZBUF1
INTEGER::IBUF2
INTEGER::IBUF1
REAL::ZZW
INTEGER::JI

INTEGER::IINDEX
REAL::ZINDEX

JI = D%NIB


PRSRIMCG_MR (JI)=0.

IF (.NOT.LDSOFT) THEN
  
  GRIM =PRCT (JI)>ICED%XRTMIN (2).AND.PRST (JI)>ICED%XRTMIN (5).AND.LDCOMPUTE (JI).AND.PT (JI)<CST%XTT

  

  

  IF (PARAMI%LPACK_INTERP) THEN
    IGRIM=0

    

    IF (GRIM ) THEN
      IGRIM=IGRIM+1
      ZBUF1 =PLBDAS (JI)
      IBUF1 =JI
    ENDIF


    

    IF (IGRIM>0) THEN
      
      ZBUF1 =MAX (1.00001, MIN (REAL (ICEP%NGAMINC)-0.00001, ICEP%XRIMINTP1*LOG (ZBUF1 )+ICEP%XRIMINTP2))
      IBUF2 =INT (ZBUF1 )
      ZBUF1 =ZBUF1 -REAL (IBUF2 )
      
      
      ZBUF2 =ICEP %XGAMINC_RIM2(IBUF2 +1)*ZBUF1 -ICEP %XGAMINC_RIM2(IBUF2 )*(ZBUF1 -1.0)
      
      ZZW =0.
      
      ZZW =ZBUF2 
    
    
    
    ENDIF

  ELSE
    IGRIM=0

    

    IF (GRIM ) THEN
      IGRIM=IGRIM+1
      ZINDEX=MAX (1.00001, MIN (REAL (ICEP%NGAMINC)-0.00001,&
      & ICEP%XRIMINTP1*LOG (PLBDAS (JI))+ICEP%XRIMINTP2))
      IINDEX=INT (ZINDEX)
      ZINDEX=ZINDEX-REAL (IINDEX)
      ZZW =ICEP %XGAMINC_RIM2(IINDEX+1)*ZINDEX-ICEP %XGAMINC_RIM2(IINDEX)*(ZINDEX-1.0)
    
    
    ELSE
      ZZW =0.
    
    
    ENDIF

  
  ENDIF


  

  

  IF (IGRIM>0) THEN

    

    IF (.NOT.ICEP%LNEWCOEFF) THEN

      IF (GRIM ) THEN
        PRSRIMCG_MR (JI)=ICEP%XSRIMCG*PLBDAS (JI)**ICEP%XEXSRIMCG*(1.0-ZZW )/PRHODREF (JI)
      ENDIF

    ELSE

      IF (GRIM ) THEN
        PRSRIMCG_MR (JI)=ICEP%XSRIMCG*PLBDAS (JI)**ICEP%XEXSRIMCG*(1.0-ZZW )*PRST (JI)
      ENDIF

    ENDIF


    IF (GRIM ) THEN
      PRSRIMCG_MR (JI)=MIN (PRST (JI), PRSRIMCG_MR (JI))
    ENDIF

  
  ENDIF

ENDIF






END SUBROUTINE ICE4_RSRIMCG_OLD_OPENACC

ENDMODULE MODE_ICE4_RSRIMCG_OLD_OPENACC
