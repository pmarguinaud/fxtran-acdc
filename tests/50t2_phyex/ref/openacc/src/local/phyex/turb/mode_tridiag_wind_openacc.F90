
MODULE MODE_TRIDIAG_WIND_OPENACC


IMPLICIT NONE


CONTAINS
SUBROUTINE TRIDIAG_WIND_OPENACC (D, PVARM, PSEA_CU, PA, PCOEFS, PTSTEP&
&, IN_PEXPL, IN_PIMPL, PRHODJA, PSOURCE, PVARP, YDSTACK)
!$ACC ROUTINE (TRIDIAG_WIND_OPENACC) SEQ      


USE MODD_DIMPHYEX,ONLY:DIMPHYEX_T
#include "fxtran_acdc_stack.h"
USE FXTRAN_ACDC_STACK_MOD
USE FXTRAN_ACDC_ABORT_MOD

IMPLICIT NONE

TYPE (DIMPHYEX_T), INTENT (IN)::D
REAL, INTENT (IN)::PVARM(D%NIJT, D%NKT)
REAL, INTENT (IN)::PSEA_CU(D%NIJT)
REAL, INTENT (IN)::PA(D%NIJT, D%NKT)
REAL, INTENT (IN)::PCOEFS(D%NIJT)
REAL, INTENT (IN)::PTSTEP
REAL, INTENT (IN)::IN_PIMPL
REAL, INTENT (IN)::IN_PEXPL
REAL, INTENT (IN)::PRHODJA(D%NIJT, D%NKT)
REAL, INTENT (IN)::PSOURCE(D%NIJT, D%NKT)
REAL, INTENT (OUT)::PVARP(D%NIJT, D%NKT)
TYPE(FXTRAN_ACDC_STACK), INTENT (IN) :: YDSTACK
TYPE(FXTRAN_ACDC_STACK) :: YLSTACK
fxtran_acdc_temp (REAL, ZGAM, (D%NIJT, D%NKT))
fxtran_acdc_temp (REAL, ZY, (D%NIJT, D%NKT))
REAL::ZBET
INTEGER::JK
INTEGER::JI
INTEGER::IKE
INTEGER::IKB
INTEGER::IKU
INTEGER::IKA
INTEGER::IKT
INTEGER::IKTE
INTEGER::IKTB
INTEGER::IIJE
INTEGER::IIJB
INTEGER::IKL
REAL::PTSTEP_IN
REAL::PIMPL
REAL::PEXPL


YLSTACK = YDSTACK



IF (KIND (ZGAM) == 8) THEN
    fxtran_acdc_alloc8 (ZGAM)
ELSEIF (KIND (ZGAM) == 4) THEN
    fxtran_acdc_alloc4 (ZGAM)
ELSE
    STOP 1
ENDIF


IF (KIND (ZY) == 8) THEN
    fxtran_acdc_alloc8 (ZY)
ELSEIF (KIND (ZY) == 4) THEN
    fxtran_acdc_alloc4 (ZY)
ELSE
    STOP 1
ENDIF


JI = D%NIB


PEXPL=IN_PEXPL
PIMPL=IN_PIMPL
PTSTEP_IN=PTSTEP
IKT=D%NKT
IKTB=D%NKTB
IKTE=D%NKTE
IKB=D%NKB
IKE=D%NKE
IKA=D%NKA
IKU=D%NKU
IKL=D%NKL
IIJB=D%NIB
IIJE=D%NIE

ZY (JI, IKB)=PVARM (JI, IKB)+PTSTEP_IN*PSOURCE (JI, IKB)-PEXPL/PRHODJA (JI, IKB)*PA (JI,&
& IKB+IKL)*(PVARM (JI, IKB+IKL)-PVARM (JI, IKB))-PIMPL*PCOEFS (JI)*PTSTEP*PSEA_CU (JI)


DO JK=IKTB+1, IKTE-1
  
  ZY (JI, JK)=PVARM (JI, JK)+PTSTEP*PSOURCE (JI, JK)-PEXPL/PRHODJA (JI, JK)*(PVARM (JI, JK-IKL)*PA&
  & (JI, JK)-PVARM (JI, JK)*(PA (JI, JK)+PA (JI, JK+IKL))+PVARM (JI, JK+IKL)*PA (JI, JK+IKL))
  
ENDDO


ZY (JI, IKE)=PVARM (JI, IKE)+PTSTEP*PSOURCE (JI, IKE)+PEXPL/PRHODJA&
& (JI, IKE)*PA (JI, IKE)*(PVARM (JI, IKE)-PVARM (JI, IKE-IKL))


IF (PIMPL>1.E-10) THEN
  
  ZBET =1.-PIMPL*(PA (JI, IKB+IKL)/PRHODJA (JI, IKB)+PCOEFS (JI)*PTSTEP)
  PVARP (JI, IKB)=ZY (JI, IKB)/ZBET 

  

  DO JK=IKB+IKL, IKE-IKL, IKL
    
    ZGAM (JI, JK)=PIMPL*PA (JI, JK)/PRHODJA (JI, JK-IKL)/ZBET 
    ZBET =1.-PIMPL*(PA (JI, JK)*(1.+ZGAM (JI, JK))+PA (JI, JK+IKL))/PRHODJA (JI, JK)
    PVARP (JI, JK)=(ZY (JI, JK)-PIMPL*PA (JI, JK)/PRHODJA (JI, JK)*PVARP (JI, JK-IKL))/ZBET 
  
  ENDDO

  
  ZGAM (JI, IKE)=PIMPL*PA (JI, IKE)/PRHODJA (JI, IKE-IKL)/ZBET 
  ZBET =1.-PIMPL*(PA (JI, IKE)*(1.+ZGAM (JI, IKE)))/PRHODJA (JI, IKE)
  PVARP (JI, IKE)=(ZY (JI, IKE)-PIMPL*PA (JI, IKE)/PRHODJA (JI, IKE)*PVARP (JI, IKE-IKL))/ZBET 

  

  DO JK=IKE-IKL, IKB,-1*IKL
    
    PVARP (JI, JK)=PVARP (JI, JK)-ZGAM (JI, JK+IKL)*PVARP (JI, JK+IKL)
  
  ENDDO

ELSE

  DO JK=IKTB, IKTE
    
    PVARP (JI, JK)=ZY (JI, JK)
  
  ENDDO

ENDIF


PVARP (JI, IKA)=PVARP (JI, IKB)
PVARP (JI, IKU)=PVARP (JI, IKE)


END SUBROUTINE TRIDIAG_WIND_OPENACC

ENDMODULE MODE_TRIDIAG_WIND_OPENACC
